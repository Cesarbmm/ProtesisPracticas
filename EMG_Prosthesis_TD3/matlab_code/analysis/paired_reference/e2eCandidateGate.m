function flags=e2eCandidateGate(f)
% Gates A..J preregistrados; K se exige sólo al cerrar con tests/hashes.
t=1e-12;
flags=struct("passA",f.cycles==0,"passB",f.newCycles==0, ...
    "passC",f.mseChangePct<=5+t,"passD",f.rewardChangePct<=5+t, ...
    "passE",f.subjectDegradations<=2 && f.motorDegradations<=1 && f.directionDegradations==0, ...
    "passF",f.flatDefined && f.maxFlatIncrease<=.02+t, ...
    "passG",f.noMotionDefined && f.maxNoMotionIncrease<=.05+t, ...
    "passH",f.neutralStepFractionOfActiveBaseline<=.10+t, ...
    "passI",f.m3Reversals==0,"passJ",f.zeroMotionFailures==0);
flags.passed=all(structfun(@(x) logical(x),flags));
end
