function [perMotor, aggregate] = e2bControlMetrics(trace)
% Metricas E2B en las escalas historicas de reward, sin cambiar sus helpers.
q=trace.q; u=trace.effectiveAction; pwm=trace.pwm;
prediction=trace.prediction; reference=trace.reference;
n=size(u,1);
assert(n>0 && isequal(size(q),[n+1 4]),"E2B:MetricsShape","Traza incompleta.");
p=configurables();
h=p.flexJoined_scale(encoder2Flex(q));
err=prediction-reference;
delta=[u(1,:); diff(u,1,1)]; % incluye accion previa inicial cero
tracking=-err.^2;
actionPenalty=p.rewardActionWeight*u.^2;
deltaPenalty=p.rewardDeltaActionWeight*delta.^2;
reward=tracking-actionPenalty-deltaPenalty;
assert(max(abs(mean(reward,2)-trace.reward(:)))<1e-12, ...
    "E2B:RewardDecomposition","La descomposicion no coincide con reward de Env.");
dq=diff(q,1,1); active=pwm~=0;
for motor=1:4
    x=prediction(:,motor); y=reference(:,motor);
    if max(x)-min(x)<=1e-12 || max(y)-min(y)<=1e-12
        rho=NaN;
    else
        corrMatrix=corrcoef(x,y); rho=corrMatrix(1,2);
    end
    eligible=pwm(1:end-1,motor)~=0 & pwm(2:end,motor)~=0;
    flipped=pwm(1:end-1,motor).*pwm(2:end,motor)<0;
    beforeError=h(1:end-1,motor)-y;
    afterError=x-y;
    overshoot=beforeError.*afterError<0 & abs(beforeError)>1e-9 & abs(afterError)>1e-9;
    noMotion=active(:,motor) & abs(dq(:,motor))<=1e-9;
    cycle=false;
    if n>=4
        last=q(end-4:end,motor); lastH=h(end-4:end,motor);
        commands=pwm(end-3:end,motor);
        cycle=all(abs(last([1 3])-last(5))<=1e-9) && ...
            abs(last(2)-last(4))<=1e-9 && abs(lastH(1)-lastH(2))>0.05 && ...
            all(commands(1:3).*commands(2:4)<0);
    end
    result=struct("motor",motor,"trackingMSE",mean(err(:,motor).^2), ...
        "MAE",mean(abs(err(:,motor))),"correlation",rho,"correlationValid",double(isfinite(rho)), ...
        "responseRange",max(h(:,motor))-min(h(:,motor)), ...
        "encoderRange",max(q(:,motor))-min(q(:,motor)), ...
        "referenceRange",max(y)-min(y), ...
        "flat_response",double(max(h(:,motor))-min(h(:,motor))<=1e-9), ...
        "action_no_motion",safeRatio(nnz(noMotion),nnz(active(:,motor))), ...
        "activeCommands",nnz(active(:,motor)),"noMotionCommands",nnz(noMotion), ...
        "actionL2",mean(u(:,motor).^2),"deltaActionL2",mean(delta(:,motor).^2), ...
        "saturationFraction",mean(abs(u(:,motor))>=.95), ...
        "pwmHighFraction",mean(abs(pwm(:,motor))>=128), ...
        "rewardMean",mean(reward(:,motor)),"rewardTotal",sum(reward(:,motor)), ...
        "trackingTerm",mean(tracking(:,motor)),"actionPenalty",mean(actionPenalty(:,motor)), ...
        "deltaActionPenalty",mean(deltaPenalty(:,motor)), ...
        "signFlipFraction",safeRatio(nnz(flipped & eligible),nnz(eligible)), ...
        "signFlips",nnz(flipped & eligible),"signFlipEligible",nnz(eligible), ...
        "overshootFraction",mean(overshoot), ...
        "directionFailures",nnz(dq(:,motor).*sign(pwm(:,motor)) < -1e-9), ...
        "zeroMotionFailures",nnz(~active(:,motor) & abs(dq(:,motor))>1e-9), ...
        "persistentTwoCycle",double(cycle));
    perMotor(motor)=result; %#ok<AGROW>
end
aggregate=rmfield(perMotor(1),"motor");
sumFields=["correlationValid","activeCommands","noMotionCommands","signFlips", ...
    "signFlipEligible","directionFailures","zeroMotionFailures","persistentTwoCycle"];
for field=string(fieldnames(aggregate))'
    values=[perMotor.(field)];
    if ismember(field,sumFields), aggregate.(field)=sum(values);
    else, aggregate.(field)=mean(values,"omitnan"); end
end
aggregate.action_no_motion=safeRatio(aggregate.noMotionCommands,aggregate.activeCommands);
aggregate.signFlipFraction=safeRatio(aggregate.signFlips,aggregate.signFlipEligible);
end

function result=safeRatio(numerator,denominator)
if denominator==0, result=NaN; else, result=numerator/denominator; end
end
