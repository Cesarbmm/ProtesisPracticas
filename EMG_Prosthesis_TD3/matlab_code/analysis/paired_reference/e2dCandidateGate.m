function result=e2dCandidateGate(f)
% Gates numericos preregistrados. Tests/integridad son un gate global posterior.
tol=1e-12;
result=struct("passA",f.cycles==0,"passB",f.mseChangePct<=5+tol, ...
    "passC",f.rewardChangePct<=5+tol, ...
    "passD",f.subjectDegradations<=2 && f.motorDegradations<=1 && f.directionDegradations==0, ...
    "passE",f.m3Reversals==0, ...
    "passF",f.motionMetricsDefined && f.maxFlatIncrease<=.02+tol && ...
        f.maxNoMotionIncrease<=.05+tol && f.pairedZeroedActiveFraction<=.20+tol);
result.passed=all(structfun(@(x) logical(x),result));
end
