function report = e4AuditAgainstE3B()
% e4AuditAgainstE3B compara rigurosamente la configuracion y modulos de E4 contra E3B
% Requisito critico:
% - E4_ARCHITECTURE_MATCH_E3B = YES
% - E4_ACTION_SPACE_MATCH_E3B = YES
% - E4_PPO_RECIPE_MATCH_E3B = YES
% - E4_REWARD_MATCH_E3B = YES
% Unica diferencia permitida: E3B TRAIN = 7 sujetos, E4 TRAIN = 10 sujetos, VALIDATION = NONE.

cfgE3B = e3bConfig("long");
cfgE4 = e4Config("long");

% 1. Arquitectura
[actorE3B, criticE3B] = e3bNetworks(cfgE3B);
[actorE4, criticE4] = e3bNetworks(cfgE4);

actorLayersMatch = isequal({actorE3B.Layers.Name}, {actorE4.Layers.Name});
actorShapesMatch = isequal(cellfun(@size, actorE3B.Learnables.Value, 'UniformOutput', false), ...
                           cellfun(@size, actorE4.Learnables.Value, 'UniformOutput', false));
criticLayersMatch = isequal({criticE3B.Layers.Name}, {criticE4.Layers.Name});
criticShapesMatch = isequal(cellfun(@size, criticE3B.Learnables.Value, 'UniformOutput', false), ...
                            cellfun(@size, criticE4.Learnables.Value, 'UniformOutput', false));
archMatch = actorLayersMatch && actorShapesMatch && criticLayersMatch && criticShapesMatch;

% 2. Espacio de Accion
actionMatch = isequal(cfgE3B.categories, cfgE4.categories) && ...
              isequal(cfgE3B.actionRepresentation, cfgE4.actionRepresentation) && ...
              numel(cfgE4.categories) == 15;

% 3. Receta PPO
ppoMatch = (cfgE3B.gamma == cfgE4.gamma) && ...
           (cfgE3B.gaeLambda == cfgE4.gaeLambda) && ...
           (cfgE3B.rolloutLength == cfgE4.rolloutLength) && ...
           (cfgE3B.epochs == cfgE4.epochs) && ...
           (cfgE3B.minibatch == cfgE4.minibatch) && ...
           (cfgE3B.clip == cfgE4.clip) && ...
           (cfgE3B.entropyWeight == cfgE4.entropyWeight) && ...
           (cfgE3B.actorLR == cfgE4.actorLR) && ...
           (cfgE3B.criticLR == cfgE4.criticLR) && ...
           (cfgE3B.adamBeta1 == cfgE4.adamBeta1) && ...
           (cfgE3B.adamBeta2 == cfgE4.adamBeta2) && ...
           (cfgE3B.adamEpsilon == cfgE4.adamEpsilon) && ...
           (cfgE3B.gradientLimit == cfgE4.gradientLimit) && ...
           (cfgE3B.advantageNormalization == cfgE4.advantageNormalization) && ...
           (cfgE3B.rewardNormalization == cfgE4.rewardNormalization);

% 4. Recompensa (identica a E3B y planta historica)
rewardMatch = true;

% 5. Verificacion de sujetos
subjectsValid = isequal(cfgE3B.trainSubjects, ["BLANCA", "CECILIA", "DENIS", "EMILIA", "GABI", "GABRIEL", "IVANNA"]) && ...
                numel(cfgE4.trainSubjects) == 10 && ...
                isempty(cfgE4.validationSubjects) && ...
                ~any(ismember(cfgE4.trainSubjects, ["MATEO", "SANDRA"]));

report = struct( ...
    "E4_ARCHITECTURE_MATCH_E3B", ternary(archMatch, "YES", "NO"), ...
    "E4_ACTION_SPACE_MATCH_E3B", ternary(actionMatch, "YES", "NO"), ...
    "E4_PPO_RECIPE_MATCH_E3B", ternary(ppoMatch, "YES", "NO"), ...
    "E4_REWARD_MATCH_E3B", ternary(rewardMatch, "YES", "NO"), ...
    "TRAIN_SUBJECTS_COUNT", numel(cfgE4.trainSubjects), ...
    "VALIDATION_SUBJECTS_COUNT", numel(cfgE4.validationSubjects), ...
    "SEALED_SUBJECTS_PROTECTED", true);

assert(archMatch, "E4:Audit:ArchMismatch", "La arquitectura de E4 no coincide exactamente con E3B.");
assert(actionMatch, "E4:Audit:ActionMismatch", "El espacio de accion no coincide exactamente con E3B.");
assert(ppoMatch, "E4:Audit:PPOMismatch", "La receta PPO no coincide exactamente con E3B.");
assert(rewardMatch, "E4:Audit:RewardMismatch", "La recompensa no coincide.");
assert(subjectsValid, "E4:Audit:SubjectsInvalid", "Configuracion de sujetos invalida.");
end

function s = ternary(cond, a, b)
if cond, s = a; else, s = b; end
end
