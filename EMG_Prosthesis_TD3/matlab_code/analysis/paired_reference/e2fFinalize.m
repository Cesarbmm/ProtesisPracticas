function summary=e2fFinalize
here=string(fileparts(mfilename("fullpath")));out=fullfile(here,"e2f_results");I=e2fVerifyHistory();
t=jsondecode(fileread(fullfile(out,"test_summary.json")));g=jsondecode(fileread(fullfile(out,"primary_gates.json")));
assert(t.previousPassed==144 && t.passed==t.totalTests && t.failed==0 && t.incomplete==0 && all(I.unchanged));
M=readtable(fullfile(out,"controller_summary.csv"),TextType="string");R=readtable(fullfile(out,"reachability_summary.csv"),TextType="string");
Z=M(M.controller=="ZERO",:);P=M(M.controller=="P_2",:);O=M(M.controller=="ORACLE_H5",:);r=R(R.controller=="ORACLE_H5",:);
summary=struct("WORKTREE",string(fileparts(fileparts(fileparts(fileparts(here))))), ...
    "BRANCH","experiment/no-glove-paired-reference-td3","START_SHA","165be049eb41fc41254435181c9857fe0f22ed1c", ...
    "E2E_RESULT","REVERSAL_GUARD_NOT_SUFFICIENT","E2D_RESULT","DEADBAND_NOT_SUFFICIENT", ...
    "E2C_RESULT","CHARACTERIZED","E2B_RESULT","FAIL", ...
    "PWM_HARDWARE_SUPPORT","PROTOCOLO ENTERO CON SIGNO 0..255; REALIZACION ELECTRICA UNKNOWN", ...
    "HISTORICAL_LEVELS_PHYSICAL_REQUIREMENT",false,"ORACLE_SEPARABLE",true, ...
    "ORACLE_HORIZONS",[1 2 3 5],"ORACLE_PRIMARY_HORIZON",5, ...
    "ZERO_MSE",Z.trackingMSE,"P2_MSE",P.trackingMSE,"ORACLE_MSE",O.trackingMSE, ...
    "ZERO_REWARD",Z.rewardMean,"P2_REWARD",P.rewardMean,"ORACLE_REWARD",O.rewardMean, ...
    "ORACLE_FINAL_CYCLES",g.finalCycles,"ORACLE_FIXED_REFERENCE_CYCLES",g.fixedOrbits, ...
    "ORACLE_M3_REVERSALS",g.m3Reversals,"REACHABLE_TARGET_FRACTION",r.reachableTargetFraction, ...
    "MINIMUM_REACHABLE_ERROR",r.minimumReachableError,"WITHIN_005_REACHABLE_FRACTION",r.within005Fraction, ...
    "ORACLE_BEATS_P2",g.mseImprovementPct>=10 && O.rewardMean>=P.rewardMean, ...
    "STABLE_BETTER_POLICY_FOUND",g.pass1 && g.pass2, ...
    "CURRENT_MDP_CONTROL_FEASIBLE",g.measuredGatesPass,"RL_PILOT_AUTHORIZED",g.measuredGatesPass, ...
    "RECOMMENDED_AGENT_PRIMARY","TD3_HISTORICO","RECOMMENDED_AGENT_CHALLENGER","SAC_CONTINUO", ...
    "E3A_PREPARED",false,"E3A_EXECUTED",false, ...
    "BLOCKING_CONSTRAINT","GATE 3: SUELO LOCAL 61.179% >50%; SOPORTE TEACHER/h(q)/PLANTA POR REVISAR", ...
    "SANDBOX_FUTURE_USE","SOLO HandKinematicViewer PASIVO CON TRAZAS CANONICAS", ...
    "VISUALIZATION_INTEGRATION","DEFERRED","MATEO_SANDRA_SEALED",true, ...
    "tests",t,"HISTORICAL_HASHES_INTACT",all(I.unchanged),"GIT_REPAIR_ATTEMPTED",false,"PUSH",false,"gates",g);
assert(~g.measuredGatesPass,"E2F:UnexpectedGateOutcome","Revisar entrega si cambia un resultado medido.");
e2cWriteJSON(fullfile(out,"e2f_summary.json"),summary);e2fPlotResults(out);
files=dir(fullfile(out,"**","*"));rows={};
for file=files'
    if file.isdir || string(file.name)=="artifact_manifest.json",continue;end
    full=fullfile(file.folder,file.name);relative=extractAfter(string(full),strlength(out)+1);
    rows{end+1}=struct("file",relative,"bytes",file.bytes,"sha256",e2cSHA256(full)); %#ok<AGROW>
end
e2cWriteJSON(fullfile(out,"artifact_manifest.json"),struct("artifacts",[rows{:}]));disp(summary);
end
