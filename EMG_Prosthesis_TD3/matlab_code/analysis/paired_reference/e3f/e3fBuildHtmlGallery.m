    "</table></div>"; ...
    "<h2>2. Figuras Resumen Globales</h2>"; ...
    "<div class='flex-row'>"; ...
    "<img class='summary-img' src='evaluation/final_checkpoint/figures/MOTOR_TRACKING_SUMMARY.png' alt='Motor Tracking Summary'>"; ...
    "<img class='summary-img' src='evaluation/final_checkpoint/figures/OPENING_CLOSING_SUMMARY.png' alt='Opening Closing Summary'>"; ...
    "</div><div class='flex-row'>"; ...
    "<img class='summary-img' src='evaluation/final_checkpoint/figures/PWM_USAGE_HEATMAP.png' alt='PWM Usage Heatmap'>"; ...
    "<img class='summary-img' src='subject_invariance.png' alt='Subject Invariance'>"; ...
    "</div>"; ...
    "<h2>3. Diagnostico Detallado (Seleccion ANNOTATED)</h2>"; ...
    "<p>Subconjunto diagnostico representativo congelado basado estrictamente en metricas numericas objetivas:</p>"; ...
    "<table><tr><th>Criterio</th><th>Sujeto</th><th>Fila</th><th>Direccion</th><th>MSE</th><th>Miniatura</th><th>Enlaces de Evidencia</th></tr>"];

