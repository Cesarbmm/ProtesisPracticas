        html = [html; "<tr><td>" + i + "</td><td><b>" + row.subject + "</b></td><td>" + row.row + "</td><td>" + row.direction + "</td>" + ...
            "<td>" + sprintf("%.6f", row.trackingMSE) + "</td><td>" + sprintf("%.4f", row.reward) + "</td>" + ...
            "<td><a href='" + row.compactPng + "' target='_blank'><img class='thumb' src='" + row.compactPng + "' alt='Thumbnail'></a></td>" + ...
            "<td><a class='btn' href='" + row.compactPng + "'>COMPACT PNG</a> " + ...
            "<a class='btn' href='" + row.compactFig + "'>COMPACT FIG</a><br>" + ...
            "<a class='btn btn-pri' href='" + row.proPng + "'>PRO PNG</a> " + ...
            "<a class='btn btn-pri' href='" + row.proFig + "'>PRO FIG</a><br>" + ...
            "<a class='btn' href='" + row.classicPng + "'>CLASSIC PNG</a> " + ...
            "<a class='btn' href='" + row.classicFig + "'>CLASSIC FIG</a><br>" + ...
            "<a class='btn btn-mat' href='" + row.traceCsv + "'>CSV</a> " + ...
            "<a class='btn btn-mat' href='" + row.traceMat + "'>MAT</a></td></tr>"];
    end
    html = [html; "</table>"];
end

