    "<title>E3F: Subject-Invariant Factorized Categorical PPO — Behavioral Evaluation</title>"; ...
    "<style>"; ...
    "body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; margin: 25px; line-height: 1.5; color: #222; background: #fdfdfd; }"; ...
