fid = fopen(htmlFile, "w", "n", "utf-8");
assert(fid >= 0, "E3F:HtmlWrite", "No se pudo escribir TEST_COMPORTAMENTAL.html");
fprintf(fid, "%s", join(html, newline));
fclose(fid);
htmlPath = string(htmlFile);
end
