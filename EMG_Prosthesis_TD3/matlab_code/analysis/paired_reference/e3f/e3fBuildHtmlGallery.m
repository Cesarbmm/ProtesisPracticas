    ar = annotatedRecords{aIdx};
    html = [html; "<tr><td><b>" + ar.reason + "</b></td><td>" + ar.subject + "</td><td>" + ar.row + "</td><td>" + ar.direction + ...
        "</td><td>" + sprintf("%.6f", ar.mse) + "</td>" + ...
