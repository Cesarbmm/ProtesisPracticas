function T=e2eStepTable(t,b,enabled)
n=size(t.pwm,1);md=t.metadata;tables=cell(1,4);
for m=1:4
    key=table(repmat(double(enabled),n,1),repmat(md.subject,n,1),repmat(md.repetition,n,1), ...
        repmat(md.side,n,1),(1:n)',repmat(m,n,1), ...
        VariableNames=["enabled","subject","repetition","side","step","motor"]);
    vals=[t.referenceBefore(:,m),t.reference(:,m),t.errorBefore(:,m),t.rawAction(:,m), ...
        t.desiredEffectiveAction(:,m),t.desiredPwm(:,m),t.previousAppliedPwm(:,m), ...
        t.pendingBefore(:,m),t.pendingAfter(:,m),t.request(:,m),t.neutralized(:,m), ...
        t.confirmed(:,m),t.cancelled(:,m),t.effectiveAction(:,m),t.pwm(:,m),b.pwm(:,m), ...
        t.q(1:n,m),t.q(2:end,m),t.prediction(:,m),t.trackingTerm(:,m),t.actionPenalty(:,m), ...
        t.deltaActionPenalty(:,m),t.rewardVector(:,m),t.reward, ...
        runLength(t.neutralized(:,m)),runLength(t.pwm(:,m)==0)];
    names=["referenceBefore","referenceAfter","errorBefore","rawAction","desiredEffective", ...
        "desiredPwm","previousAppliedPwm","pendingBefore","pendingAfter","request","neutralized", ...
        "confirmed","cancelled","effective","pwm","baselinePwm","qBefore","qAfter","hAfter", ...
        "trackingTermMotor","actionPenaltyMotor","deltaPenaltyMotor","rewardMotor","rewardEpisode", ...
        "neutralRunLength","zeroRunLength"];
    tables{m}=[key array2table(vals,VariableNames=names)];
end
T=vertcat(tables{:});
end
function n=runLength(mask)
n=zeros(size(mask));v=0;for k=1:numel(mask),if mask(k),v=v+1;else,v=0;end;n(k)=v;end
end
