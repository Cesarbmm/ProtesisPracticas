function summary=e2eFinalize
% Cierre por evidencia; no cambia gates ni integra guard en Env.
here=string(fileparts(mfilename("fullpath")));out=fullfile(here,"e2e_results");
integrity=e2eVerifyHistory();writetable(integrity,fullfile(out,"historical_integrity.csv"));
m=jsondecode(fileread(fullfile(out,"measurement_summary.json")));
t=jsondecode(fileread(fullfile(out,"test_summary.json")));
assert(t.previousTests==107 && t.previousPassed==107 && t.passed==t.totalTests && ...
    t.failed==0 && t.incomplete==0 && t.historicalFilesUnchanged,"E2E:TestGateFailed");
g=readtable(fullfile(out,"candidate_gates.csv"));s=readtable(fullfile(out,"mode_summary.csv"));
events=readtable(fullfile(out,"event_summary.csv"),TextType="string");f=readtable(fullfile(out,"fixed_reference_summary.csv"));
r=g(g.enabled==1,:);modes=s(s.enabled==1,:);e=events(events.enabled==1 & events.kind=="total",:);
result="REVERSAL_GUARD_NOT_SUFFICIENT";if r.passed,result="REVERSAL_GUARD_SUPPORTED";end
summary=struct("WORKTREE",string(fileparts(fileparts(fileparts(fileparts(here))))), ...
    "BRANCH","experiment/no-glove-paired-reference-td3","START_SHA","165be049eb41fc41254435181c9857fe0f22ed1c", ...
    "E2D_RESULT","DEADBAND_NOT_SUFFICIENT","E2C_RESULT","CHARACTERIZED","E2B_RESULT","FAIL", ...
    "P2_BASELINE_MSE",m.baselineMSE,"P2_BASELINE_REWARD",m.baselineReward,"P2_BASELINE_CYCLES",m.baselineCycles, ...
    "REVERSAL_REQUESTS",e.requests,"NEUTRALIZED_REVERSALS",e.neutralized, ...
    "CONFIRMED_REVERSALS",e.confirmed,"CANCELLED_REVERSALS",e.cancelled,"PENDING_AT_END",e.pendingEnd, ...
    "NEUTRAL_STEP_FRACTION",e.neutralStepFraction, ...
    "NEUTRAL_STEP_FRACTION_OF_ACTIVE_BASELINE",e.neutralStepFractionOfActiveBaseline, ...
    "MAX_CONSECUTIVE_NEUTRAL_STEPS",e.maxConsecutiveNeutralSteps, ...
    "E2E_MSE",r.trackingMSE,"E2E_MSE_CHANGE_PCT",r.mseChangePct, ...
    "E2E_REWARD",r.rewardMean,"E2E_REWARD_CHANGE_PCT",r.rewardChangePct, ...
    "E2E_FINAL_CYCLES",r.cycles,"E2E_NEW_FINAL_CYCLES",r.newCycles, ...
    "E2E_TRANSIENT_CYCLE_WINDOWS",r.slidingCycleWindows,"E2E_NEW_TRANSIENT_WINDOWS",r.newSlidingCycleWindows, ...
    "E2E_FLAT_RESPONSE",modes.flat_response,"E2E_ACTION_NO_MOTION",modes.action_no_motion, ...
    "P2_M3_REVERSALS",g.m3Reversals(g.enabled==0),"E2E_M3_REVERSALS",r.m3Reversals, ...
    "SUBJECT_DEGRADATIONS",r.subjectDegradations,"MOTOR_DEGRADATIONS",r.motorDegradations, ...
    "DIRECTION_DEGRADATIONS",r.directionDegradations, ...
    "FIXED_REFERENCE_CYCLES",nnz(f.enabled==1 & f.period>0), ...
    "FIXED_REFERENCE_HISTORICAL_CYCLES",nnz(f.enabled==1 & f.terminalCycle), ...
    "USES_GLOVE",false,"USES_REFERENCE",false,"USES_REWARD",false, ...
    "USES_PREVIOUS_ACTION",true,"USES_CURRENT_DESIRED_ACTION",true,"E2E_RESULT",result, ...
    "RL_AUTHORIZED",false,"E3_PREPARED",false,"E3_EXECUTED",false,"MATEO_SANDRA_SEALED",true, ...
    "tests",t,"HISTORICAL_HASHES_INTACT",all(integrity.unchanged),"GIT_REPAIR_ATTEMPTED",false,"PUSH",false, ...
    "preregistrationSHA256",m.preregistrationSHA256,"gates",table2struct(r));
e2cWriteJSON(fullfile(out,"e2e_summary.json"),summary);
old=readtable(fullfile(here,"e2d_results","epsilon_summary.csv"));old=old(old.epsilon==.08,:);
z=readtable(fullfile(here,"e2d_results","zeroed_actions.csv"),TextType="string");z=z(z.epsilon==.08 & z.kind=="total",:);
comparison=table(["P2 OFF";"E2D epsilon .08";"E2E ON"], ...
    [s.trackingMSE(1);old.trackingMSE;r.trackingMSE],[s.rewardMean(1);old.rewardMean;r.rewardMean], ...
    [s.flat_response(1);old.flat_response;modes.flat_response], ...
    [s.action_no_motion(1);old.action_no_motion;modes.action_no_motion], ...
    [g.cycles(1);0;r.cycles],[0;z.directZeroedFraction;e.neutralStepFraction], ...
    [0;z.pairedZeroedActiveFraction;e.pairedZeroedActiveFraction], ...
    VariableNames=["condition","trackingMSE","rewardMean","flat_response","action_no_motion", ...
    "finalCycles","directNeutralFraction","pairedZeroedActiveFraction"]);
writetable(comparison,fullfile(out,"e2d_descriptive_comparison.csv"));
e2ePlotResults(out);
files=dir(fullfile(out,"**","*"));rows={};
for file=files'
    if file.isdir || string(file.name)=="artifact_manifest.json",continue;end
    full=fullfile(file.folder,file.name);relative=extractAfter(string(full),strlength(out)+1);
    rows{end+1}=struct("file",relative,"bytes",file.bytes,"sha256",e2cSHA256(full)); %#ok<AGROW>
end
e2cWriteJSON(fullfile(out,"artifact_manifest.json"),struct("artifacts",[rows{:}]));disp(summary);
end
