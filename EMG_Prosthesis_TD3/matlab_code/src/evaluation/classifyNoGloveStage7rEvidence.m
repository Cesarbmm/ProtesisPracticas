function decision = classifyNoGloveStage7rEvidence( ...
        supportSummary, familySummary, options)
%classifyNoGloveStage7rEvidence applies preregistered ETAPA 7R gates.

arguments
    supportSummary table
    familySummary table
    options.minimumSupportedMotors (1, 1) double ...
        {mustBeInteger, mustBeInRange(options.minimumSupportedMotors, 1, 4)} = 3
    options.minimumPrimaryIncrementalR2 (1, 1) double = 0.10
    options.minimumSignAccuracyGain (1, 1) double = 0.05
    options.minimumPermutationMargin (1, 1) double = 0.05
    options.minimumCheckpointIncrementalR2 (1, 1) double = 0.05
    options.minimumStableCheckpoints (1, 1) double ...
        {mustBeInteger, mustBeInRange(options.minimumStableCheckpoints, 1, 4)} = 3
end

requiredSupport = ["motor", "pairMode", "source", "supportPassed"];
requiredModels = ["checkpointEpisode", "motor", "pairMode", ...
    "source", "family", "incrementalR2", "signAccuracyGain", ...
    "permutationMargin"];
if ~all(ismember(requiredSupport, ...
        string(supportSummary.Properties.VariableNames))) || ...
        ~all(ismember(requiredModels, ...
        string(familySummary.Properties.VariableNames)))
    error("classifyNoGloveStage7rEvidence:InvalidContract", ...
        "Support or family model summary is incomplete.");
end

supportAll = supportSummary(supportSummary.source == "ALL", :);
withinSupportedMotorCount = sum(supportAll.pairMode == ...
    "withinEpisode" & supportAll.supportPassed);
crossSupportedMotorCount = sum(supportAll.pairMode == ...
    "crossEpisode" & supportAll.supportPassed);
supportPassed = withinSupportedMotorCount >= ...
    options.minimumSupportedMotors && crossSupportedMotorCount >= ...
    options.minimumSupportedMotors;

families = setdiff(unique(familySummary.family, "stable"), "allEmg");
auditParts = cell(numel(families), 1);
for familyIdx = 1:numel(families)
    family = families(familyIdx);
    rows = familySummary(familySummary.family == family, :);
    auditParts{familyIdx} = auditCandidate(rows, family, options, true);
end
if isempty(auditParts)
    familyAudit = table();
else
    familyAudit = vertcat(auditParts{:});
end
allRows = familySummary(familySummary.family == "allEmg", :);
allEmgAudit = auditCandidate(allRows, "allEmg", options, false);

if ~supportPassed
    result = "insufficientMatchedSupport";
elseif ~isempty(familyAudit) && sum(familyAudit.candidatePassed) == 1
    result = "singleFamilySupported:" + ...
        familyAudit.family(familyAudit.candidatePassed);
elseif ~isempty(familyAudit) && sum(familyAudit.candidatePassed) >= 2
    result = "multiFamilyEmgAssociation";
elseif allEmgAudit.candidatePassed
    result = "distributedEmgAssociation";
else
    result = "emgNotIdentifiedUnderMatching";
end

supportAudit = table(withinSupportedMotorCount, ...
    crossSupportedMotorCount, options.minimumSupportedMotors, ...
    supportPassed, string(result), ...
    'VariableNames', ["withinSupportedMotorCount", ...
    "crossSupportedMotorCount", "minimumSupportedMotors", ...
    "supportPassed", "scientificResult"]);
decision = struct("scientificResult", string(result), ...
    "supportPassed", supportPassed, "supportAudit", supportAudit, ...
    "familyAudit", familyAudit, "allEmgAudit", allEmgAudit);
end

function audit = auditCandidate(rows, family, options, requireSources)
primary = rows(rows.checkpointEpisode == 200 & rows.source == "ALL", :);
cross = primary(primary.pairMode == "crossEpisode", :);
within = primary(primary.pairMode == "withinEpisode", :);
crossPrimaryMotorCount = sum(cross.incrementalR2 >= ...
    options.minimumPrimaryIncrementalR2 & ...
    cross.signAccuracyGain >= options.minimumSignAccuracyGain);
withinPrimaryMotorCount = sum(within.incrementalR2 >= ...
    options.minimumPrimaryIncrementalR2 & ...
    within.signAccuracyGain >= options.minimumSignAccuracyGain);
permutationMotorCount = sum(cross.permutationMargin >= ...
    options.minimumPermutationMargin);

episodes = unique(rows.checkpointEpisode, "sorted");
stableCheckpointCount = 0;
agent200Stable = false;
for episode = episodes'
    checkpoint = rows(rows.checkpointEpisode == episode & ...
        rows.source == "ALL" & rows.pairMode == "crossEpisode", :);
    stable = sum(checkpoint.incrementalR2 >= ...
        options.minimumCheckpointIncrementalR2) >= ...
        options.minimumSupportedMotors;
    stableCheckpointCount = stableCheckpointCount+stable;
    if episode == 200
        agent200Stable = stable;
    end
end

acceptance = rows(rows.checkpointEpisode == 200 & ...
    rows.source == "acceptance" & ...
    rows.pairMode == "crossEpisode", :);
steadyRest = rows(rows.checkpointEpisode == 200 & ...
    rows.source == "steadyRest" & ...
    rows.pairMode == "crossEpisode", :);
acceptancePositiveMotorCount = sum(acceptance.incrementalR2 > 0);
steadyRestPositiveMotorCount = sum(steadyRest.incrementalR2 > 0);
sourcePassed = ~requireSources || ...
    (acceptancePositiveMotorCount >= options.minimumSupportedMotors && ...
    steadyRestPositiveMotorCount >= options.minimumSupportedMotors);
candidatePassed = crossPrimaryMotorCount >= ...
    options.minimumSupportedMotors && withinPrimaryMotorCount >= ...
    options.minimumSupportedMotors && permutationMotorCount >= ...
    options.minimumSupportedMotors && stableCheckpointCount >= ...
    options.minimumStableCheckpoints && agent200Stable && sourcePassed;

audit = table(string(family), crossPrimaryMotorCount, ...
    withinPrimaryMotorCount, permutationMotorCount, ...
    stableCheckpointCount, agent200Stable, ...
    acceptancePositiveMotorCount, steadyRestPositiveMotorCount, ...
    sourcePassed, candidatePassed, ...
    'VariableNames', ["family", "crossPrimaryMotorCount", ...
    "withinPrimaryMotorCount", "permutationMotorCount", ...
    "stableCheckpointCount", "agent200Stable", ...
    "acceptancePositiveMotorCount", ...
    "steadyRestPositiveMotorCount", "sourcePassed", ...
    "candidatePassed"]);
end
