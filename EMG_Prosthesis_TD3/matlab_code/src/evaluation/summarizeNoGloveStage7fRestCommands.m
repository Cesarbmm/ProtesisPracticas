function summary = summarizeNoGloveStage7fRestCommands(episodeDirectory)
%summarizeNoGloveStage7fRestCommands measures policy commands in steady rest.

arguments
    episodeDirectory (1, 1) string
end

files = dir(fullfile(episodeDirectory, "episode*.mat"));
if isempty(files)
    error("summarizeNoGloveStage7fRestCommands:NoEpisodes", ...
        "No episode files found in %s.", episodeDirectory);
end
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
pwmParts = cell(numel(files), 1);
effectiveParts = cell(numel(files), 1);
windowActiveParts = cell(numel(files), 1);
for fileIdx = 1:numel(files)
    path = fullfile(files(fileIdx).folder, files(fileIdx).name);
    data = load(path, "stateLog", "actionPwmLog", "actionSatLog");
    if ~all(isfield(data, cellstr( ...
            ["stateLog", "actionPwmLog", "actionSatLog"])))
        error("summarizeNoGloveStage7fRestCommands:MissingField", ...
            "Episode %s does not contain the required action logs.", path);
    end
    state = double(data.stateLog);
    pwm = double(data.actionPwmLog);
    effective = double(data.actionSatLog);
    if size(state, 2) ~= layout.totalLength || ...
            ~isequal(size(pwm), size(effective)) || ...
            size(pwm, 1) ~= size(state, 1) || size(pwm, 2) ~= 4 || ...
            any(~isfinite([state(:); pwm(:); effective(:)]))
        error("summarizeNoGloveStage7fRestCommands:InvalidEpisode", ...
            "Episode %s has invalid or misaligned arrays.", path);
    end
    if any(abs(state(:, layout.referenceVelocity)) > 1e-12, "all") || ...
            any(abs(diff(state(:, layout.referencePosition), 1, 1)) > ...
            1e-12, "all")
        error("summarizeNoGloveStage7fRestCommands:NonRestReference", ...
            "Episode %s does not keep a causal zero-velocity reference.", path);
    end
    pwmParts{fileIdx} = pwm;
    effectiveParts{fileIdx} = effective;
    windowActiveParts{fileIdx} = any(abs(pwm) > 0, 2);
end
pwm = vertcat(pwmParts{:});
effective = vertcat(effectiveParts{:});
windowActive = vertcat(windowActiveParts{:});
active = abs(pwm) > 0;
saturated = abs(effective) >= 0.95;
summary = struct( ...
    "episodeCount", numel(files), "windowCount", size(pwm, 1), ...
    "componentCount", numel(pwm), "allFinite", true, ...
    "commandActiveFraction", mean(active, "all"), ...
    "windowAnyCommandFraction", mean(windowActive), ...
    "meanAbsPwm", mean(abs(pwm), "all"), ...
    "saturationFraction", mean(saturated, "all"), ...
    "commandActiveFractionByMotor", mean(active, 1), ...
    "meanAbsPwmByMotor", mean(abs(pwm), 1), ...
    "saturationFractionByMotor", mean(saturated, 1));
end
