function analysis = analyzeNoGloveStage7oBitEffects( ...
        effects, gradients, options)
%analyzeNoGloveStage7oBitEffects summarizes and classifies frozen actors.

arguments
    effects table
    gradients table
    options.primaryEpisode (1, 1) double ...
        {mustBeInteger, mustBePositive} = 200
    options.rawTolerance (1, 1) double {mustBeNonnegative} = 1e-6
    options.dominanceMargin (1, 1) double ...
        {mustBeInRange(options.dominanceMargin, 0, 1)} = 0.05
end

requiredEffects = ["checkpointEpisode", "primary", "context", ...
    "motor", "contrast", "causalValid", "classificationEligible", ...
    "deltaRaw", "deltaAbsRaw", "deltaAbsPwm", "rawChanged", ...
    "rawMagnitudeReduced", "rawMagnitudeIncreased", "pwmChanged", ...
    "quantizationLevelChanged", "zeroTo64", "sixtyFourToZero", ...
    "saturationEntry", "saturationExit", "beneficialPwm", "adversePwm"];
requiredGradients = ["checkpointEpisode", "context", "motor", ...
    "bit", "gradient"];
if ~all(ismember(requiredEffects, ...
        string(effects.Properties.VariableNames))) || ...
        ~all(ismember(requiredGradients, ...
        string(gradients.Properties.VariableNames)))
    error("analyzeNoGloveStage7oBitEffects:MissingColumn", ...
        "Effects or gradients do not satisfy the ETAPA 7O contract.");
end
if any(~isfinite(effects.deltaRaw)) || ...
        any(~isfinite(gradients.gradient))
    error("analyzeNoGloveStage7oBitEffects:Nonfinite", ...
        "Counterfactual metrics must be finite.");
end

summary = buildEffectSummary(effects);
overall = buildOverallSummary(effects);
gradientSummary = buildGradientSummary(gradients);
primaryEffects = effects( ...
    effects.checkpointEpisode == options.primaryEpisode & ...
    effects.classificationEligible, :);
primaryGradients = gradients( ...
    gradients.checkpointEpisode == options.primaryEpisode & ...
    gradients.context ~= "uncategorized", :);
if isempty(primaryEffects) || isempty(primaryGradients)
    error("analyzeNoGloveStage7oBitEffects:EmptyPrimary", ...
        "Primary causal rows are required for classification.");
end
cells = summary( ...
    summary.checkpointEpisode == options.primaryEpisode & ...
    summary.causalValid & summary.context ~= "uncategorized", :);
macroNetBenefit = mean(cells.netBenefit);
rawSensitive = any(abs(primaryEffects.deltaRaw) > ...
    options.rawTolerance) || any(abs(primaryGradients.gradient) > ...
    options.rawTolerance);
pwmSensitive = any(primaryEffects.pwmChanged);
positiveCellCount = sum(cells.netBenefit >= options.dominanceMargin);
negativeCellCount = sum(cells.netBenefit <= -options.dominanceMargin);
classification = classify(rawSensitive, pwmSensitive, ...
    macroNetBenefit, positiveCellCount, negativeCellCount, ...
    options.dominanceMargin);
recommendation = recommendationFor(classification);

primaryContrasts = overall( ...
    overall.checkpointEpisode == options.primaryEpisode & ...
    overall.causalValid, :);
classificationAudit = table(rawSensitive, pwmSensitive, ...
    macroNetBenefit, positiveCellCount, negativeCellCount, ...
    options.dominanceMargin, classification, recommendation);
analysis = struct( ...
    "schemaVersion", 1, "stage", "7O", ...
    "primaryEpisode", options.primaryEpisode, ...
    "classification", classification, ...
    "recommendation", recommendation, ...
    "effectSummary", summary, "overallSummary", overall, ...
    "gradientSummary", gradientSummary, ...
    "primaryContrasts", primaryContrasts, ...
    "classificationAudit", classificationAudit, ...
    "rawSensitive", rawSensitive, "pwmSensitive", pwmSensitive, ...
    "macroNetBenefit", macroNetBenefit, ...
    "positiveCellCount", positiveCellCount, ...
    "negativeCellCount", negativeCellCount, ...
    "thresholds", struct("rawTolerance", options.rawTolerance, ...
        "dominanceMargin", options.dominanceMargin), ...
    "oodIncludedInClassification", false, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "hardwareUsed", false, ...
    "pilotAuthorized", false, "campaignAuthorized", false);
end

function summary = buildEffectSummary(effects)
episodes = unique(effects.checkpointEpisode, "sorted");
contrasts = unique(effects.contrast, "stable");
contexts = unique(effects.context, "stable");
rows = cell(numel(episodes)*numel(contrasts)*numel(contexts)*4, 1);
cursor = 0;
for episode = episodes'
    for contrast = contrasts'
        for context = contexts'
            for motor = 1:4
                mask = effects.checkpointEpisode == episode & ...
                    effects.contrast == contrast & ...
                    effects.context == context & effects.motor == motor;
                if ~any(mask)
                    continue;
                end
                cursor = cursor+1;
                rows{cursor} = effectRow(effects(mask, :), ...
                    episode, contrast, context, motor);
            end
        end
    end
end
summary = vertcat(rows{1:cursor});
end

function overall = buildOverallSummary(effects)
episodes = unique(effects.checkpointEpisode, "sorted");
contrasts = unique(effects.contrast, "stable");
rows = cell(numel(episodes)*numel(contrasts), 1);
cursor = 0;
for episode = episodes'
    for contrast = contrasts'
        mask = effects.checkpointEpisode == episode & ...
            effects.contrast == contrast & ...
            effects.context ~= "uncategorized";
        if ~any(mask)
            continue;
        end
        cursor = cursor+1;
        rows{cursor} = effectRow(effects(mask, :), ...
            episode, contrast, "ALL", 0);
    end
end
overall = vertcat(rows{1:cursor});
end

function row = effectRow(values, episode, contrast, context, motor)
causalValid = all(values.causalValid);
beneficialFraction = mean(values.beneficialPwm);
adverseFraction = mean(values.adversePwm);
row = table(episode, episode == 200, contrast, causalValid, context, ...
    motor, height(values), mean(values.deltaRaw), ...
    mean(abs(values.deltaRaw)), max(abs(values.deltaRaw)), ...
    mean(values.deltaAbsRaw), mean(values.deltaAbsPwm), ...
    mean(values.rawChanged), mean(values.rawMagnitudeReduced), ...
    mean(values.rawMagnitudeIncreased), mean(values.pwmChanged), ...
    mean(values.quantizationLevelChanged), mean(values.zeroTo64), ...
    mean(values.sixtyFourToZero), mean(values.saturationEntry), ...
    mean(values.saturationExit), beneficialFraction, adverseFraction, ...
    beneficialFraction-adverseFraction, ...
    'VariableNames', ["checkpointEpisode", "primary", "contrast", ...
    "causalValid", "context", "motor", "sampleCount", ...
    "meanDeltaRaw", "meanAbsDeltaRaw", "maxAbsDeltaRaw", ...
    "meanDeltaAbsRaw", "meanDeltaAbsPwm", "rawChangedFraction", ...
    "rawMagnitudeReducedFraction", "rawMagnitudeIncreasedFraction", ...
    "pwmChangedFraction", "quantizationLevelChangedFraction", ...
    "zeroTo64Fraction", "sixtyFourToZeroFraction", ...
    "saturationEntryFraction", "saturationExitFraction", ...
    "beneficialPwmFraction", "adversePwmFraction", "netBenefit"]);
end

function summary = buildGradientSummary(gradients)
episodes = unique(gradients.checkpointEpisode, "sorted");
contexts = unique(gradients.context, "stable");
bits = unique(gradients.bit, "stable");
rows = cell(numel(episodes)*numel(contexts)*numel(bits)*4, 1);
cursor = 0;
for episode = episodes'
    for context = contexts'
        for bit = bits'
            for motor = 1:4
                mask = gradients.checkpointEpisode == episode & ...
                    gradients.context == context & ...
                    gradients.bit == bit & gradients.motor == motor;
                if ~any(mask)
                    continue;
                end
                values = gradients.gradient(mask);
                cursor = cursor+1;
                rows{cursor} = table(episode, episode == 200, context, ...
                    motor, bit, numel(values), mean(values), ...
                    mean(abs(values)), max(abs(values)), ...
                    mean(values > 0), mean(values < 0), ...
                    'VariableNames', ["checkpointEpisode", "primary", ...
                    "context", "motor", "bit", "sampleCount", ...
                    "meanGradient", "meanAbsGradient", ...
                    "maxAbsGradient", "positiveFraction", ...
                    "negativeFraction"]);
            end
        end
    end
end
summary = vertcat(rows{1:cursor});
end

function label = classify(rawSensitive, pwmSensitive, macro, ...
        positiveCount, negativeCount, margin)
if ~rawSensitive
    label = "bitsIgnored";
elseif ~pwmSensitive
    label = "bitsRawOnly";
elseif macro >= margin && negativeCount == 0
    label = "bitsBeneficial";
elseif macro <= -margin && positiveCount == 0
    label = "bitsAdversarial";
else
    label = "bitsContextDependent";
end
end

function recommendation = recommendationFor(classification)
switch classification
    case {"bitsIgnored", "bitsRawOnly", "bitsAdversarial"}
        recommendation = "discardState62ReturnToIntentMarkov60";
    case "bitsBeneficial"
        recommendation = "proposeNewBounded200EpisodeSmokeOnly";
    otherwise
        recommendation = ...
            "holdTrainingReturnProvisionallyToIntentMarkov60";
end
end
