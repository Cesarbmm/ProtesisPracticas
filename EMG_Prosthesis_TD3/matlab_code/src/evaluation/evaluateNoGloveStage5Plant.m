function results = evaluateNoGloveStage5Plant(configs)
%evaluateNoGloveStage5Plant measures the unchanged simulator and P baseline.
%
% The evaluation is deterministic and simulation-only. It does not create
% Env, read EMG, load an agent, train RL or access Controller hardware.

validateEffectiveConfig(configs);
diagnostic = configs.plantDiagnostic;
encoderScale = resolveEncoderScale(configs);
actuator = struct( ...
    "maxPwm", max(abs(double(configs.speeds))), ...
    "activationThreshold", configs.actionCommandActivationThreshold, ...
    "commandLevels", configs.actionCommandLevels);

[openLoopTrials, openLoopTraces] = runOpenLoopSweeps( ...
    configs, diagnostic, actuator, encoderScale);
plantByCondition = summarizeOpenLoopConditions(openLoopTrials);
plantByMotor = summarizeOpenLoopMotors(openLoopTrials);

[baselineScenarios, baselineTraces] = runClosedLoopScenarios( ...
    configs, diagnostic, actuator, encoderScale);
baselineByMotor = summarizeClosedLoopMotors(baselineScenarios);

results = struct( ...
    "schemaVersion", 1, ...
    "openLoopTrials", openLoopTrials, ...
    "plantByCondition", plantByCondition, ...
    "plantByMotor", plantByMotor, ...
    "openLoopTraces", {openLoopTraces}, ...
    "baselineScenarios", baselineScenarios, ...
    "baselineByMotor", baselineByMotor, ...
    "baselineTraces", {baselineTraces}, ...
    "encoderScale", encoderScale, ...
    "controller", configs.conventionalController, ...
    "diagnostic", diagnostic, ...
    "simulatorUsed", true, ...
    "hardwareUsed", false, ...
    "reinforcementLearningUsed", false);
end

function [trialTable, traces] = runOpenLoopSweeps( ...
        configs, diagnostic, actuator, encoderScale)
modeNames = string(diagnostic.initialModes(:));
pwmLevels = double(diagnostic.pwmLevels(:)');
directions = [-1, 1];
numTrials = numel(modeNames) * 4 * numel(directions) * numel(pwmLevels);
rows = cell(numTrials, 1);
traces = cell(numTrials, 1);
rowIdx = 0;

for modeIdx = 1:numel(modeNames)
    modeName = modeNames(modeIdx);
    initialQ = initialPositionForMode(modeName);
    initialEncoder = initialQ .* encoderScale;
    for motorIdx = 1:4
        for direction = directions
            for levelIdx = 1:numel(pwmLevels)
                rowIdx = rowIdx + 1;
                rawAction = zeros(4, 1);
                rawAction(motorIdx) = direction * ...
                    pwmLevels(levelIdx) / actuator.maxPwm;
                [effectiveAction, appliedPwm] = quantizeBaselineAction( ...
                    rawAction, actuator.maxPwm, ...
                    actuator.activationThreshold, actuator.commandLevels);
                generated = SimController.prosthesis_simulator( ...
                    initialEncoder, appliedPwm(:)', ...
                    diagnostic.stepDuration, ...
                    diagnostic.simulatorSamplingPeriod);
                encoderTrace = [initialEncoder; generated];
                numIntervals = size(generated, 1);
                samplePeriod = diagnostic.stepDuration / numIntervals;
                time = (0:numIntervals)' .* samplePeriod;
                qTrace = encoderTrace ./ encoderScale;
                [flexNorm, finishEpisode, implementationMaxAbs] = ...
                    evaluateEncoder2Flex(encoderTrace, configs);

                motorDelta = qTrace(:, motorIdx) - initialQ(motorIdx);
                movementMask = abs(motorDelta) > ...
                    diagnostic.movementThresholdNormalized;
                movementDetected = any(movementMask);
                if movementDetected
                    firstMovementIdx = find(movementMask, 1, "first");
                    timeDeadSec = time(firstMovementIdx);
                else
                    timeDeadSec = NaN;
                end
                finalEncoderDelta = encoderTrace(end, motorIdx) - ...
                    initialEncoder(motorIdx);
                finalNormalizedDelta = motorDelta(end);
                targetPwm = appliedPwm(motorIdx);
                targetAction = effectiveAction(motorIdx);
                gainCountsPerPwm = finalEncoderDelta / targetPwm;
                gainNormalizedPerAction = finalNormalizedDelta / targetAction;
                encoderVelocity = diff(encoderTrace(:, motorIdx)) ./ samplePeriod;
                normalizedVelocity = diff(qTrace(:, motorIdx)) ./ samplePeriod;
                otherMotors = setdiff(1:4, motorIdx);
                crossMotorMax = max(abs(qTrace(:, otherMotors) - ...
                    initialQ(otherMotors)), [], "all");
                mappingError = flexNorm - qTrace;
                targetMappingRmse = sqrt(mean( ...
                    mappingError(:, motorIdx).^2));
                qMin = diagnostic.positionMin(motorIdx);
                qMax = diagnostic.positionMax(motorIdx);
                targetQ = qTrace(:, motorIdx);
                outputLimitFraction = mean(targetQ <= qMin + 1e-12 | ...
                    targetQ >= qMax - 1e-12);
                positionViolationFraction = mean(targetQ < qMin - 1e-12 | ...
                    targetQ > qMax + 1e-12);
                directionConsistent = ~movementDetected || ...
                    direction * finalNormalizedDelta > 0;

                rows{rowIdx} = struct( ...
                    "trial", rowIdx, ...
                    "initialMode", modeName, ...
                    "motor", motorIdx, ...
                    "direction", direction, ...
                    "requestedPwmMagnitude", pwmLevels(levelIdx), ...
                    "rawAction", rawAction(motorIdx), ...
                    "effectiveAction", targetAction, ...
                    "appliedPwm", targetPwm, ...
                    "samplePeriodSec", samplePeriod, ...
                    "movementDetected", movementDetected, ...
                    "timeDeadSec", timeDeadSec, ...
                    "finalEncoderDelta", finalEncoderDelta, ...
                    "finalNormalizedDelta", finalNormalizedDelta, ...
                    "gainCountsPerPwm", gainCountsPerPwm, ...
                    "gainNormalizedPerAction", gainNormalizedPerAction, ...
                    "maxEncoderSpeedPerSec", max(abs(encoderVelocity)), ...
                    "maxNormalizedSpeedPerSec", max(abs(normalizedVelocity)), ...
                    "commandSaturation", abs(targetAction) >= 0.95, ...
                    "outputLimitFraction", outputLimitFraction, ...
                    "positionViolationFraction", positionViolationFraction, ...
                    "directionConsistent", directionConsistent, ...
                    "encoder2FlexMappingRmse", targetMappingRmse, ...
                    "encoder2FlexImplementationMaxAbs", implementationMaxAbs, ...
                    "encoder2FlexFinishEpisode", finishEpisode, ...
                    "crossMotorMaxNormalizedDelta", crossMotorMax, ...
                    "traceIndex", rowIdx);
                traces{rowIdx} = struct( ...
                    "trial", rowIdx, ...
                    "initialMode", modeName, ...
                    "motor", motorIdx, ...
                    "direction", direction, ...
                    "appliedPwm", targetPwm, ...
                    "time", time, ...
                    "encoder", encoderTrace, ...
                    "normalizedEncoder", qTrace, ...
                    "normalizedFlex", flexNorm);
            end
        end
    end
end
trialTable = struct2table(vertcat(rows{:}));
end

function summary = summarizeOpenLoopConditions(trials)
keys = unique(trials(:, ["initialMode", "motor", "direction"]), ...
    "rows", "stable");
rows = cell(height(keys), 1);
for idx = 1:height(keys)
    subset = trials(trials.initialMode == keys.initialMode(idx) & ...
        trials.motor == keys.motor(idx) & ...
        trials.direction == keys.direction(idx), :);
    moving = subset(subset.movementDetected, :);
    if isempty(moving)
        deadzonePwm = NaN;
        timeDeadMean = NaN;
    else
        deadzonePwm = min(abs(moving.appliedPwm));
        timeDeadMean = mean(moving.timeDeadSec, "omitnan");
    end
    rows{idx} = struct( ...
        "initialMode", keys.initialMode(idx), ...
        "motor", keys.motor(idx), ...
        "direction", keys.direction(idx), ...
        "deadzonePwm", deadzonePwm, ...
        "timeDeadMeanSec", timeDeadMean, ...
        "gainCountsPerPwmMean", mean(subset.gainCountsPerPwm), ...
        "gainNormalizedPerActionMean", ...
            mean(subset.gainNormalizedPerAction), ...
        "maxEncoderSpeedPerSec", max(subset.maxEncoderSpeedPerSec), ...
        "maxNormalizedSpeedPerSec", max(subset.maxNormalizedSpeedPerSec), ...
        "directionConsistencyFraction", mean(subset.directionConsistent), ...
        "commandSaturationFraction", mean(subset.commandSaturation), ...
        "outputLimitFractionMean", mean(subset.outputLimitFraction), ...
        "positionViolationFractionMean", ...
            mean(subset.positionViolationFraction), ...
        "encoder2FlexMappingRmseMean", ...
            mean(subset.encoder2FlexMappingRmse), ...
        "encoder2FlexImplementationMaxAbs", ...
            max(subset.encoder2FlexImplementationMaxAbs), ...
        "crossMotorMaxNormalizedDelta", ...
            max(subset.crossMotorMaxNormalizedDelta));
end
summary = struct2table(vertcat(rows{:}));
end

function summary = summarizeOpenLoopMotors(trials)
rows = cell(4, 1);
for motorIdx = 1:4
    subset = trials(trials.motor == motorIdx, :);
    rows{motorIdx} = struct( ...
        "motor", motorIdx, ...
        "deadzonePositiveHomePwm", conditionDeadzone( ...
            subset, "home", 1), ...
        "deadzoneNegativeHomePwm", conditionDeadzone( ...
            subset, "home", -1), ...
        "deadzonePositiveIntermediatePwm", conditionDeadzone( ...
            subset, "intermediate", 1), ...
        "deadzoneNegativeIntermediatePwm", conditionDeadzone( ...
            subset, "intermediate", -1), ...
        "timeDeadMeanSec", mean(subset.timeDeadSec, "omitnan"), ...
        "gainPositiveIntermediate", conditionMean( ...
            subset, "intermediate", 1, "gainNormalizedPerAction"), ...
        "gainNegativeIntermediate", conditionMean( ...
            subset, "intermediate", -1, "gainNormalizedPerAction"), ...
        "maxNormalizedSpeedPerSec", max(subset.maxNormalizedSpeedPerSec), ...
        "directionConsistencyFraction", mean(subset.directionConsistent), ...
        "commandSaturationFraction", mean(subset.commandSaturation), ...
        "positionViolationFractionMean", ...
            mean(subset.positionViolationFraction), ...
        "encoder2FlexMappingRmseMean", ...
            mean(subset.encoder2FlexMappingRmse), ...
        "encoder2FlexImplementationMaxAbs", ...
            max(subset.encoder2FlexImplementationMaxAbs), ...
        "crossMotorMaxNormalizedDelta", ...
            max(subset.crossMotorMaxNormalizedDelta));
end
summary = struct2table(vertcat(rows{:}));
end

function value = conditionDeadzone(tableValue, modeName, direction)
subset = tableValue(tableValue.initialMode == modeName & ...
    tableValue.direction == direction & tableValue.movementDetected, :);
if isempty(subset)
    value = NaN;
else
    value = min(abs(subset.appliedPwm));
end
end

function value = conditionMean(tableValue, modeName, direction, fieldName)
subset = tableValue(tableValue.initialMode == modeName & ...
    tableValue.direction == direction, :);
value = mean(subset.(fieldName), "omitnan");
end

function [scenarioTable, traces] = runClosedLoopScenarios( ...
        configs, diagnostic, actuator, encoderScale)
modeNames = string(diagnostic.initialModes(:));
profileNames = ["step", "ramp"];
directions = [-1, 1];
numScenarios = numel(modeNames) * 4 * numel(profileNames) * ...
    numel(directions);
rows = cell(numScenarios, 1);
traces = cell(numScenarios, 1);
rowIdx = 0;
dt = double(configs.period);
numSteps = round(diagnostic.closedLoopDuration / dt);

for modeIdx = 1:numel(modeNames)
    modeName = modeNames(modeIdx);
    initialQ = initialPositionForMode(modeName);
    for motorIdx = 1:4
        for profileIdx = 1:numel(profileNames)
            profileName = profileNames(profileIdx);
            for direction = directions
                rowIdx = rowIdx + 1;
                qReference = buildReference( ...
                    initialQ, motorIdx, profileName, direction, ...
                    numSteps, dt, diagnostic);
                trace = simulateClosedLoop( ...
                    initialQ, qReference, configs, actuator, ...
                    encoderScale, diagnostic);
                qResponse = trace.normalizedEncoder(2:end, :);
                targetError = qResponse(:, motorIdx) - ...
                    qReference(:, motorIdx);
                targetMotion = qResponse(:, motorIdx) - initialQ(motorIdx);
                referenceExcursion = max(abs( ...
                    qReference(:, motorIdx) - initialQ(motorIdx)));
                isDegenerate = referenceExcursion <= ...
                    diagnostic.movementThresholdNormalized;
                movementMask = abs(targetMotion) > ...
                    diagnostic.movementThresholdNormalized;
                movementDetected = any(movementMask);
                if movementDetected
                    timeDeadSec = find(movementMask, 1, "first") * dt;
                else
                    timeDeadSec = NaN;
                end
                directionalProgress = direction * targetMotion(end);
                noMotionFlag = ~isDegenerate && ~movementDetected;
                wrongDirectionFlag = ~isDegenerate && movementDetected && ...
                    directionalProgress <= 0;
                otherMotors = setdiff(1:4, motorIdx);
                crossMotorMax = max(abs(qResponse(:, otherMotors) - ...
                    initialQ(otherMotors)), [], "all");
                crossMotorFlag = crossMotorMax > ...
                    diagnostic.movementThresholdNormalized;
                positionViolationFlag = any(qResponse < ...
                    diagnostic.positionMin - 1e-12 | qResponse > ...
                    diagnostic.positionMax + 1e-12, "all");
                deltaAction = diff([zeros(1, 4); trace.effectiveAction], ...
                    1, 1);
                mappingError = trace.normalizedFlex(2:end, :) - qResponse;

                rows{rowIdx} = struct( ...
                    "scenario", rowIdx, ...
                    "initialMode", modeName, ...
                    "profile", profileName, ...
                    "motor", motorIdx, ...
                    "direction", direction, ...
                    "referenceExcursion", referenceExcursion, ...
                    "isDegenerateAtPositionLimit", isDegenerate, ...
                    "movementDetected", movementDetected, ...
                    "timeDeadSec", timeDeadSec, ...
                    "trackingMse", mean(targetError.^2), ...
                    "trackingMae", mean(abs(targetError)), ...
                    "finalAbsoluteError", abs(targetError(end)), ...
                    "directionalProgress", directionalProgress, ...
                    "maxNormalizedSpeedPerSec", max(abs( ...
                        diff(trace.normalizedEncoder(:, motorIdx)) ./ dt)), ...
                    "actionL2", mean(trace.effectiveAction.^2, "all"), ...
                    "deltaActionL2", mean(deltaAction.^2, "all"), ...
                    "saturationFraction", mean(abs( ...
                        trace.effectiveAction) >= 0.95, "all"), ...
                    "crossMotorMaxNormalizedDelta", crossMotorMax, ...
                    "encoder2FlexMappingRmse", sqrt(mean( ...
                        mappingError(:, motorIdx).^2)), ...
                    "encoder2FlexImplementationMaxAbs", ...
                        trace.encoder2FlexImplementationMaxAbs, ...
                    "noMotionFlag", noMotionFlag, ...
                    "wrongDirectionFlag", wrongDirectionFlag, ...
                    "crossMotorRegressionFlag", crossMotorFlag, ...
                    "positionViolationFlag", positionViolationFlag, ...
                    "functionalFlag", noMotionFlag || wrongDirectionFlag || ...
                        crossMotorFlag || positionViolationFlag, ...
                    "traceIndex", rowIdx);
                trace.scenario = rowIdx;
                trace.initialMode = modeName;
                trace.profile = profileName;
                trace.motor = motorIdx;
                trace.direction = direction;
                traces{rowIdx} = trace;
            end
        end
    end
end
scenarioTable = struct2table(vertcat(rows{:}));
end

function reference = buildReference(initialQ, motorIdx, profileName, ...
        direction, numSteps, dt, diagnostic)
reference = repmat(initialQ, numSteps, 1);
switch profileName
    case "step"
        displacement = diagnostic.referenceStepAmplitude * ...
            ones(numSteps, 1);
    case "ramp"
        displacement = min(diagnostic.referenceStepAmplitude, ...
            (1:numSteps)' .* dt .* diagnostic.referenceRampRate);
    otherwise
        error("evaluateNoGloveStage5Plant:InvalidReferenceProfile", ...
            "Unsupported reference profile %s.", profileName);
end
reference(:, motorIdx) = min(diagnostic.positionMax(motorIdx), ...
    max(diagnostic.positionMin(motorIdx), ...
    initialQ(motorIdx) + direction .* displacement));
end

function trace = simulateClosedLoop(initialQ, qReference, configs, ...
        actuator, encoderScale, diagnostic)
numSteps = size(qReference, 1);
dt = double(configs.period);
encoder = initialQ .* encoderScale;
previousQ = initialQ;
previousReference = initialQ;
encoderLog = nan(numSteps + 1, 4);
qLog = nan(numSteps + 1, 4);
rawActionLog = nan(numSteps, 4);
effectiveActionLog = nan(numSteps, 4);
pwmLog = nan(numSteps, 4);
encoderLog(1, :) = encoder;
qLog(1, :) = initialQ;

for stepIdx = 1:numSteps
    currentQ = encoder ./ encoderScale;
    currentVelocity = (currentQ - previousQ) ./ dt;
    referenceVelocity = (qReference(stepIdx, :) - ...
        previousReference) ./ dt;
    [rawAction, effectiveAction, appliedPwm] = ...
        quantizedIntentPdController( ...
        qReference(stepIdx, :), currentQ, referenceVelocity, ...
        currentVelocity, configs.conventionalController, actuator);
    generated = SimController.prosthesis_simulator( ...
        encoder, appliedPwm(:)', dt, ...
        diagnostic.simulatorSamplingPeriod);
    previousQ = currentQ;
    previousReference = qReference(stepIdx, :);
    encoder = generated(end, :);
    encoderLog(stepIdx + 1, :) = encoder;
    qLog(stepIdx + 1, :) = encoder ./ encoderScale;
    rawActionLog(stepIdx, :) = rawAction(:)';
    effectiveActionLog(stepIdx, :) = effectiveAction(:)';
    pwmLog(stepIdx, :) = appliedPwm(:)';
end
[flexNorm, ~, implementationMaxAbs] = ...
    evaluateEncoder2Flex(encoderLog, configs);
trace = struct( ...
    "time", (0:numSteps)' .* dt, ...
    "qReference", qReference, ...
    "encoder", encoderLog, ...
    "normalizedEncoder", qLog, ...
    "normalizedFlex", flexNorm, ...
    "rawAction", rawActionLog, ...
    "effectiveAction", effectiveActionLog, ...
    "appliedPwm", pwmLog, ...
    "encoder2FlexImplementationMaxAbs", implementationMaxAbs);
end

function summary = summarizeClosedLoopMotors(scenarios)
rows = cell(4, 1);
for motorIdx = 1:4
    subset = scenarios(scenarios.motor == motorIdx, :);
    nondegenerate = subset(~subset.isDegenerateAtPositionLimit, :);
    stepRows = nondegenerate(nondegenerate.profile == "step", :);
    rampRows = nondegenerate(nondegenerate.profile == "ramp", :);
    rows{motorIdx} = struct( ...
        "motor", motorIdx, ...
        "scenarioCount", height(subset), ...
        "nondegenerateScenarioCount", height(nondegenerate), ...
        "trackingMseMean", mean(nondegenerate.trackingMse), ...
        "trackingMaeMean", mean(nondegenerate.trackingMae), ...
        "stepTrackingMseMean", mean(stepRows.trackingMse), ...
        "rampTrackingMseMean", mean(rampRows.trackingMse), ...
        "finalAbsoluteErrorMean", mean(nondegenerate.finalAbsoluteError), ...
        "actionL2Mean", mean(nondegenerate.actionL2), ...
        "deltaActionL2Mean", mean(nondegenerate.deltaActionL2), ...
        "saturationFractionMean", mean(nondegenerate.saturationFraction), ...
        "timeDeadMeanSec", mean(nondegenerate.timeDeadSec, "omitnan"), ...
        "maxNormalizedSpeedPerSec", ...
            max(nondegenerate.maxNormalizedSpeedPerSec), ...
        "noMotionFlagCount", sum(nondegenerate.noMotionFlag), ...
        "wrongDirectionFlagCount", ...
            sum(nondegenerate.wrongDirectionFlag), ...
        "crossMotorRegressionFlagCount", ...
            sum(nondegenerate.crossMotorRegressionFlag), ...
        "positionViolationFlagCount", ...
            sum(nondegenerate.positionViolationFlag), ...
        "functionalFlagCount", sum(nondegenerate.functionalFlag), ...
        "encoder2FlexMappingRmseMean", ...
            mean(nondegenerate.encoder2FlexMappingRmse), ...
        "encoder2FlexImplementationMaxAbs", ...
            max(nondegenerate.encoder2FlexImplementationMaxAbs), ...
        "crossMotorMaxNormalizedDelta", ...
            max(nondegenerate.crossMotorMaxNormalizedDelta));
end
summary = struct2table(vertcat(rows{:}));
end

function [normalizedFlex, finishEpisode, implementationMaxAbs] = ...
        evaluateEncoder2Flex(encoderTrace, configs)
[converted, finishEpisode] = encoder2Flex(encoderTrace);
normalizedFlex = configs.flexJoined_scale(converted);
independent = independentEncoder2Flex(encoderTrace);
independentNormalized = configs.flexJoined_scale(independent);
implementationMaxAbs = max(abs( ...
    normalizedFlex - independentNormalized), [], "all");
end

function converted = independentEncoder2Flex(encoderTrace)
fingers = definitions("fingers");
motorIdx = definitions("motorIdx");
gap = definitions("gap");
breakLimit = definitions("breakLimit");
flexLow = definitions("flex_low_lim");
flexMax = definitions("flex_max_lim");
converted = double(encoderTrace);
for fingerIdx = 1:numel(fingers)
    finger = fingers{fingerIdx};
    motor = motorIdx.(finger);
    x = abs(double(encoderTrace(:, motor)));
    y = nan(size(x));
    below = x < gap.(finger);
    linear = x >= gap.(finger) & x <= breakLimit.(finger);
    above = x > breakLimit.(finger);
    slope = (flexMax.(finger) - flexLow.(finger)) / ...
        (breakLimit.(finger) - gap.(finger));
    intercept = flexMax.(finger) - slope * breakLimit.(finger);
    y(below) = flexLow.(finger);
    y(linear) = slope .* x(linear) + intercept;
    y(above) = flexMax.(finger);
    converted(:, motor) = y;
end
end

function initialQ = initialPositionForMode(modeName)
switch string(modeName)
    case "home"
        initialQ = zeros(1, 4);
    case "intermediate"
        initialQ = 0.5 * ones(1, 4);
    otherwise
        error("evaluateNoGloveStage5Plant:InvalidInitialMode", ...
            "Unsupported initial mode %s.", modeName);
end
end

function encoderScale = resolveEncoderScale(configs)
unitNormalized = double(configs.encoder2state_scale(ones(4, 1)));
if numel(unitNormalized) ~= 4 || any(~isfinite(unitNormalized)) || ...
        any(unitNormalized <= 0)
    error("evaluateNoGloveStage5Plant:InvalidEncoderScale", ...
        "encoder2state_scale must expose four positive finite scales.");
end
encoderScale = (1 ./ unitNormalized(:))';
end

function validateEffectiveConfig(configs)
required = { ...
    'run_training', 'newTraining', 'simMotors', 'connect_glove', ...
    'usePrerecorded', 'referenceSource', 'observationVariant', ...
    'actionInterfaceVariant', 'quantizeCommandsForSimulation', ...
    'unifyActions', 'speeds', 'actionCommandActivationThreshold', ...
    'actionCommandLevels', 'encoder2state_scale', 'flexJoined_scale', ...
    'period', 'conventionalController', 'plantDiagnostic'};
if ~isstruct(configs) || ~isscalar(configs) || ...
        ~all(isfield(configs, required))
    error("evaluateNoGloveStage5Plant:IncompleteConfig", ...
        "Effective configuration is incomplete.");
end
unsafe = configs.run_training || configs.newTraining || ...
    ~configs.simMotors || configs.connect_glove || ~configs.usePrerecorded;
if unsafe || string(configs.referenceSource) ~= "emgIntent" || ...
        string(configs.observationVariant) ~= "intentMarkov60" || ...
        string(configs.actionInterfaceVariant) ~= "baselineQuantized" || ...
        ~configs.quantizeCommandsForSimulation || configs.unifyActions
    error("evaluateNoGloveStage5Plant:UnsafeConfig", ...
        "ETAPA 5 requires the simulation-only no-glove baseline profile.");
end
diagnostic = configs.plantDiagnostic;
requiredDiagnostic = { ...
    'initialModes', 'pwmLevels', 'stepDuration', ...
    'simulatorSamplingPeriod', 'movementThresholdNormalized', ...
    'referenceStepAmplitude', 'referenceRampRate', ...
    'closedLoopDuration', 'positionMin', 'positionMax'};
if ~isstruct(diagnostic) || ~isscalar(diagnostic) || ...
        ~all(isfield(diagnostic, requiredDiagnostic))
    error("evaluateNoGloveStage5Plant:InvalidDiagnosticConfig", ...
        "plantDiagnostic is incomplete.");
end
end
