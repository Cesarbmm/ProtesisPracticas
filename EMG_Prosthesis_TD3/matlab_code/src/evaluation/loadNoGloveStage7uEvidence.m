function data = loadNoGloveStage7uEvidence(options)
%loadNoGloveStage7uEvidence loads the two real-log cohorts for ETAPA 7U.
%
% No actor is loaded and no simulation is run. Both cohorts are real Env
% episode logs already saved by prior stages: the ETAPA 7S rest gate-stress
% corpus (reused via loadNoGloveStage7tEvidence, hash-validated) and the
% Agent200 acceptance-evaluation episodes from ETAPA 7N's checkpoint_200
% evaluation (structural validation: episode count, field contract, and an
% explicit check that repetitionId/state layout match the frozen intent
% pipeline). Nothing here modifies any of those files.

arguments
    options.stage7sRunRoot (1, 1) string = ...
        "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7s_artifacts\stage7s_final\2026-08-31_22-58-01-555"
    options.acceptanceEpisodeDirectory (1, 1) string = ...
        "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7n_artifacts\stage7n_corrected_final\2026-08-29_07-34-46-814\checkpoint_evaluations\control60\episode_200\acceptance\26-08-29 07 36 5"
end

restEvidence = loadNoGloveStage7tEvidence(options.stage7sRunRoot);

restFiles = restEvidence.restEpisodeInventory;
restGateActive = cell(height(restFiles), 1);
for idx = 1:height(restFiles)
    episodeData = load(restFiles.filePath(idx), "intentProvenanceLog");
    provenance = episodeData.intentProvenanceLog;
    nonEmpty = ~cellfun(@isempty, provenance);
    if sum(nonEmpty) ~= 20
        error("loadNoGloveStage7uEvidence:RestProvenanceLength", ...
            "Rest episode %d does not have 20 causal transitions.", ...
            restFiles.episode(idx));
    end
    restGateActive{idx} = cellfun(@(p) logical(p.gateActive), ...
        provenance(nonEmpty));
end

if ~isfolder(options.acceptanceEpisodeDirectory)
    error("loadNoGloveStage7uEvidence:AcceptanceDirectoryMissing", ...
        "Acceptance episode directory not found: %s", ...
        options.acceptanceEpisodeDirectory);
end
episodeFiles = dir(fullfile(options.acceptanceEpisodeDirectory, "episode*.mat"));
if isempty(episodeFiles)
    error("loadNoGloveStage7uEvidence:NoAcceptanceEpisodes", ...
        "No acceptance episode files found.");
end
[~, order] = sort({episodeFiles.name});
episodeFiles = episodeFiles(order);

requiredFields = ["rawActionLog", "effectiveActionLog", "appliedPwmLog", ...
    "intentProvenanceLog", "rewardInfoLog", "referenceHistory", ...
    "trackingPredictionHistory", "positionSafetyInterventionLog", ...
    "observationVariant", "stateLength"];
acceptanceEpisodes = repmat(struct( ...
    "episode", 0, "filePath", "", "stepCount", 0, ...
    "rawAction", [], "effectiveAction", [], "pwm", [], ...
    "gateActive", [], "trackingMse", [], "trackingMae", [], ...
    "referenceHistory", [], "trackingPredictionHistory", [], ...
    "safetyIntervention", []), numel(episodeFiles), 1);

for idx = 1:numel(episodeFiles)
    filePath = string(fullfile(episodeFiles(idx).folder, episodeFiles(idx).name));
    raw = load(filePath);
    if ~all(isfield(raw, cellstr(requiredFields))) || ...
            string(raw.observationVariant) ~= "intentMarkov60" || ...
            double(raw.stateLength) ~= 60
        error("loadNoGloveStage7uEvidence:AcceptanceContract", ...
            "Acceptance episode %s is not a state-60 emgIntent episode.", ...
            filePath);
    end
    stepCount = size(raw.rawActionLog, 1);
    provenance = raw.intentProvenanceLog(1:stepCount);
    nonEmpty = ~cellfun(@isempty, provenance);
    if ~all(nonEmpty)
        error("loadNoGloveStage7uEvidence:AcceptanceProvenanceGap", ...
            "Acceptance episode %s has an incomplete provenance log.", ...
            filePath);
    end
    gateActive = cellfun(@(p) logical(p.gateActive), provenance);
    trackingMse = cellfun(@(s) double(s.trackingMse), ...
        raw.rewardInfoLog(1:stepCount));
    trackingMae = cellfun(@(s) double(s.trackingMae), ...
        raw.rewardInfoLog(1:stepCount));
    acceptanceEpisodes(idx) = struct( ...
        "episode", idx, "filePath", filePath, "stepCount", stepCount, ...
        "rawAction", double(raw.rawActionLog(1:stepCount, :)), ...
        "effectiveAction", double(raw.effectiveActionLog(1:stepCount, :)), ...
        "pwm", double(raw.appliedPwmLog(1:stepCount, :)), ...
        "gateActive", gateActive(:), ...
        "trackingMse", trackingMse(:), "trackingMae", trackingMae(:), ...
        "referenceHistory", double(raw.referenceHistory(1:stepCount, :)), ...
        "trackingPredictionHistory", ...
            double(raw.trackingPredictionHistory(1:stepCount, :)), ...
        "safetyIntervention", ...
            double(raw.positionSafetyInterventionLog(1:stepCount, :)));
end

data = struct( ...
    "schemaVersion", 1, "stage", "7U", ...
    "restEvidence", restEvidence, "restGateActive", {restGateActive}, ...
    "acceptanceEpisodes", acceptanceEpisodes, ...
    "acceptanceEpisodeDirectory", options.acceptanceEpisodeDirectory, ...
    "actorLoaded", false, "actorRetrained", false, ...
    "environmentUsed", false, "simulationUsed", false, ...
    "trainingUsed", false, "hardwareUsed", false);
end
