function summary = summarizeNoGloveStage7hHoldReward( ...
        episodeDirectory, settings, options)
%summarizeNoGloveStage7hHoldReward audits causal hold reward diagnostics.

arguments
    episodeDirectory (1, 1) string
    settings (1, 1) struct
    options.requireSteadyRest (1, 1) logical = false
    options.tolerance (1, 1) double {mustBeNonnegative} = 1e-12
end

requiredSettings = ["actionWeight", "velocityTolerance", ...
    "positionMseTolerance"];
if ~all(isfield(settings, cellstr(requiredSettings)))
    error("summarizeNoGloveStage7hHoldReward:InvalidSettings", ...
        "Hold reward settings are incomplete.");
end
settingsValues = [settings.actionWeight, settings.velocityTolerance, ...
    settings.positionMseTolerance];
if any(~isfinite(settingsValues)) || any(settingsValues < 0)
    error("summarizeNoGloveStage7hHoldReward:InvalidSettings", ...
        "Hold reward settings must be finite and nonnegative.");
end

files = dir(fullfile(episodeDirectory, "episode*.mat"));
if isempty(files)
    error("summarizeNoGloveStage7hHoldReward:NoEpisodes", ...
        "No episode files found in %s.", episodeDirectory);
end
[~, order] = sort({files.name});
files = files(order);
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
holdActiveParts = cell(numel(files), 1);
holdPositionParts = cell(numel(files), 1);
holdVelocityParts = cell(numel(files), 1);
holdActionParts = cell(numel(files), 1);
holdPenaltyParts = cell(numel(files), 1);
pwmParts = cell(numel(files), 1);
maximumDiagnosticError = 0;
for fileIdx = 1:numel(files)
    path = fullfile(files(fileIdx).folder, files(fileIdx).name);
    data = load(path, "stateLog", "actionSatLog", "actionPwmLog", ...
        "rewardInfoLog", "referenceSource", "observationVariant");
    required = ["stateLog", "actionSatLog", "actionPwmLog", ...
        "rewardInfoLog", "referenceSource", "observationVariant"];
    if ~all(isfield(data, cellstr(required))) || ...
            string(data.referenceSource) ~= "emgIntent" || ...
            string(data.observationVariant) ~= "intentMarkov60"
        error("summarizeNoGloveStage7hHoldReward:EpisodeContract", ...
            "Episode %s violates the 7H no-glove contract.", path);
    end
    state = double(data.stateLog);
    action = double(data.actionSatLog);
    pwm = double(data.actionPwmLog);
    stepCount = size(state, 1);
    if size(state, 2) ~= layout.totalLength || ...
            ~isequal(size(action), size(pwm), [stepCount, 4]) || ...
            ~iscell(data.rewardInfoLog) || ...
            numel(data.rewardInfoLog) ~= stepCount || ...
            any(~isfinite([state(:); action(:); pwm(:)]))
        error("summarizeNoGloveStage7hHoldReward:EpisodeArrays", ...
            "Episode %s has invalid or misaligned arrays.", path);
    end
    if options.requireSteadyRest && ( ...
            any(abs(state(:, layout.referenceVelocity)) > ...
                settings.velocityTolerance, "all") || ...
            any(abs(diff(state(:, layout.referencePosition), 1, 1)) > ...
                options.tolerance, "all"))
        error("summarizeNoGloveStage7hHoldReward:NonRestReference", ...
            "Episode %s does not preserve steady rest.", path);
    end

    expectedPosition = mean((state(:, layout.encoder)- ...
        state(:, layout.referencePosition)).^2, 2);
    expectedVelocity = max(abs(state(:, layout.referenceVelocity)), [], 2);
    expectedActive = expectedVelocity <= settings.velocityTolerance & ...
        expectedPosition <= settings.positionMseTolerance;
    recordedActive = zeros(stepCount, 1);
    recordedPosition = zeros(stepCount, 1);
    recordedVelocity = zeros(stepCount, 1);
    recordedAction = zeros(stepCount, 1);
    recordedPenalty = zeros(stepCount, 1);
    for stepIdx = 1:stepCount
        info = data.rewardInfoLog{stepIdx};
        fields = ["holdActive", "holdPositionMse", ...
            "holdVelocityMaxAbs", "holdActionL2", ...
            "holdActionPenalty"];
        if ~isstruct(info) || ~isscalar(info) || ...
                ~all(isfield(info, cellstr(fields)))
            error("summarizeNoGloveStage7hHoldReward:RewardInfo", ...
                "Episode %s step %d lacks hold diagnostics.", ...
                path, stepIdx);
        end
        values = cellfun(@(name) double(info.(name)), cellstr(fields));
        if any(~isfinite(values)) || any(values < 0)
            error("summarizeNoGloveStage7hHoldReward:RewardInfo", ...
                "Episode %s step %d has invalid hold diagnostics.", ...
                path, stepIdx);
        end
        recordedActive(stepIdx) = info.holdActive;
        recordedPosition(stepIdx) = info.holdPositionMse;
        recordedVelocity(stepIdx) = info.holdVelocityMaxAbs;
        recordedAction(stepIdx) = info.holdActionL2;
        recordedPenalty(stepIdx) = info.holdActionPenalty;
    end
    expectedAction = double(expectedActive).*mean(action.^2, 2);
    expectedPenalty = settings.actionWeight.*expectedAction;
    errors = abs([recordedActive-double(expectedActive); ...
        recordedPosition-expectedPosition; ...
        recordedVelocity-expectedVelocity; ...
        recordedAction-expectedAction; ...
        recordedPenalty-expectedPenalty]);
    maximumDiagnosticError = max(maximumDiagnosticError, max(errors));
    if max(errors) > options.tolerance
        error("summarizeNoGloveStage7hHoldReward:DiagnosticMismatch", ...
            "Episode %s hold diagnostics do not match state_t.", path);
    end
    holdActiveParts{fileIdx} = recordedActive;
    holdPositionParts{fileIdx} = recordedPosition;
    holdVelocityParts{fileIdx} = recordedVelocity;
    holdActionParts{fileIdx} = recordedAction;
    holdPenaltyParts{fileIdx} = recordedPenalty;
    pwmParts{fileIdx} = pwm;
end

holdActive = vertcat(holdActiveParts{:});
holdPosition = vertcat(holdPositionParts{:});
holdVelocity = vertcat(holdVelocityParts{:});
holdAction = vertcat(holdActionParts{:});
holdPenalty = vertcat(holdPenaltyParts{:});
pwm = vertcat(pwmParts{:});
summary = struct( ...
    "episodeCount", numel(files), ...
    "windowCount", numel(holdActive), ...
    "allFinite", true, ...
    "holdActiveFraction", mean(holdActive), ...
    "holdPositionMseMean", mean(holdPosition), ...
    "holdPositionMseMax", max(holdPosition), ...
    "holdVelocityMaxAbs", max(holdVelocity), ...
    "holdActionL2Mean", mean(holdAction), ...
    "holdActionPenaltyMean", mean(holdPenalty), ...
    "activeHoldWindowAnyCommandFraction", conditionalMean( ...
        any(abs(pwm) > 0, 2), holdActive > 0), ...
    "maximumDiagnosticReplayError", maximumDiagnosticError);
end

function value = conditionalMean(values, mask)
if ~any(mask)
    value = NaN;
else
    value = mean(values(mask));
end
end
