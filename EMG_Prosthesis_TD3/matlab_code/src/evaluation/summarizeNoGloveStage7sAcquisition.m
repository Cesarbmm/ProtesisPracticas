function summary = summarizeNoGloveStage7sAcquisition( ...
        corpus, pairSet, calibration, frozenEmgScale, ...
        frozenContextScale, acceptanceInvariant, options)
%summarizeNoGloveStage7sAcquisition audits causal prospective state logs.

arguments
    corpus (1, 1) struct
    pairSet (1, 1) struct
    calibration (1, 1) struct
    frozenEmgScale double
    frozenContextScale double
    acceptanceInvariant (1, 1) logical
    options.targetActivity (1, 1) double {mustBePositive} = 0.13
    options.activityTolerance (1, 1) double {mustBePositive} = 1e-10
end

required = ["states", "rawAction", "effectiveAction", "pwm", ...
    "qBefore", "qAfter", "qReference", "vReference", ...
    "safetyIntervention", "metadata", "inventory", ...
    "alignmentAudit", "futureLeakageUsed"];
if ~all(isfield(corpus, cellstr(required))) || ...
        ~all(isfield(pairSet, ["emgScale", "contextScale", ...
        "scaleSource", "stateCounterfactualUsed", "hybridStateUsed"]))
    error("summarizeNoGloveStage7sAcquisition:InvalidContract", ...
        "The combined corpus or pair set is incomplete.");
end
restRows = corpus.metadata.source == "steadyRest";
restInventory = corpus.inventory.source == "steadyRest";
restAlignment = corpus.alignmentAudit.source == "steadyRest";
episodes = unique(corpus.metadata.episode(restRows));
referenceHoldMaximumError = 0;
for episode = episodes'
    rows = restRows & corpus.metadata.episode == episode;
    reference = corpus.qReference(rows, :);
    referenceHoldMaximumError = max(referenceHoldMaximumError, ...
        max(abs(reference-reference(1, :)), [], "all"));
end
qMin = double(calibration.limits.positionMin(:)');
qMax = double(calibration.limits.positionMax(:)');
positionLimitsRespected = all(corpus.qBefore(restRows, :) >= qMin & ...
    corpus.qBefore(restRows, :) <= qMax, "all") && ...
    all(corpus.qAfter(restRows, :) >= qMin & ...
    corpus.qAfter(restRows, :) <= qMax, "all");
declared = restRows & corpus.metadata.gateContext == "declaredRest";
activityError = max(abs(corpus.metadata.activity(declared) - ...
    options.targetActivity), [], "all", "omitnan");
if isempty(activityError)
    activityError = inf;
end
alignmentColumns = ["referenceMaximumError", ...
    "nextStateMaximumError", "provenancePositionMaximumError", ...
    "provenanceVelocityMaximumError", "effectiveActionMaximumError", ...
    "pwmMismatchCount"];
alignmentValues = table2array(corpus.alignmentAudit( ...
    restAlignment, alignmentColumns));
alignmentPassed = all(alignmentValues(:, 1:5) <= 1e-12, "all") && ...
    all(alignmentValues(:, 6) == 0);

values = [corpus.states(restRows, :), corpus.rawAction(restRows, :), ...
    corpus.effectiveAction(restRows, :), corpus.pwm(restRows, :), ...
    corpus.qAfter(restRows, :), corpus.qReference(restRows, :), ...
    corpus.vReference(restRows, :)];
summary = struct( ...
    "schemaVersion", 1, "stage", "7S", ...
    "episodeCount", sum(restInventory), ...
    "stateCount", sum(restRows), ...
    "allFinite", all(isfinite(values), "all"), ...
    "state60", size(corpus.states, 2) == 60 && ...
        string(corpus.stateDecision) == "intentMarkov60", ...
    "positionLimitsRespected", positionLimitsRespected, ...
    "gateActiveCount", sum(corpus.metadata.gateActive(restRows)), ...
    "countdownCount", ...
        sum(corpus.metadata.lowActivityCountdown(restRows)), ...
    "nonzeroReferenceVelocityCount", ...
        sum(abs(corpus.vReference(restRows, :)) > 0, "all"), ...
    "referenceHoldMaximumError", referenceHoldMaximumError, ...
    "declaredRestActivityMaximumError", activityError, ...
    "declaredRestActivityExact", activityError <= ...
        options.activityTolerance, ...
    "initialRestStateCount", sum(restRows & ...
        corpus.metadata.gateContext == "initialRest"), ...
    "declaredRestStateCount", sum(declared), ...
    "safetyInterventionCount", ...
        sum(corpus.safetyIntervention(restRows, :), "all"), ...
    "alignmentPassed", alignmentPassed, ...
    "acceptanceInvariant", acceptanceInvariant, ...
    "frozenScalesUsed", string(pairSet.scaleSource) == ...
        "frozenOverride" && ...
        isequal(double(pairSet.emgScale), ...
        double(frozenEmgScale(:)')) && ...
        isequal(double(pairSet.contextScale), ...
        double(frozenContextScale(:)')), ...
    "completeObservedStates", true, ...
    "hybridStateUsed", logical(pairSet.hybridStateUsed), ...
    "stateCounterfactualUsed", ...
        logical(pairSet.stateCounterfactualUsed), ...
    "futureLeakageUsed", logical(corpus.futureLeakageUsed), ...
    "hardwareUsed", false, "trainingUsed", false);
end
