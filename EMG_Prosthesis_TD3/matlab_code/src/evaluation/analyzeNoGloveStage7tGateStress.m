function analysis = analyzeNoGloveStage7tGateStress(data, options)
%analyzeNoGloveStage7tGateStress audits frozen causal gate-stress logs.

arguments
    data (1, 1) struct
    options.alignmentTolerance (1, 1) double {mustBePositive} = 1e-12
    options.homeTolerance (1, 1) double {mustBePositive} = 1e-4
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
end

required = ["corpus", "pairSet", "design", "configs", ...
    "restEpisodeInventory", "parentValidated", "actorsLoaded", ...
    "environmentUsed", "simulationUsed", "trainingUsed", ...
    "hardwareUsed"];
if ~all(isfield(data, cellstr(required))) || ...
        ~data.parentValidated || data.actorsLoaded || ...
        data.environmentUsed || data.simulationUsed || ...
        data.trainingUsed || data.hardwareUsed
    error("analyzeNoGloveStage7tGateStress:InvalidEvidence", ...
        "A validated frozen offline ETAPA 7S input is required.");
end

[mapping, alignmentAudit, captureUsage] = mapCausalInputs(data, options);

% ETAPA 7T amendment 2 (2026-09-02): the idealized calibrated positionMax is
% not the simulator's actual reachable firstStep endpoint for Opening-type
% episodes (see deriveNoGloveStage7tReachableEndpoints.m). The upper
% endpoint used everywhere below is derived from, and certified against, the
% frozen firstStep corpus itself instead of being assumed.
qMinRow = double(data.configs.intentCalibration.limits.positionMin(:)');
firstStepRows = mapping.stateRow( ...
    data.corpus.metadata.step(mapping.stateRow) == 1);
equilibriumEndpoints = deriveNoGloveStage7tReachableEndpoints( ...
    data.corpus.states(firstStepRows, 41:44), qMinRow, options.homeTolerance);

componentTable = buildComponentTable(data.corpus, mapping, ...
    data.configs.intentCalibration.limits, equilibriumEndpoints, options);
globalCommandSummary = summarizeCommands(componentTable, "global");
channelCommandSummary = summarizeCommands(componentTable, "channel");
sideCommandSummary = summarizeCommands(componentTable, "side");
poseCommandSummary = summarizeCommands(componentTable, "pose");
stepCommandSummary = summarizeCommands(componentTable, "step");
decision = classifyNoGloveStage7tConsequence(componentTable);
[emgDistanceTable, emgDistanceSummary] = ...
    auditEmgDistribution(data.corpus, mapping, ...
    double(data.pairSet.emgScale(:)'));
context = auditNoGloveStage7tContextDivergence( ...
    data.corpus, data.pairSet);

first = componentTable.phase == "firstStep";
firstStateRows = unique(componentTable.stateRow(first));
states = data.corpus.states(firstStateRows, :);
firstQ = states(:, 41:44);
atEndpoint = abs(firstQ-equilibriumEndpoints.qLower) <= options.homeTolerance | ...
    abs(firstQ-equilibriumEndpoints.qUpper) <= options.homeTolerance;
firstStepInvariant = ...
    equilibriumEndpoints.upperEquilibriumConsistent && ...
    all(atEndpoint, "all") && ...
    all(abs(states(:, 45:52)) <= options.alignmentTolerance, "all") && ...
    all(abs(states(:, 53:56)-states(:, 41:44)) <= ...
        options.alignmentTolerance, "all") && ...
    all(abs(states(:, 57:60)) <= options.alignmentTolerance, "all") && ...
    all(componentTable.zeroControlDemand(first));
referenceFrozen = validateFrozenReference(data.corpus, ...
    options.alignmentTolerance);
alignmentPassed = height(alignmentAudit) == 80 && ...
    all(alignmentAudit.captureCandidateCount == 1) && ...
    all(alignmentAudit.rawMaximumError <= options.alignmentTolerance) && ...
    all(alignmentAudit.featureMaximumError <= options.alignmentTolerance) && ...
    all(alignmentAudit.stateMaximumError <= options.alignmentTolerance) && ...
    all(alignmentAudit.repetitionIdMatched);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7T", "result", "PASS", ...
    "scientificResult", decision.classification, ...
    "recommendation", decision.recommendation, ...
    "stateDecision", "intentMarkov60", ...
    "state62Disposition", "provisionallyRejected", ...
    "equilibriumEndpoints", equilibriumEndpoints, ...
    "componentTable", componentTable, ...
    "globalCommandSummary", globalCommandSummary, ...
    "channelCommandSummary", channelCommandSummary, ...
    "sideCommandSummary", sideCommandSummary, ...
    "poseCommandSummary", poseCommandSummary, ...
    "stepCommandSummary", stepCommandSummary, ...
    "decision", decision, "alignmentAudit", alignmentAudit, ...
    "captureUsage", captureUsage, ...
    "emgDistanceTable", emgDistanceTable, ...
    "emgDistanceSummary", emgDistanceSummary, ...
    "context", context, ...
    "prospectiveStateCount", sum( ...
        data.corpus.metadata.source == "steadyRest"), ...
    "prospectiveComponentCount", height(componentTable), ...
    "firstStepComponentCount", sum(first), ...
    "postFirstComponentCount", sum(~first), ...
    "firstStepInvariant", firstStepInvariant, ...
    "firstStepLowerEndpointFraction", ...
        mean(componentTable.homeAtDecision(first)), ...
    "firstStepUpperEndpointFraction", ...
        mean(componentTable.upperEndpointAtDecision(first)), ...
    "referenceFrozen", referenceFrozen, ...
    "alignmentPassed", alignmentPassed, ...
    "minimumNonzeroAbsolutePwm", minimumNonzeroPwm(componentTable), ...
    "simulationSafetyInterventionCount", ...
        sum(componentTable.safetyIntervention), ...
    "actorLoaded", false, "actorEvaluated", false, ...
    "environmentUsed", false, "simulationUsed", false, ...
    "trainingUsed", false, "hardwareUsed", false, ...
    "stateCounterfactualUsed", false, "hybridStateUsed", false, ...
    "rewardChanged", false, "quantizationChanged", false, ...
    "td3Changed", false, "simulatorChanged", false, ...
    "safetyChanged", false, "gateChanged", false, ...
    "dtwCalculated", false);
end

function [mapping, audit, usage] = mapCausalInputs(data, options)
corpus = data.corpus;
design = data.design;
inventory = sortrows(data.restEpisodeInventory, "episode");
restRows = find(corpus.metadata.source == "steadyRest");
mapping = table(restRows, zeros(numel(restRows), 1), ...
    zeros(numel(restRows), 1), zeros(numel(restRows), 1), ...
    zeros(numel(restRows), 1), zeros(numel(restRows), 1), ...
    zeros(numel(restRows), 1), ...
    'VariableNames', ["stateRow", "captureEpisode", "cellRow", ...
    "side", "window", "dominantChannel", "dominantActivation"]);

auditRows = repmat(struct( ...
    "simulationEpisode", 0, "captureEpisode", 0, ...
    "cellRow", 0, "side", 0, "repetitionId", 0, ...
    "captureCandidateCount", 0, "rawMaximumError", NaN, ...
    "featureMaximumError", NaN, "stateMaximumError", NaN, ...
    "repetitionIdMatched", false), height(inventory), 1);

for inventoryIdx = 1:height(inventory)
    simulationEpisode = inventory.episode(inventoryIdx);
    episodeRows = find(corpus.metadata.source == "steadyRest" & ...
        corpus.metadata.episode == simulationEpisode);
    [~, order] = sort(corpus.metadata.step(episodeRows));
    episodeRows = episodeRows(order);
    if numel(episodeRows) ~= 20
        error("analyzeNoGloveStage7tGateStress:EpisodeLength", ...
            "Episode %d does not contain 20 decisions.", ...
            simulationEpisode);
    end
    episodeData = load(inventory.filePath(inventoryIdx), ...
        "emgLog", "stateLog", "repetitionId");
    if ~iscell(episodeData.emgLog) || ...
            numel(episodeData.emgLog) ~= 20 || ...
            ~isequal(size(episodeData.stateLog), [20, 60])
        error("analyzeNoGloveStage7tGateStress:EpisodeContract", ...
            "Episode %d is incomplete.", simulationEpisode);
    end
    loggedRaw = vertcat(episodeData.emgLog{:});
    captureErrors = inf(80, 1);
    for capture = 1:80
        row = ceil(capture/2);
        side = 1+mod(capture-1, 2);
        raw = double(design.emgs{row, side});
        captureErrors(capture) = max(abs( ...
            raw(41:840, :)-loggedRaw), [], "all");
    end
    candidates = find(captureErrors <= options.alignmentTolerance);
    if numel(candidates) ~= 1
        error("analyzeNoGloveStage7tGateStress:CaptureAlignment", ...
            "Episode %d matched %d design captures.", ...
            simulationEpisode, numel(candidates));
    end
    capture = candidates(1);
    cellRow = ceil(capture/2);
    side = 1+mod(capture-1, 2);
    captureRaw = double(design.emgs{cellRow, side});
    featureError = 0;
    rawError = captureErrors(capture);
    for step = 1:20
        raw = captureRaw((step-1)*40+(1:40), :);
        feature = data.configs.fGetFeatures(raw);
        featureError = max(featureError, max(abs( ...
            double(feature(:)')-corpus.states(episodeRows(step), 1:40))));
        designRow = design.designTable.episode == capture & ...
            design.designTable.window == step;
        if sum(designRow) ~= 1
            error("analyzeNoGloveStage7tGateStress:DesignJoin", ...
                "Capture %d step %d is not unique.", capture, step);
        end
        mapRow = find(mapping.stateRow == episodeRows(step));
        mapping.captureEpisode(mapRow) = capture;
        mapping.cellRow(mapRow) = cellRow;
        mapping.side(mapRow) = side;
        mapping.window(mapRow) = step;
        mapping.dominantChannel(mapRow) = ...
            design.designTable.dominantChannel(designRow);
        mapping.dominantActivation(mapRow) = ...
            design.designTable.dominantActivation(designRow);
    end
    stateError = max(abs(double(episodeData.stateLog) - ...
        corpus.states(episodeRows, :)), [], "all");
    auditRows(inventoryIdx) = struct( ...
        "simulationEpisode", simulationEpisode, ...
        "captureEpisode", capture, "cellRow", cellRow, ...
        "side", side, "repetitionId", double(episodeData.repetitionId), ...
        "captureCandidateCount", numel(candidates), ...
        "rawMaximumError", rawError, ...
        "featureMaximumError", featureError, ...
        "stateMaximumError", stateError, ...
        "repetitionIdMatched", ...
            double(episodeData.repetitionId) == cellRow);
end
if any(mapping.captureEpisode == 0) || ...
        any(mapping.dominantChannel < 1 | mapping.dominantChannel > 7)
    error("analyzeNoGloveStage7tGateStress:IncompleteMapping", ...
        "Not every prospective state received a causal design row.");
end
audit = struct2table(auditRows);
captures = (1:80)';
episodeUseCount = zeros(80, 1);
for capture = 1:80
    episodeUseCount(capture) = sum(audit.captureEpisode == capture);
end
usage = table(captures, ceil(captures/2), ...
    1+mod(captures-1, 2), episodeUseCount, episodeUseCount > 0, ...
    'VariableNames', ["captureEpisode", "cellRow", "side", ...
    "episodeUseCount", "used"]);
end

function values = buildComponentTable( ...
        corpus, mapping, limits, equilibriumEndpoints, options)
n = height(mapping);
stateRow = repelem(mapping.stateRow, 4, 1);
motor = repmat((1:4)', n, 1);
linear = sub2ind(size(corpus.rawAction), stateRow, motor);
episode = repelem(corpus.metadata.episode(mapping.stateRow), 4, 1);
step = repelem(corpus.metadata.step(mapping.stateRow), 4, 1);
phase = repmat("postFirst", 4*n, 1);
phase(step == 1) = "firstStep";
captureEpisode = repelem(mapping.captureEpisode, 4, 1);
side = repelem(mapping.side, 4, 1);
dominantChannel = repelem(mapping.dominantChannel, 4, 1);
dominantActivation = repelem(mapping.dominantActivation, 4, 1);
q = corpus.states(sub2ind(size(corpus.states), stateRow, 40+motor));
deltaQ = corpus.states(sub2ind(size(corpus.states), stateRow, 44+motor));
previousEffectiveAction = corpus.states(sub2ind( ...
    size(corpus.states), stateRow, 48+motor));
qReference = corpus.states(sub2ind( ...
    size(corpus.states), stateRow, 52+motor));
vReference = corpus.states(sub2ind( ...
    size(corpus.states), stateRow, 56+motor));
rawAction = corpus.rawAction(linear);
effectiveAction = corpus.effectiveAction(linear);
pwm = corpus.pwm(linear);
safetyIntervention = corpus.safetyIntervention(linear);
saturation = abs(effectiveAction) >= options.saturationThreshold;
qMin = double(limits.positionMin(:));
% Amendment 2 (2026-09-02): the upper reference is the simulator's derived,
% certified equilibrium (deriveNoGloveStage7tReachableEndpoints.m), not the
% idealized calibrated positionMax, which Opening-type resets never reach.
qUpper = double(equilibriumEndpoints.qUpper(:));
motorMinimum = qMin(motor);
motorMaximum = qUpper(motor);
homeAtDecision = abs(q-motorMinimum) <= options.homeTolerance;
upperEndpointAtDecision = ...
    abs(q-motorMaximum) <= options.homeTolerance;
initialPose = repmat("interior", numel(q), 1);
initialPose(homeAtDecision) = "lowerEndpoint";
initialPose(upperEndpointAtDecision) = "upperEndpoint";
zeroControlDemand = corpus.zeroControlDemand(linear);
values = table(stateRow, episode, step, phase, captureEpisode, side, ...
    dominantChannel, dominantActivation, motor, q, deltaQ, ...
    previousEffectiveAction, qReference, vReference, rawAction, ...
    effectiveAction, pwm, saturation, safetyIntervention, ...
    homeAtDecision, upperEndpointAtDecision, initialPose, ...
    zeroControlDemand);
end

function summary = summarizeCommands(values, mode)
switch mode
    case "global"
        phases = ["firstStep", "postFirst", "ALL"];
        parts = cell(numel(phases)*5, 1);
        cursor = 0;
        for phase = phases
            for motor = 0:4
                cursor = cursor+1;
                rows = true(height(values), 1);
                if phase ~= "ALL"
                    rows = rows & values.phase == phase;
                end
                if motor ~= 0
                    rows = rows & values.motor == motor;
                end
                parts{cursor} = commandSummaryRow( ...
                    values(rows, :), phase, motor, 0);
            end
        end
    case "channel"
        phases = ["firstStep", "postFirst"];
        parts = cell(numel(phases)*7*5, 1);
        cursor = 0;
        for phase = phases
            for channel = 1:7
                for motor = 0:4
                    cursor = cursor+1;
                    rows = values.phase == phase & ...
                        values.dominantChannel == channel;
                    if motor ~= 0
                        rows = rows & values.motor == motor;
                    end
                    parts{cursor} = commandSummaryRow( ...
                        values(rows, :), phase, motor, channel);
                end
            end
        end
    case "side"
        phases = ["firstStep", "postFirst"];
        parts = cell(numel(phases)*2*5, 1);
        cursor = 0;
        for phase = phases
            for side = 1:2
                for motor = 0:4
                    cursor = cursor+1;
                    rows = values.phase == phase & values.side == side;
                    if motor ~= 0
                        rows = rows & values.motor == motor;
                    end
                    parts{cursor} = commandSummaryRow( ...
                        values(rows, :), phase, motor, side);
                end
            end
        end
    case "pose"
        phases = ["firstStep", "postFirst"];
        poses = ["lowerEndpoint", "upperEndpoint", "interior"];
        parts = cell(numel(phases)*numel(poses)*5, 1);
        cursor = 0;
        for phase = phases
            for pose = poses
                for motor = 0:4
                    cursor = cursor+1;
                    rows = values.phase == phase & ...
                        values.initialPose == pose;
                    if motor ~= 0
                        rows = rows & values.motor == motor;
                    end
                    parts{cursor} = commandSummaryRow( ...
                        values(rows, :), phase, motor, pose);
                end
            end
        end
    case "step"
        parts = cell(20*5, 1);
        cursor = 0;
        for step = 1:20
            for motor = 0:4
                cursor = cursor+1;
                rows = values.step == step;
                if motor ~= 0
                    rows = rows & values.motor == motor;
                end
                parts{cursor} = commandSummaryRow( ...
                    values(rows, :), compose("%d", step), motor, step);
            end
        end
    otherwise
        error("analyzeNoGloveStage7tGateStress:UnknownSummary", ...
            "Unknown summary mode %s.", mode);
end
summary = vertcat(parts{:});
summary.Properties.VariableNames{4} = char(mode+"Key");
end

function row = commandSummaryRow(values, group, motor, key)
nonzero = values.pwm ~= 0;
positive = values.pwm > 0;
negative = values.pwm < 0;
row = table(string(group), motor, height(values), key, ...
    mean(values.rawAction), mean(abs(values.rawAction)), ...
    localPercentile(abs(values.rawAction), 50), ...
    localPercentile(abs(values.rawAction), 95), ...
    mean(abs(values.effectiveAction)), mean(abs(values.pwm)), ...
    safeMean(nonzero), safeMean(abs(values.pwm) == 64), ...
    safeMean(values.saturation), ...
    safeMean(values.safetyIntervention > 0), ...
    sum(values.safetyIntervention), safeMean(positive), ...
    safeMean(negative), safeMean(~positive & ~negative), ...
    safeMean(values.homeAtDecision), ...
    safeMean(values.upperEndpointAtDecision), ...
    safeMean(values.zeroControlDemand), ...
    'VariableNames', ["group", "motor", "componentCount", "key", ...
    "meanRawAction", "meanAbsoluteRawAction", ...
    "p50AbsoluteRawAction", "p95AbsoluteRawAction", ...
    "meanAbsoluteEffectiveAction", "meanAbsolutePwm", ...
    "nonzeroPwmFraction", "pwm64Fraction", ...
    "saturationFraction", "safetyEventFraction", ...
    "safetyInterventionCount", "positivePwmFraction", ...
    "negativePwmFraction", "zeroPwmFraction", ...
    "homeAtDecisionFraction", "upperEndpointAtDecisionFraction", ...
    "zeroControlDemandFraction"]);
end

function passed = validateFrozenReference(corpus, tolerance)
rest = corpus.metadata.source == "steadyRest";
passed = all(abs(corpus.vReference(rest, :)) <= tolerance, "all");
episodes = unique(corpus.metadata.episode(rest))';
for episode = episodes
    rows = rest & corpus.metadata.episode == episode;
    reference = corpus.qReference(rows, :);
    passed = passed && all(abs(reference-reference(1, :)) <= ...
        tolerance, "all");
end
end

function [distances, summary] = auditEmgDistribution(corpus, mapping, scale)
acceptanceRows = corpus.metadata.source == "acceptance";
acceptance = corpus.states(acceptanceRows, 1:40)./scale;
prospective = corpus.states(mapping.stateRow, 1:40)./scale;
nearestAcceptanceEmgRms = zeros(height(mapping), 1);
for row = 1:height(mapping)
    difference = prospective(row, :) - acceptance;
    nearestAcceptanceEmgRms(row) = min(sqrt(mean(difference.^2, 2)));
end
episode = corpus.metadata.episode(mapping.stateRow);
step = corpus.metadata.step(mapping.stateRow);
phase = repmat("postFirst", height(mapping), 1);
phase(step == 1) = "firstStep";
distances = table(mapping.stateRow, episode, step, phase, ...
    mapping.captureEpisode, mapping.side, mapping.dominantChannel, ...
    nearestAcceptanceEmgRms, ...
    'VariableNames', ["stateRow", "episode", "step", "phase", ...
    "captureEpisode", "side", "dominantChannel", ...
    "nearestAcceptanceEmgRms"]);

phases = ["firstStep", "postFirst", "ALL"];
parts = cell(numel(phases)*8, 1);
cursor = 0;
for phaseValue = phases
    for channel = 0:7
        cursor = cursor+1;
        rows = true(height(distances), 1);
        if phaseValue ~= "ALL"
            rows = rows & distances.phase == phaseValue;
        end
        if channel ~= 0
            rows = rows & distances.dominantChannel == channel;
        end
        values = nearestAcceptanceEmgRms(rows);
        parts{cursor} = table(phaseValue, channel, numel(values), ...
            localPercentile(values, 50), localPercentile(values, 95), ...
            maxOrNaN(values), safeMean(values > 1), safeMean(values > 3), ...
            'VariableNames', ["phase", "dominantChannel", ...
            "stateCount", "medianNearestAcceptanceEmgRms", ...
            "p95NearestAcceptanceEmgRms", ...
            "maximumNearestAcceptanceEmgRms", ...
            "fractionAboveOne", "fractionAboveThree"]);
    end
end
summary = vertcat(parts{:});
end

function value = minimumNonzeroPwm(values)
selected = abs(values.pwm(values.pwm ~= 0));
if isempty(selected)
    value = NaN;
else
    value = min(selected);
end
end

function value = maxOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = safeMean(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = localPercentile(values, percentage)
values = sort(double(values(:)));
if isempty(values)
    value = NaN;
    return;
end
position = 1+(numel(values)-1)*percentage/100;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    weight = position-lower;
    value = values(lower)*(1-weight)+values(upper)*weight;
end
end
