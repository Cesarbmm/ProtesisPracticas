function analysis = analyzeNoGloveStage7fActionWeightAblation( ...
        control, candidate, options)
%analyzeNoGloveStage7fActionWeightAblation applies the pre-registered gate.

arguments
    control (1, 1) struct
    candidate (1, 1) struct
    options.minimumActionL2Reduction (1, 1) double ...
        {mustBeInRange(options.minimumActionL2Reduction, 0, 1)} = 0.10
    options.maximumTrackingMseRatio (1, 1) double ...
        {mustBePositive} = 1.05
    options.maximumRestActiveWindowFraction (1, 1) double ...
        {mustBeInRange(options.maximumRestActiveWindowFraction, 0, 1)} = 0.01
    options.maximumAcceptanceSaturation (1, 1) double ...
        {mustBeInRange(options.maximumAcceptanceSaturation, 0, 1)} = 0.196043
    options.maximumAcceptanceDeltaActionL2 (1, 1) double ...
        {mustBeNonnegative} = 0.257108
    options.maximumRestSaturation (1, 1) double ...
        {mustBeInRange(options.maximumRestSaturation, 0, 1)} = 0
    options.maximumDecodedRestFalseActivation (1, 1) double ...
        {mustBeInRange(options.maximumDecodedRestFalseActivation, 0, 1)} = 0.01
    options.comparisonTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
end

validateVariant(control, "control", 0.01);
validateVariant(candidate, "candidate", 0.05);

controlRow = buildVariantRow(control);
candidateRow = buildVariantRow(candidate);
variantSummary = [controlRow; candidateRow];

actionL2Reduction = relativeReduction( ...
    control.acceptance.actionL2, candidate.acceptance.actionL2);
restPwmReduction = relativeReduction( ...
    control.rest.meanAbsPwm, candidate.rest.meanAbsPwm);
trackingMseRatio = safeRatio( ...
    candidate.acceptance.trackingMse, control.acceptance.trackingMse);
deltaActionRatio = safeRatio( ...
    candidate.acceptance.deltaActionL2, ...
    control.acceptance.deltaActionL2);
saturationRatio = safeRatio( ...
    candidate.acceptance.saturationFraction, ...
    control.acceptance.saturationFraction);

tol = options.comparisonTolerance;
checks = struct( ...
    "finite", control.training.allFinite && control.acceptance.allFinite && ...
        control.rest.allFinite && candidate.training.allFinite && ...
        candidate.acceptance.allFinite && candidate.rest.allFinite, ...
    "positionLimits", ...
        candidate.training.positionViolationEpisodeCount == 0 && ...
        candidate.acceptance.positionViolationEpisodeCount == 0 && ...
        candidate.rest.positionViolationEpisodeCount == 0, ...
    "trainingSafetyInterventionsNotWorse", ...
        candidate.training.positionSafetyInterventionCount <= ...
        control.training.positionSafetyInterventionCount, ...
    "acceptanceSafetyInterventionsNotWorse", ...
        candidate.acceptance.positionSafetyInterventionCount <= ...
        control.acceptance.positionSafetyInterventionCount, ...
    "restSafetyInterventionsNotWorse", ...
        candidate.rest.positionSafetyInterventionCount <= ...
        control.rest.positionSafetyInterventionCount, ...
    "trackingNonRegression", trackingMseRatio <= ...
        options.maximumTrackingMseRatio+tol, ...
    "materialActionReduction", actionL2Reduction >= ...
        options.minimumActionL2Reduction-tol, ...
    "deltaActionAbsolute", candidate.acceptance.deltaActionL2 <= ...
        options.maximumAcceptanceDeltaActionL2+tol, ...
    "deltaActionNotWorse", candidate.acceptance.deltaActionL2 <= ...
        control.acceptance.deltaActionL2+tol, ...
    "acceptanceSaturationAbsolute", ...
        candidate.acceptance.saturationFraction <= ...
        options.maximumAcceptanceSaturation+tol, ...
    "acceptanceSaturationNotWorse", ...
        candidate.acceptance.saturationFraction <= ...
        control.acceptance.saturationFraction+tol, ...
    "motor2Functional", ...
        candidate.acceptance.motor2FunctionalFlagCount == 0, ...
    "otherMotorsFunctional", ...
        candidate.acceptance.otherMotorFunctionalFlagCount == 0, ...
    "decodedRestFalseActivation", ...
        candidate.decodedRestFalseActivationFraction <= ...
        options.maximumDecodedRestFalseActivation+tol, ...
    "restSaturation", candidate.rest.saturationFraction <= ...
        options.maximumRestSaturation+tol, ...
    "policyRestWindows", candidate.rest.windowAnyCommandFraction <= ...
        options.maximumRestActiveWindowFraction+tol);

gatePassed = all(struct2array(checks));
classification = classifyResult(checks, gatePassed);
comparison = table( ...
    actionL2Reduction, restPwmReduction, trackingMseRatio, ...
    deltaActionRatio, saturationRatio, gatePassed, classification);
checkNames = string(fieldnames(checks));
checkPassed = cellfun(@(name) logical(checks.(name)), ...
    cellstr(checkNames));
gateChecks = table(checkNames, checkPassed, ...
    'VariableNames', ["check", "passed"]);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7F", ...
    "ablationFactor", "intentRewardActionWeight", ...
    "controlActionWeight", control.actionWeight, ...
    "candidateActionWeight", candidate.actionWeight, ...
    "variantSummary", variantSummary, ...
    "restMotorSummary", [buildRestMotorRows(control); ...
        buildRestMotorRows(candidate)], ...
    "comparison", comparison, "checks", checks, ...
    "gateChecks", gateChecks, "gatePassed", gatePassed, ...
    "classification", classification, ...
    "thresholds", struct( ...
        "minimumActionL2Reduction", options.minimumActionL2Reduction, ...
        "maximumTrackingMseRatio", options.maximumTrackingMseRatio, ...
        "maximumRestActiveWindowFraction", ...
            options.maximumRestActiveWindowFraction, ...
        "maximumAcceptanceSaturation", ...
            options.maximumAcceptanceSaturation, ...
        "maximumAcceptanceDeltaActionL2", ...
            options.maximumAcceptanceDeltaActionL2, ...
        "maximumRestSaturation", options.maximumRestSaturation, ...
        "maximumDecodedRestFalseActivation", ...
            options.maximumDecodedRestFalseActivation), ...
    "rootCauseIdentified", false, ...
    "singleRewardParameterChanged", true, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false, ...
    "dtwCalculated", false, "hardwareUsed", false);
end

function validateVariant(value, expectedLabel, expectedWeight)
required = ["label", "actionWeight", "training", "acceptance", ...
    "rest", "decodedRestFalseActivationFraction", "checkpointSha256"];
if ~all(isfield(value, cellstr(required))) || ...
        string(value.label) ~= expectedLabel || ...
        value.actionWeight ~= expectedWeight
    error("analyzeNoGloveStage7fActionWeightAblation:InvalidVariant", ...
        "Expected %s with action weight %.17g.", ...
        expectedLabel, expectedWeight);
end
requiredTraining = ["allFinite", "positionViolationEpisodeCount", ...
    "positionSafetyInterventionCount"];
requiredAcceptance = [requiredTraining, "trackingMse", "trackingMae", ...
    "actionL2", "deltaActionL2", "saturationFraction", ...
    "motor2FunctionalFlagCount", "otherMotorFunctionalFlagCount"];
requiredRest = [requiredTraining, "commandActiveFraction", ...
    "windowAnyCommandFraction", "meanAbsPwm", "saturationFraction", ...
    "commandActiveFractionByMotor", "meanAbsPwmByMotor", ...
    "saturationFractionByMotor"];
if ~all(isfield(value.training, cellstr(requiredTraining))) || ...
        ~all(isfield(value.acceptance, cellstr(requiredAcceptance))) || ...
        ~all(isfield(value.rest, cellstr(requiredRest)))
    error("analyzeNoGloveStage7fActionWeightAblation:MissingMetric", ...
        "Variant %s has an incomplete metric contract.", expectedLabel);
end
numeric = [value.actionWeight, value.decodedRestFalseActivationFraction, ...
    struct2array(rmfield(value.training, "allFinite")), ...
    struct2array(rmfield(value.acceptance, "allFinite")), ...
    value.rest.positionViolationEpisodeCount, ...
    value.rest.positionSafetyInterventionCount, ...
    value.rest.commandActiveFraction, value.rest.windowAnyCommandFraction, ...
    value.rest.meanAbsPwm, value.rest.saturationFraction, ...
    value.rest.commandActiveFractionByMotor, ...
    value.rest.meanAbsPwmByMotor, value.rest.saturationFractionByMotor];
if any(~isfinite(numeric)) || any(numeric < 0) || ...
        ~isscalar(value.training.allFinite) || ...
        ~isscalar(value.acceptance.allFinite) || ...
        ~isscalar(value.rest.allFinite) || ...
        strlength(string(value.checkpointSha256)) == 0
    error("analyzeNoGloveStage7fActionWeightAblation:InvalidMetric", ...
        "Variant %s metrics must be finite and nonnegative.", expectedLabel);
end
end

function row = buildVariantRow(value)
row = table(string(value.label), value.actionWeight, ...
    string(value.checkpointSha256), ...
    value.acceptance.trackingMse, value.acceptance.trackingMae, ...
    value.acceptance.actionL2, value.acceptance.deltaActionL2, ...
    value.acceptance.saturationFraction, ...
    value.rest.commandActiveFraction, ...
    value.rest.windowAnyCommandFraction, value.rest.meanAbsPwm, ...
    value.rest.saturationFraction, ...
    value.decodedRestFalseActivationFraction, ...
    value.training.positionViolationEpisodeCount, ...
    value.acceptance.positionViolationEpisodeCount, ...
    value.rest.positionViolationEpisodeCount, ...
    value.training.positionSafetyInterventionCount, ...
    value.acceptance.positionSafetyInterventionCount, ...
    value.rest.positionSafetyInterventionCount, ...
    value.acceptance.motor2FunctionalFlagCount, ...
    value.acceptance.otherMotorFunctionalFlagCount, ...
    'VariableNames', ["variant", "actionWeight", "checkpointSha256", ...
    "trackingMse", "trackingMae", "actionL2", "deltaActionL2", ...
    "saturationFraction", "restCommandActiveFraction", ...
    "restWindowAnyCommandFraction", "restMeanAbsPwm", ...
    "restSaturationFraction", "decodedRestFalseActivationFraction", ...
    "trainingPositionViolationEpisodes", ...
    "acceptancePositionViolationEpisodes", ...
    "restPositionViolationEpisodes", ...
    "trainingSafetyInterventions", "acceptanceSafetyInterventions", ...
    "restSafetyInterventions", "motor2FunctionalFlagCount", ...
    "otherMotorFunctionalFlagCount"]);
end

function rows = buildRestMotorRows(value)
rows = table(repmat(string(value.label), 4, 1), (1:4)', ...
    value.rest.commandActiveFractionByMotor(:), ...
    value.rest.meanAbsPwmByMotor(:), ...
    value.rest.saturationFractionByMotor(:), ...
    'VariableNames', ["variant", "motor", "commandActiveFraction", ...
    "meanAbsPwm", "saturationFraction"]);
end

function value = relativeReduction(control, candidate)
if control == 0
    value = double(candidate == 0);
else
    value = (control-candidate)/abs(control);
end
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    value = double(numerator ~= 0)*Inf;
    if numerator == 0
        value = 1;
    end
else
    value = numerator/denominator;
end
end

function classification = classifyResult(checks, gatePassed)
if gatePassed
    classification = "actionRegularizationSupported";
elseif ~checks.finite || ~checks.positionLimits
    classification = "safetyOrValidityFailure";
elseif ~checks.trackingNonRegression
    classification = "trackingRegression";
elseif ~checks.materialActionReduction
    classification = "noMaterialEffortReduction";
elseif ~checks.policyRestWindows || ~checks.restSaturation || ...
        ~checks.decodedRestFalseActivation
    classification = "effortReducedButRestGateFailed";
elseif ~checks.motor2Functional || ~checks.otherMotorsFunctional
    classification = "functionalGateFailed";
elseif ~checks.deltaActionAbsolute || ~checks.deltaActionNotWorse || ...
        ~checks.acceptanceSaturationAbsolute || ...
        ~checks.acceptanceSaturationNotWorse || ...
        ~checks.trainingSafetyInterventionsNotWorse || ...
        ~checks.acceptanceSafetyInterventionsNotWorse || ...
        ~checks.restSafetyInterventionsNotWorse
    classification = "dynamicRegularityGateFailed";
else
    classification = "ablationUnresolved";
end
end
