function analysis = analyzeNoGloveStage7bDesignedResponse( ...
        componentTable, pairingTable, protocolTable, splitName, options)
%analyzeNoGloveStage7bDesignedResponse audits designed temporal pulses.
%
% The matched Agent200/P table is partitioned by pre-registered synergy
% axis. Lag selection remains held-out by repetition and uses the ETAPA 7A
% common-support contract. Onset/offset latency is measured independently.

arguments
    componentTable table
    pairingTable table
    protocolTable table
    splitName (1, 1) string
    options.targetMotors (1, :) double = [2 3]
    options.maxLagSteps (1, 1) double ...
        {mustBeInteger, mustBePositive} = 5
    options.activeVelocityThreshold (1, 1) double ...
        {mustBePositive} = 0.005
    options.motionVelocityThreshold (1, 1) double ...
        {mustBePositive} = 0.001
    options.offsetHoldSteps (1, 1) double ...
        {mustBeInteger, mustBePositive} = 2
    options.minimumSamplesPerFold (1, 1) double ...
        {mustBeInteger, mustBePositive} = 10
    options.minimumBenefitFraction (1, 1) double ...
        {mustBeInRange(options.minimumBenefitFraction, 0, 1)} = 0.05
    options.minimumMaterialFoldFraction (1, 1) double ...
        {mustBeInRange(options.minimumMaterialFoldFraction, 0, 1)} = 0.75
    options.minimumSignConsistency (1, 1) double ...
        {mustBeInRange(options.minimumSignConsistency, 0, 1)} = 0.75
    options.maximumBoundaryFraction (1, 1) double ...
        {mustBeInRange(options.maximumBoundaryFraction, 0, 1)} = 0.25
    options.minimumFiniteOnsetFraction (1, 1) double ...
        {mustBeInRange(options.minimumFiniteOnsetFraction, 0, 1)} = 1.0
    options.periodSec (1, 1) double {mustBePositive} = 0.2
end

validateInputs(componentTable, pairingTable, protocolTable, ...
    splitName, options);
[enrichedTable, episodeProtocol] = attachProtocol( ...
    componentTable, pairingTable, protocolTable);
axes = unique(episodeProtocol.synergyAxis, "stable");

axisAnalyses = cell(numel(axes), 1);
lagTables = cell(numel(axes), 1);
foldTables = cell(numel(axes), 1);
summaryTables = cell(numel(axes), 1);
sourceTables = cell(numel(axes), 1);
for axisIdx = 1:numel(axes)
    axisName = axes(axisIdx);
    episodeIds = episodeProtocol.episode( ...
        episodeProtocol.synergyAxis == axisName);
    axisValues = enrichedTable( ...
        ismember(enrichedTable.episode, episodeIds), :);
    axisAnalysis = analyzeNoGloveStage7aLagConfirmation( ...
        axisValues, splitName, ...
        "targetMotors", options.targetMotors, ...
        "targetRegimes", ["opening", "closing"], ...
        "maxLagSteps", options.maxLagSteps, ...
        "activeVelocityThreshold", options.activeVelocityThreshold, ...
        "minimumSamplesPerFold", options.minimumSamplesPerFold, ...
        "minimumBenefitFraction", options.minimumBenefitFraction, ...
        "minimumMaterialFoldFraction", ...
            options.minimumMaterialFoldFraction, ...
        "minimumSignConsistency", options.minimumSignConsistency, ...
        "maximumBoundaryFraction", options.maximumBoundaryFraction, ...
        "periodSec", options.periodSec);
    axisAnalyses{axisIdx} = axisAnalysis;
    lagTables{axisIdx} = addAxis( ...
        axisAnalysis.calibrationLagTable, axisName);
    foldTables{axisIdx} = addAxis( ...
        axisAnalysis.foldEvaluationTable, axisName);
    summaryTables{axisIdx} = addAxis( ...
        axisAnalysis.confirmationSummary, axisName);
    sourceTables{axisIdx} = addAxis( ...
        axisAnalysis.sourceDecision, axisName);
end

calibrationLagTable = vertcat(lagTables{:});
foldEvaluationTable = vertcat(foldTables{:});
lagConfirmationSummary = vertcat(summaryTables{:});
axisSourceDecision = vertcat(sourceTables{:});
eventLatencyTable = buildEventLatencyTable( ...
    enrichedTable, episodeProtocol, options);
eventLatencySummary = summarizeEventLatency(eventLatencyTable);
designedGateTable = buildDesignedGate( ...
    lagConfirmationSummary, eventLatencySummary, options);
sourceDecision = summarizeSources(designedGateTable);
primaryDecision = sourceDecision(sourceDecision.commandSource == "Agent200", :);
if height(primaryDecision) ~= 1
    error("analyzeNoGloveStage7bDesignedResponse:MissingPrimary", ...
        "Expected exactly one Agent200 decision.");
end

analysis = struct( ...
    "schemaVersion", 1, ...
    "stage", "7B", ...
    "split", splitName, ...
    "targetMotors", options.targetMotors, ...
    "synergyAxes", axes, ...
    "maxLagSteps", options.maxLagSteps, ...
    "periodSec", options.periodSec, ...
    "preRegisteredLagBound", true, ...
    "commonInteriorSupport", true, ...
    "fullEndpointErrorRetained", true, ...
    "episodeProtocol", episodeProtocol, ...
    "componentTable", enrichedTable, ...
    "axisAnalyses", {axisAnalyses}, ...
    "calibrationLagTable", calibrationLagTable, ...
    "foldEvaluationTable", foldEvaluationTable, ...
    "lagConfirmationSummary", lagConfirmationSummary, ...
    "axisSourceDecision", axisSourceDecision, ...
    "eventLatencyTable", eventLatencyTable, ...
    "eventLatencySummary", eventLatencySummary, ...
    "designedGateTable", designedGateTable, ...
    "sourceDecision", sourceDecision, ...
    "primaryDecision", primaryDecision, ...
    "causalCompensationGatePassed", ...
        primaryDecision.causalCompensationCandidate, ...
    "compensationInterventionExecuted", false, ...
    "filteredReferenceInterventionExecuted", false, ...
    "dtwCalculated", false, ...
    "dtwRewardUsed", false, ...
    "runTraining", false, ...
    "agent7250Loaded", false, ...
    "hardwareUsed", false);
end

function validateInputs(values, pairing, protocol, splitName, options)
requiredValues = ["split", "commandSource", "episode", ...
    "repetitionId", "step", "motor", "qBefore", "qAfter", ...
    "qReference", "referenceVelocity", "deltaQ", "velocity", ...
    "appliedPwm", "effectiveAction", "saturated", ...
    "safetyInterventionCount", "positionViolation"];
requiredPairing = ["episode", "repetitionId", "referenceMaxAbs", ...
    "referenceVelocityMaxAbs", "initialPositionMaxAbs", ...
    "sourceTemporalAlignmentMaxAbs"];
requiredProtocol = ["profileId", "repetitionId", "side", ...
    "synergyAxis", "directionName", "expectedIntentSign"];
if ~all(ismember(requiredValues, string(values.Properties.VariableNames))) || ...
        ~all(ismember(requiredPairing, ...
        string(pairing.Properties.VariableNames))) || ...
        ~all(ismember(requiredProtocol, ...
        string(protocol.Properties.VariableNames)))
    error("analyzeNoGloveStage7bDesignedResponse:MissingVariable", ...
        "Input tables do not satisfy the ETAPA 7B contract.");
end
if isempty(values) || any(string(values.split) ~= splitName)
    error("analyzeNoGloveStage7bDesignedResponse:InvalidSplit", ...
        "componentTable must contain only split %s.", splitName);
end
numericFields = ["episode", "repetitionId", "step", "motor", ...
    "qBefore", "qAfter", "qReference", "referenceVelocity", ...
    "deltaQ", "velocity", "appliedPwm", "effectiveAction", ...
    "safetyInterventionCount"];
for fieldIdx = 1:numel(numericFields)
    fieldName = numericFields(fieldIdx);
    fieldValue = values.(fieldName);
    if ~isnumeric(fieldValue) || ~isreal(fieldValue) || ...
            any(~isfinite(fieldValue), "all")
        error("analyzeNoGloveStage7bDesignedResponse:NonfiniteData", ...
            "%s must be finite real numeric data.", fieldName);
    end
end
if any(values.positionViolation) || ...
        any(pairing.referenceMaxAbs ~= 0) || ...
        any(pairing.referenceVelocityMaxAbs ~= 0) || ...
        any(pairing.initialPositionMaxAbs ~= 0) || ...
        any(pairing.sourceTemporalAlignmentMaxAbs > 1e-12)
    error("analyzeNoGloveStage7bDesignedResponse:PairingOrSafetyFailure", ...
        "Exact pairing and zero position violations are required.");
end
if numel(unique(options.targetMotors)) ~= numel(options.targetMotors) || ...
        any(~ismember(options.targetMotors, 1:4))
    error("analyzeNoGloveStage7bDesignedResponse:InvalidMotors", ...
        "targetMotors must be unique values in 1:4.");
end
end

function [values, episodeProtocol] = attachProtocol( ...
        values, pairing, protocol)
episodeProtocol = pairing(:, ["episode", "repetitionId"]);
episodeProtocol.side = 1 + mod(episodeProtocol.episode-1, 2);
episodeProtocol.profileId = strings(height(episodeProtocol), 1);
episodeProtocol.synergyAxis = strings(height(episodeProtocol), 1);
episodeProtocol.directionName = strings(height(episodeProtocol), 1);
episodeProtocol.expectedIntentSign = zeros(height(episodeProtocol), 1);
for rowIdx = 1:height(episodeProtocol)
    match = protocol.repetitionId == episodeProtocol.repetitionId(rowIdx) & ...
        protocol.side == episodeProtocol.side(rowIdx);
    if sum(match) ~= 1
        error("analyzeNoGloveStage7bDesignedResponse:ProtocolMismatch", ...
            "Episode %d does not resolve to exactly one profile.", ...
            episodeProtocol.episode(rowIdx));
    end
    episodeProtocol.profileId(rowIdx) = protocol.profileId(match);
    episodeProtocol.synergyAxis(rowIdx) = protocol.synergyAxis(match);
    episodeProtocol.directionName(rowIdx) = protocol.directionName(match);
    episodeProtocol.expectedIntentSign(rowIdx) = ...
        protocol.expectedIntentSign(match);
end
if height(unique(episodeProtocol(:, ["repetitionId", "side"]), ...
        "rows")) ~= height(protocol) || height(episodeProtocol) ~= height(protocol)
    error("analyzeNoGloveStage7bDesignedResponse:ProtocolCoverage", ...
        "Every designed profile must appear exactly once.");
end
[found, mapping] = ismember(values.episode, episodeProtocol.episode);
if ~all(found) || any(values.repetitionId ~= ...
        episodeProtocol.repetitionId(mapping))
    error("analyzeNoGloveStage7bDesignedResponse:EpisodeMismatch", ...
        "Component episode/repetition mapping is inconsistent.");
end
values.profileId = episodeProtocol.profileId(mapping);
values.synergyAxis = episodeProtocol.synergyAxis(mapping);
values.designedDirection = episodeProtocol.directionName(mapping);
values.profileSide = episodeProtocol.side(mapping);
end

function output = addAxis(input, axisName)
output = input;
output.synergyAxis = repmat(axisName, height(output), 1);
output = movevars(output, "synergyAxis", "After", "commandSource");
end

function latency = buildEventLatencyTable(values, protocol, options)
sources = unique(values.commandSource, "stable");
rowCount = numel(sources) * height(protocol) * numel(options.targetMotors);
rows = repmat(emptyLatencyRow(), rowCount, 1);
rowIdx = 0;
for sourceIdx = 1:numel(sources)
    for protocolIdx = 1:height(protocol)
        episode = protocol.episode(protocolIdx);
        for motorIdx = 1:numel(options.targetMotors)
            motor = options.targetMotors(motorIdx);
            selected = sortrows(values( ...
                values.commandSource == sources(sourceIdx) & ...
                values.episode == episode & values.motor == motor, :), ...
                "step");
            if isempty(selected) || ...
                    ~isequal(double(selected.step(:)), ...
                    (1:height(selected))')
                error("analyzeNoGloveStage7bDesignedResponse:InvalidEpisode", ...
                    "Each source-episode-motor trace must be contiguous.");
            end
            active = abs(selected.referenceVelocity) >= ...
                options.activeVelocityThreshold;
            activeIndices = find(active);
            if isempty(activeIndices) || ...
                    any(diff(activeIndices) ~= 1)
                error("analyzeNoGloveStage7bDesignedResponse:InvalidPulse", ...
                    "Designed reference must have one contiguous active pulse.");
            end
            direction = sign(median( ...
                selected.referenceVelocity(activeIndices)));
            if direction ~= protocol.expectedIntentSign(protocolIdx)
                error("analyzeNoGloveStage7bDesignedResponse:DirectionMismatch", ...
                    "Decoded reference direction does not match its protocol.");
            end
            referenceOn = activeIndices(1);
            referenceOff = activeIndices(end);
            velocity = double(selected.velocity);
            directionalMotion = direction .* velocity >= ...
                options.motionVelocityThreshold;
            responseOnRelative = find( ...
                directionalMotion(referenceOn:end), 1, "first");
            if isempty(responseOnRelative)
                responseOn = NaN;
                onsetDelay = NaN;
            else
                responseOn = referenceOn + responseOnRelative - 1;
                onsetDelay = responseOn-referenceOn;
            end
            responseOff = findSettledIndex(velocity, referenceOff+1, ...
                options.motionVelocityThreshold, options.offsetHoldSteps);
            if isnan(responseOff)
                offsetDelay = NaN;
            else
                offsetDelay = responseOff-referenceOff;
            end
            preReferenceMotion = any(abs(velocity(1:referenceOn-1)) >= ...
                options.motionVelocityThreshold);
            preReferenceIndices = 1:referenceOn-1;
            preReferenceCommandFraction = mean( ...
                abs(selected.appliedPwm(preReferenceIndices)) > 0);
            preReferenceMeanAbsPwm = mean( ...
                abs(selected.appliedPwm(preReferenceIndices)));
            preReferenceMeanAbsEffectiveAction = mean( ...
                abs(selected.effectiveAction(preReferenceIndices)));
            preReferenceMeanAbsVelocity = mean( ...
                abs(velocity(preReferenceIndices)));
            rowIdx = rowIdx + 1;
            row = emptyLatencyRow();
            row.commandSource = sources(sourceIdx);
            row.synergyAxis = protocol.synergyAxis(protocolIdx);
            row.directionName = protocol.directionName(protocolIdx);
            row.profileId = protocol.profileId(protocolIdx);
            row.episode = episode;
            row.repetitionId = protocol.repetitionId(protocolIdx);
            row.motor = motor;
            row.referenceDirection = direction;
            row.referenceOnStep = referenceOn;
            row.referenceOffStep = referenceOff;
            row.responseOnStep = responseOn;
            row.responseOffStep = responseOff;
            row.onsetDelaySteps = onsetDelay;
            row.onsetDelaySec = onsetDelay * options.periodSec;
            row.offsetDelaySteps = offsetDelay;
            row.offsetDelaySec = offsetDelay * options.periodSec;
            row.preReferenceMotion = preReferenceMotion;
            row.preReferenceCommandFraction = ...
                preReferenceCommandFraction;
            row.preReferenceMeanAbsPwm = preReferenceMeanAbsPwm;
            row.preReferenceMeanAbsEffectiveAction = ...
                preReferenceMeanAbsEffectiveAction;
            row.preReferenceMeanAbsVelocity = ...
                preReferenceMeanAbsVelocity;
            row.finiteOnset = isfinite(onsetDelay);
            row.finiteOffset = isfinite(offsetDelay);
            row.directionalResponseFraction = mean( ...
                direction .* velocity(activeIndices) >= ...
                options.motionVelocityThreshold);
            row.peakDirectionalVelocity = max(direction .* velocity);
            row.endpointAbsoluteError = abs( ...
                selected.qAfter(end)-selected.qReference(end));
            row.trackingMse = mean(( ...
                selected.qAfter-selected.qReference).^2);
            row.saturationFraction = mean(selected.saturated);
            row.safetyInterventionCount = ...
                sum(selected.safetyInterventionCount);
            rows(rowIdx) = row;
        end
    end
end
latency = struct2table(rows);
end

function settledIndex = findSettledIndex( ...
        velocity, startIndex, threshold, holdSteps)
settledIndex = NaN;
lastStart = numel(velocity)-holdSteps+1;
for candidate = startIndex:lastStart
    if all(abs(velocity(candidate:candidate+holdSteps-1)) < threshold)
        settledIndex = candidate;
        return;
    end
end
end

function summary = summarizeEventLatency(latency)
keys = unique(latency(:, ["commandSource", "synergyAxis", ...
    "directionName", "motor"]), "rows", "stable");
rows = repmat(emptyLatencySummaryRow(), height(keys), 1);
for keyIdx = 1:height(keys)
    values = latency( ...
        latency.commandSource == keys.commandSource(keyIdx) & ...
        latency.synergyAxis == keys.synergyAxis(keyIdx) & ...
        latency.directionName == keys.directionName(keyIdx) & ...
        latency.motor == keys.motor(keyIdx), :);
    row = emptyLatencySummaryRow();
    row.commandSource = keys.commandSource(keyIdx);
    row.synergyAxis = keys.synergyAxis(keyIdx);
    row.directionName = keys.directionName(keyIdx);
    row.motor = keys.motor(keyIdx);
    row.episodeCount = height(values);
    row.finiteOnsetFraction = mean(values.finiteOnset);
    row.finiteOffsetFraction = mean(values.finiteOffset);
    row.preReferenceMotionFraction = mean(values.preReferenceMotion);
    row.meanPreReferenceCommandFraction = ...
        mean(values.preReferenceCommandFraction);
    row.maximumPreReferenceCommandFraction = ...
        max(values.preReferenceCommandFraction);
    row.meanPreReferenceAbsPwm = mean(values.preReferenceMeanAbsPwm);
    row.meanPreReferenceAbsEffectiveAction = ...
        mean(values.preReferenceMeanAbsEffectiveAction);
    row.meanPreReferenceAbsVelocity = ...
        mean(values.preReferenceMeanAbsVelocity);
    row.medianOnsetDelaySteps = median(values.onsetDelaySteps, "omitnan");
    row.maximumOnsetDelaySteps = max(values.onsetDelaySteps, [], "omitnan");
    row.medianOnsetDelaySec = median(values.onsetDelaySec, "omitnan");
    row.medianOffsetDelaySteps = median(values.offsetDelaySteps, "omitnan");
    row.medianOffsetDelaySec = median(values.offsetDelaySec, "omitnan");
    row.meanDirectionalResponseFraction = ...
        mean(values.directionalResponseFraction);
    row.meanPeakDirectionalVelocity = mean(values.peakDirectionalVelocity);
    row.meanEndpointAbsoluteError = mean(values.endpointAbsoluteError);
    row.trackingMse = mean(values.trackingMse);
    row.saturationFraction = mean(values.saturationFraction);
    row.safetyInterventionCount = sum(values.safetyInterventionCount);
    rows(keyIdx) = row;
end
summary = struct2table(rows);
end

function gate = buildDesignedGate(lagSummary, eventSummary, options)
rows = repmat(emptyDesignedGateRow(), height(lagSummary), 1);
for rowIdx = 1:height(lagSummary)
    lag = lagSummary(rowIdx, :);
    directionName = regimeToDirection(lag.regime);
    event = eventSummary( ...
        eventSummary.commandSource == lag.commandSource & ...
        eventSummary.synergyAxis == lag.synergyAxis & ...
        eventSummary.directionName == directionName & ...
        eventSummary.motor == lag.motor, :);
    if height(event) ~= 1
        error("analyzeNoGloveStage7bDesignedResponse:EventMismatch", ...
            "Expected one event summary for each lag summary row.");
    end
    eventGate = event.finiteOnsetFraction >= ...
        options.minimumFiniteOnsetFraction && ...
        event.preReferenceMotionFraction == 0 && ...
        event.maximumPreReferenceCommandFraction == 0 && ...
        event.medianOnsetDelaySteps >= 0 && ...
        event.medianOnsetDelaySteps <= options.maxLagSteps;
    candidate = lag.causalCompensationCandidate && eventGate;
    if candidate
        classification = "designedPositiveDelayConfirmed";
        recommendation = ...
            "Stop; a separate target-only causal intervention may be proposed.";
    elseif lag.classification == "boundaryUnresolved"
        classification = "unresolvedAtPreRegisteredBound";
        recommendation = ...
            "Do not widen post-hoc or compensate; inspect controller dynamics.";
    elseif lag.classification == "noHeldOutMaterialBenefit"
        classification = "fixedLagRejectedOnDesignedProfiles";
        recommendation = ...
            "Return to controller/safety diagnosis without temporal correction.";
    else
        classification = "designedTemporalGateFailed";
        recommendation = "Do not run compensation or filtering.";
    end
    row = emptyDesignedGateRow();
    row.commandSource = lag.commandSource;
    row.synergyAxis = lag.synergyAxis;
    row.regime = lag.regime;
    row.directionName = directionName;
    row.motor = lag.motor;
    row.heldOutImprovementFraction = lag.heldOutImprovementFraction;
    row.medianSelectedLagSteps = lag.medianSelectedLagSteps;
    row.boundarySelectionFraction = lag.boundarySelectionFraction;
    row.finiteOnsetFraction = event.finiteOnsetFraction;
    row.preReferenceMotionFraction = event.preReferenceMotionFraction;
    row.meanPreReferenceCommandFraction = ...
        event.meanPreReferenceCommandFraction;
    row.maximumPreReferenceCommandFraction = ...
        event.maximumPreReferenceCommandFraction;
    row.meanPreReferenceAbsPwm = event.meanPreReferenceAbsPwm;
    row.meanPreReferenceAbsEffectiveAction = ...
        event.meanPreReferenceAbsEffectiveAction;
    row.meanPreReferenceAbsVelocity = ...
        event.meanPreReferenceAbsVelocity;
    row.medianOnsetDelaySteps = event.medianOnsetDelaySteps;
    row.medianOnsetDelaySec = event.medianOnsetDelaySec;
    row.lagGatePassed = lag.causalCompensationCandidate;
    row.eventGatePassed = eventGate;
    row.causalCompensationCandidate = candidate;
    row.classification = classification;
    row.recommendation = recommendation;
    rows(rowIdx) = row;
end
gate = struct2table(rows);
end

function directionName = regimeToDirection(regime)
if regime == "closing"
    directionName = "positive";
elseif regime == "opening"
    directionName = "negative";
else
    error("analyzeNoGloveStage7bDesignedResponse:UnexpectedRegime", ...
        "ETAPA 7B only accepts opening and closing.");
end
end

function decision = summarizeSources(gate)
sources = unique(gate.commandSource, "stable");
rows = repmat(emptySourceDecisionRow(), numel(sources), 1);
for sourceIdx = 1:numel(sources)
    values = gate(gate.commandSource == sources(sourceIdx), :);
    candidateCount = sum(values.causalCompensationCandidate);
    unresolvedCount = sum( ...
        values.classification == "unresolvedAtPreRegisteredBound");
    rejectedCount = sum( ...
        values.classification == "fixedLagRejectedOnDesignedProfiles");
    if candidateCount > 0
        classification = "designedCausalCandidate";
        recommendation = ...
            "Stop before any intervention and request explicit authorization.";
    elseif unresolvedCount > 0
        classification = "designedTemporalPatternUnresolved";
        recommendation = ...
            "Do not compensate, filter or widen the lag bound post-hoc.";
    else
        classification = "fixedLagHypothesisRejected";
        recommendation = ...
            "Continue controller/safety diagnosis without temporal correction.";
    end
    row = emptySourceDecisionRow();
    row.commandSource = sources(sourceIdx);
    row.gateRowCount = height(values);
    row.causalCandidateCount = candidateCount;
    row.unresolvedCount = unresolvedCount;
    row.rejectedCount = rejectedCount;
    row.causalCompensationCandidate = candidateCount > 0;
    row.classification = classification;
    row.recommendation = recommendation;
    rows(sourceIdx) = row;
end
decision = struct2table(rows);
end

