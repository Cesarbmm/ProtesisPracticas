function analysis = analyzeNoGloveStage7qAttribution( ...
        primaryCorpus, sharedEvaluations, ownCorpora, options)
%analyzeNoGloveStage7qAttribution attributes frozen state-60 commands.

arguments
    primaryCorpus (1, 1) struct
    sharedEvaluations struct
    ownCorpora struct
    options.expectedPrimaryComponentCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 2064
    options.positionBoundaryTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-9
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
    options.scaleFloor (1, 1) double {mustBePositive} = 1e-6
    options.ridgeLambda (1, 1) double {mustBePositive} = 1
    options.foldCount (1, 1) double {mustBeInteger, mustBePositive} = 5
    options.minimumSensitivityShare (1, 1) double ...
        {mustBeInRange(options.minimumSensitivityShare, 0, 1)} = 0.50
    options.minimumSensitivityRatio (1, 1) double ...
        {mustBeGreaterThanOrEqual(options.minimumSensitivityRatio, 1)} = 2
    options.minimumAssociationR2 (1, 1) double = 0.25
    options.minimumAssociationMargin (1, 1) double ...
        {mustBeNonnegative} = 0.10
    options.minimumTemporalShare (1, 1) double ...
        {mustBeInRange(options.minimumTemporalShare, 0, 1)} = 0.50
    options.minimumMotorAgreement (1, 1) double ...
        {mustBeInteger, mustBeInRange(options.minimumMotorAgreement, 1, 4)} = 3
    options.latePwmRelativeIncrease (1, 1) double ...
        {mustBeNonnegative} = 0.25
    options.lateFractionIncrease (1, 1) double ...
        {mustBeInRange(options.lateFractionIncrease, 0, 1)} = 0.10
end

validateInputs(primaryCorpus, sharedEvaluations, ownCorpora);
episodes = reshape([sharedEvaluations.episode], [], 1);
blocks = blockContract();
states = double(primaryCorpus.states);
metadata = primaryCorpus.metadata;
stateScale = std(states, 0, 1);
stateScale(stateScale < options.scaleFloor) = options.scaleFloor;
primaryWindow = ismember(metadata.gateContext, ...
    ["initialRest", "declaredRest"]);
primaryMask = primaryCorpus.zeroControlDemand & primaryWindow;
if sum(primaryMask, "all") ~= options.expectedPrimaryComponentCount
    error("analyzeNoGloveStage7qAttribution:PrimaryCount", ...
        "The preregistered primary component count changed.");
end

agent200Idx = find(episodes == 200, 1);
agent200Pwm = double(sharedEvaluations(agent200Idx).pwm);
agent200Outward = outwardMask(primaryCorpus.qBefore, agent200Pwm, ...
    options.positionBoundaryTolerance);

primaryComponents = buildPrimaryComponents(primaryCorpus, ...
    sharedEvaluations(agent200Idx), primaryMask, agent200Outward);
[gradientComponents, gradientSummary] = buildGradientTables( ...
    sharedEvaluations, primaryCorpus, primaryMask, blocks, stateScale);
associationSummary = buildAssociationSummary(sharedEvaluations, ...
    states, metadata, primaryMask, blocks, options);
temporalSummary = buildTemporalSummary(sharedEvaluations, states, ...
    metadata, primaryMask, blocks);
priorActionSummary = buildPriorActionSummary(sharedEvaluations, ...
    states, primaryMask);
sharedCheckpointSummary = buildSharedCheckpointSummary( ...
    sharedEvaluations, primaryCorpus, primaryMask, agent200Outward, options);
ownCheckpointSummary = buildOwnCheckpointSummary(ownCorpora, options);
[scientificResult, blockDecisionAudit, decisionAudit] = ...
    selectAttribution(gradientSummary, associationSummary, ...
    temporalSummary, sharedCheckpointSummary, blocks, options);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7Q", "result", "PASS", ...
    "scientificResult", scientificResult, ...
    "stateDecision", "intentMarkov60", ...
    "state62Disposition", "provisionallyRejected", ...
    "primaryComponentCount", sum(primaryMask, "all"), ...
    "primaryWindowCount", sum(any(primaryMask, 2)), ...
    "agent200OutwardComponentCount", sum(agent200Outward, "all"), ...
    "stateScale", stateScale, "blockContract", blocks, ...
    "primaryComponents", primaryComponents, ...
    "gradientComponents", gradientComponents, ...
    "gradientSummary", gradientSummary, ...
    "associationSummary", associationSummary, ...
    "temporalSummary", temporalSummary, ...
    "priorActionSummary", priorActionSummary, ...
    "sharedCheckpointSummary", sharedCheckpointSummary, ...
    "ownCheckpointSummary", ownCheckpointSummary, ...
    "blockDecisionAudit", blockDecisionAudit, ...
    "decisionAudit", decisionAudit, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "hardwareUsed", false, ...
    "stateCounterfactualUsed", false, "futureLeakageUsed", false, ...
    "rewardChanged", false, "quantizationChanged", false, ...
    "td3Changed", false, "simulatorChanged", false, ...
    "safetyChanged", false, "gateChanged", false);
end

function validateInputs(corpus, evaluations, ownCorpora)
requiredCorpus = ["states", "rawAction", "effectiveAction", "pwm", ...
    "qBefore", "qReference", "vReference", "zeroControlDemand", ...
    "safetyIntervention", "metadata"];
requiredEvaluation = ["episode", "raw", "effective", "pwm", "gradients"];
if ~all(isfield(corpus, cellstr(requiredCorpus))) || ...
        numel(evaluations) ~= 4 || numel(ownCorpora) ~= 4 || ...
        ~all(isfield(evaluations, cellstr(requiredEvaluation))) || ...
        ~all(isfield(ownCorpora, ["episode", "corpus"]))
    error("analyzeNoGloveStage7qAttribution:InvalidContract", ...
        "Corpus, checkpoint evaluations or own corpora are incomplete.");
end
count = size(corpus.states, 1);
if size(corpus.states, 2) ~= 60 || height(corpus.metadata) ~= count || ...
        ~isequal(sort([evaluations.episode]), [50, 100, 150, 200]) || ...
        ~isequal(sort([ownCorpora.episode]), [50, 100, 150, 200])
    error("analyzeNoGloveStage7qAttribution:InvalidDimensions", ...
        "Expected aligned state-60 checkpoints 50/100/150/200.");
end
for idx = 1:numel(evaluations)
    value = evaluations(idx);
    if ~isequal(size(value.raw), [count, 4]) || ...
            ~isequal(size(value.effective), [count, 4]) || ...
            ~isequal(size(value.pwm), [count, 4]) || ...
            ~isequal(size(value.gradients), [count, 4, 60]) || ...
            any(~isfinite([value.raw(:); value.effective(:); ...
                value.pwm(:); value.gradients(:)]))
        error("analyzeNoGloveStage7qAttribution:InvalidEvaluation", ...
            "A checkpoint evaluation is nonfinite or misaligned.");
    end
end
end

function blocks = blockContract()
blocks = table( ...
    ["emgFeatures"; "q"; "deltaQ"; "previousEffectiveAction"; ...
        "qRef"; "vRef"], ...
    [1; 41; 45; 49; 53; 57], [40; 44; 48; 52; 56; 60], ...
    [40; 4; 4; 4; 4; 4], ...
    'VariableNames', ["block", "firstIndex", "lastIndex", "dimension"]);
end

function tableValue = buildPrimaryComponents(corpus, evaluation, ...
        primaryMask, agent200Outward)
count = size(corpus.states, 1);
windowIndex = repelem(corpus.metadata.windowIndex, 4);
rowId = repelem(corpus.metadata.rowId, 4);
source = repelem(corpus.metadata.source, 4);
episode = repelem(corpus.metadata.episode, 4);
step = repelem(corpus.metadata.step, 4);
context = repelem(corpus.metadata.gateContext, 4);
motor = repmat((1:4)', count, 1);
q = reshape(corpus.qBefore', [], 1);
qRef = reshape(corpus.qReference', [], 1);
vRef = reshape(corpus.vReference', [], 1);
uPrevious = reshape(corpus.states(:, 49:52)', [], 1);
raw = reshape(evaluation.raw', [], 1);
effective = reshape(evaluation.effective', [], 1);
pwm = reshape(evaluation.pwm', [], 1);
safety = reshape(corpus.safetyIntervention', [], 1);
isPrimary = reshape(primaryMask', [], 1);
outward = reshape(agent200Outward', [], 1);
tableValue = table(windowIndex, rowId, source, episode, step, context, ...
    motor, q, qRef, vRef, uPrevious, raw, effective, pwm, outward, ...
    safety, 'VariableNames', ["windowIndex", "rowId", "source", ...
    "episode", "step", "context", "motor", "q", "qRef", "vRef", ...
    "previousEffectiveAction", "rawAction", "effectiveAction", "pwm", ...
    "outwardAtBoundary", "safetyInterventionCount"]);
tableValue = tableValue(isPrimary, :);
end

function [components, summary] = buildGradientTables( ...
        evaluations, corpus, primaryMask, blocks, stateScale)
parts = cell(numel(evaluations)*4*height(blocks), 1);
cursor = 0;
for evalIdx = 1:numel(evaluations)
    gradients = evaluations(evalIdx).gradients;
    scaledByBlock = zeros(size(corpus.states, 1), 4, height(blocks));
    rawByBlock = zeros(size(scaledByBlock));
    for blockIdx = 1:height(blocks)
        indices = blocks.firstIndex(blockIdx):blocks.lastIndex(blockIdx);
        for motor = 1:4
            gradient = reshape(gradients(:, motor, indices), ...
                size(corpus.states, 1), []);
            rawByBlock(:, motor, blockIdx) = ...
                sqrt(mean(gradient.^2, 2));
            scaledByBlock(:, motor, blockIdx) = sqrt(mean( ...
                (gradient.*stateScale(indices)).^2, 2));
        end
    end
    totals = sum(scaledByBlock, 3);
    for motor = 1:4
        mask = primaryMask(:, motor);
        for blockIdx = 1:height(blocks)
            cursor = cursor+1;
            scaled = scaledByBlock(mask, motor, blockIdx);
            shares = scaled./totals(mask, motor);
            shares(totals(mask, motor) == 0) = NaN;
            parts{cursor} = table( ...
                repmat(evaluations(evalIdx).episode, sum(mask), 1), ...
                corpus.metadata.windowIndex(mask), ...
                corpus.metadata.rowId(mask), ...
                corpus.metadata.source(mask), ...
                corpus.metadata.episode(mask), ...
                corpus.metadata.step(mask), ...
                corpus.metadata.gateContext(mask), ...
                repmat(motor, sum(mask), 1), ...
                repmat(blocks.block(blockIdx), sum(mask), 1), ...
                rawByBlock(mask, motor, blockIdx), scaled, shares, ...
                'VariableNames', ["checkpointEpisode", "windowIndex", ...
                "rowId", "source", "episode", "step", "context", ...
                "motor", "block", "rawGradientRms", ...
                "scaledGradientRms", "scaledSensitivityShare"]);
        end
    end
end
components = vertcat(parts{:});
groups = findgroups(components.checkpointEpisode, components.motor, ...
    components.block);
episode = splitapply(@(x) x(1), components.checkpointEpisode, groups);
motor = splitapply(@(x) x(1), components.motor, groups);
block = splitapply(@(x) x(1), components.block, groups);
componentCount = splitapply(@numel, components.rawGradientRms, groups);
meanRawGradientRms = splitapply(@mean, ...
    components.rawGradientRms, groups);
medianRawGradientRms = splitapply(@median, ...
    components.rawGradientRms, groups);
meanScaledGradientRms = splitapply(@mean, ...
    components.scaledGradientRms, groups);
medianScaledGradientRms = splitapply(@median, ...
    components.scaledGradientRms, groups);
meanScaledSensitivityShare = splitapply(@localMeanOmitNan, ...
    components.scaledSensitivityShare, groups);
medianScaledSensitivityShare = splitapply(@localMedianOmitNan, ...
    components.scaledSensitivityShare, groups);
summary = table(episode, motor, block, componentCount, ...
    meanRawGradientRms, medianRawGradientRms, ...
    meanScaledGradientRms, medianScaledGradientRms, ...
    meanScaledSensitivityShare, medianScaledSensitivityShare, ...
    'VariableNames', ["checkpointEpisode", "motor", "block", ...
    "componentCount", "meanRawGradientRms", "medianRawGradientRms", ...
    "meanScaledGradientRms", "medianScaledGradientRms", ...
    "meanScaledSensitivityShare", "medianScaledSensitivityShare"]);
end

function summary = buildAssociationSummary(evaluations, states, ...
        metadata, primaryMask, blocks, options)
parts = cell(numel(evaluations)*4*height(blocks), 1);
cursor = 0;
for evalIdx = 1:numel(evaluations)
    for motor = 1:4
        mask = primaryMask(:, motor);
        keys = metadata.source(mask) + ":" + ...
            compose("%05d", metadata.episode(mask));
        for blockIdx = 1:height(blocks)
            indices = blocks.firstIndex(blockIdx):blocks.lastIndex(blockIdx);
            [r2, correlation, foldRows] = groupedRidgeAssociation( ...
                states(mask, indices), ...
                evaluations(evalIdx).raw(mask, motor), keys, ...
                options.foldCount, options.ridgeLambda);
            cursor = cursor+1;
            parts{cursor} = table(evaluations(evalIdx).episode, ...
                motor, blocks.block(blockIdx), sum(mask), ...
                options.foldCount, min(foldRows), r2, correlation, ...
                'VariableNames', ["checkpointEpisode", "motor", ...
                "block", "componentCount", "foldCount", ...
                "minimumTestRows", "crossValidatedR2", ...
                "predictionCorrelation"]);
        end
    end
end
summary = vertcat(parts{:});
end

function [r2, correlation, foldRows] = groupedRidgeAssociation( ...
        predictors, response, groupKeys, foldCount, lambda)
[~, ~, groupIndex] = unique(groupKeys);
fold = mod(groupIndex-1, foldCount)+1;
prediction = nan(size(response));
foldRows = zeros(foldCount, 1);
for foldIdx = 1:foldCount
    test = fold == foldIdx;
    train = ~test;
    foldRows(foldIdx) = sum(test);
    centerX = mean(predictors(train, :), 1);
    scaleX = std(predictors(train, :), 0, 1);
    scaleX(scaleX < 1e-8) = 1;
    xTrain = (predictors(train, :)-centerX)./scaleX;
    xTest = (predictors(test, :)-centerX)./scaleX;
    centerY = mean(response(train));
    yTrain = response(train)-centerY;
    beta = (xTrain'*xTrain + lambda*eye(size(xTrain, 2))) \ ...
        (xTrain'*yTrain);
    prediction(test) = centerY+xTest*beta;
end
residual = sum((response-prediction).^2);
total = sum((response-mean(response)).^2);
if total == 0
    r2 = NaN;
else
    r2 = 1-residual/total;
end
correlation = localCorrelation(response, prediction);
end

function summary = buildTemporalSummary(evaluations, states, metadata, ...
        primaryMask, blocks)
sameTrajectory = false(size(states, 1), 1);
sameTrajectory(2:end) = metadata.source(2:end) == ...
    metadata.source(1:end-1) & metadata.episode(2:end) == ...
    metadata.episode(1:end-1) & metadata.step(2:end) == ...
    metadata.step(1:end-1)+1;
parts = cell(numel(evaluations)*4*height(blocks), 1);
cursor = 0;
for evalIdx = 1:numel(evaluations)
    for motor = 1:4
        current = find(sameTrajectory & primaryMask(:, motor));
        current = current(primaryMask(current-1, motor));
        previous = current-1;
        contribution = zeros(numel(current), height(blocks));
        for blockIdx = 1:height(blocks)
            indices = blocks.firstIndex(blockIdx):blocks.lastIndex(blockIdx);
            gradient = reshape(evaluations(evalIdx).gradients( ...
                previous, motor, indices), numel(previous), []);
            deltaState = states(current, indices)-states(previous, indices);
            contribution(:, blockIdx) = sum(gradient.*deltaState, 2);
        end
        actualDelta = evaluations(evalIdx).raw(current, motor) - ...
            evaluations(evalIdx).raw(previous, motor);
        approximationError = abs(actualDelta-sum(contribution, 2));
        meanAbsolute = mean(abs(contribution), 1);
        denominator = sum(meanAbsolute);
        for blockIdx = 1:height(blocks)
            cursor = cursor+1;
            parts{cursor} = table(evaluations(evalIdx).episode, ...
                motor, blocks.block(blockIdx), numel(current), ...
                meanAbsolute(blockIdx), median(abs( ...
                    contribution(:, blockIdx))), ...
                safeRatio(meanAbsolute(blockIdx), denominator), ...
                mean(abs(actualDelta)), mean(approximationError), ...
                median(approximationError), ...
                'VariableNames', ["checkpointEpisode", "motor", ...
                "block", "transitionCount", ...
                "meanAbsoluteContribution", ...
                "medianAbsoluteContribution", ...
                "absoluteContributionFraction", ...
                "meanAbsoluteActionDelta", ...
                "meanLinearApproximationError", ...
                "medianLinearApproximationError"]);
        end
    end
end
summary = vertcat(parts{:});
end

function summary = buildPriorActionSummary(evaluations, states, primaryMask)
parts = cell(numel(evaluations)*4, 1);
cursor = 0;
for evalIdx = 1:numel(evaluations)
    for motor = 1:4
        cursor = cursor+1;
        mask = primaryMask(:, motor);
        previous = states(mask, 48+motor);
        action = evaluations(evalIdx).raw(mask, motor);
        diagonal = evaluations(evalIdx).gradients(mask, motor, 48+motor);
        diagonal = diagonal(:);
        crossIndices = setdiff(49:52, 48+motor);
        cross = reshape(evaluations(evalIdx).gradients( ...
            mask, motor, crossIndices), sum(mask), []);
        nonzero = previous ~= 0 & action ~= 0;
        summarySign = safeRatio(sum(sign(previous(nonzero)) == ...
            sign(action(nonzero))), sum(nonzero));
        parts{cursor} = table(evaluations(evalIdx).episode, motor, ...
            sum(mask), median(diagonal), median(abs(diagonal)), ...
            median(mean(abs(cross), 2)), ...
            localCorrelation(previous, action), summarySign, ...
            mean(abs(action-previous)), ...
            'VariableNames', ["checkpointEpisode", "motor", ...
            "componentCount", "medianSignedDiagonalGradient", ...
            "medianAbsoluteDiagonalGradient", ...
            "medianMeanAbsoluteCrossMotorGradient", ...
            "previousCurrentActionCorrelation", ...
            "previousCurrentSignAgreement", ...
            "meanAbsoluteCurrentMinusPrevious"]);
    end
end
summary = vertcat(parts{:});
end

function summary = buildSharedCheckpointSummary(evaluations, corpus, ...
        primaryMask, agent200Outward, options)
parts = cell(numel(evaluations), 1);
for idx = 1:numel(evaluations)
    cohorts = struct( ...
        "all", true(size(primaryMask)), ...
        "primaryZeroDemand", primaryMask, ...
        "steadyRest", repmat(corpus.metadata.source == ...
            "steadyRest", 1, 4), ...
        "agent200OutwardSet", agent200Outward);
    parts{idx} = summarizeCommands(evaluations(idx).episode, ...
        "sharedAgent200States", cohorts, corpus.qBefore, ...
        evaluations(idx).raw, evaluations(idx).effective, ...
        evaluations(idx).pwm, options);
end
summary = vertcat(parts{:});
end

function summary = buildOwnCheckpointSummary(ownCorpora, options)
parts = cell(numel(ownCorpora), 1);
for idx = 1:numel(ownCorpora)
    corpus = ownCorpora(idx).corpus;
    primaryWindow = ismember(corpus.metadata.gateContext, ...
        ["initialRest", "declaredRest"]);
    primaryMask = corpus.zeroControlDemand & primaryWindow;
    cohorts = struct( ...
        "all", true(size(primaryMask)), ...
        "primaryZeroDemand", primaryMask, ...
        "steadyRest", repmat(corpus.metadata.source == ...
            "steadyRest", 1, 4));
    parts{idx} = summarizeCommands(ownCorpora(idx).episode, ...
        "ownCheckpointCorpus", cohorts, corpus.qBefore, ...
        corpus.rawAction, corpus.effectiveAction, corpus.pwm, options);
end
summary = vertcat(parts{:});
end

function summary = summarizeCommands(checkpointEpisode, replayMode, ...
        cohorts, q, raw, effective, pwm, options)
cohortNames = string(fieldnames(cohorts));
parts = cell(numel(cohortNames)*5, 1);
cursor = 0;
outward = outwardMask(q, pwm, options.positionBoundaryTolerance);
saturated = abs(effective) >= options.saturationThreshold;
for cohortIdx = 1:numel(cohortNames)
    cohort = cohortNames(cohortIdx);
    eligible = cohorts.(cohort);
    for motor = 0:4
        cursor = cursor+1;
        if motor == 0
            mask = eligible;
        else
            mask = false(size(eligible));
            mask(:, motor) = eligible(:, motor);
        end
        parts{cursor} = table(checkpointEpisode, string(replayMode), ...
            cohort, motor, sum(mask, "all"), ...
            safeMean(abs(raw(mask))), safeMean(abs(pwm(mask))), ...
            safeRatio(sum(pwm(mask) ~= 0), sum(mask, "all")), ...
            safeRatio(sum(saturated(mask)), sum(mask, "all")), ...
            safeRatio(sum(outward(mask)), sum(mask, "all")), ...
            'VariableNames', ["checkpointEpisode", "replayMode", ...
            "cohort", "motor", "componentCount", ...
            "meanAbsoluteRawAction", "meanAbsolutePwm", ...
            "nonzeroPwmFraction", "saturationFraction", ...
            "outwardAtBoundaryFraction"]);
    end
end
summary = vertcat(parts{:});
end

function mask = outwardMask(q, pwm, tolerance)
mask = (q <= tolerance & pwm < 0) | ...
    (q >= 1-tolerance & pwm > 0);
end

function [result, blockAudit, decisionAudit] = selectAttribution( ...
        gradientSummary, associationSummary, temporalSummary, ...
        commandSummary, blocks, options)
blockCount = height(blocks);
gradientStrong = zeros(blockCount, 1);
associationStrong = zeros(blockCount, 1);
temporalStrong = zeros(blockCount, 1);
for motor = 1:4
    gradientRows = gradientSummary( ...
        gradientSummary.checkpointEpisode == 200 & ...
        gradientSummary.motor == motor, :);
    [top, second] = topTwo(gradientRows.block, ...
        gradientRows.medianScaledSensitivityShare);
    if top.value >= options.minimumSensitivityShare && ...
            dominanceRatio(top.value, second.value) >= ...
            options.minimumSensitivityRatio
        gradientStrong(blocks.block == top.name) = ...
            gradientStrong(blocks.block == top.name)+1;
    end

    associationRows = associationSummary( ...
        associationSummary.checkpointEpisode == 200 & ...
        associationSummary.motor == motor, :);
    [top, second] = topTwo(associationRows.block, ...
        associationRows.crossValidatedR2);
    if top.value >= options.minimumAssociationR2 && ...
            top.value-second.value >= options.minimumAssociationMargin
        associationStrong(blocks.block == top.name) = ...
            associationStrong(blocks.block == top.name)+1;
    end

    temporalRows = temporalSummary( ...
        temporalSummary.checkpointEpisode == 200 & ...
        temporalSummary.motor == motor, :);
    [top, ~] = topTwo(temporalRows.block, ...
        temporalRows.absoluteContributionFraction);
    if top.value >= options.minimumTemporalShare
        temporalStrong(blocks.block == top.name) = ...
            temporalStrong(blocks.block == top.name)+1;
    end
end
eligible = gradientStrong >= options.minimumMotorAgreement & ...
    associationStrong >= options.minimumMotorAgreement & ...
    temporalStrong >= options.minimumMotorAgreement;
candidateNames = blocks.block(eligible);

primaryRows = commandSummary(commandSummary.cohort == ...
    "primaryZeroDemand" & commandSummary.motor == 0, :);
agent200 = primaryRows(primaryRows.checkpointEpisode == 200, :);
earlier = primaryRows(primaryRows.checkpointEpisode < 200, :);
earlierMaxPwm = max(earlier.meanAbsolutePwm);
earlierMaxNonzero = max(earlier.nonzeroPwmFraction);
earlierMaxOutward = max(earlier.outwardAtBoundaryFraction);
pwmRatio = safeRatio(agent200.meanAbsolutePwm, earlierMaxPwm);
nonzeroIncrease = agent200.nonzeroPwmFraction-earlierMaxNonzero;
outwardIncrease = agent200.outwardAtBoundaryFraction-earlierMaxOutward;
late = pwmRatio >= 1+options.latePwmRelativeIncrease && ...
    (nonzeroIncrease >= options.lateFractionIncrease || ...
    outwardIncrease >= options.lateFractionIncrease);
if numel(candidateNames) == 1
    result = "uniqueUpstreamBlock:"+candidateNames;
elseif late
    result = "lateTrainingEmergence";
else
    result = "distributedOrUnresolved";
end

blockAudit = table(blocks.block, gradientStrong, associationStrong, ...
    temporalStrong, eligible, ...
    'VariableNames', ["block", "strongGradientMotorCount", ...
    "strongAssociationMotorCount", "strongTemporalMotorCount", ...
    "uniqueBlockEligible"]);
decisionAudit = table(string(result), options.minimumMotorAgreement, ...
    options.minimumSensitivityShare, options.minimumSensitivityRatio, ...
    options.minimumAssociationR2, options.minimumAssociationMargin, ...
    options.minimumTemporalShare, pwmRatio, ...
    options.latePwmRelativeIncrease, nonzeroIncrease, outwardIncrease, ...
    options.lateFractionIncrease, late, ...
    'VariableNames', ["scientificResult", "minimumMotorAgreement", ...
    "minimumSensitivityShare", "minimumSensitivityRatio", ...
    "minimumAssociationR2", "minimumAssociationMargin", ...
    "minimumTemporalShare", "agent200ToEarlierMaxMeanAbsPwmRatio", ...
    "requiredLatePwmRelativeIncrease", ...
    "agent200NonzeroFractionIncrease", ...
    "agent200OutwardFractionIncrease", ...
    "requiredLateFractionIncrease", "lateTrainingGatePassed"]);
end

function [top, second] = topTwo(names, values)
values(~isfinite(values)) = -Inf;
[sorted, order] = sort(values, "descend");
top = struct("name", names(order(1)), "value", sorted(1));
if numel(sorted) > 1
    second = struct("name", names(order(2)), "value", sorted(2));
else
    second = struct("name", "", "value", -Inf);
end
end

function value = localCorrelation(a, b)
a = double(a(:));
b = double(b(:));
if numel(a) < 2 || std(a) == 0 || std(b) == 0
    value = NaN;
else
    centeredA = a-mean(a);
    centeredB = b-mean(b);
    value = sum(centeredA.*centeredB)/sqrt( ...
        sum(centeredA.^2)*sum(centeredB.^2));
end
end

function value = safeRatio(numerator, denominator)
if denominator == 0 || ~isfinite(denominator)
    value = NaN;
else
    value = numerator/denominator;
end
end

function value = dominanceRatio(top, second)
if top > 0 && second <= 0
    value = Inf;
elseif second > 0
    value = top/second;
else
    value = NaN;
end
end

function value = safeMean(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = localMeanOmitNan(values)
values = values(isfinite(values));
value = safeMean(values);
end

function value = localMedianOmitNan(values)
