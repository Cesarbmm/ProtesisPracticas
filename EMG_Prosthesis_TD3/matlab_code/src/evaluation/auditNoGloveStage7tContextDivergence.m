function audit = auditNoGloveStage7tContextDivergence(corpus, pairSet, options)
%auditNoGloveStage7tContextDivergence decomposes failed real-state matching.

arguments
    corpus (1, 1) struct
    pairSet (1, 1) struct
    options.contextMaximumThreshold (1, 1) double ...
        {mustBePositive} = 0.25
    options.minimumEmgDistance (1, 1) double ...
        {mustBePositive} = 0.50
end

requiredCorpus = ["states", "zeroControlDemand", "metadata"];
requiredPairSet = ["metadata", "primaryMask", "emgScale", ...
    "contextScale", "statesEvaluated"];
if ~all(isfield(corpus, cellstr(requiredCorpus))) || ...
        ~all(isfield(pairSet, cellstr(requiredPairSet))) || ...
        size(corpus.states, 2) ~= 60 || ...
        ~isequal(corpus.states, pairSet.statesEvaluated) || ...
        ~isequal(size(pairSet.primaryMask), ...
        size(corpus.zeroControlDemand)) || ...
        ~isequal(pairSet.primaryMask, ...
        pairSet.primaryMask & corpus.zeroControlDemand) || ...
        ~ismember("fold", ...
        string(pairSet.metadata.Properties.VariableNames))
    error("auditNoGloveStage7tContextDivergence:InvalidContract", ...
        "The locked state-60 matching contract is invalid.");
end
states = double(corpus.states);
metadata = pairSet.metadata;
emgScale = double(pairSet.emgScale(:)');
contextScale = double(pairSet.contextScale(:)');
if ~isequal(size(emgScale), [1, 40]) || ...
        ~isequal(size(contextScale), [1, 20]) || ...
        any(~isfinite([emgScale, contextScale])) || ...
        any([emgScale, contextScale] <= 0)
    error("auditNoGloveStage7tContextDivergence:InvalidScales", ...
        "Frozen positive 40/20 scales are required.");
end

blockNames = ["q", "deltaQ", "previousEffectiveAction", ...
    "qReference", "vReference"];
blockIndices = {1:4, 5:8, 9:12, 13:16, 17:20};
rest = metadata.source == "steadyRest";
maximumRows = sum(pairSet.primaryMask(rest, :), "all");
rows = repmat(emptyQueryRow(), maximumRows, 1);
selectedBlockMaximum = nan(maximumRows, 5);
selectedBlockRms = nan(maximumRows, 5);
minimumWithoutBlock = nan(maximumRows, 5);
cursor = 0;

for motor = 1:4
    queries = find(rest & pairSet.primaryMask(:, motor));
    for query = queries'
        cursor = cursor+1;
        candidates = find(rest & ...
            metadata.gateContext == metadata.gateContext(query) & ...
            metadata.fold == metadata.fold(query) & ...
            metadata.episode ~= metadata.episode(query));
        emgRms = zeros(0, 1);
        contextDifference = zeros(0, 20);
        if ~isempty(candidates)
            emgDifference = (states(query, 1:40) - ...
                states(candidates, 1:40))./emgScale;
            emgRmsAll = sqrt(mean(emgDifference.^2, 2));
            eligible = emgRmsAll >= options.minimumEmgDistance;
            candidates = candidates(eligible);
            emgRms = emgRmsAll(eligible);
            contextDifference = (states(query, 41:60) - ...
                states(candidates, 41:60))./contextScale;
        end

        selectedDonor = 0;
        selectedEmgRms = NaN;
        minimumContextMaximum = NaN;
        minimumContextRms = NaN;
        if ~isempty(candidates)
            candidateMaximum = max(abs(contextDifference), [], 2);
            candidateRms = sqrt(mean(contextDifference.^2, 2));
            [minimumContextMaximum, selected] = min(candidateMaximum);
            selectedDonor = candidates(selected);
            selectedEmgRms = emgRms(selected);
            minimumContextRms = candidateRms(selected);
            for block = 1:5
                indices = blockIndices{block};
                values = contextDifference(selected, indices);
                selectedBlockMaximum(cursor, block) = max(abs(values));
                selectedBlockRms(cursor, block) = sqrt(mean(values.^2));
                kept = setdiff(1:20, indices);
                minimumWithoutBlock(cursor, block) = min(max( ...
                    abs(contextDifference(:, kept)), [], 2));
            end
        end
        phase = "postFirst";
        if metadata.step(query) == 1
            phase = "firstStep";
        end
        rows(cursor) = struct( ...
            "queryAuditRow", cursor, "queryRow", query, ...
            "motor", motor, "episode", metadata.episode(query), ...
            "step", metadata.step(query), "phase", phase, ...
            "fold", metadata.fold(query), ...
            "gateContext", string(metadata.gateContext(query)), ...
            "candidateCount", numel(candidates), ...
            "selectedDonorRow", selectedDonor, ...
            "selectedDonorEpisode", selectedEpisode( ...
                metadata, selectedDonor), ...
            "selectedDonorStep", selectedStep(metadata, selectedDonor), ...
            "selectedEmgRms", selectedEmgRms, ...
            "minimumContextMaximum", minimumContextMaximum, ...
            "minimumContextRms", minimumContextRms, ...
            "fullMatch", isfinite(minimumContextMaximum) && ...
                minimumContextMaximum <= ...
                options.contextMaximumThreshold);
    end
end
if cursor ~= maximumRows
    error("auditNoGloveStage7tContextDivergence:RowCount", ...
        "Primary query count changed during the audit.");
end
queryTable = struct2table(rows);

blockParts = cell(5, 1);
for block = 1:5
    selectedMaximum = selectedBlockMaximum(:, block);
    selectedRms = selectedBlockRms(:, block);
    noBlockMinimum = minimumWithoutBlock(:, block);
    exceedsThreshold = selectedMaximum > ...
        options.contextMaximumThreshold;
    restoredWithoutBlock = ~queryTable.fullMatch & ...
        noBlockMinimum <= options.contextMaximumThreshold;
    isDominant = false(height(queryTable), 1);
    for row = 1:height(queryTable)
        if all(isfinite(selectedBlockMaximum(row, :))) && ...
                ~queryTable.fullMatch(row)
            maximum = max(selectedBlockMaximum(row, :));
            isDominant(row) = selectedMaximum(row) == maximum;
        end
    end
    blockParts{block} = table( ...
        queryTable.queryAuditRow, queryTable.queryRow, ...
        queryTable.motor, queryTable.episode, queryTable.step, ...
        queryTable.phase, repmat(blockNames(block), ...
        height(queryTable), 1), selectedMaximum, selectedRms, ...
        exceedsThreshold, isDominant, noBlockMinimum, ...
        restoredWithoutBlock, ...
        'VariableNames', ["queryAuditRow", "queryRow", "motor", ...
        "episode", "step", "phase", "block", ...
        "selectedBlockMaximum", "selectedBlockRms", ...
        "exceedsThreshold", "isDominant", ...
        "minimumWithoutBlock", "restoredWithoutBlock"]);
end
blockTable = vertcat(blockParts{:});

phaseSummary = summarizeQueries(queryTable, "phase");
stepSummary = summarizeQueries(queryTable, "step");
blockSummary = summarizeBlocks(blockTable);
audit = struct( ...
    "schemaVersion", 1, "stage", "7T", ...
    "queryTable", queryTable, "blockTable", blockTable, ...
    "phaseSummary", phaseSummary, "stepSummary", stepSummary, ...
    "blockSummary", blockSummary, "blockNames", blockNames, ...
    "queryCount", height(queryTable), ...
    "firstStepQueryCount", sum(queryTable.phase == "firstStep"), ...
    "postFirstQueryCount", sum(queryTable.phase == "postFirst"), ...
    "fullMatchCount", sum(queryTable.fullMatch), ...
    "contextMaximumThreshold", options.contextMaximumThreshold, ...
    "minimumEmgDistance", options.minimumEmgDistance, ...
    "distanceBlockOmissionOnly", true, ...
    "stateCounterfactualUsed", false, "actorEvaluated", false);
end

function summary = summarizeQueries(values, groupingVariable)
groups = unique(values.(groupingVariable), "stable");
parts = cell(numel(groups)*5, 1);
cursor = 0;
for groupIdx = 1:numel(groups)
    group = groups(groupIdx);
    groupRows = values.(groupingVariable) == group;
    for motor = 0:4
        cursor = cursor+1;
        rows = groupRows;
        if motor ~= 0
            rows = rows & values.motor == motor;
        end
        selected = values(rows, :);
        finite = isfinite(selected.minimumContextMaximum);
        candidateFraction = safeMean(selected.candidateCount > 0);
        matchFraction = safeMean(selected.fullMatch);
        med = localPercentile(selected.minimumContextMaximum(finite), 50);
        p95 = localPercentile(selected.minimumContextMaximum(finite), 95);
        if groupingVariable == "phase"
            label = string(group);
        else
            label = compose("%d", group);
        end
        parts{cursor} = table(label, motor, height(selected), ...
            sum(selected.candidateCount > 0), candidateFraction, ...
            sum(selected.fullMatch), matchFraction, med, p95, ...
            'VariableNames', ["group", "motor", "queryCount", ...
            "queriesWithCandidate", "candidateFraction", ...
            "fullMatchCount", "fullMatchFraction", ...
            "medianMinimumContextMaximum", ...
            "p95MinimumContextMaximum"]);
    end
end
summary = vertcat(parts{:});
end

function summary = summarizeBlocks(values)
phases = unique(values.phase, "stable")';
blocks = unique(values.block, "stable")';
parts = cell(numel(phases)*5*numel(blocks), 1);
cursor = 0;
for phase = phases
    for motor = 0:4
        for block = blocks
            cursor = cursor+1;
            rows = values.phase == phase & values.block == block;
            if motor ~= 0
                rows = rows & values.motor == motor;
            end
            selected = values(rows, :);
            finite = isfinite(selected.selectedBlockMaximum);
            parts{cursor} = table(phase, motor, block, height(selected), ...
                safeMean(selected.exceedsThreshold(finite)), ...
                safeMean(selected.isDominant(finite)), ...
                safeMean(selected.restoredWithoutBlock(finite)), ...
                localPercentile( ...
                    selected.selectedBlockMaximum(finite), 50), ...
                localPercentile( ...
                    selected.minimumWithoutBlock(finite), 50), ...
                'VariableNames', ["phase", "motor", "block", ...
                "queryCount", "thresholdExceedanceFraction", ...
                "dominantBlockFraction", "restorationFraction", ...
                "medianSelectedBlockMaximum", ...
                "medianMinimumWithoutBlock"]);
        end
    end
end
summary = vertcat(parts{:});
end

function value = selectedEpisode(metadata, row)
if row == 0
    value = 0;
else
    value = metadata.episode(row);
end
end

function value = selectedStep(metadata, row)
if row == 0
    value = 0;
else
    value = metadata.step(row);
end
end

function value = safeMean(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = localPercentile(values, percentage)
values = sort(double(values(:)));
if isempty(values)
    value = NaN;
    return;
end
position = 1+(numel(values)-1)*percentage/100;
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    weight = position-lower;
    value = values(lower)*(1-weight)+values(upper)*weight;
end
end

function row = emptyQueryRow()
row = struct( ...
    "queryAuditRow", 0, "queryRow", 0, "motor", 0, ...
    "episode", 0, "step", 0, "phase", "", "fold", 0, ...
    "gateContext", "", "candidateCount", 0, ...
    "selectedDonorRow", 0, "selectedDonorEpisode", 0, ...
    "selectedDonorStep", 0, "selectedEmgRms", NaN, ...
    "minimumContextMaximum", NaN, "minimumContextRms", NaN, ...
    "fullMatch", false);
end
