function pairSet = buildNoGloveStage7rRealPairs(corpus, options)
%buildNoGloveStage7rRealPairs matches complete observed state-60 rows.

arguments
    corpus (1, 1) struct
    options.expectedPrimaryComponentCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 2064
    options.contextMaximumThreshold (1, 1) double ...
        {mustBePositive} = 0.25
    options.minimumEmgDistance (1, 1) double ...
        {mustBePositive} = 0.50
    options.foldCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 5
    options.scaleFloor (1, 1) double {mustBePositive} = 1e-6
    options.contextGrid (1, :) double {mustBePositive} = [0.15, 0.25, 0.50]
    options.emgGrid (1, :) double {mustBePositive} = [0.25, 0.50, 0.75]
    options.minimumPairCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 100
    options.minimumUniqueEpisodes (1, 1) double ...
        {mustBeInteger, mustBePositive} = 20
    options.maximumDonorReuseFraction (1, 1) double ...
        {mustBeInRange(options.maximumDonorReuseFraction, 0, 1)} = 0.10
    options.emgScaleOverride double = []
    options.contextScaleOverride double = []
end

required = ["states", "zeroControlDemand", "metadata"];
if ~all(isfield(corpus, cellstr(required))) || ...
        size(corpus.states, 2) ~= 60 || ...
        size(corpus.zeroControlDemand, 2) ~= 4 || ...
        size(corpus.states, 1) ~= height(corpus.metadata) || ...
        any(~isfinite([corpus.states(:); corpus.zeroControlDemand(:)]))
    error("buildNoGloveStage7rRealPairs:InvalidCorpus", ...
        "Expected an aligned finite state-60 corpus.");
end
requiredMetadata = ["windowIndex", "rowId", "source", "episode", ...
    "step", "gateContext"];
if ~all(ismember(requiredMetadata, ...
        string(corpus.metadata.Properties.VariableNames)))
    error("buildNoGloveStage7rRealPairs:MetadataSchema", ...
        "Corpus metadata is incomplete.");
end

states = double(corpus.states);
metadata = corpus.metadata;
primaryWindow = ismember(metadata.gateContext, ...
    ["initialRest", "declaredRest"]);
primaryMask = corpus.zeroControlDemand & primaryWindow;
if sum(primaryMask, "all") ~= options.expectedPrimaryComponentCount
    error("buildNoGloveStage7rRealPairs:PrimaryCount", ...
        "The preregistered primary component count changed.");
end
metadata.fold = assignEpisodeFolds(metadata, options.foldCount);
[emgScale, contextScale, scaleSource] = resolveScales( ...
    states, options);

[pairTable, deltaContext, deltaEmg] = matchPairs(states, metadata, ...
    primaryMask, contextScale, emgScale, ...
    options.contextMaximumThreshold, options.minimumEmgDistance);
pairTable.permutedPairRow = buildPermutationIndex(pairTable);
supportSummary = summarizeSupport(pairTable, metadata, primaryMask, options);

gridParts = cell(numel(options.contextGrid)*numel(options.emgGrid), 1);
cursor = 0;
for contextThreshold = options.contextGrid
    for emgThreshold = options.emgGrid
        cursor = cursor+1;
        if contextThreshold == options.contextMaximumThreshold && ...
                emgThreshold == options.minimumEmgDistance
            gridPairs = pairTable;
        else
            gridPairs = matchPairs(states, metadata, primaryMask, ...
                contextScale, emgScale, contextThreshold, emgThreshold);
        end
        grid = summarizeSupport(gridPairs, metadata, primaryMask, options);
        grid = grid(grid.source == "ALL", :);
        grid.contextMaximumThreshold = repmat(contextThreshold, ...
            height(grid), 1);
        grid.minimumEmgDistance = repmat(emgThreshold, height(grid), 1);
        gridParts{cursor} = movevars(grid, ...
            ["contextMaximumThreshold", "minimumEmgDistance"], ...
            "Before", 1);
    end
end
gridSummary = vertcat(gridParts{:});

pairSet = struct( ...
    "schemaVersion", 1, "stage", "7R", ...
    "table", pairTable, "deltaContext", deltaContext, ...
    "deltaEmg", deltaEmg, "emgScale", emgScale, ...
    "contextScale", contextScale, "primaryMask", primaryMask, ...
    "metadata", metadata, "supportSummary", supportSummary, ...
    "gridSummary", gridSummary, ...
    "primaryComponentCount", sum(primaryMask, "all"), ...
    "pairCount", height(pairTable), ...
    "contextMaximumThreshold", options.contextMaximumThreshold, ...
    "minimumEmgDistance", options.minimumEmgDistance, ...
    "foldCount", options.foldCount, ...
    "scaleSource", scaleSource, ...
    "statesEvaluated", states, ...
    "stateCounterfactualUsed", false, "hybridStateUsed", false, ...
    "futureLeakageUsed", false);
end

function [emgScale, contextScale, source] = resolveScales(states, options)
emgOverride = options.emgScaleOverride;
contextOverride = options.contextScaleOverride;
if isempty(emgOverride) ~= isempty(contextOverride)
    error("buildNoGloveStage7rRealPairs:IncompleteScaleOverride", ...
        "EMG and context scale overrides must be provided together.");
end
if isempty(emgOverride)
    emgScale = std(states(:, 1:40), 0, 1);
    contextScale = std(states(:, 41:60), 0, 1);
    emgScale(emgScale < options.scaleFloor) = options.scaleFloor;
    contextScale(contextScale < options.scaleFloor) = options.scaleFloor;
    source = "corpusStandardDeviation";
    return;
end
emgScale = double(emgOverride(:)');
contextScale = double(contextOverride(:)');
if ~isequal(size(emgScale), [1, 40]) || ...
        ~isequal(size(contextScale), [1, 20]) || ...
        ~isreal(emgScale) || ~isreal(contextScale) || ...
        any(~isfinite([emgScale, contextScale])) || ...
        any([emgScale, contextScale] <= 0)
    error("buildNoGloveStage7rRealPairs:InvalidScaleOverride", ...
        "Frozen scales must be finite positive 1-by-40 and 1-by-20 rows.");
end
source = "frozenOverride";
end

function fold = assignEpisodeFolds(metadata, foldCount)
fold = zeros(height(metadata), 1);
sources = unique(metadata.source, "stable")';
for source = sources
    sourceRows = metadata.source == source;
    episodes = unique(metadata.episode(sourceRows), "sorted");
    for rank = 1:numel(episodes)
        rows = sourceRows & metadata.episode == episodes(rank);
        fold(rows) = 1+mod(rank-1, foldCount);
    end
end
if any(fold == 0)
    error("buildNoGloveStage7rRealPairs:FoldAssignment", ...
        "Every real state must receive an episode fold.");
end
end

function [pairs, deltaContext, deltaEmg] = matchPairs( ...
        states, metadata, primaryMask, contextScale, emgScale, ...
        contextThreshold, emgThreshold)
maximumPairs = 2*sum(primaryMask, "all");
rows = repmat(emptyPairRow(), maximumPairs, 1);
deltaContext = zeros(maximumPairs, 20);
deltaEmg = zeros(maximumPairs, 40);
cursor = 0;
pairModes = ["withinEpisode", "crossEpisode"];
for motor = 1:4
    queryRows = find(primaryMask(:, motor));
    for pairMode = pairModes
        for query = queryRows'
            candidates = find(primaryMask(:, motor) & ...
                metadata.source == metadata.source(query) & ...
                metadata.gateContext == metadata.gateContext(query));
            if pairMode == "withinEpisode"
                candidates = candidates( ...
                    metadata.episode(candidates) == ...
                    metadata.episode(query) & ...
                    metadata.step(candidates) ~= metadata.step(query));
            else
                candidates = candidates( ...
                    metadata.episode(candidates) ~= ...
                    metadata.episode(query) & ...
                    metadata.fold(candidates) == metadata.fold(query));
            end
            if isempty(candidates)
                continue;
            end
            contextDifference = (states(query, 41:60) - ...
                states(candidates, 41:60))./contextScale;
            emgDifference = (states(query, 1:40) - ...
                states(candidates, 1:40))./emgScale;
            contextMaximum = max(abs(contextDifference), [], 2);
            contextRms = sqrt(mean(contextDifference.^2, 2));
            emgRms = sqrt(mean(emgDifference.^2, 2));
            eligible = contextMaximum <= contextThreshold & ...
                emgRms >= emgThreshold;
            if ~any(eligible)
                continue;
            end
            eligibleRows = find(eligible);
            [~, local] = min(contextRms(eligible));
            selectedCandidate = eligibleRows(local);
            donor = candidates(selectedCandidate);
            cursor = cursor+1;
            rows(cursor) = struct( ...
                "pairRow", cursor, "motor", motor, ...
                "pairMode", pairMode, ...
                "source", string(metadata.source(query)), ...
                "fold", metadata.fold(query), ...
                "queryRow", query, "donorRow", donor, ...
                "queryRowId", string(metadata.rowId(query)), ...
                "donorRowId", string(metadata.rowId(donor)), ...
                "queryEpisode", metadata.episode(query), ...
                "donorEpisode", metadata.episode(donor), ...
                "queryStep", metadata.step(query), ...
                "donorStep", metadata.step(donor), ...
                "gateContext", string(metadata.gateContext(query)), ...
                "contextRms", contextRms(selectedCandidate), ...
                "contextMaximum", contextMaximum(selectedCandidate), ...
                "emgRms", emgRms(selectedCandidate), ...
                "permutedPairRow", 0);
            deltaContext(cursor, :) = contextDifference( ...
                selectedCandidate, :);
            deltaEmg(cursor, :) = emgDifference(selectedCandidate, :);
        end
    end
end
rows = rows(1:cursor);
deltaContext = deltaContext(1:cursor, :);
deltaEmg = deltaEmg(1:cursor, :);
if isempty(rows)
    pairs = struct2table(emptyPairRow());
    pairs(1, :) = [];
else
    pairs = struct2table(rows);
end
end

function permutation = buildPermutationIndex(pairs)
permutation = zeros(height(pairs), 1);
if isempty(pairs)
    return;
end
groups = findgroups(pairs.motor, pairs.pairMode, pairs.source, pairs.fold);
for group = unique(groups)'
    rows = find(groups == group);
    [~, order] = sort(pairs.queryRow(rows));
    rows = rows(order);
    if numel(rows) == 1
        permutation(rows) = rows;
    else
        permutation(rows) = rows([2:end, 1]);
    end
end
end

function summary = summarizeSupport(pairs, metadata, primaryMask, options)
sources = ["ALL"; unique(metadata.source, "stable")];
parts = cell(4*2*numel(sources), 1);
cursor = 0;
for motor = 1:4
    for pairMode = ["withinEpisode", "crossEpisode"]
        for source = sources'
            cursor = cursor+1;
            if source == "ALL"
                pairRows = pairs.motor == motor & ...
                    pairs.pairMode == pairMode;
                eligibleRows = primaryMask(:, motor);
            else
                pairRows = pairs.motor == motor & ...
                    pairs.pairMode == pairMode & pairs.source == source;
                eligibleRows = primaryMask(:, motor) & ...
                    metadata.source == source;
            end
            selected = pairs(pairRows, :);
            count = height(selected);
            queryEpisodeKey = selected.source + ":" + ...
                compose("%05d", selected.queryEpisode);
            donorEpisodeKey = selected.source + ":" + ...
                compose("%05d", selected.donorEpisode);
            foldKey = selected.source + ":" + ...
                compose("%d", selected.fold);
            maximumReuse = maximumDonorReuse(selected);
            uniqueQueryEpisodes = numel(unique(queryEpisodeKey));
            uniqueDonorEpisodes = numel(unique(donorEpisodeKey));
            observedFolds = numel(unique(foldKey));
            passed = count >= options.minimumPairCount && ...
                uniqueQueryEpisodes >= options.minimumUniqueEpisodes && ...
                observedFolds == options.foldCount && ...
                maximumReuse <= options.maximumDonorReuseFraction;
            parts{cursor} = table(motor, pairMode, source, ...
                sum(eligibleRows), count, ...
                safeRatio(count, sum(eligibleRows)), ...
                uniqueQueryEpisodes, uniqueDonorEpisodes, observedFolds, ...
                maximumReuse, passed, ...
                'VariableNames', ["motor", "pairMode", "source", ...
                "eligibleQueryCount", "pairCount", "queryCoverage", ...
                "uniqueQueryEpisodeCount", "uniqueDonorEpisodeCount", ...
                "observedFoldCount", "maximumDonorReuseFraction", ...
                "supportPassed"]);
        end
    end
end
summary = vertcat(parts{:});
end

function value = maximumDonorReuse(pairs)
if isempty(pairs)
    value = NaN;
    return;
end
[groups, ~] = findgroups(pairs.donorRow);
counts = splitapply(@numel, pairs.donorRow, groups);
value = max(counts)/height(pairs);
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator/denominator;
end
end

function row = emptyPairRow()
row = struct("pairRow", 0, "motor", 0, "pairMode", "", ...
    "source", "", "fold", 0, "queryRow", 0, "donorRow", 0, ...
    "queryRowId", "", "donorRowId", "", ...
    "queryEpisode", 0, "donorEpisode", 0, ...
    "queryStep", 0, "donorStep", 0, "gateContext", "", ...
    "contextRms", NaN, "contextMaximum", NaN, "emgRms", NaN, ...
    "permutedPairRow", 0);
end
