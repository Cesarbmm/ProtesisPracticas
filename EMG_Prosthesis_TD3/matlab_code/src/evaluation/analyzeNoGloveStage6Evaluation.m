function analysis = analyzeNoGloveStage6Evaluation(episodeDirectory, options)
%analyzeNoGloveStage6Evaluation audits intentMarkov60 episode files.

arguments
    episodeDirectory (1, 1) string
    options.positionMin (1, 4) double = zeros(1, 4)
    options.positionMax (1, 4) double = ones(1, 4)
    options.positionTolerance (1, 1) double {mustBeNonnegative} = 1e-9
    options.activeVelocityThreshold (1, 1) double {mustBeNonnegative} = 0.005
    options.motionTolerance (1, 1) double {mustBeNonnegative} = 1e-4
    options.minimumActiveSamples (1, 1) double {mustBeInteger, mustBePositive} = 3
end

episodeFiles = dir(fullfile(episodeDirectory, "episode*.mat"));
if isempty(episodeFiles)
    error("analyzeNoGloveStage6Evaluation:NoEpisodes", ...
        "No episode files found in %s.", episodeDirectory);
end

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
episodeCount = numel(episodeFiles);
finiteEpisode = true(episodeCount, 1);
positionViolationByEpisodeMotor = false(episodeCount, 4);
wrongDirectionByEpisodeMotor = false(episodeCount, 4);
noMotionByEpisodeMotor = false(episodeCount, 4);
activeSampleCountByEpisodeMotor = zeros(episodeCount, 4);
directionAgreementByEpisodeMotor = nan(episodeCount, 4);
meanSignedResponseByEpisodeMotor = nan(episodeCount, 4);
safetyInterventionCountByEpisodeMotor = zeros(episodeCount, 4);
safetyEnabledByEpisode = false(episodeCount, 1);

for episodeIdx = 1:episodeCount
    episodePath = fullfile(episodeFiles(episodeIdx).folder, ...
        episodeFiles(episodeIdx).name);
    data = load(episodePath, "stateLog", "actionSatLog", ...
        "rewardLog", "referenceHistory", "trackingPredictionHistory", ...
        "referenceSource", "observationVariant", "stateLength");
    episodeVariables = string(who("-file", episodePath));
    if all(ismember(["simulationPositionSafety", ...
            "positionSafetyInterventionLog"], episodeVariables))
        safetyData = load(episodePath, "simulationPositionSafety", ...
            "positionSafetyInterventionLog");
        safetyEnabledByEpisode(episodeIdx) = ...
            logical(safetyData.simulationPositionSafety.enabled);
        safetyLog = double(safetyData.positionSafetyInterventionLog);
        if size(safetyLog, 2) ~= 4 || any(safetyLog < 0, "all") || ...
                any(~isfinite(safetyLog), "all")
            error("analyzeNoGloveStage6Evaluation:InvalidSafetyLog", ...
                "Episode %s has an invalid position-safety log.", episodePath);
        end
        safetyInterventionCountByEpisodeMotor(episodeIdx, :) = ...
            sum(safetyLog, 1);
    end
    assertIntentEpisodeContract(data, episodePath, layout.totalLength);

    state = double(data.stateLog);
    action = double(data.actionSatLog);
    reward = double(data.rewardLog);
    reference = double(data.referenceHistory);
    prediction = double(data.trackingPredictionHistory);
    critical = [state(:); action(:); reward(:); ...
        reference(:); prediction(:)];
    finiteEpisode(episodeIdx) = all(isfinite(critical));

    q = state(:, layout.encoder);
    qMin = options.positionMin - options.positionTolerance;
    qMax = options.positionMax + options.positionTolerance;
    positionViolationByEpisodeMotor(episodeIdx, :) = ...
        any(q < qMin | q > qMax, 1);

    if size(state, 1) < 2
        continue;
    end
    deltaQ = diff(q, 1, 1);
    referenceVelocity = state(1:end-1, layout.referenceVelocity);
    for motorIdx = 1:4
        active = abs(referenceVelocity(:, motorIdx)) >= ...
            options.activeVelocityThreshold;
        activeCount = sum(active);
        activeSampleCountByEpisodeMotor(episodeIdx, motorIdx) = activeCount;
        if activeCount < options.minimumActiveSamples
            continue;
        end
        signedResponse = sign(referenceVelocity(active, motorIdx)) .* ...
            deltaQ(active, motorIdx);
        moving = abs(deltaQ(active, motorIdx)) >= options.motionTolerance;
        meanSignedResponseByEpisodeMotor(episodeIdx, motorIdx) = ...
            mean(signedResponse, "omitnan");
        noMotionByEpisodeMotor(episodeIdx, motorIdx) = ~any(moving);
        if any(moving)
            directionAgreementByEpisodeMotor(episodeIdx, motorIdx) = ...
                mean(signedResponse(moving) >= -options.motionTolerance);
            wrongDirectionByEpisodeMotor(episodeIdx, motorIdx) = ...
                mean(signedResponse(moving), "omitnan") < ...
                -options.motionTolerance;
        end
    end
end

nonfiniteByEpisodeMotor = repmat(~finiteEpisode, 1, 4);
functionalByEpisodeMotor = positionViolationByEpisodeMotor | ...
    wrongDirectionByEpisodeMotor | noMotionByEpisodeMotor | ...
    nonfiniteByEpisodeMotor;
summary = summarizeEpisodeDirectory(episodeDirectory);

analysis = struct( ...
    "schemaVersion", 1, ...
    "episodeDirectory", episodeDirectory, ...
    "episodeCount", episodeCount, ...
    "referenceSource", string(summary.referenceSource), ...
    "observationVariant", "intentMarkov60", ...
    "stateLength", layout.totalLength, ...
    "allFinite", all(finiteEpisode), ...
    "nonfiniteEpisodeCount", sum(~finiteEpisode), ...
    "positionViolationEpisodeCount", ...
        sum(any(positionViolationByEpisodeMotor, 2)), ...
    "positionViolationFlagCountByMotor", ...
        sum(positionViolationByEpisodeMotor, 1), ...
    "wrongDirectionFlagCountByMotor", ...
        sum(wrongDirectionByEpisodeMotor, 1), ...
    "noMotionFlagCountByMotor", sum(noMotionByEpisodeMotor, 1), ...
    "functionalFlagCountByMotor", sum(functionalByEpisodeMotor, 1), ...
    "motor2FunctionalFlagCount", sum(functionalByEpisodeMotor(:, 2)), ...
    "otherMotorFunctionalFlagCount", ...
        sum(functionalByEpisodeMotor(:, [1, 3, 4]), "all"), ...
    "activeSampleCountByMotor", ...
        sum(activeSampleCountByEpisodeMotor, 1), ...
    "directionAgreementByMotor", ...
        mean(directionAgreementByEpisodeMotor, 1, "omitnan"), ...
    "meanSignedResponseByMotor", ...
        mean(meanSignedResponseByEpisodeMotor, 1, "omitnan"), ...
    "trackingMse", summary.trackingMseMean, ...
    "trackingMae", summary.trackingMaeMean, ...
    "velocityMse", summary.velocityMseMean, ...
    "actionL2", summary.actionL2Mean, ...
    "deltaActionL2", summary.deltaActionL2Mean, ...
    "saturationFraction", summary.saturationFractionMean, ...
    "trackingMseByMotor", readMotorSummary(summary, "trackingMseMotor"), ...
    "trackingMaeByMotor", readMotorSummary(summary, "trackingMaeMotor"), ...
    "saturationFractionByMotor", ...
        readMotorSummary(summary, "saturationFractionMotor"), ...
    "deltaActionL2ByMotor", ...
        readMotorSummary(summary, "deltaActionL2Motor"), ...
    "positionSafetyEnabledForAllEpisodes", all(safetyEnabledByEpisode), ...
    "positionSafetyInterventionCount", ...
        sum(safetyInterventionCountByEpisodeMotor, "all"), ...
    "positionSafetyInterventionCountByMotor", ...
        sum(safetyInterventionCountByEpisodeMotor, 1), ...
    "positionSafetyInterventionCountByEpisodeMotor", ...
        safetyInterventionCountByEpisodeMotor, ...
    "finiteEpisode", finiteEpisode, ...
    "positionViolationByEpisodeMotor", positionViolationByEpisodeMotor, ...
    "wrongDirectionByEpisodeMotor", wrongDirectionByEpisodeMotor, ...
    "noMotionByEpisodeMotor", noMotionByEpisodeMotor, ...
    "functionalByEpisodeMotor", functionalByEpisodeMotor, ...
    "directionAgreementByEpisodeMotor", directionAgreementByEpisodeMotor);
end

function assertIntentEpisodeContract(data, episodePath, expectedLength)
requiredFields = ["stateLog", "actionSatLog", "rewardLog", ...
    "referenceHistory", "trackingPredictionHistory", ...
    "referenceSource", "observationVariant", "stateLength"];
if ~all(isfield(data, cellstr(requiredFields)))
    error("analyzeNoGloveStage6Evaluation:MissingEpisodeField", ...
        "Episode %s does not satisfy the ETAPA 6 log contract.", episodePath);
end
if string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= expectedLength || ...
        size(data.stateLog, 2) ~= expectedLength
    error("analyzeNoGloveStage6Evaluation:IncompatibleEpisode", ...
        "Episode %s is not an intentMarkov60 episode.", episodePath);
end
end

function values = readMotorSummary(summary, prefix)
values = nan(1, 4);
for motorIdx = 1:4
    fieldName = sprintf("%s%dMean", prefix, motorIdx);
    if isfield(summary, fieldName)
        values(motorIdx) = double(summary.(fieldName));
    end
end
end
