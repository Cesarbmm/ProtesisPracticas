function gate = classifyNoGloveStage7sSupportGate( ...
        acquisition, supportSummary, options)
%classifyNoGloveStage7sSupportGate gates models behind prospective support.

arguments
    acquisition (1, 1) struct
    supportSummary table
    options.expectedEpisodeCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 80
    options.expectedStateCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 1600
    options.minimumSupportedMotors (1, 1) double ...
        {mustBeInteger, mustBeInRange(options.minimumSupportedMotors, 1, 4)} = 3
end

required = ["episodeCount", "stateCount", "allFinite", ...
    "state60", "positionLimitsRespected", "gateActiveCount", ...
    "countdownCount", "nonzeroReferenceVelocityCount", ...
    "referenceHoldMaximumError", "declaredRestActivityExact", ...
    "alignmentPassed", ...
    "acceptanceInvariant", "frozenScalesUsed", ...
    "completeObservedStates", "hybridStateUsed", ...
    "stateCounterfactualUsed", "futureLeakageUsed", ...
    "hardwareUsed", "trainingUsed"];
if ~all(isfield(acquisition, cellstr(required)))
    error("classifyNoGloveStage7sSupportGate:InvalidAcquisition", ...
        "The prospective acquisition summary is incomplete.");
end
requiredColumns = ["motor", "pairMode", "source", "supportPassed"];
if ~all(ismember(requiredColumns, ...
        string(supportSummary.Properties.VariableNames)))
    error("classifyNoGloveStage7sSupportGate:InvalidSupport", ...
        "The matched support table is incomplete.");
end

steadyCross = supportSummary( ...
    supportSummary.source == "steadyRest" & ...
    supportSummary.pairMode == "crossEpisode", :);
globalCross = supportSummary( ...
    supportSummary.source == "ALL" & ...
    supportSummary.pairMode == "crossEpisode", :);
globalWithin = supportSummary( ...
    supportSummary.source == "ALL" & ...
    supportSummary.pairMode == "withinEpisode", :);
if height(steadyCross) ~= 4 || height(globalCross) ~= 4 || ...
        height(globalWithin) ~= 4
    error("classifyNoGloveStage7sSupportGate:MissingSupportRows", ...
        "Support rows are required for all four motors and both modes.");
end
steadyRestCrossSupportedMotorCount = sum(steadyCross.supportPassed);
globalCrossSupportedMotorCount = sum(globalCross.supportPassed);
globalWithinSupportedMotorCount = sum(globalWithin.supportPassed);

checks = struct( ...
    "episodeCountExact", acquisition.episodeCount == ...
        options.expectedEpisodeCount, ...
    "stateCountExact", acquisition.stateCount == ...
        options.expectedStateCount, ...
    "finite", logical(acquisition.allFinite), ...
    "state60", logical(acquisition.state60), ...
    "positionLimits", logical(acquisition.positionLimitsRespected), ...
    "gateNeverActive", acquisition.gateActiveCount == 0, ...
    "countdownNeverActive", acquisition.countdownCount == 0, ...
    "referenceVelocityZero", ...
        acquisition.nonzeroReferenceVelocityCount == 0, ...
    "referenceHeld", acquisition.referenceHoldMaximumError <= 1e-12, ...
    "declaredRestActivityExact", ...
        logical(acquisition.declaredRestActivityExact), ...
    "alignment", logical(acquisition.alignmentPassed), ...
    "acceptanceInvariant", logical(acquisition.acceptanceInvariant), ...
    "frozenScales", logical(acquisition.frozenScalesUsed), ...
    "completeObservedStates", ...
        logical(acquisition.completeObservedStates), ...
    "noHybridState", ~logical(acquisition.hybridStateUsed), ...
    "noStateCounterfactual", ...
        ~logical(acquisition.stateCounterfactualUsed), ...
    "noFutureLeakage", ~logical(acquisition.futureLeakageUsed), ...
    "steadyRestCrossSupport", ...
        steadyRestCrossSupportedMotorCount >= ...
        options.minimumSupportedMotors, ...
    "globalCrossSupport", globalCrossSupportedMotorCount >= ...
        options.minimumSupportedMotors, ...
    "globalWithinSupport", globalWithinSupportedMotorCount >= ...
        options.minimumSupportedMotors, ...
    "noHardware", ~logical(acquisition.hardwareUsed), ...
    "noTraining", ~logical(acquisition.trainingUsed));
passed = all(struct2array(checks));
scientificResult = "prospectiveSupportFailed";
if passed
    scientificResult = "prospectiveSupportPassed";
end
gate = struct( ...
    "schemaVersion", 1, "stage", "7S", ...
    "passed", passed, "scientificResult", scientificResult, ...
    "checks", checks, ...
    "steadyRestCrossSupportedMotorCount", ...
        steadyRestCrossSupportedMotorCount, ...
    "globalCrossSupportedMotorCount", globalCrossSupportedMotorCount, ...
    "globalWithinSupportedMotorCount", globalWithinSupportedMotorCount, ...
    "minimumSupportedMotors", options.minimumSupportedMotors, ...
    "modelsAuthorized", passed);
end
