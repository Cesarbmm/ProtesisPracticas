function decision = classifyNoGloveStage7tConsequence(componentTable, options)
%classifyNoGloveStage7tConsequence classifies frozen first-step commands.

arguments
    componentTable table
    options.minimumChannelCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 6
    options.minimumMotorCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 3
    options.nonzeroPwmFractionThreshold (1, 1) double ...
        {mustBeInRange(options.nonzeroPwmFractionThreshold, 0, 1)} = 0.50
end

required = ["phase", "dominantChannel", "motor", "pwm", ...
    "safetyIntervention"];
if ~all(ismember(required, ...
        string(componentTable.Properties.VariableNames))) || ...
        isempty(componentTable) || ...
        any(~isfinite([componentTable.dominantChannel; ...
        componentTable.motor; componentTable.pwm; ...
        componentTable.safetyIntervention])) || ...
        any(componentTable.motor < 1 | componentTable.motor > 4) || ...
        any(componentTable.dominantChannel < 1 | ...
        componentTable.dominantChannel > 7) || ...
        any(componentTable.safetyIntervention < 0)
    error("classifyNoGloveStage7tConsequence:InvalidTable", ...
        "A finite first-step component contract is required.");
end
first = componentTable(componentTable.phase == "firstStep", :);
if isempty(first) || numel(unique(first.dominantChannel)) ~= 7 || ...
        numel(unique(first.motor)) ~= 4
    error("classifyNoGloveStage7tConsequence:IncompleteFirstStep", ...
        "First-step evidence must contain seven channels and four motors.");
end

channels = (1:7)';
channelFraction = zeros(7, 1);
for idx = 1:7
    rows = first.dominantChannel == channels(idx);
    channelFraction(idx) = mean(first.pwm(rows) ~= 0);
end
channelPassed = channelFraction >= options.nonzeroPwmFractionThreshold;
channelAudit = table(channels, channelFraction, channelPassed, ...
    'VariableNames', ["dominantChannel", ...
    "nonzeroPwmComponentFraction", "thresholdPassed"]);

motors = (1:4)';
motorFraction = zeros(4, 1);
for idx = 1:4
    rows = first.motor == motors(idx);
    motorFraction(idx) = mean(first.pwm(rows) ~= 0);
end
motorPassed = motorFraction >= options.nonzeroPwmFractionThreshold;
motorAudit = table(motors, motorFraction, motorPassed, ...
    'VariableNames', ["motor", "nonzeroPwmFraction", ...
    "thresholdPassed"]);

passedChannels = sum(channelPassed);
passedMotors = sum(motorPassed);
safetyCount = sum(first.safetyIntervention);
broad = passedChannels >= options.minimumChannelCount && ...
    passedMotors >= options.minimumMotorCount && safetyCount > 0;
specific = passedChannels >= 1 && passedMotors >= 1;
if broad
    classification = "broadSyntheticGateStressConsequence";
    recommendation = "preregisterSingleFactorGateAggregationAblation";
elseif specific
    classification = "channelSpecificSyntheticGateStressConsequence";
    recommendation = "auditChannelCalibrationAndOrder";
else
    classification = "limitedSyntheticGateStressConsequence";
    recommendation = "closeSyntheticPathAndRequireShadowMode";
end

decision = struct( ...
    "schemaVersion", 1, "stage", "7T", ...
    "classification", classification, ...
    "recommendation", recommendation, ...
    "passedChannelCount", passedChannels, ...
    "passedMotorCount", passedMotors, ...
    "firstStepSafetyInterventionCount", safetyCount, ...
    "minimumChannelCount", options.minimumChannelCount, ...
    "minimumMotorCount", options.minimumMotorCount, ...
    "nonzeroPwmFractionThreshold", ...
        options.nonzeroPwmFractionThreshold, ...
    "channelAudit", channelAudit, "motorAudit", motorAudit);
end
