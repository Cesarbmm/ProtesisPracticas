function data = loadNoGloveStage7qCheckpointSet( ...
        stage7pRunRoot, stage7nRunRoot)
%loadNoGloveStage7qCheckpointSet loads immutable state-60 evidence.

arguments
    stage7pRunRoot (1, 1) string
    stage7nRunRoot (1, 1) string
end

manifest7pPath = fullfile(stage7pRunRoot, "manifest.json");
results7pPath = fullfile(stage7pRunRoot, "stage7p_results.mat");
manifest7nPath = fullfile(stage7nRunRoot, "manifest.json");
summaryPath = fullfile(stage7nRunRoot, "checkpoint_summary.csv");
requiredFiles = [manifest7pPath, results7pPath, ...
    manifest7nPath, summaryPath];
if any(~isfile(requiredFiles))
    error("loadNoGloveStage7qCheckpointSet:MissingParent", ...
        "Canonical ETAPA 7P/7N inputs are missing.");
end

expected7pManifestHash = ...
    "9B6BC4198AE8B36C4BE062E51D82BE7709870D2DBD3C74A5F7FE68AB015034D9";
expected7nManifestHash = ...
    "082DADB41DAA1DAB6AE2B5E02AE15191479410F10B5DF0398837814BFC53D480";
actual7pManifestHash = localFileSha256(manifest7pPath);
actual7nManifestHash = localFileSha256(manifest7nPath);
manifest7p = jsondecode(fileread(manifest7pPath));
manifest7n = jsondecode(fileread(manifest7nPath));
if actual7pManifestHash ~= expected7pManifestHash || ...
        string(manifest7p.stage) ~= "7P" || ...
        string(manifest7p.result) ~= "PASS" || ...
        string(manifest7p.scientificResult) ~= ...
            "noAblationSupported" || ...
        string(manifest7p.stateDecision) ~= "intentMarkov60" || ...
        logical(manifest7p.hardwareUsed) || ...
        logical(manifest7p.trainingUsed)
    error("loadNoGloveStage7qCheckpointSet:Stage7pChanged", ...
        "ETAPA 7P does not match the preregistered parent.");
end
if actual7nManifestHash ~= expected7nManifestHash || ...
        string(manifest7n.stage) ~= "7N" || ...
        string(manifest7n.result) ~= "PASS" || ...
        logical(manifest7n.hardwareUsed)
    error("loadNoGloveStage7qCheckpointSet:Stage7nChanged", ...
        "ETAPA 7N does not match the preregistered parent.");
end

parent = load(results7pPath, "corpus", "analysis", "actuator");
if ~all(isfield(parent, ["corpus", "analysis", "actuator"])) || ...
        string(parent.analysis.futureAblationSelection) ~= ...
            "noAblationSupported" || ...
        string(parent.corpus.stateDecision) ~= "intentMarkov60" || ...
        parent.corpus.windowCount ~= 3410
    error("loadNoGloveStage7qCheckpointSet:InvalidStage7pResults", ...
        "ETAPA 7P MAT evidence violates its frozen contract.");
end
primaryWindow = ismember(parent.corpus.metadata.gateContext, ...
    ["initialRest", "declaredRest"]);
primaryComponentCount = sum( ...
    parent.corpus.zeroControlDemand(primaryWindow, :), "all");
primaryPwm = parent.corpus.pwm(primaryWindow, :);
primaryDemand = parent.corpus.zeroControlDemand(primaryWindow, :);
if primaryComponentCount ~= 2064 || ...
        any(primaryPwm(primaryDemand) == 0)
    error("loadNoGloveStage7qCheckpointSet:PrimaryCohortChanged", ...
        "The preregistered 2,064-component primary cohort changed.");
end

summary = readtable(summaryPath, "TextType", "string");
requiredColumns = ["variant", "observationVariant", "stateLength", ...
    "episode", "checkpointPath", "checkpointSha256", ...
    "acceptanceDirectory", "restDirectory"];
if ~all(ismember(requiredColumns, ...
        string(summary.Properties.VariableNames)))
    error("loadNoGloveStage7qCheckpointSet:SummarySchema", ...
        "The ETAPA 7N checkpoint summary schema changed.");
end
summary = summary(summary.variant == "control60", :);
summary = sortrows(summary, "episode");
episodes = [50; 100; 150; 200];
expectedHashes = [ ...
    "D697DA3BB6CE9672330A359DDE3DD43ACEECCB5E2F151EF6E13D3C8C2EC2D013"; ...
    "3B54D4C5122D7133E9472EE8ED641418A79E0FA7E57A6501AC1C5E611357AB3F"; ...
    "B760B7EE45F62D6B2E12C1B0A3281E119182CAF96653A293E07E9EFE567A7A66"; ...
    "440F003450A368A13A0E5DACB04FD7755BB929033EB879B217E47F32B5AA185E"];
if height(summary) ~= 4 || ...
        ~isequal(double(summary.episode), episodes) || ...
        any(summary.observationVariant ~= "intentMarkov60") || ...
        any(double(summary.stateLength) ~= 60)
    error("loadNoGloveStage7qCheckpointSet:CheckpointRows", ...
        "Expected control60 checkpoints 50/100/150/200.");
end

ownCorpora = repmat(struct("episode", 0, "corpus", struct()), 4, 1);
checkpointInventory = table('Size', [4, 5], ...
    'VariableTypes', ["double", "string", "string", "string", "double"], ...
    'VariableNames', ["episode", "checkpointPath", "expectedSha256", ...
    "actualSha256", "bytes"]);
for idx = 1:4
    checkpointPath = string(summary.checkpointPath(idx));
    actualHash = localFileSha256(checkpointPath);
    if string(summary.checkpointSha256(idx)) ~= expectedHashes(idx) || ...
            actualHash ~= expectedHashes(idx)
        error("loadNoGloveStage7qCheckpointSet:CheckpointChanged", ...
            "Agent%d does not match its preregistered SHA-256.", ...
            episodes(idx));
    end
    sources = struct( ...
        "acceptance", string(summary.acceptanceDirectory(idx)), ...
        "steadyRest", string(summary.restDirectory(idx)));
    corpus = loadNoGloveStage7pInterfaceCorpus( ...
        sources, parent.actuator);
    ownCorpora(idx) = struct("episode", episodes(idx), ...
        "corpus", corpus);
    info = dir(checkpointPath);
    checkpointInventory(idx, :) = {episodes(idx), checkpointPath, ...
        expectedHashes(idx), actualHash, info.bytes};
end

agent200 = ownCorpora(4).corpus;
if ~isequal(agent200.states, parent.corpus.states) || ...
        ~isequal(agent200.rawAction, parent.corpus.rawAction) || ...
        ~isequal(agent200.pwm, parent.corpus.pwm)
    error("loadNoGloveStage7qCheckpointSet:Agent200ReplayCorpus", ...
        "Reloaded Agent200 evidence differs from ETAPA 7P.");
end

data = struct( ...
    "stage7p", struct("runRoot", stage7pRunRoot, ...
        "manifestSha256", actual7pManifestHash, ...
        "manifest", manifest7p, "validated", true), ...
    "stage7n", struct("runRoot", stage7nRunRoot, ...
        "manifestSha256", actual7nManifestHash, ...
        "manifest", manifest7n, "validated", true), ...
    "primaryCorpus", parent.corpus, ...
    "parentAnalysis", parent.analysis, ...
    "actuator", parent.actuator, ...
    "checkpointTable", summary, ...
    "checkpointInventory", checkpointInventory, ...
    "ownCorpora", ownCorpora, ...
    "primaryComponentCount", primaryComponentCount, ...
    "trainingLogsUsed", false, "state62Loaded", false, ...
    "agent7250Loaded", false);
end

function hash = localFileSha256(filePath)
if ~isfile(filePath)
    error("loadNoGloveStage7qCheckpointSet:MissingFile", ...
        "Missing file: %s", filePath);
end
escaped = strrep(char(filePath), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("loadNoGloveStage7qCheckpointSet:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = string(strtrim(output));
end
