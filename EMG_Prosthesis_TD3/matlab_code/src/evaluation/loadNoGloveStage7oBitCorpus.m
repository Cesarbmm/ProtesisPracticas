function corpus = loadNoGloveStage7oBitCorpus(sources, options)
%loadNoGloveStage7oBitCorpus loads and deterministically stratifies 7N logs.

arguments
    sources (1, 1) struct
    options.maxPerContext (1, 1) double ...
        {mustBeInteger, mustBePositive} = 512
    options.numericTolerance (1, 1) double {mustBeNonnegative} = 1e-12
    options.holdPositionMseTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
end

requiredSources = ["training", "acceptance", "steadyRest"];
if ~all(isfield(sources, cellstr(requiredSources)))
    error("loadNoGloveStage7oBitCorpus:MissingSource", ...
        "Sources must include training, acceptance and steadyRest.");
end
layout = buildObservationLayout( ...
    "intentDeclaredRestHoldMarkov62", 40, 3, 4);
stateParts = cell(numel(requiredSources), 1);
actionParts = cell(numel(requiredSources), 1);
metaParts = cell(numel(requiredSources), 1);
inventoryParts = cell(numel(requiredSources), 1);
for sourceIdx = 1:numel(requiredSources)
    source = requiredSources(sourceIdx);
    directory = string(sources.(source));
    [stateParts{sourceIdx}, actionParts{sourceIdx}, ...
        metaParts{sourceIdx}, inventoryParts{sourceIdx}] = ...
        loadDirectory(directory, source, layout, options);
end
allStates = vertcat(stateParts{:});
allActions = vertcat(actionParts{:});
allMetadata = vertcat(metaParts{:});
inventory = vertcat(inventoryParts{:});

contextOrder = ["initialRest", "declaredRestFar", ...
    "nearBeforeLatch", "latchActive", "driftAfterLatch", ...
    "intentionalMovement", "lowActivityCountdown", "uncategorized"];
selected = false(height(allMetadata), 1);
available = zeros(numel(contextOrder), 1);
selectedCount = zeros(numel(contextOrder), 1);
for contextIdx = 1:numel(contextOrder)
    indices = find(allMetadata.context == contextOrder(contextIdx));
    available(contextIdx) = numel(indices);
    if numel(indices) > options.maxPerContext
        local = unique(round(linspace(1, numel(indices), ...
            options.maxPerContext)));
        indices = indices(local);
    end
    selected(indices) = true;
    selectedCount(contextIdx) = numel(indices);
end
selectedIndices = find(selected);
metadata = allMetadata(selectedIndices, :);
metadata.corpusRow = (1:height(metadata))';
metadata = movevars(metadata, "corpusRow", "Before", 1);
states = allStates(selectedIndices, :);
loggedActions = allActions(selectedIndices, :);
contextCounts = table(contextOrder', available, selectedCount, ...
    'VariableNames', ["context", "availableCount", "selectedCount"]);
sourceNames = requiredSources';
availableSourceCount = arrayfun(@(name) ...
    sum(allMetadata.source == name), sourceNames);
selectedSourceCount = arrayfun(@(name) ...
    sum(metadata.source == name), sourceNames);
sourceCounts = table(sourceNames, availableSourceCount, ...
    selectedSourceCount, 'VariableNames', ...
    ["source", "availableCount", "selectedCount"]);

corpus = struct( ...
    "schemaVersion", 1, "states", states, ...
    "prefix60", states(:, 1:60), ...
    "loggedActions", loggedActions, "metadata", metadata, ...
    "inventory", inventory, "contextCounts", contextCounts, ...
    "sourceCounts", sourceCounts, ...
    "allAvailableRowCount", height(allMetadata), ...
    "selectedRowCount", height(metadata), ...
    "maxPerContext", options.maxPerContext, ...
    "holdPositionMseTolerance", options.holdPositionMseTolerance, ...
    "causalReplayMismatchCount", 0, ...
    "futureLeakageUsed", false);
end

function [states, actions, metadata, inventory] = loadDirectory( ...
        directory, source, layout, options)
files = dir(fullfile(directory, "episode*.mat"));
if isempty(files)
    error("loadNoGloveStage7oBitCorpus:NoEpisodes", ...
        "No episode files found in %s.", directory);
end
episodeNumber = arrayfun(@(file) parseEpisode(file.name), files);
[episodeNumber, order] = sort(episodeNumber);
files = files(order);
stateCells = cell(numel(files), 1);
actionCells = cell(numel(files), 1);
metaCells = cell(numel(files), 1);
inventoryRows = repmat(struct("source", "", "episode", 0, ...
    "filePath", "", "stepCount", 0), numel(files), 1);
for fileIdx = 1:numel(files)
    path = string(fullfile(files(fileIdx).folder, files(fileIdx).name));
    data = load(path, "stateLog", "actionLog", ...
        "intentProvenanceLog", "referenceSource", ...
        "observationVariant", "stateLength");
    required = ["stateLog", "actionLog", "intentProvenanceLog", ...
        "referenceSource", "observationVariant", "stateLength"];
    if ~all(isfield(data, cellstr(required))) || ...
            string(data.referenceSource) ~= "emgIntent" || ...
            string(data.observationVariant) ~= ...
                "intentDeclaredRestHoldMarkov62" || ...
            double(data.stateLength) ~= 62
        error("loadNoGloveStage7oBitCorpus:EpisodeContract", ...
            "Episode %s violates the state-62 contract.", path);
    end
    state = double(data.stateLog);
    action = double(data.actionLog);
    count = size(state, 1);
    if size(state, 2) ~= 62 || ~isequal(size(action), [count, 4]) || ...
            ~iscell(data.intentProvenanceLog) || ...
            numel(data.intentProvenanceLog) ~= count || ...
            any(~isfinite([state(:); action(:)]))
        error("loadNoGloveStage7oBitCorpus:EpisodeArrays", ...
            "Episode %s contains invalid arrays.", path);
    end
    declared = validateBit(state(:, layout.declaredRest), path, ...
        "declaredRest", options.numericTolerance);
    latch = validateBit(state(:, layout.holdLatch), path, ...
        "holdLatch", options.numericTolerance);
    positionMse = mean((state(:, layout.encoder) - ...
        state(:, layout.referencePosition)).^2, 2);
    expectedDeclared = true(count, 1);
    expectedLatch = false(count, 1);
    expectedLatch(1) = positionMse(1) <= ...
        options.holdPositionMseTolerance + options.numericTolerance;
    countdown = false(count, 1);
    gateActive = false(count, 1);
    provenance = data.intentProvenanceLog;
    for stepIdx = 2:count
        item = provenance{stepIdx-1};
        fields = ["schemaVersion", "declaredRestAfter", ...
            "holdLatchAfter", "holdPositionMseAfter", ...
            "lowActivityCountdown", "gateActive"];
        if ~isstruct(item) || ~isscalar(item) || ...
                ~all(isfield(item, cellstr(fields))) || ...
                double(item.schemaVersion) ~= 2
            error("loadNoGloveStage7oBitCorpus:ProvenanceContract", ...
                "Episode %s lacks aligned provenance at step %d.", ...
                path, stepIdx-1);
        end
        expectedDeclared(stepIdx) = logical(item.declaredRestAfter);
        expectedLatch(stepIdx) = logical(item.holdLatchAfter);
        countdown(stepIdx) = logical(item.lowActivityCountdown);
        gateActive(stepIdx) = logical(item.gateActive);
        if abs(double(item.holdPositionMseAfter)-positionMse(stepIdx)) > ...
                options.numericTolerance
            error("loadNoGloveStage7oBitCorpus:PositionMseMismatch", ...
                "Episode %s step %d has a replay mismatch.", ...
                path, stepIdx);
        end
    end
    if any(declared ~= expectedDeclared) || any(latch ~= expectedLatch)
        error("loadNoGloveStage7oBitCorpus:CausalBitMismatch", ...
            "Episode %s does not replay bits 61/62 exactly.", path);
    end
    steps = (1:count)';
    context = classifyNoGloveStage7oContexts(state, steps, ...
        countdown, gateActive, ...
        "holdPositionMseTolerance", ...
            options.holdPositionMseTolerance);
    rowId = source + ":" + compose("%05d", episodeNumber(fileIdx)) + ...
        ":" + compose("%03d", steps);
    stateCells{fileIdx} = state;
    actionCells{fileIdx} = action;
    metaCells{fileIdx} = table(rowId, repmat(source, count, 1), ...
        repmat(episodeNumber(fileIdx), count, 1), steps, ...
        repmat(fileIdx, count, 1), context, declared, latch, ...
        positionMse, countdown, gateActive, ...
        'VariableNames', ["rowId", "source", "episode", "step", ...
        "sourceFileIndex", "context", "declaredRest", "holdLatch", ...
        "positionMse", "lowActivityCountdown", "gateActive"]);
    inventoryRows(fileIdx) = struct("source", source, ...
        "episode", episodeNumber(fileIdx), "filePath", path, ...
        "stepCount", count);
end
states = vertcat(stateCells{:});
actions = vertcat(actionCells{:});
metadata = vertcat(metaCells{:});
inventory = struct2table(inventoryRows);
end

function episode = parseEpisode(name)
token = regexp(name, '^episode(\d+)\.mat$', 'tokens', 'once');
if isempty(token)
    error("loadNoGloveStage7oBitCorpus:EpisodeName", ...
        "Unexpected episode file %s.", name);
end
episode = str2double(token{1});
end

function bit = validateBit(values, path, label, tolerance)
if any(abs(values-round(values)) > tolerance) || ...
        any(values < -tolerance | values > 1+tolerance)
    error("loadNoGloveStage7oBitCorpus:InvalidBit", ...
        "Episode %s contains invalid %s values.", path, label);
end
bit = logical(round(values));
end
