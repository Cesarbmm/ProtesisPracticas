function analysis = analyzeNoGloveStage7dTrainingSupport( ...
        query, training, queryActorEvaluator, trainingActorEvaluator, ...
        biaslessActorEvaluator, biasAudit, actuator, options)
%analyzeNoGloveStage7dTrainingSupport audits real training-state support.
%
% The query contains the 128 observed pre-rest states from ETAPA 7B. The
% support corpus contains only observations recorded during Agent200
% training for which v_ref is zero and q_ref is held from the preceding
% recorded step. Actor evaluation is offline and deterministic.

arguments
    query struct
    training struct
    queryActorEvaluator function_handle
    trainingActorEvaluator function_handle
    biaslessActorEvaluator function_handle
    biasAudit struct
    actuator struct
    options.referenceTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.replayTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.scaleTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.distanceTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.supportQuantile (1, 1) double ...
        {mustBeInRange(options.supportQuantile, 0.5, 1)} = 0.95
    options.minimumSupportFraction (1, 1) double ...
        {mustBeInRange(options.minimumSupportFraction, 0, 1)} = 0.75
    options.falseActivationLimit (1, 1) double ...
        {mustBeInRange(options.falseActivationLimit, 0, 1)} = 0.01
    options.materialRawActionDelta (1, 1) double ...
        {mustBePositive} = 0.05
    options.minimumMaterialBiasFraction (1, 1) double ...
        {mustBeInRange(options.minimumMaterialBiasFraction, 0, 1)} = 0.25
    options.minimumBiasActiveReduction (1, 1) double ...
        {mustBeInRange(options.minimumBiasActiveReduction, 0, 1)} = 0.50
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
end

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
validateInputs(query, training, biasAudit, actuator, options, layout);

queryAction = evaluateHandle(queryActorEvaluator, query.state);
replayError = abs(queryAction-query.rawAction);
if any(replayError > options.replayTolerance, "all")
    error("analyzeNoGloveStage7dTrainingSupport:ReplayMismatch", ...
        "Agent200 does not reproduce the ETAPA 7B query actions (max %.17g).", ...
        max(replayError, [], "all"));
end
trainingAction = evaluateHandle(trainingActorEvaluator, training.state);
queryBiaslessAction = evaluateHandle(biaslessActorEvaluator, query.state);
trainingBiaslessAction = evaluateHandle( ...
    biaslessActorEvaluator, training.state);

[queryEffective, queryPwm] = quantizeRows(queryAction, actuator);
[trainingEffective, trainingPwm] = ...
    quantizeRows(trainingAction, actuator);
[queryBiaslessEffective, queryBiaslessPwm] = ...
    quantizeRows(queryBiaslessAction, actuator);
[trainingBiaslessEffective, trainingBiaslessPwm] = ...
    quantizeRows(trainingBiaslessAction, actuator);

[featureScaleTable, blockDefinitions] = buildFeatureScales( ...
    training.state, layout, options.scaleTolerance);
[blockSupport, nearestByBlock, jointNearest] = measureSupport( ...
    query, training, featureScaleTable, blockDefinitions, options);

jointTrainingRows = jointNearest.trainingRow;
nearestTrainingAction = trainingAction(jointTrainingRows, :);
nearestTrainingEffective = trainingEffective(jointTrainingRows, :);
nearestTrainingPwm = trainingPwm(jointTrainingRows, :);
nearestActionTable = buildNearestActionTable( ...
    query, jointNearest, queryAction, queryEffective, queryPwm, ...
    nearestTrainingAction, nearestTrainingEffective, nearestTrainingPwm);

preMask = training.phase == "preActivationHold";
postMask = training.phase == "postActivationHold";
actionSummary = [ ...
    summarizeActions("queryObservedPreRest", queryAction, ...
        queryEffective, queryPwm, options); ...
    summarizeActions("nearestTrainingReferenceHold", ...
        nearestTrainingAction, nearestTrainingEffective, ...
        nearestTrainingPwm, options); ...
    summarizeActions("allTrainingReferenceHold", trainingAction, ...
        trainingEffective, trainingPwm, options); ...
    summarizeActions("trainingPreActivationHold", ...
        trainingAction(preMask, :), trainingEffective(preMask, :), ...
        trainingPwm(preMask, :), options); ...
    summarizeActions("trainingPostActivationHold", ...
        trainingAction(postMask, :), trainingEffective(postMask, :), ...
        trainingPwm(postMask, :), options); ...
    summarizeActions("biaslessQueryObservedPreRest", ...
        queryBiaslessAction, queryBiaslessEffective, ...
        queryBiaslessPwm, options); ...
    summarizeActions("biaslessTrainingPreActivationHold", ...
        trainingBiaslessAction(preMask, :), ...
        trainingBiaslessEffective(preMask, :), ...
        trainingBiaslessPwm(preMask, :), options)];

motorActionSummary = [ ...
    summarizeActionsByMotor("queryObservedPreRest", queryAction, ...
        queryEffective, queryPwm, options); ...
    summarizeActionsByMotor("nearestTrainingReferenceHold", ...
        nearestTrainingAction, nearestTrainingEffective, ...
        nearestTrainingPwm, options); ...
    summarizeActionsByMotor("trainingPreActivationHold", ...
        trainingAction(preMask, :), trainingEffective(preMask, :), ...
        trainingPwm(preMask, :), options); ...
    summarizeActionsByMotor("trainingPostActivationHold", ...
        trainingAction(postMask, :), trainingEffective(postMask, :), ...
        trainingPwm(postMask, :), options); ...
    summarizeActionsByMotor("biaslessQueryObservedPreRest", ...
        queryBiaslessAction, queryBiaslessEffective, ...
        queryBiaslessPwm, options)];

biasEffectSummary = [ ...
    summarizeBiasEffect("queryObservedPreRest", queryAction, ...
        queryEffective, queryBiaslessAction, queryBiaslessEffective, ...
        options); ...
    summarizeBiasEffect("trainingPreActivationHold", ...
        trainingAction(preMask, :), trainingEffective(preMask, :), ...
        trainingBiaslessAction(preMask, :), ...
        trainingBiaslessEffective(preMask, :), options); ...
    summarizeBiasEffect("allTrainingReferenceHold", trainingAction, ...
        trainingEffective, trainingBiaslessAction, ...
        trainingBiaslessEffective, options)];

zeroProbe = measureZeroProbe(biasAudit, training, ...
    featureScaleTable, blockDefinitions, blockSupport, actuator, options);
decision = classifyEvidence(blockSupport, actionSummary, ...
    biasEffectSummary, zeroProbe, options);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7D", ...
    "observationVariant", "intentMarkov60", ...
    "supportCorpusContract", ...
        "recordedTrainingStateWithZeroVrefAndHeldQrefFromPriorStep", ...
    "supportCalibrationContract", ...
        "crossEpisodeNearestNeighborP95RobustDiagonalDistance", ...
    "queryStateCount", size(query.state, 1), ...
    "trainingEpisodeCount", numel(unique(training.episode)), ...
    "trainingEligibleStateCount", size(training.state, 1), ...
    "trainingPreActivationStateCount", sum(preMask), ...
    "trainingPostActivationStateCount", sum(postMask), ...
    "replayMaximumAbsoluteError", max(replayError, [], "all"), ...
    "replayMeanAbsoluteError", mean(replayError, "all"), ...
    "featureScaleTable", featureScaleTable, ...
    "blockSupport", blockSupport, ...
    "nearestByBlock", nearestByBlock, ...
    "jointNearest", jointNearest, ...
    "nearestActionTable", nearestActionTable, ...
    "actionSummary", actionSummary, ...
    "motorActionSummary", motorActionSummary, ...
    "biasParameterSummary", biasAudit.parameterTable, ...
    "biasEffectSummary", biasEffectSummary, ...
    "zeroInputProbe", zeroProbe, ...
    "sourceDecision", decision, ...
    "rootCauseIdentified", false, ...
    "standardizedEmgUsedAsPhysicalAmplitude", false, ...
    "zeroInputInterpretedAsPhysicalEmg", false, ...
    "zeroInputProbeIsOodDiagnostic", true, ...
    "hybridStateCreated", false, ...
    "behavioralInterventionExecuted", false, ...
    "compensationInterventionExecuted", false, ...
    "filteredReferenceInterventionExecuted", false, ...
    "dtwCalculated", false, "dtwRewardUsed", false, ...
    "runTraining", false, "agent7250Loaded", false, ...
    "envCreated", false, "simulatorInvoked", false, ...
    "rewardInvoked", false, "hardwareUsed", false);
end

function validateInputs(query, training, biasAudit, actuator, options, layout)
requiredQuery = ["state", "rawAction", "episode", "step"];
requiredTraining = ["state", "episode", "step", ...
    "previousReferencePosition", "phase"];
requiredBias = ["parameterTable", "zeroInputOriginalAction", ...
    "zeroInputBiaslessAction"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
if ~all(isfield(query, cellstr(requiredQuery))) || ...
        ~all(isfield(training, cellstr(requiredTraining))) || ...
        ~all(isfield(biasAudit, cellstr(requiredBias))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator)))
    error("analyzeNoGloveStage7dTrainingSupport:MissingField", ...
        "Query, training, bias or actuator contract is incomplete.");
end
validateStateMatrix(query.state, layout.totalLength, "query");
validateStateMatrix(training.state, layout.totalLength, "training");
if ~isequal(size(query.rawAction), [size(query.state, 1), 4]) || ...
        any(~isfinite(query.rawAction), "all") || ...
        numel(query.episode) ~= size(query.state, 1) || ...
        numel(query.step) ~= size(query.state, 1)
    error("analyzeNoGloveStage7dTrainingSupport:InvalidQuery", ...
        "Query metadata or saved action is invalid.");
end
trainingCount = size(training.state, 1);
if numel(training.episode) ~= trainingCount || ...
        numel(training.step) ~= trainingCount || ...
        ~isequal(size(training.previousReferencePosition), ...
            [trainingCount, 4]) || ...
        numel(training.phase) ~= trainingCount || ...
        any(~ismember(training.phase, ...
            ["preActivationHold", "postActivationHold"]))
    error("analyzeNoGloveStage7dTrainingSupport:InvalidTraining", ...
        "Training support metadata is invalid.");
end
if numel(unique(training.episode)) < 2 || ...
        ~all(ismember(["preActivationHold", "postActivationHold"], ...
            unique(training.phase)))
    error("analyzeNoGloveStage7dTrainingSupport:InsufficientTraining", ...
        "Cross-episode calibration requires both reference-hold phases.");
end
vRef = training.state(:, layout.referenceVelocity);
qRef = training.state(:, layout.referencePosition);
if any(abs(vRef) > options.referenceTolerance, "all") || ...
        any(abs(qRef-training.previousReferencePosition) > ...
            options.referenceTolerance, "all")
    error("analyzeNoGloveStage7dTrainingSupport:NonholdTrainingState", ...
        "Every training state must have zero v_ref and held q_ref.");
end
if any(abs(query.state(:, layout.referenceVelocity)) > ...
        options.referenceTolerance, "all")
    error("analyzeNoGloveStage7dTrainingSupport:NonrestQuery", ...
        "Every query state must have zero v_ref.");
end
if ~istable(biasAudit.parameterTable) || ...
        ~isequal(size(biasAudit.zeroInputOriginalAction), [1, 4]) || ...
        ~isequal(size(biasAudit.zeroInputBiaslessAction), [1, 4]) || ...
        any(~isfinite(biasAudit.zeroInputOriginalAction), "all") || ...
        any(~isfinite(biasAudit.zeroInputBiaslessAction), "all")
    error("analyzeNoGloveStage7dTrainingSupport:InvalidBiasAudit", ...
        "Bias audit must contain finite parameter and zero-input data.");
end
end

function validateStateMatrix(value, expectedLength, label)
if ~isnumeric(value) || ~isreal(value) || isempty(value) || ...
        size(value, 2) ~= expectedLength || any(~isfinite(value), "all")
    error("analyzeNoGloveStage7dTrainingSupport:InvalidState", ...
        "%s states must be finite real N-by-%d.", label, expectedLength);
end
end

function actions = evaluateHandle(evaluator, states)
actions = double(evaluator(double(states)));
if ~isequal(size(actions), [size(states, 1), 4]) || ...
        ~isreal(actions) || any(~isfinite(actions), "all")
    error("analyzeNoGloveStage7dTrainingSupport:InvalidActorOutput", ...
        "Actor evaluator must return a finite N-by-4 matrix.");
end
end

function [tableValue, definitions] = buildFeatureScales( ...
        state, layout, tolerance)
definitions = struct( ...
    "name", {"emgFeatures", "encoder", "deltaEncoder", ...
        "previousEffectiveAction", "referencePosition", ...
        "referenceVelocity", "joint"}, ...
    "indices", {layout.emg, layout.encoder, layout.deltaEncoder, ...
        layout.previousEffectiveAction, layout.referencePosition, ...
        layout.referenceVelocity, 1:layout.totalLength});
featureIndex = (1:layout.totalLength)';
block = strings(layout.totalLength, 1);
block(layout.emg) = "emgFeatures";
block(layout.encoder) = "encoder";
block(layout.deltaEncoder) = "deltaEncoder";
block(layout.previousEffectiveAction) = "previousEffectiveAction";
block(layout.referencePosition) = "referencePosition";
block(layout.referenceVelocity) = "referenceVelocity";
center = median(state, 1)';
madScale = (1.482602218505602 * ...
    median(abs(state-median(state, 1)), 1))';
stdScale = std(state, 0, 1)';
rangeValue = (max(state, [], 1)-min(state, [], 1))';
scale = madScale;
scaleSource = repmat("robustMAD", layout.totalLength, 1);
fallback = scale <= tolerance & stdScale > tolerance & ...
    rangeValue > tolerance;
scale(fallback) = stdScale(fallback);
scaleSource(fallback) = "standardDeviationFallback";
variable = scale > tolerance & rangeValue > tolerance;
scale(~variable) = NaN;
scaleSource(~variable) = "invariantExcluded";
tableValue = table(featureIndex, block, center, madScale, stdScale, ...
    rangeValue, scale, scaleSource, variable);
end

function [summary, nearestLong, jointNearest] = measureSupport( ...
        query, training, scaleTable, definitions, options)
summaryRows = repmat(emptySupportRow(), numel(definitions), 1);
nearestCells = cell(numel(definitions), 1);
jointNearest = table();
for blockIdx = 1:numel(definitions)
    definition = definitions(blockIdx);
    mask = ismember(scaleTable.featureIndex, definition.indices) & ...
        scaleTable.variable;
    indices = scaleTable.featureIndex(mask)';
    scales = scaleTable.scale(mask)';
    row = emptySupportRow();
    row.block = string(definition.name);
    row.dimensionCount = numel(definition.indices);
    row.variableDimensionCount = numel(indices);
    if isempty(indices)
        row.classification = "invariantNoDistance";
        nearestCells{blockIdx} = table();
        summaryRows(blockIdx) = row;
        continue
    end
    trainZ = training.state(:, indices)./scales;
    queryZ = query.state(:, indices)./scales;
    calibrationDistance = crossEpisodeNearestDistance( ...
        trainZ, training.episode);
    threshold = max(quantile(calibrationDistance, ...
        options.supportQuantile), options.distanceTolerance);
    [queryDistance, trainingRow] = nearestDistance(queryZ, trainZ);
    supported = queryDistance <= threshold+options.distanceTolerance;
    row.calibrationDistanceMedian = median(calibrationDistance);
    row.calibrationDistanceP95 = quantile(calibrationDistance, 0.95);
    row.calibrationDistanceMaximum = max(calibrationDistance);
    row.supportThreshold = threshold;
    row.queryDistanceMedian = median(queryDistance);
    row.queryDistanceP95 = quantile(queryDistance, 0.95);
    row.queryDistanceMaximum = max(queryDistance);
    row.supportFraction = mean(supported);
    if row.supportFraction >= options.minimumSupportFraction
        row.classification = "supported";
    else
        row.classification = "outOfSupport";
    end
    nearestCells{blockIdx} = table( ...
        repmat(string(definition.name), numel(queryDistance), 1), ...
        query.episode(:), query.step(:), trainingRow, ...
        training.episode(trainingRow), training.step(trainingRow), ...
        queryDistance, supported, ...
        'VariableNames', ["block", "queryEpisode", "queryStep", ...
        "trainingRow", "trainingEpisode", "trainingStep", ...
        "distance", "supported"]);
    if string(definition.name) == "joint"
        jointNearest = nearestCells{blockIdx}(:, 2:end);
    end
    summaryRows(blockIdx) = row;
end
summary = struct2table(summaryRows);
nearestCells = nearestCells(~cellfun(@isempty, nearestCells));
nearestLong = vertcat(nearestCells{:});
if isempty(jointNearest)
    error("analyzeNoGloveStage7dTrainingSupport:JointInvariant", ...
        "The complete training state cannot be invariant.");
end
end

function row = emptySupportRow()
row = struct("block", "", "dimensionCount", 0, ...
    "variableDimensionCount", 0, ...
    "calibrationDistanceMedian", NaN, ...
    "calibrationDistanceP95", NaN, ...
    "calibrationDistanceMaximum", NaN, "supportThreshold", NaN, ...
    "queryDistanceMedian", NaN, "queryDistanceP95", NaN, ...
    "queryDistanceMaximum", NaN, "supportFraction", NaN, ...
    "classification", "");
end

function distance = crossEpisodeNearestDistance(values, episode)
distance = nan(size(values, 1), 1);
episodes = unique(episode(:))';
for episodeId = episodes
    queryRows = episode == episodeId;
    donorRows = ~queryRows;
    if ~any(donorRows)
        error("analyzeNoGloveStage7dTrainingSupport:NoCrossEpisodeDonor", ...
            "Training episode %d has no cross-episode donor.", episodeId);
    end
    distance(queryRows) = nearestDistance( ...
        values(queryRows, :), values(donorRows, :));
end
end

function [distance, index] = nearestDistance(query, corpus)
queryNorm = sum(query.^2, 2);
corpusNorm = sum(corpus.^2, 2)';
distanceSquared = max(queryNorm+corpusNorm-2*(query*corpus'), 0);
[distanceSquared, index] = min(distanceSquared, [], 2);
distance = sqrt(distanceSquared/size(query, 2));
end

function value = buildNearestActionTable(query, nearest, ...
        queryRaw, queryEffective, queryPwm, trainingRaw, ...
        trainingEffective, trainingPwm)
rowCount = size(queryRaw, 1);
[queryRow, motor] = ndgrid((1:rowCount)', 1:4);
queryRow = queryRow(:);
motor = motor(:);
linear = sub2ind(size(queryRaw), queryRow, motor);
value = table(query.episode(queryRow), query.step(queryRow), motor, ...
    nearest.trainingEpisode(queryRow), nearest.trainingStep(queryRow), ...
    nearest.distance(queryRow), nearest.supported(queryRow), ...
    queryRaw(linear), queryEffective(linear), queryPwm(linear), ...
    trainingRaw(linear), trainingEffective(linear), ...
    trainingPwm(linear), ...
    abs(queryRaw(linear)-trainingRaw(linear)), ...
    'VariableNames', ["queryEpisode", "queryStep", "motor", ...
    "trainingEpisode", "trainingStep", "jointDistance", ...
    "jointSupported", "queryRawAction", "queryEffectiveAction", ...
    "queryPwm", "trainingRawAction", "trainingEffectiveAction", ...
    "trainingPwm", "absoluteRawActionDifference"]);
end

function row = summarizeActions(label, raw, effective, pwm, options)
if isempty(raw)
    error("analyzeNoGloveStage7dTrainingSupport:EmptyActionGroup", ...
        "Action group %s is empty.", label);
end
active = abs(effective) > 0;
row = table(string(label), size(raw, 1), numel(raw), ...
    mean(active, "all"), mean(any(active, 2)), ...
    mean(abs(raw), "all"), mean(abs(effective), "all"), ...
    mean(abs(pwm), "all"), ...
    mean(abs(effective) >= options.saturationThreshold, "all"), ...
    'VariableNames', ["source", "stateCount", "componentCount", ...
    "commandActiveFraction", "windowAnyCommandFraction", ...
    "meanAbsRawAction", "meanAbsEffectiveAction", "meanAbsPwm", ...
    "saturationFraction"]);
end

function value = summarizeActionsByMotor(label, raw, effective, pwm, options)
rows = cell(4, 1);
for motor = 1:4
    active = abs(effective(:, motor)) > 0;
    rows{motor} = table(string(label), motor, size(raw, 1), ...
        mean(active), mean(abs(raw(:, motor))), ...
        mean(abs(effective(:, motor))), mean(abs(pwm(:, motor))), ...
        mean(abs(effective(:, motor)) >= options.saturationThreshold), ...
        'VariableNames', ["source", "motor", "stateCount", ...
        "commandActiveFraction", "meanAbsRawAction", ...
        "meanAbsEffectiveAction", "meanAbsPwm", ...
        "saturationFraction"]);
end
value = vertcat(rows{:});
end

function row = summarizeBiasEffect(label, originalRaw, ...
        originalEffective, biaslessRaw, biaslessEffective, options)
delta = abs(originalRaw-biaslessRaw);
originalActive = abs(originalEffective) > 0;
biaslessActive = abs(biaslessEffective) > 0;
row = table(string(label), size(originalRaw, 1), ...
    mean(delta, "all"), max(delta, [], "all"), ...
    mean(delta >= options.materialRawActionDelta, "all"), ...
    mean(originalActive, "all"), mean(biaslessActive, "all"), ...
    mean(originalActive, "all")-mean(biaslessActive, "all"), ...
    'VariableNames', ["source", "stateCount", ...
    "meanAbsoluteRawActionChange", "maximumAbsoluteRawActionChange", ...
    "materialRawActionChangeFraction", ...
    "originalCommandActiveFraction", ...
    "biaslessCommandActiveFraction", ...
    "commandActiveFractionReduction"]);
end

function probe = measureZeroProbe(biasAudit, training, scaleTable, ...
        definitions, blockSupport, actuator, options)
zeroState = zeros(1, 60);
joint = definitions(string({definitions.name}) == "joint");
mask = ismember(scaleTable.featureIndex, joint.indices) & ...
    scaleTable.variable;
indices = scaleTable.featureIndex(mask)';
scales = scaleTable.scale(mask)';
[distance, trainingRow] = nearestDistance( ...
    zeroState(:, indices)./scales, training.state(:, indices)./scales);
jointSummary = blockSupport(blockSupport.block == "joint", :);
supported = distance <= jointSummary.supportThreshold+ ...
    options.distanceTolerance;
[originalEffective, originalPwm] = quantizeRows( ...
    biasAudit.zeroInputOriginalAction, actuator);
[biaslessEffective, biaslessPwm] = quantizeRows( ...
    biasAudit.zeroInputBiaslessAction, actuator);
probe = table(true, false, distance, jointSummary.supportThreshold, ...
    supported, trainingRow, training.episode(trainingRow), ...
    training.step(trainingRow), ...
    mean(abs(originalEffective) > 0, "all"), ...
    mean(abs(biaslessEffective) > 0, "all"), ...
    mean(abs(biasAudit.zeroInputOriginalAction), "all"), ...
    mean(abs(biasAudit.zeroInputBiaslessAction), "all"), ...
    mean(abs(originalPwm), "all"), mean(abs(biaslessPwm), "all"), ...
    biasAudit.zeroInputOriginalAction(1), ...
    biasAudit.zeroInputOriginalAction(2), ...
    biasAudit.zeroInputOriginalAction(3), ...
    biasAudit.zeroInputOriginalAction(4), ...
    originalEffective(1), originalEffective(2), ...
    originalEffective(3), originalEffective(4), ...
    originalPwm(1), originalPwm(2), originalPwm(3), originalPwm(4), ...
    biasAudit.zeroInputBiaslessAction(1), ...
    biasAudit.zeroInputBiaslessAction(2), ...
    biasAudit.zeroInputBiaslessAction(3), ...
    biasAudit.zeroInputBiaslessAction(4), ...
    'VariableNames', ["declaredOodProbe", ...
    "interpretedAsPhysicalEmgAmplitude", "jointDistance", ...
    "jointSupportThreshold", "withinMeasuredTrainingSupport", ...
    "nearestTrainingRow", "nearestTrainingEpisode", ...
    "nearestTrainingStep", "originalCommandActiveFraction", ...
    "biaslessCommandActiveFraction", "originalMeanAbsRawAction", ...
    "biaslessMeanAbsRawAction", "originalMeanAbsPwm", ...
    "biaslessMeanAbsPwm", ...
    "originalRawActionM1", "originalRawActionM2", ...
    "originalRawActionM3", "originalRawActionM4", ...
    "originalEffectiveActionM1", "originalEffectiveActionM2", ...
    "originalEffectiveActionM3", "originalEffectiveActionM4", ...
    "originalPwmM1", "originalPwmM2", "originalPwmM3", ...
    "originalPwmM4", "biaslessRawActionM1", ...
    "biaslessRawActionM2", "biaslessRawActionM3", ...
    "biaslessRawActionM4"]);
end

function decision = classifyEvidence(blockSupport, actionSummary, ...
        biasEffect, zeroProbe, options)
joint = blockSupport(blockSupport.block == "joint", :);
emg = blockSupport(blockSupport.block == "emgFeatures", :);
query = actionSummary(actionSummary.source == ...
    "queryObservedPreRest", :);
trainingPre = actionSummary(actionSummary.source == ...
    "trainingPreActivationHold", :);
biaslessQuery = actionSummary(actionSummary.source == ...
    "biaslessQueryObservedPreRest", :);
biasQuery = biasEffect(biasEffect.source == ...
    "queryObservedPreRest", :);

outOfSupport = joint.supportFraction < ...
    options.minimumSupportFraction || emg.supportFraction < ...
    options.minimumSupportFraction;
trainingRestCommands = ...
    trainingPre.windowAnyCommandFraction > options.falseActivationLimit;
biasMaterial = ...
    biasQuery.materialRawActionChangeFraction >= ...
        options.minimumMaterialBiasFraction && ...
    biasQuery.commandActiveFractionReduction >= ...
        options.minimumBiasActiveReduction && ...
    biaslessQuery.windowAnyCommandFraction <= options.falseActivationLimit && ...
    zeroProbe.originalCommandActiveFraction > options.falseActivationLimit;

if trainingRestCommands
    classification = "trainingRestAlsoCommands";
elseif outOfSupport
    classification = "restStateOutOfTrainingSupport";
elseif biasMaterial
    classification = "actorBiasContribution";
else
    classification = "causeStillUnresolved";
end
decision = table(classification, outOfSupport, ...
    trainingRestCommands, biasMaterial, joint.supportFraction, ...
    emg.supportFraction, query.windowAnyCommandFraction, ...
    trainingPre.windowAnyCommandFraction, ...
    trainingPre.commandActiveFraction, ...
    biaslessQuery.windowAnyCommandFraction, ...
    biasQuery.materialRawActionChangeFraction, ...
    biasQuery.commandActiveFractionReduction, ...
    zeroProbe.withinMeasuredTrainingSupport, false, ...
    'VariableNames', ["classification", ...
    "restStateOutOfTrainingSupport", "trainingRestAlsoCommands", ...
    "actorBiasContribution", "jointSupportFraction", ...
    "emgSupportFraction", "queryWindowAnyCommandFraction", ...
    "trainingRestWindowAnyCommandFraction", ...
    "trainingRestComponentCommandFraction", ...
    "biaslessQueryWindowAnyCommandFraction", ...
    "materialBiasChangeFraction", "biasActiveFractionReduction", ...
    "zeroInputWithinMeasuredTrainingSupport", "rootCauseIdentified"]);
end

function [effective, pwm] = quantizeRows(actions, actuator)
effective = nan(size(actions));
pwm = nan(size(actions));
for rowIdx = 1:size(actions, 1)
    [effectiveRow, pwmRow] = quantizeBaselineAction( ...
        actions(rowIdx, :), actuator.maxPwm, ...
        actuator.activationThreshold, actuator.commandLevels);
    effective(rowIdx, :) = double(effectiveRow(:))';
    pwm(rowIdx, :) = double(pwmRow(:))';
end
