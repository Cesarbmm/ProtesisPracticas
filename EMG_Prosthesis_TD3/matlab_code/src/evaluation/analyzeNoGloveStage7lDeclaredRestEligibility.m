function analysis = analyzeNoGloveStage7lDeclaredRestEligibility( ...
        decisions, windows, options)
%analyzeNoGloveStage7lDeclaredRestEligibility replays a semantic latch.
%
% The latch is eligible only during episode initialization or decoder-declared
% rest. It releases at the first non-rest decision and cannot use future rows.

arguments
    decisions table
    windows table
    options.entryPositionMseTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.farCorrectionMse (1, 1) double ...
        {mustBePositive} = 2.5e-3
    options.minimumRestCoverage (1, 1) double ...
        {mustBeInRange(options.minimumRestCoverage, 0, 1)} = 0.90
    options.expectedEpisodeCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 548
    options.expectedWindowCount (1, 1) double ...
        {mustBeInteger, mustBePositive} = 31220
end

[decisions, windows] = validateAndAlignInputs(decisions, windows, options);
windowAudit = replayCorpus(decisions, windows, options);
segmentAudit = buildSegmentAudit(windowAudit);
episodeAudit = buildEpisodeAudit(windowAudit);
variantSummary = buildVariantSummary(windowAudit, options);
provenanceSummary = buildProvenanceSummary(windowAudit, options);

episodeCount = height(episodeAudit);
windowCount = height(windowAudit);
stopped = windowAudit.stopped;
semanticCoverage = mean(ismember(windowAudit.provenance(stopped), ...
    ["episodeInitialization", "decoderRest", ...
    "activeCountdownZero", "activeSynergyZero", ...
    "mechanicalPositionLimitZero", "mechanicalRateLimitZero", ...
    "unresolvedActiveZero"]));
minimumVariantRestCoverage = min(variantSummary.steadyRestLatchCoverage);
nonRestLeakageCount = sum(windowAudit.nonRestLeakage);
prematureCount = sum(windowAudit.prematureFarStartedLatch);
recoveredCount = sum(windowAudit.recoveredByMemory);
prefixMismatchCount = sum(windowAudit.prefixMismatch);
prefixCheckCount = episodeCount;

checks = struct( ...
    "integrity", episodeCount == options.expectedEpisodeCount && ...
        windowCount == options.expectedWindowCount, ...
    "semanticCoverage", semanticCoverage == 1, ...
    "restCoverage", minimumVariantRestCoverage >= ...
        options.minimumRestCoverage, ...
    "noNonRestLeakage", nonRestLeakageCount == 0, ...
    "noPrematureFarStartedLatch", prematureCount == 0, ...
    "addsMemorySupport", recoveredCount > 0, ...
    "prefixCausal", prefixMismatchCount == 0);
if ~checks.integrity || ~checks.semanticCoverage || ~checks.prefixCausal
    classification = "declaredRestEligibilityAuditInvalid";
elseif ~checks.restCoverage
    classification = "declaredRestCoverageInsufficient";
elseif ~checks.noNonRestLeakage
    classification = "declaredRestNonRestLeakage";
elseif ~checks.noPrematureFarStartedLatch
    classification = "declaredRestPrematureFarStartedExposure";
elseif ~checks.addsMemorySupport
    classification = "declaredRestLatchAddsNoSupport";
else
    classification = "offlineDeclaredRestEligibilitySupported";
end
gateChecks = table( ...
    ["episodeCount"; "decisionWindowCount"; ...
    "stoppedSemanticLabelCoverage"; "minimumVariantSteadyRestCoverage"; ...
    "nonRestLeakageCount"; "prematureFarStartedLatchCount"; ...
    "recoveredByMemoryCount"; "prefixMismatchCount"], ...
    [episodeCount; windowCount; semanticCoverage; ...
    minimumVariantRestCoverage; nonRestLeakageCount; prematureCount; ...
    recoveredCount; prefixMismatchCount], ...
    [options.expectedEpisodeCount; options.expectedWindowCount; 1; ...
    options.minimumRestCoverage; 0; 0; 1; 0], ...
    ["equal"; "equal"; "equal"; "greaterOrEqual"; "equal"; ...
    "equal"; "greaterOrEqual"; "equal"], ...
    logical([episodeCount == options.expectedEpisodeCount; ...
    windowCount == options.expectedWindowCount; checks.semanticCoverage; ...
    checks.restCoverage; checks.noNonRestLeakage; ...
    checks.noPrematureFarStartedLatch; checks.addsMemorySupport; ...
    checks.prefixCausal]), ...
    'VariableNames', ["check", "observed", "threshold", ...
    "comparison", "passed"]);
contractSupported = all(gateChecks.passed);

sourceDecision = table(classification, contractSupported, ...
    semanticCoverage, minimumVariantRestCoverage, ...
    sum(windowAudit.declaredRest), nonRestLeakageCount, prematureCount, ...
    recoveredCount, sum(windowAudit.rawFarCorrection), ...
    sum(windowAudit.latchedRawFarCorrection), ...
    sum(windowAudit.differsFromStage7jLatch), prefixCheckCount, ...
    prefixMismatchCount, recoveredCount > 0, ...
    "intentDeclaredRestHoldMarkov62", 62, false, false, false, ...
    'VariableNames', ["classification", "contractSupported", ...
    "stoppedSemanticLabelCoverage", "minimumVariantSteadyRestCoverage", ...
    "declaredRestWindowCount", "nonRestLeakageCount", ...
    "prematureFarStartedLatchCount", "recoveredByMemoryCount", ...
    "rawFarCorrectionWindowCount", "latchedRawFarCorrectionWindowCount", ...
    "stage7jLatchDifferenceCount", "prefixCheckCount", ...
    "prefixMismatchCount", "explicitMemoryRequired", ...
    "proposedObservationVariant", "proposedObservationDimension", ...
    "observationVariantImplemented", "behavioralAblationAuthorized", ...
    "stage7jContractReauthorized"]);

analysis = struct("schemaVersion", 1, "stage", "7L", ...
    "windowAudit", windowAudit, "segmentAudit", segmentAudit, ...
    "episodeAudit", episodeAudit, "variantSummary", variantSummary, ...
    "provenanceSummary", provenanceSummary, "gateChecks", gateChecks, ...
    "sourceDecision", sourceDecision, "classification", classification, ...
    "contractSupported", contractSupported, "checks", checks, ...
    "thresholds", struct( ...
        "entryPositionMseTolerance", ...
            options.entryPositionMseTolerance, ...
        "farCorrectionMse", options.farCorrectionMse, ...
        "minimumRestCoverage", options.minimumRestCoverage), ...
    "prefixCheckCount", prefixCheckCount, ...
    "prefixMismatchCount", prefixMismatchCount, ...
    "explicitMemoryRequired", recoveredCount > 0, ...
    "proposedObservationVariant", "intentDeclaredRestHoldMarkov62", ...
    "proposedObservationDimension", 62, ...
    "observationVariantImplemented", false, ...
    "behavioralInterventionExecuted", false, ...
    "stage7jContractReauthorized", false, ...
    "rootCauseIdentified", false, ...
    "policyChanged", false, "rewardChanged", false, ...
    "referenceChanged", false, "stateChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "simulatorInvoked", false, ...
    "runTraining", false, "agentLoaded", false, ...
    "envCreated", false, "rewardFunctionInvoked", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false);
end

function [decisions, windows] = validateAndAlignInputs( ...
        decisions, windows, options)
decisionRequired = ["variant", "source", "episode", "repetitionId", ...
    "step", "windowIndex", "stopped", "provenance", ...
    "latchActive", "stoppedSegmentId", "segmentFarStarted"];
windowRequired = ["variant", "source", "episode", "repetitionId", ...
    "step", "windowIndex", "holdPositionMse", "stopped"];
if isempty(decisions) || isempty(windows) || ...
        ~all(ismember(decisionRequired, ...
        string(decisions.Properties.VariableNames))) || ...
        ~all(ismember(windowRequired, ...
        string(windows.Properties.VariableNames))) || ...
        height(decisions) ~= options.expectedWindowCount || ...
        height(windows) ~= options.expectedWindowCount
    error("analyzeNoGloveStage7lDeclaredRestEligibility:InvalidCorpus", ...
        "The frozen Stage 7K/7I corpus is incomplete.");
end
variants = sort(unique(string(decisions.variant)))';
sources = unique(string(decisions.source));
if ~isequal(variants, ["candidate", "control"]) || ...
        ~all(ismember(["training", "acceptance", "steadyRest"], sources))
    error("analyzeNoGloveStage7lDeclaredRestEligibility:InvalidCorpus", ...
        "Both variants and all three frozen sources are required.");
end
decisionKey = buildKey(decisions);
windowKey = buildKey(windows);
if numel(unique(decisionKey)) ~= height(decisions) || ...
        numel(unique(windowKey)) ~= height(windows)
    error("analyzeNoGloveStage7lDeclaredRestEligibility:DuplicateKey", ...
        "The frozen corpus contains duplicate decision keys.");
end
[matched, location] = ismember(decisionKey, windowKey);
if ~all(matched) || numel(unique(location)) ~= height(windows)
    error("analyzeNoGloveStage7lDeclaredRestEligibility:KeyMismatch", ...
        "Stage 7K decisions do not match Stage 7I windows exactly.");
end
windows = windows(location, :);
numeric = [double(decisions.episode); double(decisions.repetitionId); ...
    double(decisions.step); double(decisions.windowIndex); ...
    double(decisions.stoppedSegmentId); ...
    double(windows.holdPositionMse)];
if any(~isfinite(numeric)) || any(windows.holdPositionMse < 0) || ...
        ~isequal(logical(decisions.stopped), logical(windows.stopped)) || ...
        any(strlength(string(decisions.provenance)) == 0) || ...
        height(unique(decisions(:, ["variant", "source", "episode"]), ...
        "rows")) ~= options.expectedEpisodeCount
    error("analyzeNoGloveStage7lDeclaredRestEligibility:InvalidCorpus", ...
        "Frozen values or episode cardinality violate the input contract.");
end
end

function key = buildKey(values)
key = string(values.variant)+"|"+string(values.source)+"|"+ ...
    string(values.episode)+"|"+string(values.repetitionId)+"|"+ ...
    string(values.step)+"|"+string(values.windowIndex);
end

function audit = replayCorpus(decisions, windows, options)
count = height(decisions);
provenance = string(decisions.provenance);
declaredRest = ismember(provenance, ...
    ["episodeInitialization", "decoderRest"]);
nearTarget = windows.holdPositionMse <= ...
    options.entryPositionMseTolerance;
instantEligible = declaredRest & nearTarget;
latch = false(count, 1);
entry = false(count, 1);
release = false(count, 1);
prefixMismatch = false(count, 1);
keys = string(decisions.variant)+"|"+string(decisions.source)+"|"+ ...
    string(decisions.episode);
[groups, uniqueKeys] = findgroups(keys);
for groupIdx = 1:numel(uniqueKeys)
    indices = find(groups == groupIdx);
    [steps, order] = sort(double(decisions.step(indices)));
    indices = indices(order);
    if ~isequal(steps', 1:numel(indices))
        error("analyzeNoGloveStage7lDeclaredRestEligibility:StepOrder", ...
            "Episode steps are not contiguous.");
    end
    replay = replayEpisode(declaredRest(indices), nearTarget(indices));
    latch(indices) = replay.latch;
    entry(indices) = replay.entry;
    release(indices) = replay.release;
    cut = max(1, floor(numel(indices)/2));
    prefix = replayEpisode(declaredRest(indices(1:cut)), ...
        nearTarget(indices(1:cut)));
    prefixMismatch(indices(1)) = ...
        ~isequal(prefix.latch, replay.latch(1:cut)) || ...
        ~isequal(prefix.entry, replay.entry(1:cut)) || ...
        ~isequal(prefix.release, replay.release(1:cut));
end
beforeFarConvergence = classifyBeforeFarConvergence( ...
    decisions, nearTarget);
premature = latch & beforeFarConvergence;
rawFar = logical(decisions.stopped) & ...
    ismember(string(decisions.source), ["training", "acceptance"]) & ...
    windows.holdPositionMse >= options.farCorrectionMse;
oldLatch = logical(decisions.latchActive);
audit = table(string(decisions.variant), string(decisions.source), ...
    double(decisions.episode), double(decisions.repetitionId), ...
    double(decisions.step), double(decisions.windowIndex), ...
    provenance, double(windows.holdPositionMse), ...
    logical(decisions.stopped), declaredRest, nearTarget, ...
    instantEligible, latch, entry, release, latch & ~instantEligible, ...
    latch & ~declaredRest, double(decisions.stoppedSegmentId), ...
    logical(decisions.segmentFarStarted), beforeFarConvergence, ...
    premature, rawFar, latch & rawFar, oldLatch, latch ~= oldLatch, ...
    prefixMismatch, ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "step", "windowIndex", "provenance", ...
    "holdPositionMse", "stopped", "declaredRest", "nearTarget", ...
    "instantEligible", "latchActive", "latchEntry", "latchRelease", ...
    "recoveredByMemory", "nonRestLeakage", "stoppedSegmentId", ...
    "segmentFarStarted", "beforeFarConvergence", ...
    "prematureFarStartedLatch", "rawFarCorrection", ...
    "latchedRawFarCorrection", "stage7jLatchActive", ...
    "differsFromStage7jLatch", "prefixMismatch"]);
end

function replay = replayEpisode(declaredRest, nearTarget)
count = numel(declaredRest);
latch = false(count, 1);
entry = false(count, 1);
release = false(count, 1);
previous = false;
for idx = 1:count
    if ~declaredRest(idx)
        latch(idx) = false;
    elseif nearTarget(idx)
        latch(idx) = true;
    else
        latch(idx) = previous;
    end
    entry(idx) = latch(idx) && ~previous;
    release(idx) = ~latch(idx) && previous;
    previous = latch(idx);
end
replay = struct("latch", latch, "entry", entry, "release", release);
end

function before = classifyBeforeFarConvergence(decisions, nearTarget)
before = false(height(decisions), 1);
valid = decisions.stoppedSegmentId > 0 & decisions.segmentFarStarted;
keys = string(decisions.variant)+"|"+string(decisions.source)+"|"+ ...
    string(decisions.episode)+"|"+string(decisions.stoppedSegmentId);
[groups, uniqueKeys] = findgroups(keys(valid));
validIndices = find(valid);
for groupIdx = 1:numel(uniqueKeys)
    indices = validIndices(groups == groupIdx);
    [~, order] = sort(double(decisions.step(indices)));
    indices = indices(order);
    converged = false;
    for idx = indices'
        if nearTarget(idx)
            converged = true;
        end
        before(idx) = ~converged;
    end
end
end

function audit = buildSegmentAudit(windows)
stopped = windows(windows.stoppedSegmentId > 0, :);
keys = stopped.variant+"|"+stopped.source+"|"+ ...
    string(stopped.episode)+"|"+string(stopped.stoppedSegmentId);
[groups, uniqueKeys] = findgroups(keys);
parts = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = stopped(groups == groupIdx, :);
    [~, order] = sort(values.step);
    values = values(order, :);
    nearSteps = values.step(values.nearTarget);
    firstNearStep = NaN;
    if ~isempty(nearSteps)
        firstNearStep = min(nearSteps);
    end
    parts{groupIdx} = table(values.variant(1), values.source(1), ...
        values.episode(1), values.repetitionId(1), ...
        values.stoppedSegmentId(1), min(values.step), max(values.step), ...
        height(values), values.holdPositionMse(1), ...
        values.segmentFarStarted(1), any(values.nearTarget), ...
        firstNearStep, sum(values.beforeFarConvergence), ...
        sum(values.prematureFarStartedLatch), any(values.latchActive), ...
        sum(values.recoveredByMemory), sum(values.rawFarCorrection), ...
        sum(values.latchedRawFarCorrection), ...
        'VariableNames', ["variant", "source", "episode", ...
        "repetitionId", "stoppedSegmentId", "startStep", "endStep", ...
        "windowCount", "startPositionMse", "farStarted", ...
        "reachedNearTarget", "firstNearStep", ...
        "preconvergenceWindowCount", "prematureLatchWindowCount", ...
        "latchEverActive", "recoveredWindowCount", ...
        "rawFarCorrectionWindowCount", ...
        "latchedRawFarCorrectionWindowCount"]);
end
audit = vertcat(parts{:});
end

function audit = buildEpisodeAudit(windows)
keys = windows.variant+"|"+windows.source+"|"+string(windows.episode);
[groups, uniqueKeys] = findgroups(keys);
parts = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = windows(groups == groupIdx, :);
    parts{groupIdx} = table(values.variant(1), values.source(1), ...
        values.episode(1), values.repetitionId(1), height(values), ...
        sum(values.declaredRest), mean(values.latchActive), ...
        sum(values.recoveredByMemory), sum(values.nonRestLeakage), ...
        sum(values.prematureFarStartedLatch), sum(values.latchEntry), ...
        sum(values.latchRelease), sum(values.differsFromStage7jLatch), ...
        'VariableNames', ["variant", "source", "episode", ...
        "repetitionId", "windowCount", "declaredRestWindowCount", ...
        "latchCoverage", "recoveredByMemoryCount", ...
        "nonRestLeakageCount", "prematureFarStartedLatchCount", ...
        "entryCount", "releaseCount", "stage7jLatchDifferenceCount"]);
end
audit = vertcat(parts{:});
end

function summary = buildVariantSummary(windows, options)
variants = ["control", "candidate"];
parts = cell(numel(variants), 1);
for idx = 1:numel(variants)
    variant = variants(idx);
    values = windows(windows.variant == variant, :);
    rest = values(values.source == "steadyRest", :);
    far = values.rawFarCorrection;
    parts{idx} = table(variant, height(values), ...
        sum(values.declaredRest), mean(rest.instantEligible), ...
        mean(rest.latchActive), sum(values.recoveredByMemory), ...
        sum(values.nonRestLeakage), ...
        sum(values.prematureFarStartedLatch), sum(far), ...
        meanOrNaN(values.latchActive(far)), ...
        sum(values.latchedRawFarCorrection), ...
        sum(values.differsFromStage7jLatch), ...
        sum(values.latchEntry), sum(values.latchRelease), ...
        'VariableNames', ["variant", "windowCount", ...
        "declaredRestWindowCount", "steadyRestInstantCoverage", ...
        "steadyRestLatchCoverage", "recoveredByMemoryCount", ...
        "nonRestLeakageCount", "prematureFarStartedLatchCount", ...
        "rawFarCorrectionWindowCount", "latchedRawFarExposure", ...
        "latchedRawFarCorrectionWindowCount", ...
        "stage7jLatchDifferenceCount", "entryCount", "releaseCount"]);
end
summary = vertcat(parts{:});
if any(summary.steadyRestLatchCoverage < options.minimumRestCoverage)
    return
end
end

function summary = buildProvenanceSummary(windows, options)
[groups, variant, source, provenance] = findgroups( ...
    windows.variant, windows.source, windows.provenance);
windowCount = splitapply(@numel, windows.step, groups);
declaredRestCount = splitapply(@sum, windows.declaredRest, groups);
latchCount = splitapply(@sum, windows.latchActive, groups);
recoveredCount = splitapply(@sum, windows.recoveredByMemory, groups);
nonRestLeakageCount = splitapply(@sum, windows.nonRestLeakage, groups);
prematureCount = splitapply(@sum, ...
    windows.prematureFarStartedLatch, groups);
rawFarCount = splitapply(@sum, windows.holdPositionMse >= ...
    options.farCorrectionMse, groups);
summary = table(variant, source, provenance, windowCount, ...
    declaredRestCount, latchCount, recoveredCount, nonRestLeakageCount, ...
    prematureCount, rawFarCount);
end

function value = meanOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = mean(double(values));
end
end
