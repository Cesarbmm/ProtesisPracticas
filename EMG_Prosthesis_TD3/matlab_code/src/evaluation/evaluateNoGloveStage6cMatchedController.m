function direction = thresholdDirection(value, threshold)
direction = zeros(size(value));
direction(value >= threshold) = 1;
direction(value <= -threshold) = -1;
end

function value = safeFraction(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator / denominator;
end
end

function value = meanMotorEpisodeDelta(values)
episodes = unique(values.episode, "stable");
perEpisode = zeros(numel(episodes), 1);
for episodeIdx = 1:numel(episodes)
    action = values.effectiveAction( ...
        values.episode == episodes(episodeIdx));
    if numel(action) > 1
        perEpisode(episodeIdx) = mean(diff(action).^2);
    end
end
value = mean(perEpisode);
end
