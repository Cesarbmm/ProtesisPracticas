function result = evaluateNoGloveStage6cMatchedController( ...
        sourceEpisodeDirectory, configs, splitName, options)
%evaluateNoGloveStage6cMatchedController replay a matched P/PD baseline.
%
% The saved ETAPA 6A Agent200 episode is the immutable source of q_ref,
% v_ref and the initial encoder position. The conventional controller is
% simulated from that same initial position and reference. The agent is
% never loaded or invoked. This makes commandSource the sole intentional
% intervention while preserving the simulator, quantizer and safety layer.

arguments
    sourceEpisodeDirectory (1, 1) string
    configs (1, 1) struct
    splitName (1, 1) string
    options.activeVelocityThreshold (1, 1) double ...
        {mustBeNonnegative} = 0.005
    options.motionTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.positionTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-9
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
    options.simulatorSamplingPeriod (1, 1) double ...
        {mustBePositive} = 0.14
end

validateProfile(configs);
if ~isfolder(sourceEpisodeDirectory)
    error("evaluateNoGloveStage6cMatchedController:DirectoryNotFound", ...
        "Source episode directory not found: %s", sourceEpisodeDirectory);
end
if ismissing(splitName) || strlength(splitName) == 0
    error("evaluateNoGloveStage6cMatchedController:InvalidSplit", ...
        "splitName must be nonempty.");
end

episodeFiles = dir(fullfile(sourceEpisodeDirectory, "episode*.mat"));
if isempty(episodeFiles)
    error("evaluateNoGloveStage6cMatchedController:NoEpisodes", ...
        "No episode files found in %s.", sourceEpisodeDirectory);
end
[~, order] = sort({episodeFiles.name});
episodeFiles = episodeFiles(order);

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
actuator = struct( ...
    "maxPwm", max(abs(double(configs.speeds))), ...
    "activationThreshold", ...
        double(configs.actionCommandActivationThreshold), ...
    "commandLevels", double(configs.actionCommandLevels));
componentTables = cell(numel(episodeFiles), 2);
pairRows = repmat(emptyPairRow(), numel(episodeFiles), 1);

for episodeIdx = 1:numel(episodeFiles)
    episodePath = string(fullfile(episodeFiles(episodeIdx).folder, ...
        episodeFiles(episodeIdx).name));
    source = loadSourceEpisode(episodePath, configs, layout);
    conventional = simulateConventional(source, configs, actuator, options);
    componentTables{episodeIdx, 1} = buildComponentTable( ...
        source, source.agentTrace, splitName, "Agent200", ...
        episodeIdx, configs, options);
    componentTables{episodeIdx, 2} = buildComponentTable( ...
        source, conventional, splitName, "conventionalP", ...
        episodeIdx, configs, options);

    row = emptyPairRow();
    row.episode = episodeIdx;
    row.fileName = string(episodeFiles(episodeIdx).name);
    row.repetitionId = source.repetitionId;
    row.stepCount = size(source.reference, 1);
    row.referenceMaxAbs = max(abs( ...
        conventional.reference - source.reference), [], "all");
    row.referenceVelocityMaxAbs = max(abs( ...
        conventional.referenceVelocity - source.referenceVelocity), ...
        [], "all");
    row.initialPositionMaxAbs = max(abs( ...
        conventional.qBefore(1, :) - source.agentTrace.qBefore(1, :)), ...
        [], "all");
    row.sourceTemporalAlignmentMaxAbs = ...
        source.temporalAlignmentMaxAbs;
    pairRows(episodeIdx) = row;
end

componentTable = vertcat(componentTables{:});
pairingTable = struct2table(pairRows);
episodeSummary = summarizeEpisodes(componentTable, configs, options);
motorEpisodeFlags = buildMotorEpisodeFlags( ...
    componentTable, configs, options);
motorSummary = summarizeMotors(componentTable, motorEpisodeFlags);
aggregateSummary = summarizeSources( ...
    componentTable, motorEpisodeFlags, pairingTable, episodeSummary);

pairing = struct( ...
    "episodeCount", height(pairingTable), ...
    "stepCount", sum(pairingTable.stepCount), ...
    "componentCountPerSource", height(componentTable) / 2, ...
    "referenceMaxAbs", max(pairingTable.referenceMaxAbs), ...
    "referenceVelocityMaxAbs", ...
        max(pairingTable.referenceVelocityMaxAbs), ...
    "initialPositionMaxAbs", ...
        max(pairingTable.initialPositionMaxAbs), ...
    "sourceTemporalAlignmentMaxAbs", ...
        max(pairingTable.sourceTemporalAlignmentMaxAbs), ...
    "allExact", all(pairingTable.referenceMaxAbs == 0) && ...
        all(pairingTable.referenceVelocityMaxAbs == 0) && ...
        all(pairingTable.initialPositionMaxAbs == 0) && ...
        all(pairingTable.sourceTemporalAlignmentMaxAbs <= 1e-12));
if ~pairing.allExact
    error("evaluateNoGloveStage6cMatchedController:PairingFailed", ...
        "Reference, initial-position or source temporal pairing failed.");
end

result = struct( ...
    "schemaVersion", 1, ...
    "split", splitName, ...
    "sourceEpisodeDirectory", sourceEpisodeDirectory, ...
    "controller", configs.conventionalController, ...
    "actuator", actuator, ...
    "simulationPositionSafety", configs.simulationPositionSafety, ...
    "simulatorSamplingPeriod", options.simulatorSamplingPeriod, ...
    "pairing", pairing, ...
    "pairingTable", pairingTable, ...
    "componentTable", componentTable, ...
    "episodeSummary", episodeSummary, ...
    "motorEpisodeFlags", motorEpisodeFlags, ...
    "motorSummary", motorSummary, ...
    "aggregateSummary", aggregateSummary, ...
    "agentLoaded", false, ...
    "reinforcementLearningInvoked", false, ...
    "simulatorInvokedForConventionalOnly", true, ...
    "hardwareUsed", false, ...
    "dtwCalculated", false);
end

function validateProfile(configs)
required = [ ...
    "simMotors", "connect_glove", "usePrerecorded", ...
    "referenceSource", "observationVariant", ...
    "actionInterfaceVariant", "quantizeCommandsForSimulation", ...
    "unifyActions", "period", "speeds", ...
    "actionCommandActivationThreshold", "actionCommandLevels", ...
    "conventionalController", "simulationPositionSafety"];
if ~all(isfield(configs, cellstr(required)))
    error("evaluateNoGloveStage6cMatchedController:IncompleteConfig", ...
        "Effective configuration is incomplete.");
end
safe = logical(configs.simMotors) && ~logical(configs.connect_glove) && ...
    logical(configs.usePrerecorded) && ...
    string(configs.referenceSource) == "emgIntent" && ...
    string(configs.observationVariant) == "intentMarkov60" && ...
    string(configs.actionInterfaceVariant) == "baselineQuantized" && ...
    logical(configs.quantizeCommandsForSimulation) && ...
    ~logical(configs.unifyActions) && ...
    logical(configs.simulationPositionSafety.enabled) && ...
    string(configs.simulationPositionSafety.mode) == ...
        "clipTrajectoryOutput";
if ~safe
    error("evaluateNoGloveStage6cMatchedController:UnsafeConfig", ...
        "ETAPA 6C requires the simulation-only matched no-glove profile.");
end
if ~isnumeric(configs.period) || ~isscalar(configs.period) || ...
        ~isfinite(configs.period) || configs.period <= 0
    error("evaluateNoGloveStage6cMatchedController:InvalidPeriod", ...
        "period must be a finite positive scalar.");
end
% Exercise both public validators before any episode is simulated.
quantizedIntentPdController(zeros(4, 1), zeros(4, 1), ...
    zeros(4, 1), zeros(4, 1), configs.conventionalController, ...
    struct("maxPwm", max(abs(double(configs.speeds))), ...
        "activationThreshold", ...
            double(configs.actionCommandActivationThreshold), ...
        "commandLevels", double(configs.actionCommandLevels)));
limitSimulationPosition(zeros(0, 4), configs.simulationPositionSafety);
end

function source = loadSourceEpisode(episodePath, configs, layout)
required = [ ...
    "stateLog", "trackingPredictionHistory", "referenceHistory", ...
    "actionLog", "actionSatLog", "actionPwmLog", ...
    "positionSafetyInterventionLog", "simulationPositionSafety", ...
    "referenceSource", "observationVariant", "stateLength", ...
    "repetitionId"];
available = string(who("-file", episodePath));
if ~all(ismember(required, available))
    missing = setdiff(required, available);
    error("evaluateNoGloveStage6cMatchedController:MissingEpisodeField", ...
        "Episode %s is missing: %s.", episodePath, strjoin(missing, ", "));
end
data = load(episodePath, required{:});
if string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= layout.totalLength || ...
        ~logical(data.simulationPositionSafety.enabled)
    error("evaluateNoGloveStage6cMatchedController:IncompatibleEpisode", ...
        "Episode %s is not a position-limited intentMarkov60 trace.", ...
        episodePath);
end
assertSameSafety(data.simulationPositionSafety, ...
    configs.simulationPositionSafety, episodePath);

state = double(data.stateLog);
stepCount = size(state, 1);
fourMatrices = {data.trackingPredictionHistory, ...
    data.referenceHistory, data.actionLog, data.actionSatLog, ...
    data.actionPwmLog, data.positionSafetyInterventionLog};
if stepCount == 0 || size(state, 2) ~= layout.totalLength || ...
        any(cellfun(@(value) ~isequal(size(value), [stepCount, 4]), ...
        fourMatrices))
    error("evaluateNoGloveStage6cMatchedController:DimensionMismatch", ...
        "Episode %s has incompatible log dimensions.", episodePath);
end
allFinite = all(isfinite(state), "all") && all(cellfun( ...
    @(value) all(isfinite(double(value)), "all"), fourMatrices));
if ~allFinite
    error("evaluateNoGloveStage6cMatchedController:NonfiniteEpisode", ...
        "Episode %s contains NaN or Inf.", episodePath);
end

qBefore = state(:, layout.encoder);
qAfter = double(data.trackingPredictionHistory);
reference = state(:, layout.referencePosition);
referenceVelocity = state(:, layout.referenceVelocity);
referenceError = max(abs(reference - ...
    double(data.referenceHistory)), [], "all");
if referenceError > 1e-12
    error("evaluateNoGloveStage6cMatchedController:ReferenceMisalignment", ...
        "Episode %s reference is not the one visible before action_t.", ...
        episodePath);
end
if stepCount > 1
    temporalError = max(abs( ...
        qAfter(1:end-1, :) - qBefore(2:end, :)), [], "all");
else
    temporalError = 0;
end
if temporalError > 1e-12
    error("evaluateNoGloveStage6cMatchedController:TemporalMisalignment", ...
        "Episode %s is not aligned as state_t/action_t/q_(t+1).", ...
        episodePath);
end

source = struct( ...
    "episodePath", episodePath, ...
    "repetitionId", double(data.repetitionId), ...
    "reference", reference, ...
    "referenceVelocity", referenceVelocity, ...
    "temporalAlignmentMaxAbs", temporalError, ...
    "agentTrace", struct( ...
        "qBefore", qBefore, ...
        "qAfter", qAfter, ...
        "reference", reference, ...
        "referenceVelocity", referenceVelocity, ...
        "rawAction", double(data.actionLog), ...
        "effectiveAction", double(data.actionSatLog), ...
        "appliedPwm", double(data.actionPwmLog), ...
        "safetyInterventionCount", ...
            double(data.positionSafetyInterventionLog)));
end

function assertSameSafety(actual, expected, episodePath)
fields = ["enabled", "mode", "positionMin", "positionMax", ...
    "encoderScale"];
if ~all(isfield(actual, cellstr(fields))) || ...
        ~all(isfield(expected, cellstr(fields)))
    error("evaluateNoGloveStage6cMatchedController:InvalidSafety", ...
        "Episode %s lacks the full safety contract.", episodePath);
end
same = logical(actual.enabled) == logical(expected.enabled) && ...
    string(actual.mode) == string(expected.mode) && ...
    isequal(double(actual.positionMin(:)'), ...
        double(expected.positionMin(:)')) && ...
    isequal(double(actual.positionMax(:)'), ...
        double(expected.positionMax(:)')) && ...
    isequal(double(actual.encoderScale(:)'), ...
        double(expected.encoderScale(:)'));
if ~same
    error("evaluateNoGloveStage6cMatchedController:SafetyMismatch", ...
        "Episode %s uses a different position-safety configuration.", ...
        episodePath);
end
end

function trace = simulateConventional(source, configs, actuator, options)
stepCount = size(source.reference, 1);
dt = double(configs.period);
encoderScale = double(configs.simulationPositionSafety.encoderScale(:)');
encoder = source.agentTrace.qBefore(1, :) .* encoderScale;
previousQ = encoder ./ encoderScale;

qBefore = nan(stepCount, 4);
qAfter = nan(stepCount, 4);
rawAction = nan(stepCount, 4);
effectiveAction = nan(stepCount, 4);
appliedPwm = nan(stepCount, 4);
safetyCount = nan(stepCount, 4);

for stepIdx = 1:stepCount
    currentQ = encoder ./ encoderScale;
    currentVelocity = (currentQ - previousQ) ./ dt;
    [raw, effective, pwm] = quantizedIntentPdController( ...
        source.reference(stepIdx, :), currentQ, ...
        source.referenceVelocity(stepIdx, :), currentVelocity, ...
        configs.conventionalController, actuator);
    trajectory = SimController.prosthesis_simulator( ...
        encoder, pwm(:)', dt, options.simulatorSamplingPeriod);
    [trajectory, safety] = limitSimulationPosition( ...
        trajectory, configs.simulationPositionSafety);
    if isempty(trajectory) || any(~isfinite(trajectory), "all")
        error("evaluateNoGloveStage6cMatchedController:InvalidSimulation", ...
            "Conventional simulation returned empty or nonfinite data.");
    end
    nextEncoder = trajectory(end, :);

    qBefore(stepIdx, :) = currentQ;
    qAfter(stepIdx, :) = nextEncoder ./ encoderScale;
    rawAction(stepIdx, :) = raw(:)';
    effectiveAction(stepIdx, :) = effective(:)';
    appliedPwm(stepIdx, :) = pwm(:)';
    safetyCount(stepIdx, :) = safety.interventionCountByMotor;

    previousQ = currentQ;
    encoder = nextEncoder;
end

trace = struct( ...
    "qBefore", qBefore, ...
    "qAfter", qAfter, ...
    "reference", source.reference, ...
    "referenceVelocity", source.referenceVelocity, ...
    "rawAction", rawAction, ...
    "effectiveAction", effectiveAction, ...
    "appliedPwm", appliedPwm, ...
    "safetyInterventionCount", safetyCount);
end

function values = buildComponentTable(source, trace, splitName, ...
        commandSource, episodeIdx, configs, options)
stepCount = size(trace.qBefore, 1);
[step, motor] = ndgrid((1:stepCount)', 1:4);
dt = double(configs.period);
deltaQ = trace.qAfter - trace.qBefore;
velocity = deltaQ ./ dt;
positionError = trace.reference - trace.qBefore;
velocityError = velocity - trace.referenceVelocity;
previousAction = [zeros(1, 4); trace.effectiveAction(1:end-1, :)];
deltaAction = trace.effectiveAction - previousAction;
activeReference = abs(trace.referenceVelocity) >= ...
    options.activeVelocityThreshold;
moving = abs(deltaQ) >= options.motionTolerance;
commandDirection = sign(trace.appliedPwm);
referenceDirection = thresholdDirection( ...
    trace.referenceVelocity, options.activeVelocityThreshold);
positionErrorDirection = thresholdDirection( ...
    positionError, options.motionTolerance);
motionDirection = thresholdDirection(deltaQ, options.motionTolerance);
qMin = double(configs.simulationPositionSafety.positionMin(:)');
qMax = double(configs.simulationPositionSafety.positionMax(:)');
qMinMatrix = repmat(qMin, stepCount, 1);
qMaxMatrix = repmat(qMax, stepCount, 1);

count = stepCount * 4;
values = table( ...
    repmat(splitName, count, 1), ...
    repmat(commandSource, count, 1), ...
    repmat(episodeIdx, count, 1), ...
    repmat(source.repetitionId, count, 1), ...
    step(:), motor(:), ...
    trace.qBefore(:), trace.qAfter(:), trace.reference(:), ...
    trace.referenceVelocity(:), positionError(:), deltaQ(:), ...
    velocity(:), trace.rawAction(:), trace.effectiveAction(:), ...
    trace.appliedPwm(:), deltaAction(:), ...
    (trace.qAfter(:) - trace.reference(:)).^2, ...
    abs(trace.qAfter(:) - trace.reference(:)), ...
    velocityError(:).^2, trace.effectiveAction(:).^2, ...
    deltaAction(:).^2, ...
    abs(trace.effectiveAction(:)) >= options.saturationThreshold, ...
    trace.safetyInterventionCount(:), activeReference(:), moving(:), ...
    referenceDirection(:), positionErrorDirection(:), ...
    commandDirection(:), motionDirection(:), ...
    activeReference(:) & commandDirection(:) ~= 0 & ...
        commandDirection(:) ~= referenceDirection(:), ...
    positionErrorDirection(:) ~= 0 & commandDirection(:) ~= 0 & ...
        commandDirection(:) ~= positionErrorDirection(:), ...
    commandDirection(:) ~= 0 & motionDirection(:) ~= 0 & ...
        commandDirection(:) ~= motionDirection(:), ...
    trace.qBefore(:) < qMinMatrix(:) - ...
        options.positionTolerance | ...
        trace.qBefore(:) > qMaxMatrix(:) + ...
        options.positionTolerance | ...
        trace.qAfter(:) < qMinMatrix(:) - ...
        options.positionTolerance | ...
        trace.qAfter(:) > qMaxMatrix(:) + ...
        options.positionTolerance, ...
    'VariableNames', { ...
    'split', 'commandSource', 'episode', 'repetitionId', 'step', ...
    'motor', 'qBefore', 'qAfter', 'qReference', ...
    'referenceVelocity', 'positionError', 'deltaQ', 'velocity', ...
    'rawAction', 'effectiveAction', 'appliedPwm', 'deltaAction', ...
    'trackingSquaredError', 'trackingAbsoluteError', ...
    'velocitySquaredError', 'actionSquared', 'deltaActionSquared', ...
    'saturated', 'safetyInterventionCount', 'activeReference', ...
    'moving', 'referenceDirection', 'positionErrorDirection', ...
    'commandDirection', 'motionDirection', ...
    'commandOpposesReferenceVelocity', ...
    'commandOpposesPositionError', 'responseOpposesCommand', ...
    'positionViolation'});
end

function summary = summarizeEpisodes(componentTable, configs, options)
sources = unique(componentTable.commandSource, "stable");
episodes = unique(componentTable.episode, "stable");
rows = repmat(emptyEpisodeRow(), numel(sources) * numel(episodes), 1);
rowIdx = 0;
for sourceIdx = 1:numel(sources)
    for episodeIdx = 1:numel(episodes)
        rowIdx = rowIdx + 1;
        selected = componentTable.commandSource == sources(sourceIdx) & ...
            componentTable.episode == episodes(episodeIdx);
        values = componentTable(selected, :);
        row = emptyEpisodeRow();
        row.commandSource = sources(sourceIdx);
        row.episode = episodes(episodeIdx);
        row.repetitionId = values.repetitionId(1);
        row.stepCount = height(values) / 4;
        row.trackingMse = mean(values.trackingSquaredError);
        row.trackingMae = mean(values.trackingAbsoluteError);
        row.velocityMse = mean(values.velocitySquaredError);
        row.actionL2 = mean(values.actionSquared);
        action = reshape(values.effectiveAction, row.stepCount, 4);
        if row.stepCount > 1
            actionDelta = diff(action, 1, 1);
            row.deltaActionL2 = mean(sum(actionDelta.^2, 2));
        else
            row.deltaActionL2 = 0;
        end
        row.saturationFraction = mean(values.saturated);
        row.safetyInterventionCount = ...
            sum(values.safetyInterventionCount);
        row.positionViolation = any(values.positionViolation);
        row.activeReferenceFraction = mean(values.activeReference);
        row.decoderFalseActivationFraction = mean( ...
            abs(values.referenceVelocity) >= ...
            options.activeVelocityThreshold);
        row.maxPwmMagnitude = max(abs(values.appliedPwm));
        row.positionMin = min(values.qAfter);
        row.positionMax = max(values.qAfter);
        rows(rowIdx) = row;
    end
end
summary = struct2table(rows);
if any(summary.positionMin < ...
        min(configs.simulationPositionSafety.positionMin) - ...
        options.positionTolerance) || ...
        any(summary.positionMax > ...
        max(configs.simulationPositionSafety.positionMax) + ...
        options.positionTolerance)
    error("evaluateNoGloveStage6cMatchedController:PositionViolation", ...
        "A matched trace exceeded the configured position limits.");
end
end

function flags = buildMotorEpisodeFlags(componentTable, configs, options)
sources = unique(componentTable.commandSource, "stable");
episodes = unique(componentTable.episode, "stable");
rows = repmat(emptyFlagRow(), numel(sources) * numel(episodes) * 4, 1);
rowIdx = 0;
qMin = double(configs.simulationPositionSafety.positionMin(:)');
qMax = double(configs.simulationPositionSafety.positionMax(:)');
for sourceIdx = 1:numel(sources)
    for episodeIdx = 1:numel(episodes)
        for motorIdx = 1:4
            rowIdx = rowIdx + 1;
            selected = componentTable.commandSource == sources(sourceIdx) & ...
                componentTable.episode == episodes(episodeIdx) & ...
                componentTable.motor == motorIdx;
            values = componentTable(selected, :);
            active = values.activeReference;
            movingActive = active & values.moving;
            signedResponse = values.referenceDirection .* values.deltaQ;
            row = emptyFlagRow();
            row.commandSource = sources(sourceIdx);
            row.episode = episodes(episodeIdx);
            row.motor = motorIdx;
            row.activeSampleCount = sum(active);
            row.noMotionFlag = any(active) && ~any(movingActive);
            row.wrongDirectionFlag = any(movingActive) && ...
                mean(signedResponse(movingActive)) < ...
                -options.motionTolerance;
            row.positionViolationFlag = any( ...
                values.qBefore < qMin(motorIdx) - ...
                    options.positionTolerance | ...
                values.qBefore > qMax(motorIdx) + ...
                    options.positionTolerance | ...
                values.qAfter < qMin(motorIdx) - ...
                    options.positionTolerance | ...
                values.qAfter > qMax(motorIdx) + ...
                    options.positionTolerance);
            row.functionalFlag = row.noMotionFlag || ...
                row.wrongDirectionFlag || row.positionViolationFlag;
            rows(rowIdx) = row;
        end
    end
end
flags = struct2table(rows);
end

function summary = summarizeMotors(componentTable, motorEpisodeFlags)
sources = unique(componentTable.commandSource, "stable");
rows = repmat(emptyMotorRow(), numel(sources) * 4, 1);
rowIdx = 0;
for sourceIdx = 1:numel(sources)
    for motorIdx = 1:4
        rowIdx = rowIdx + 1;
        values = componentTable( ...
            componentTable.commandSource == sources(sourceIdx) & ...
            componentTable.motor == motorIdx, :);
        flags = motorEpisodeFlags( ...
            motorEpisodeFlags.commandSource == sources(sourceIdx) & ...
            motorEpisodeFlags.motor == motorIdx, :);
        activeCount = sum(values.activeReference);
        movingWithCommand = sum(values.moving & values.appliedPwm ~= 0);
        positionErrorCount = sum(values.positionErrorDirection ~= 0);
        row = emptyMotorRow();
        row.commandSource = sources(sourceIdx);
        row.motor = motorIdx;
        row.componentCount = height(values);
        row.activeReferenceCount = activeCount;
        row.trackingMse = mean(values.trackingSquaredError);
        row.trackingMae = mean(values.trackingAbsoluteError);
        row.velocityMse = mean(values.velocitySquaredError);
        row.actionL2 = mean(values.actionSquared);
        row.deltaActionL2 = meanMotorEpisodeDelta(values);
        row.saturationFraction = mean(values.saturated);
        row.safetyInterventionCount = ...
            sum(values.safetyInterventionCount);
        row.noMotionActiveFraction = safeFraction( ...
            sum(values.activeReference & ~values.moving), activeCount);
        row.commandOpposesReferenceVelocityFraction = safeFraction( ...
            sum(values.commandOpposesReferenceVelocity), activeCount);
        row.commandOpposesPositionErrorFraction = safeFraction( ...
            sum(values.commandOpposesPositionError), positionErrorCount);
        row.responseOpposesCommandFraction = safeFraction( ...
            sum(values.responseOpposesCommand), movingWithCommand);
        row.noMotionFlagCount = sum(flags.noMotionFlag);
        row.wrongDirectionFlagCount = sum(flags.wrongDirectionFlag);
        row.positionViolationFlagCount = sum(flags.positionViolationFlag);
        row.functionalFlagCount = sum(flags.functionalFlag);
        rows(rowIdx) = row;
    end
end
summary = struct2table(rows);
end

function summary = summarizeSources( ...
        componentTable, motorEpisodeFlags, pairing, episodeSummary)
sources = unique(componentTable.commandSource, "stable");
rows = repmat(emptyAggregateRow(), numel(sources), 1);
for sourceIdx = 1:numel(sources)
    values = componentTable( ...
        componentTable.commandSource == sources(sourceIdx), :);
    flags = motorEpisodeFlags( ...
        motorEpisodeFlags.commandSource == sources(sourceIdx), :);
    episodes = episodeSummary( ...
        episodeSummary.commandSource == sources(sourceIdx), :);
    row = emptyAggregateRow();
    row.commandSource = sources(sourceIdx);
    row.episodeCount = height(pairing);
    row.componentCount = height(values);
    row.trackingMse = mean(episodes.trackingMse);
    row.trackingMae = mean(episodes.trackingMae);
    row.velocityMse = mean(episodes.velocityMse);
    row.actionL2 = mean(episodes.actionL2);
    row.deltaActionL2 = mean(episodes.deltaActionL2);
    row.saturationFraction = mean(episodes.saturationFraction);
    row.safetyInterventionCount = sum(values.safetyInterventionCount);
    row.motor2FunctionalFlagCount = sum( ...
        flags.functionalFlag(flags.motor == 2));
    row.otherMotorFunctionalFlagCount = sum( ...
        flags.functionalFlag(flags.motor ~= 2));
    row.positionViolationFlagCount = sum(flags.positionViolationFlag);
    row.commandOpposesReferenceVelocityFraction = safeFraction( ...
        sum(values.commandOpposesReferenceVelocity), ...
        sum(values.activeReference));
    row.commandOpposesPositionErrorFraction = safeFraction( ...
        sum(values.commandOpposesPositionError), ...
        sum(values.positionErrorDirection ~= 0));
    row.responseOpposesCommandFraction = safeFraction( ...
        sum(values.responseOpposesCommand), ...
        sum(values.moving & values.appliedPwm ~= 0));
    rows(sourceIdx) = row;
end
summary = struct2table(rows);
end

function row = emptyPairRow()
row = struct("episode", 0, "fileName", "", "repetitionId", 0, ...
    "stepCount", 0, "referenceMaxAbs", NaN, ...
    "referenceVelocityMaxAbs", NaN, ...
    "initialPositionMaxAbs", NaN, ...
    "sourceTemporalAlignmentMaxAbs", NaN);
end

function row = emptyEpisodeRow()
