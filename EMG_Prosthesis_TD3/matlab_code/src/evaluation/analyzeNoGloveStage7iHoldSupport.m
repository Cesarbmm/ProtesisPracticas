function analysis = analyzeNoGloveStage7iHoldSupport(windows, options)
%analyzeNoGloveStage7iHoldSupport diagnoses 7H hold support offline.

arguments
    windows table
    options.velocityTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.currentPositionMseTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.farCorrectionMse (1, 1) double ...
        {mustBePositive} = 2.5e-3
    options.minimumRestCoverage (1, 1) double ...
        {mustBeInRange(options.minimumRestCoverage, 0, 1)} = 0.90
    options.maximumFarCorrectionExposure (1, 1) double ...
        {mustBeInRange(options.maximumFarCorrectionExposure, 0, 1)} = 0.05
    options.softGateTau (1, :) double ...
        {mustBePositive} = [1e-4, 5e-4, 1e-3, 2.5e-3]
end

validateWindows(windows, options);
[episodeTimeline, exitAudit, timelineSummary] = ...
    buildRestTimeline(windows);
stratumSummary = buildStratumSummary(windows);
[epsilonCurve, supportDecision] = buildEpsilonCurve(windows, options);
softGateSummary = buildSoftGateSummary(windows, options);

candidate = supportDecision(supportDecision.variant == "candidate", :);
if height(candidate) ~= 1
    error("analyzeNoGloveStage7iHoldSupport:CandidateDecision", ...
        "Expected one candidate support decision.");
end
if candidate.feasibleThresholdExists
    classification = "offlineHoldSupportDomainExists";
elseif candidate.restOnlyThresholdExists
    classification = "holdSupportNotSeparableFromFarCorrection";
else
    classification = "restCoverageUnresolved";
end
sourceDecision = table(classification, ...
    logical(candidate.feasibleThresholdExists), ...
    candidate.minimumFeasiblePositionMseTolerance, ...
    logical(candidate.restOnlyThresholdExists), ...
    candidate.minimumRestOnlyPositionMseTolerance, ...
    candidate.farCorrectionExposureAtRestThreshold, false, ...
    'VariableNames', ["classification", ...
    "feasibleThresholdExists", ...
    "minimumFeasiblePositionMseTolerance", ...
    "restOnlyThresholdExists", ...
    "minimumRestOnlyPositionMseTolerance", ...
    "farCorrectionExposureAtRestThreshold", ...
    "rootCauseIdentified"]);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7I", ...
    "episodeTimeline", episodeTimeline, "exitAudit", exitAudit, ...
    "timelineSummary", timelineSummary, ...
    "stratumSummary", stratumSummary, ...
    "epsilonCurve", epsilonCurve, ...
    "supportDecision", supportDecision, ...
    "softGateSummary", softGateSummary, ...
    "sourceDecision", sourceDecision, ...
    "classification", classification, ...
    "thresholds", struct( ...
        "velocityTolerance", options.velocityTolerance, ...
        "currentPositionMseTolerance", ...
            options.currentPositionMseTolerance, ...
        "farCorrectionMse", options.farCorrectionMse, ...
        "minimumRestCoverage", options.minimumRestCoverage, ...
        "maximumFarCorrectionExposure", ...
            options.maximumFarCorrectionExposure, ...
        "softGateTau", options.softGateTau), ...
    "rootCauseIdentified", false, ...
    "behavioralInterventionExecuted", false, ...
    "policyChanged", false, "rewardChanged", false, ...
    "simulatorInvoked", false, "runTraining", false, ...
    "agentLoaded", false, "envCreated", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "pilotAuthorized", false);
end

function validateWindows(windows, options)
required = ["variant", "source", "episode", "step", ...
    "windowIndex", "qDecision", "qReference", "vReference", ...
    "rawAction", "effectiveAction", "pwm", "safetyIntervention", ...
    "holdPositionMse", "holdVelocityMaxAbs", "stopped", ...
    "eligible", "holdActionL2", "holdActionPenalty"];
if isempty(windows) || ~all(ismember(required, ...
        string(windows.Properties.VariableNames))) || ...
        ~isequal(sort(unique(string(windows.variant)))', ...
        ["candidate", "control"]) || ...
        ~all(ismember(["training", "acceptance", "steadyRest"], ...
        unique(string(windows.source))))
    error("analyzeNoGloveStage7iHoldSupport:InvalidCorpus", ...
        "Window corpus is incomplete.");
end
matrixNames = ["qDecision", "qReference", "vReference", ...
    "rawAction", "effectiveAction", "pwm", "safetyIntervention"];
numeric = [windows.holdPositionMse; windows.holdVelocityMaxAbs; ...
    windows.holdActionL2; windows.holdActionPenalty];
for name = matrixNames
    value = windows.(name);
    if ~isnumeric(value) || size(value, 2) ~= 4
        error("analyzeNoGloveStage7iHoldSupport:InvalidCorpus", ...
            "%s must contain four motors.", name);
    end
    numeric = [numeric; value(:)]; %#ok<AGROW>
end
expectedStopped = windows.holdVelocityMaxAbs <= ...
    options.velocityTolerance;
expectedEligible = expectedStopped & windows.holdPositionMse <= ...
    options.currentPositionMseTolerance;
if any(~isfinite(numeric)) || any(windows.holdPositionMse < 0) || ...
        any(windows.safetyIntervention < 0, "all") || ...
        ~isequal(logical(windows.stopped), expectedStopped) || ...
        ~isequal(logical(windows.eligible), expectedEligible)
    error("analyzeNoGloveStage7iHoldSupport:InvalidCorpus", ...
        "Window values or the current hold replay are invalid.");
end
end

function [timeline, exits, summary] = buildRestTimeline(windows)
rest = windows(windows.source == "steadyRest", :);
keys = rest.variant+"|"+string(rest.episode);
[groups, uniqueKeys] = findgroups(keys);
rows = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = rest(groups == groupIdx, :);
    [~, order] = sort(values.step);
    values = values(order, :);
    if ~isequal(double(values.step)', 1:height(values))
        error("analyzeNoGloveStage7iHoldSupport:StepOrder", ...
            "Steady-rest episode steps are not contiguous.");
    end
    eligible = logical(values.eligible);
    exitsLocal = find(eligible(1:end-1) & ~eligible(2:end))+1;
    entriesLocal = find(~eligible(1:end-1) & eligible(2:end))+1;
    firstExit = minimumOrNaN(exitsLocal);
    precedingMeanAbsPwm = NaN;
    precedingMaxAbsPwm = NaN;
    precedingActionL2 = NaN;
    precedingSafetyComponentCount = NaN;
    precedingAnySafety = NaN;
    mseBeforeExit = NaN;
    mseAfterExit = NaN;
    mseJumpAtExit = NaN;
    if ~isnan(firstExit)
        previous = firstExit-1;
        precedingMeanAbsPwm = mean(abs(values.pwm(previous, :)));
        precedingMaxAbsPwm = max(abs(values.pwm(previous, :)));
        precedingActionL2 = mean(values.effectiveAction(previous, :).^2);
        precedingSafetyComponentCount = sum( ...
            values.safetyIntervention(previous, :) > 0);
        precedingAnySafety = precedingSafetyComponentCount > 0;
        mseBeforeExit = values.holdPositionMse(previous);
        mseAfterExit = values.holdPositionMse(firstExit);
        mseJumpAtExit = mseAfterExit-mseBeforeExit;
    end
    rows{groupIdx} = table(values.variant(1), values.episode(1), ...
        values.repetitionId(1), height(values), eligible(1), ...
        ~eligible(1), ~isempty(exitsLocal), firstExit, ...
        numel(entriesLocal), longestTrueRun(eligible), mean(eligible), ...
        precedingMeanAbsPwm, precedingMaxAbsPwm, ...
        precedingActionL2, precedingSafetyComponentCount, ...
        precedingAnySafety, mseBeforeExit, mseAfterExit, mseJumpAtExit, ...
        'VariableNames', ["variant", "episode", "repetitionId", ...
        "stepCount", "initialEligible", "initialMismatch", ...
        "exitedEligibleRegion", "firstExitStep", "reentryCount", ...
        "longestEligibleRun", "eligibleFraction", ...
        "precedingMeanAbsPwm", "precedingMaxAbsPwm", ...
        "precedingActionL2", "precedingSafetyComponentCount", ...
        "precedingAnySafety", "mseBeforeExit", "mseAfterExit", ...
        "mseJumpAtExit"]);
end
timeline = vertcat(rows{:});
exits = timeline(timeline.exitedEligibleRegion, :);
variants = ["control", "candidate"];
summaryRows = cell(2, 1);
for idx = 1:2
    values = timeline(timeline.variant == variants(idx), :);
    exitValues = values(values.exitedEligibleRegion, :);
    summaryRows{idx} = table(variants(idx), height(values), ...
        mean(values.initialMismatch), ...
        mean(values.exitedEligibleRegion), ...
        meanFinite(values.firstExitStep), ...
        medianFinite(values.firstExitStep), mean(values.reentryCount), ...
        mean(values.longestEligibleRun), mean(values.eligibleFraction), ...
        meanFinite(exitValues.precedingMeanAbsPwm), ...
        meanFinite(exitValues.precedingActionL2), ...
        meanFinite(exitValues.precedingAnySafety), ...
        meanFinite(exitValues.mseJumpAtExit), ...
        'VariableNames', ["variant", "episodeCount", ...
        "initialMismatchFraction", "exitEpisodeFraction", ...
        "meanFirstExitStep", "medianFirstExitStep", ...
        "meanReentryCount", "meanLongestEligibleRun", ...
        "meanEligibleFraction", "meanPrecedingAbsPwmAtExit", ...
        "meanPrecedingActionL2AtExit", ...
        "precedingSafetyAtExitFraction", "meanMseJumpAtExit"]);
end
summary = vertcat(summaryRows{:});
end

function summary = buildStratumSummary(windows)
variants = ["control", "candidate"];
sources = ["training", "acceptance", "steadyRest"];
rows = cell(0, 1);
for variant = variants
    for source = sources
        values = windows(windows.variant == variant & ...
            windows.source == source, :);
        q = quantile(values.holdPositionMse, [0.05, 0.50, 0.95]);
        rows{end+1, 1} = table(variant, source, height(values), ...
            numel(unique(values.episode)), mean(values.stopped), ...
            mean(values.eligible), mean(values.holdPositionMse), ...
            min(values.holdPositionMse), q(1), q(2), q(3), ...
            max(values.holdPositionMse), ...
            mean(any(abs(values.pwm) > 0, 2)), ...
            mean(any(values.safetyIntervention > 0, 2)), ...
            'VariableNames', ["variant", "source", "windowCount", ...
            "episodeCount", "stoppedFraction", "eligibleFraction", ...
            "meanHoldPositionMse", "minHoldPositionMse", ...
            "p05HoldPositionMse", "medianHoldPositionMse", ...
            "p95HoldPositionMse", "maxHoldPositionMse", ...
            "windowAnyCommandFraction", ...
            "windowAnySafetyInterventionFraction"]); %#ok<AGROW>
    end
end
summary = vertcat(rows{:});
end

function [curve, decisions] = buildEpsilonCurve(windows, options)
variants = ["control", "candidate"];
curveParts = cell(2, 1);
decisionRows = cell(2, 1);
for variantIdx = 1:2
    variant = variants(variantIdx);
    variantRows = windows.variant == variant;
    rest = windows(variantRows & windows.source == "steadyRest", :);
    stoppedRows = variantRows & windows.stopped;
    farRows = stoppedRows & ...
        ismember(windows.source, ["training", "acceptance"]) & ...
        windows.holdPositionMse >= options.farCorrectionMse;
    far = windows(farRows, :);
    if isempty(rest) || isempty(far)
        error("analyzeNoGloveStage7iHoldSupport:EmptyStratum", ...
            "Variant %s lacks rest or far-correction support.", variant);
    end
    observed = unique(double(windows.holdPositionMse(stoppedRows)));
    above = observed+max(1e-12, eps(observed));
    thresholds = unique([0; options.currentPositionMseTolerance; ...
        options.farCorrectionMse; 1; observed; above]);
    restCoverage = fractionAtOrBelow( ...
        sort(double(rest.holdPositionMse)), thresholds);
    farExposure = fractionAtOrBelow( ...
        sort(double(far.holdPositionMse)), thresholds);
    restGate = restCoverage >= options.minimumRestCoverage;
    feasible = restGate & ...
        farExposure <= options.maximumFarCorrectionExposure;
    curveParts{variantIdx} = table( ...
        repmat(variant, numel(thresholds), 1), thresholds, ...
        restCoverage, farExposure, restGate, feasible, ...
        'VariableNames', ["variant", "positionMseTolerance", ...
        "restCoverage", "farCorrectionExposure", ...
        "restGatePassed", "feasible"]);
    currentIdx = find(thresholds == ...
        options.currentPositionMseTolerance, 1);
    minimumFeasible = minimumOrNaN(thresholds(feasible));
    minimumRestOnly = minimumOrNaN(thresholds(restGate));
    farAtRest = valueAtThreshold( ...
        thresholds, farExposure, minimumRestOnly);
    decisionRows{variantIdx} = table(variant, ...
        restCoverage(currentIdx), farExposure(currentIdx), ...
        any(feasible), minimumFeasible, any(restGate), ...
        minimumRestOnly, farAtRest, ...
        'VariableNames', ["variant", "currentRestCoverage", ...
        "currentFarCorrectionExposure", ...
        "feasibleThresholdExists", ...
        "minimumFeasiblePositionMseTolerance", ...
        "restOnlyThresholdExists", ...
        "minimumRestOnlyPositionMseTolerance", ...
        "farCorrectionExposureAtRestThreshold"]);
end
curve = vertcat(curveParts{:});
decisions = vertcat(decisionRows{:});
end

function summary = buildSoftGateSummary(windows, options)
variants = ["control", "candidate"];
rows = cell(0, 1);
for variant = variants
    variantRows = windows.variant == variant;
    restMse = windows.holdPositionMse(variantRows & ...
        windows.source == "steadyRest");
    farMask = variantRows & windows.stopped & ...
        ismember(windows.source, ["training", "acceptance"]) & ...
        windows.holdPositionMse >= options.farCorrectionMse;
    farMse = windows.holdPositionMse(farMask);
    for tau = options.softGateTau
        restWeight = exp(-restMse./tau);
        farWeight = exp(-farMse./tau);
        rows{end+1, 1} = table(variant, tau, ...
            mean(restWeight), median(restWeight), ...
            mean(farWeight), median(farWeight), ...
            'VariableNames', ["variant", "tau", ...
            "meanRestWeight", "medianRestWeight", ...
            "meanFarCorrectionWeight", ...
            "medianFarCorrectionWeight"]); %#ok<AGROW>
    end
end
summary = vertcat(rows{:});
end

function fractions = fractionAtOrBelow(sortedValues, thresholds)
fractions = zeros(numel(thresholds), 1);
count = numel(sortedValues);
for idx = 1:numel(thresholds)
    low = 1;
    high = count;
    last = 0;
    while low <= high
        middle = floor((low+high)/2);
        if sortedValues(middle) <= thresholds(idx)
            last = middle;
            low = middle+1;
        else
            high = middle-1;
        end
    end
    fractions(idx) = last/count;
end
end

function value = valueAtThreshold(thresholds, values, selected)
if isnan(selected)
    value = NaN;
else
    value = values(find(thresholds == selected, 1));
end
end

function value = minimumOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = min(values);
end
end

function lengthValue = longestTrueRun(values)
edges = diff([false; values(:); false]);
starts = find(edges == 1);
stops = find(edges == -1)-1;
if isempty(starts)
    lengthValue = 0;
else
    lengthValue = max(stops-starts+1);
end
end

function value = meanFinite(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = medianFinite(values)
values = double(values(isfinite(values)));
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end
