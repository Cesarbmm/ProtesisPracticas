function data = loadNoGloveStage7tEvidence(stage7sRunRoot)
%loadNoGloveStage7tEvidence loads the immutable ETAPA 7S acquisition.

arguments
    stage7sRunRoot (1, 1) string
end

expected = struct( ...
    "manifest", ...
        "6E8A9FE1244C885A8AE3F149AE946D5D1D662B541C554F675E308F540F7FB5CD", ...
    "results", ...
        "FEC0054E4BB364BBC3DF64CC1FEAF11C52C6A69DF3C2A32C82AD2E50390A8AB0", ...
    "lock", ...
        "823A72918E6552038AC151E647E5D61E590D0F1E16EB45B93E51D15668FC33DD", ...
    "design", ...
        "364D5B8EFF53FA3A3DFE29BCD2A73D6DA77B27871F5C64796D838E2AC01D64A8", ...
    "dataset", ...
        "590791ACD221ABFC3BD5B5C7586E3716E54EEDCE0CDD67E358E005984835F956", ...
    "configs", ...
        "A4A421C60BD7EB7ECF4A1146741A99C39C92BA724B2482149D89C8F075283729");

paths = struct( ...
    "manifest", fullfile(stage7sRunRoot, "manifest.json"), ...
    "results", fullfile(stage7sRunRoot, "stage7s_results.mat"), ...
    "lock", fullfile(stage7sRunRoot, "acquisition_lock.mat"), ...
    "design", fullfile(stage7sRunRoot, "dataset_design.mat"));
names = string(fieldnames(paths));
for idx = 1:numel(names)
    name = names(idx);
    actual = localFileSha256(paths.(name));
    if actual ~= expected.(name)
        error("loadNoGloveStage7tEvidence:ParentChanged", ...
            "ETAPA 7S %s hash changed: %s.", name, actual);
    end
end

manifest = jsondecode(fileread(paths.manifest));
requiredManifest = ["stage", "result", "scientificResult", ...
    "supportGatePassed", "stateDecision", "episodeCount", ...
    "prospectiveRestStateCount", "modelsExecuted", ...
    "agent200LoadedForSimulation", "trainingUsed", ...
    "hardwareUsed", "simulationUsed", "acquisitionDirectory", ...
    "datasetPath", "datasetSha256"];
if ~all(isfield(manifest, cellstr(requiredManifest))) || ...
        string(manifest.stage) ~= "7S" || ...
        string(manifest.result) ~= "PASS" || ...
        string(manifest.scientificResult) ~= "prospectiveSupportFailed" || ...
        logical(manifest.supportGatePassed) || ...
        string(manifest.stateDecision) ~= "intentMarkov60" || ...
        double(manifest.episodeCount) ~= 80 || ...
        double(manifest.prospectiveRestStateCount) ~= 1600 || ...
        logical(manifest.modelsExecuted) || ...
        ~logical(manifest.agent200LoadedForSimulation) || ...
        logical(manifest.trainingUsed) || logical(manifest.hardwareUsed) || ...
        ~logical(manifest.simulationUsed)
    error("loadNoGloveStage7tEvidence:ManifestContract", ...
        "ETAPA 7S manifest does not match the frozen failed-support run.");
end
if localFileSha256(string(manifest.datasetPath)) ~= expected.dataset || ...
        upper(string(manifest.datasetSha256)) ~= expected.dataset
    error("loadNoGloveStage7tEvidence:DatasetChanged", ...
        "The prospective raw-EMG fixture changed.");
end

stage = load(paths.results, "manifest", "supportGate", "options");
locked = load(paths.lock, "acquisition", "corpus", ...
    "episodeInventory", "pairSet", "supportGate");
designData = load(paths.design, "design");
if ~all(isfield(stage, ["manifest", "supportGate", "options"])) || ...
        ~all(isfield(locked, ["acquisition", "corpus", ...
        "episodeInventory", "pairSet", "supportGate"])) || ...
        ~isfield(designData, "design")
    error("loadNoGloveStage7tEvidence:MatContract", ...
        "A frozen ETAPA 7S MAT contract is incomplete.");
end
if string(stage.manifest.scientificResult) ~= ...
        "prospectiveSupportFailed" || stage.supportGate.passed || ...
        locked.supportGate.passed
    error("loadNoGloveStage7tEvidence:DecisionChanged", ...
        "ETAPA 7S support decision changed.");
end

corpus = locked.corpus;
requiredCorpus = ["states", "rawAction", "effectiveAction", ...
    "pwm", "qBefore", "qAfter", "qReference", "vReference", ...
    "zeroControlDemand", "safetyIntervention", "metadata", ...
    "inventory", "alignmentAudit"];
if ~all(isfield(corpus, cellstr(requiredCorpus))) || ...
        size(corpus.states, 2) ~= 60 || ...
        any(~isfinite([corpus.states(:); corpus.rawAction(:); ...
        corpus.effectiveAction(:); corpus.pwm(:)]))
    error("loadNoGloveStage7tEvidence:CorpusContract", ...
        "The locked state/action corpus is invalid.");
end
restRows = corpus.metadata.source == "steadyRest";
restInventory = corpus.inventory.source == "steadyRest";
if sum(restRows) ~= 1600 || sum(restInventory) ~= 80 || ...
        numel(unique(corpus.metadata.episode(restRows))) ~= 80 || ...
        any(corpus.metadata.step(restRows) < 1 | ...
        corpus.metadata.step(restRows) > 20)
    error("loadNoGloveStage7tEvidence:RestCohortChanged", ...
        "Expected 80 prospective episodes and 1600 states.");
end

design = designData.design;
if ~all(isfield(design, ["emgs", "designTable", "metadata", ...
        "frozenEmgScale"])) || numel(design.emgs) ~= 80 || ...
        height(design.designTable) ~= 1680 || ...
        logical(design.metadata.physiologicalRestEvidence)
    error("loadNoGloveStage7tEvidence:DesignContract", ...
        "The synthetic design contract changed.");
end

configsPath = fullfile(string(manifest.acquisitionDirectory), ...
    "00_configs.mat");
if localFileSha256(configsPath) ~= expected.configs
    error("loadNoGloveStage7tEvidence:ConfigsChanged", ...
        "The effective acquisition configs changed.");
end
configData = load(configsPath, "configs");
if ~isfield(configData, "configs") || ...
        ~isfield(configData.configs, "fGetFeatures") || ...
        ~isa(configData.configs.fGetFeatures, "function_handle") || ...
        ~logical(configData.configs.simMotors) || ...
        logical(configData.configs.connect_glove) || ...
        logical(configData.configs.run_training) || ...
        string(configData.configs.referenceSource) ~= "emgIntent" || ...
        string(configData.configs.observationVariant) ~= "intentMarkov60"
    error("loadNoGloveStage7tEvidence:ConfigsContract", ...
        "The acquisition was not the frozen offline-safe state-60 profile.");
end

restEpisodeInventory = locked.episodeInventory( ...
    locked.episodeInventory.source == "steadyRest", :);
if height(restEpisodeInventory) ~= 80 || ...
        ~ismember("sha256", ...
        string(restEpisodeInventory.Properties.VariableNames))
    error("loadNoGloveStage7tEvidence:EpisodeInventory", ...
        "The prospective episode inventory is incomplete.");
end
for idx = 1:height(restEpisodeInventory)
    if localFileSha256(restEpisodeInventory.filePath(idx)) ~= ...
            upper(string(restEpisodeInventory.sha256(idx)))
        error("loadNoGloveStage7tEvidence:EpisodeChanged", ...
            "Prospective episode %d changed.", ...
            restEpisodeInventory.episode(idx));
    end
end

data = struct( ...
    "schemaVersion", 1, "stage", "7T", ...
    "stage7sRunRoot", stage7sRunRoot, ...
    "parentManifest", manifest, "parentStage", stage, ...
    "acquisition", locked.acquisition, "corpus", corpus, ...
    "episodeInventory", locked.episodeInventory, ...
    "restEpisodeInventory", restEpisodeInventory, ...
    "pairSet", locked.pairSet, "supportGate", locked.supportGate, ...
    "design", design, "configs", configData.configs, ...
    "configsPath", configsPath, "expectedHashes", expected, ...
    "parentValidated", true, "actorsLoaded", false, ...
    "environmentUsed", false, "simulationUsed", false, ...
    "trainingUsed", false, "hardwareUsed", false);
end

function hash = localFileSha256(filePath)
if ~isfile(filePath)
    error("loadNoGloveStage7tEvidence:MissingFile", ...
        "Missing file: %s", filePath);
end
escaped = strrep(char(string(filePath)), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("loadNoGloveStage7tEvidence:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = upper(string(strtrim(output)));
end
