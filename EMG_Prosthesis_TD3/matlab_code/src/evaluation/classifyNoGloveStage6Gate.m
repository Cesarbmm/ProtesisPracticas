function gate = classifyNoGloveStage6Gate( ...
        acceptanceAnalysis, restAnalysis, restFalseActivationFraction, ...
        trainingAnalysis)
%classifyNoGloveStage6Gate applies the explicit ETAPA 6 simulation gate.

arguments
    acceptanceAnalysis (1, 1) struct
    restAnalysis (1, 1) struct
    restFalseActivationFraction (1, 1) double
    trainingAnalysis (1, 1) struct = struct()
end

trainingFinite = true;
trainingPositionViolationEpisodeCount = 0;
if ~isempty(fieldnames(trainingAnalysis))
    trainingFinite = logical(trainingAnalysis.allFinite);
    trainingPositionViolationEpisodeCount = ...
        double(trainingAnalysis.positionViolationEpisodeCount);
end

thresholds = struct( ...
    "saturationFractionMax", 0.196043, ...
    "deltaActionL2Max", 0.257108, ...
    "restFalseActivationFractionMax", 0.01, ...
    "restSaturationFractionMax", 0);

checks = struct( ...
    "finite", trainingFinite && acceptanceAnalysis.allFinite && ...
        restAnalysis.allFinite, ...
    "positionLimits", ...
        trainingPositionViolationEpisodeCount == 0 && ...
        acceptanceAnalysis.positionViolationEpisodeCount == 0 && ...
        restAnalysis.positionViolationEpisodeCount == 0, ...
    "saturation", acceptanceAnalysis.saturationFraction <= ...
        thresholds.saturationFractionMax, ...
    "deltaAction", acceptanceAnalysis.deltaActionL2 <= ...
        thresholds.deltaActionL2Max, ...
    "motor2", acceptanceAnalysis.motor2FunctionalFlagCount == 0, ...
    "otherMotors", ...
        acceptanceAnalysis.otherMotorFunctionalFlagCount == 0, ...
    "restSaturation", restAnalysis.saturationFraction <= ...
        thresholds.restSaturationFractionMax, ...
    "restFalseActivation", restFalseActivationFraction <= ...
        thresholds.restFalseActivationFractionMax);
checkValues = struct2array(checks);

gate = struct( ...
    "schemaVersion", 1, ...
    "passed", all(checkValues), ...
    "thresholds", thresholds, ...
    "checks", checks, ...
    "acceptanceSaturationFraction", ...
        acceptanceAnalysis.saturationFraction, ...
    "acceptanceDeltaActionL2", acceptanceAnalysis.deltaActionL2, ...
    "acceptancePositionViolationEpisodeCount", ...
        acceptanceAnalysis.positionViolationEpisodeCount, ...
    "trainingPositionViolationEpisodeCount", ...
        trainingPositionViolationEpisodeCount, ...
    "motor2FunctionalFlagCount", ...
        acceptanceAnalysis.motor2FunctionalFlagCount, ...
    "otherMotorFunctionalFlagCount", ...
        acceptanceAnalysis.otherMotorFunctionalFlagCount, ...
    "restSaturationFraction", restAnalysis.saturationFraction, ...
    "restFalseActivationFraction", restFalseActivationFraction);
end
