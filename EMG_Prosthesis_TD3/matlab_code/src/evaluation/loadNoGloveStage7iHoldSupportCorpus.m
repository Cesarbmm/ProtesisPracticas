function [windows, episodes] = loadNoGloveStage7iHoldSupportCorpus( ...
        variant, directories, settings, options)
%loadNoGloveStage7iHoldSupportCorpus loads frozen 7H logs offline.

arguments
    variant (1, 1) string
    directories (1, 1) struct
    settings (1, 1) struct
    options.replayTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
end

if ~any(variant == ["control", "candidate"])
    error("loadNoGloveStage7iHoldSupportCorpus:InvalidVariant", ...
        "variant must be control or candidate.");
end
requiredDirectories = ["training", "acceptance", "steadyRest"];
requiredSettings = ["holdActionWeight", "velocityTolerance", ...
    "positionMseTolerance"];
if ~all(isfield(directories, cellstr(requiredDirectories))) || ...
        ~all(isfield(settings, cellstr(requiredSettings)))
    error("loadNoGloveStage7iHoldSupportCorpus:InvalidContract", ...
        "Directories or hold settings are incomplete.");
end
settingValues = [settings.holdActionWeight, ...
    settings.velocityTolerance, settings.positionMseTolerance];
if any(~isfinite(settingValues)) || any(settingValues < 0)
    error("loadNoGloveStage7iHoldSupportCorpus:InvalidContract", ...
        "Hold settings must be finite and nonnegative.");
end

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
sources = requiredDirectories;
windowParts = cell(0, 1);
episodeParts = cell(0, 1);
windowCursor = 0;
for sourceIdx = 1:numel(sources)
    source = sources(sourceIdx);
    directory = string(directories.(source));
    files = dir(fullfile(directory, "episode*.mat"));
    if isempty(files)
        error("loadNoGloveStage7iHoldSupportCorpus:NoEpisodes", ...
            "No episode files found under %s.", directory);
    end
    episodeNumbers = parseEpisodeNumbers(files);
    [episodeNumbers, order] = sort(episodeNumbers);
    files = files(order);
    for fileIdx = 1:numel(files)
        path = string(fullfile(files(fileIdx).folder, files(fileIdx).name));
        data = load(path, "stateLog", "actionLog", "actionSatLog", ...
            "actionPwmLog", "positionSafetyInterventionLog", ...
            "rewardInfoLog", "referenceSource", ...
            "observationVariant", "stateLength", "repetitionId");
        validateEpisode(data, path, layout.totalLength);
        state = double(data.stateLog);
        rawAction = double(data.actionLog);
        effectiveAction = double(data.actionSatLog);
        pwm = double(data.actionPwmLog);
        safety = double(data.positionSafetyInterventionLog);
        stepCount = size(state, 1);
        qDecision = state(:, layout.encoder);
        qReference = state(:, layout.referencePosition);
        vReference = state(:, layout.referenceVelocity);
        holdPositionMse = mean((qDecision-qReference).^2, 2);
        holdVelocityMaxAbs = max(abs(vReference), [], 2);
        stopped = holdVelocityMaxAbs <= settings.velocityTolerance;
        eligible = stopped & ...
            holdPositionMse <= settings.positionMseTolerance;
        expectedHoldActionL2 = double(eligible).* ...
            mean(effectiveAction.^2, 2);
        expectedHoldPenalty = settings.holdActionWeight.* ...
            expectedHoldActionL2;
        recorded = readRewardDiagnostics(data.rewardInfoLog, path);
        replayErrors = abs([recorded.holdActive-double(eligible), ...
            recorded.holdPositionMse-holdPositionMse, ...
            recorded.holdVelocityMaxAbs-holdVelocityMaxAbs, ...
            recorded.holdActionL2-expectedHoldActionL2, ...
            recorded.holdActionPenalty-expectedHoldPenalty]);
        maximumReplayError = max(replayErrors, [], "all");
        if maximumReplayError > options.replayTolerance
            error("loadNoGloveStage7iHoldSupportCorpus:ReplayMismatch", ...
                "Hold diagnostics do not replay from state_t in %s.", path);
        end
        if source == "steadyRest" && (any(~stopped) || ...
                any(abs(diff(qReference, 1, 1)) > ...
                options.replayTolerance, "all"))
            error("loadNoGloveStage7iHoldSupportCorpus:NonSteadyRest", ...
                "Steady-rest episode %s changes its reference.", path);
        end
        repetitionId = double(data.repetitionId);
        if ~isscalar(repetitionId) || ~isfinite(repetitionId)
            error("loadNoGloveStage7iHoldSupportCorpus:RepetitionId", ...
                "Episode %s has an invalid repetitionId.", path);
        end
        windowIndex = windowCursor+(1:stepCount)';
        windowParts{end+1, 1} = table( ...
            repmat(variant, stepCount, 1), ...
            repmat(source, stepCount, 1), ...
            repmat(episodeNumbers(fileIdx), stepCount, 1), ...
            repmat(repetitionId, stepCount, 1), (1:stepCount)', ...
            windowIndex, qDecision, qReference, vReference, ...
            rawAction, effectiveAction, pwm, safety, ...
            holdPositionMse, holdVelocityMaxAbs, stopped, eligible, ...
            expectedHoldActionL2, expectedHoldPenalty, ...
            'VariableNames', ["variant", "source", "episode", ...
            "repetitionId", "step", "windowIndex", "qDecision", ...
            "qReference", "vReference", "rawAction", ...
            "effectiveAction", "pwm", "safetyIntervention", ...
            "holdPositionMse", "holdVelocityMaxAbs", "stopped", ...
            "eligible", "holdActionL2", "holdActionPenalty"]); %#ok<AGROW>
        episodeParts{end+1, 1} = table(variant, source, ...
            episodeNumbers(fileIdx), repetitionId, stepCount, ...
            max(max(abs(vReference))), maximumReplayError, path, ...
            'VariableNames', ["variant", "source", "episode", ...
            "repetitionId", "stepCount", ...
            "referenceVelocityMaxAbs", ...
            "maximumDiagnosticReplayError", "episodePath"]); %#ok<AGROW>
        windowCursor = windowCursor+stepCount;
    end
end
windows = vertcat(windowParts{:});
episodes = vertcat(episodeParts{:});
end

function validateEpisode(data, path, expectedStateLength)
required = ["stateLog", "actionLog", "actionSatLog", ...
    "actionPwmLog", "positionSafetyInterventionLog", ...
    "rewardInfoLog", "referenceSource", "observationVariant", ...
    "stateLength", "repetitionId"];
if ~all(isfield(data, cellstr(required))) || ...
        string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= expectedStateLength
    error("loadNoGloveStage7iHoldSupportCorpus:EpisodeContract", ...
        "Episode %s violates the frozen 7H contract.", path);
end
state = double(data.stateLog);
raw = double(data.actionLog);
effective = double(data.actionSatLog);
pwm = double(data.actionPwmLog);
safety = double(data.positionSafetyInterventionLog);
stepCount = size(state, 1);
if size(state, 2) ~= expectedStateLength || ...
        ~isequal(size(raw), size(effective), size(pwm), size(safety), ...
        [stepCount, 4]) || ~iscell(data.rewardInfoLog) || ...
        numel(data.rewardInfoLog) ~= stepCount || ...
        any(~isfinite([state(:); raw(:); effective(:); pwm(:); safety(:)])) || ...
        any(safety(:) < 0)
    error("loadNoGloveStage7iHoldSupportCorpus:EpisodeArrays", ...
        "Episode %s has invalid or misaligned arrays.", path);
end
end

function recorded = readRewardDiagnostics(rewardInfoLog, path)
stepCount = numel(rewardInfoLog);
names = ["holdActive", "holdPositionMse", ...
    "holdVelocityMaxAbs", "holdActionL2", "holdActionPenalty"];
recorded = struct();
for name = names
    recorded.(name) = zeros(stepCount, 1);
end
for stepIdx = 1:stepCount
    info = rewardInfoLog{stepIdx};
    if ~isstruct(info) || ~isscalar(info) || ...
            ~all(isfield(info, cellstr(names)))
        error("loadNoGloveStage7iHoldSupportCorpus:RewardInfo", ...
            "Episode %s step %d lacks 7H diagnostics.", path, stepIdx);
    end
    for name = names
        value = double(info.(name));
        if ~isscalar(value) || ~isfinite(value) || value < 0
            error("loadNoGloveStage7iHoldSupportCorpus:RewardInfo", ...
                "Episode %s step %d has invalid %s.", ...
                path, stepIdx, name);
        end
        recorded.(name)(stepIdx) = value;
    end
end
end

function numbers = parseEpisodeNumbers(files)
numbers = zeros(numel(files), 1);
for idx = 1:numel(files)
    token = regexp(files(idx).name, '^episode(\d+)\.mat$', ...
        'tokens', 'once');
    if isempty(token)
        error("loadNoGloveStage7iHoldSupportCorpus:EpisodeName", ...
            "Unexpected episode filename %s.", files(idx).name);
    end
    numbers(idx) = str2double(token{1});
end
if numel(unique(numbers)) ~= numel(numbers)
    error("loadNoGloveStage7iHoldSupportCorpus:DuplicateEpisode", ...
        "Episode numbers must be unique within each source.");
end
end
