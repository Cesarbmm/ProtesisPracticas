function analysis = analyzeNoGloveStage7gActionMargins( ...
        components, actuator, options)
%analyzeNoGloveStage7gActionMargins audits offline threshold separability.

arguments
    components table
    actuator (1, 1) struct
    options.maximumRestWindowActiveFraction (1, 1) double ...
        {mustBeInRange(options.maximumRestWindowActiveFraction, 0, 1)} = 0.01
    options.maximumMovementCommandLoss (1, 1) double ...
        {mustBeInRange(options.maximumMovementCommandLoss, 0, 1)} = 0.05
    options.maximumMotor2CommandLoss (1, 1) double ...
        {mustBeInRange(options.maximumMotor2CommandLoss, 0, 1)} = 0.05
    options.quantizationTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
end

validateInputs(components, actuator);
quantizationAudit = auditRecordedQuantization(components, actuator);
if quantizationAudit.maximumEffectiveActionError > ...
        options.quantizationTolerance || ...
        quantizationAudit.maximumPwmError > options.quantizationTolerance
    error("analyzeNoGloveStage7gActionMargins:QuantizationMismatch", ...
        "Recorded actions do not reproduce baselineQuantized.");
end

distributionSummary = summarizeDistributions( ...
    components, actuator.activationThreshold);
[thresholdCurve, thresholdDecision] = buildThresholdCurves( ...
    components, actuator, options);
candidate = thresholdDecision( ...
    thresholdDecision.variant == "candidate", :);
if height(candidate) ~= 1
    error("analyzeNoGloveStage7gActionMargins:CandidateDecision", ...
        "Expected exactly one candidate threshold decision.");
end
if candidate.feasibleThresholdExists
    classification = "offlineThresholdSeparationExists";
elseif candidate.restOnlyThresholdExists
    classification = "restMovementNotSeparableBySingleThreshold";
else
    classification = "restSuppressionUnresolved";
end
sourceDecision = table(classification, ...
    logical(candidate.feasibleThresholdExists), ...
    candidate.minimumFeasibleThreshold, ...
    logical(candidate.restOnlyThresholdExists), ...
    candidate.minimumRestOnlyThreshold, ...
    candidate.movementCommandLossAtRestThreshold, ...
    candidate.motor2CommandLossAtRestThreshold, false, ...
    'VariableNames', ["classification", "feasibleThresholdExists", ...
    "minimumFeasibleThreshold", "restOnlyThresholdExists", ...
    "minimumRestOnlyThreshold", "movementCommandLossAtRestThreshold", ...
    "motor2CommandLossAtRestThreshold", "rootCauseIdentified"]);

analysis = struct("schemaVersion", 1, "stage", "7G", ...
    "distributionSummary", distributionSummary, ...
    "thresholdCurve", thresholdCurve, ...
    "thresholdDecision", thresholdDecision, ...
    "quantizationAudit", quantizationAudit, ...
    "sourceDecision", sourceDecision, ...
    "classification", classification, ...
    "thresholds", struct( ...
        "maximumRestWindowActiveFraction", ...
            options.maximumRestWindowActiveFraction, ...
        "maximumMovementCommandLoss", ...
            options.maximumMovementCommandLoss, ...
        "maximumMotor2CommandLoss", ...
            options.maximumMotor2CommandLoss), ...
    "currentActivationThreshold", actuator.activationThreshold, ...
    "thresholdAppliedToEnvironment", false, ...
    "policyChanged", false, "quantizationChanged", false, ...
    "simulatorInvoked", false, "runTraining", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "rootCauseIdentified", false);
end

function validateInputs(components, actuator)
requiredColumns = ["variant", "source", "episode", "step", "motor", ...
    "windowIndex", "phase", "rawAction", "effectiveAction", "pwm", ...
    "referenceVelocity"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
if ~all(ismember(requiredColumns, ...
        string(components.Properties.VariableNames))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator))) || ...
        isempty(components)
    error("analyzeNoGloveStage7gActionMargins:MissingField", ...
        "Component table or actuator contract is incomplete.");
end
if ~isequal(unique(string(components.variant))', ...
        ["candidate", "control"]) || ...
        ~all(ismember(["steadyRest", "preActivation", "movement", ...
        "postActivationHold"], unique(string(components.phase)))) || ...
        any(~ismember(double(components.motor), 1:4)) || ...
        any(~isfinite([double(components.rawAction); ...
        double(components.effectiveAction); double(components.pwm); ...
        double(components.referenceVelocity)])) || ...
        actuator.activationThreshold ~= 0.05
    error("analyzeNoGloveStage7gActionMargins:InvalidCorpus", ...
        "Corpus must contain both 7F variants and all causal phases.");
end
end

function audit = auditRecordedQuantization(components, actuator)
keys = string(components.variant)+"|"+string(components.source)+"|"+ ...
    string(components.windowIndex);
[groups, uniqueKeys] = findgroups(keys);
effectiveError = zeros(numel(uniqueKeys), 1);
pwmError = zeros(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    rows = find(groups == groupIdx);
    [~, order] = sort(components.motor(rows));
    rows = rows(order);
    if numel(rows) ~= 4 || ...
            ~isequal(double(components.motor(rows))', 1:4)
        error("analyzeNoGloveStage7gActionMargins:WindowContract", ...
            "Every recorded window must contain four ordered motors.");
    end
    [effective, pwm] = quantizeBaselineAction( ...
        double(components.rawAction(rows)), actuator.maxPwm, ...
        actuator.activationThreshold, actuator.commandLevels);
    effectiveError(groupIdx) = max(abs(effective- ...
        double(components.effectiveAction(rows))));
    pwmError(groupIdx) = max(abs(pwm-double(components.pwm(rows))));
end
audit = struct("windowCount", numel(uniqueKeys), ...
    "componentCount", height(components), ...
    "maximumEffectiveActionError", max(effectiveError), ...
    "maximumPwmError", max(pwmError), ...
    "exactlyReproduced", max(effectiveError) == 0 && max(pwmError) == 0);
end

function summary = summarizeDistributions(components, currentThreshold)
variants = ["control", "candidate"];
phases = ["steadyRest", "preActivation", "movement", ...
    "postActivationHold", "inactiveOther"];
rows = cell(0, 1);
for variant = variants
    for phase = phases
        phaseRows = components.variant == variant & ...
            components.phase == phase;
        if ~any(phaseRows)
            continue;
        end
        rows{end+1, 1} = distributionRow( ...
            variant, phase, 0, components(phaseRows, :), ...
            currentThreshold); %#ok<AGROW>
        for motor = 1:4
            mask = phaseRows & components.motor == motor;
            if any(mask)
                rows{end+1, 1} = distributionRow( ...
                    variant, phase, motor, components(mask, :), ...
                    currentThreshold); %#ok<AGROW>
            end
        end
    end
end
summary = vertcat(rows{:});
end

function row = distributionRow(variant, phase, motor, values, threshold)
absoluteRaw = abs(double(values.rawAction));
margin = absoluteRaw-threshold;
rawQuantiles = quantile(absoluteRaw, [0.05 0.50 0.95]);
marginQuantiles = quantile(margin, [0.05 0.50 0.95]);
row = table(variant, phase, motor, height(values), ...
    numel(unique(values.windowIndex)), mean(abs(values.pwm) > 0), ...
    mean(absoluteRaw), min(absoluteRaw), rawQuantiles(1), ...
    rawQuantiles(2), rawQuantiles(3), max(absoluteRaw), ...
    mean(abs(values.effectiveAction)), mean(abs(values.pwm)), ...
    mean(margin), marginQuantiles(1), marginQuantiles(2), ...
    marginQuantiles(3), ...
    'VariableNames', ["variant", "phase", "motor", ...
    "componentCount", "windowCount", "currentCommandActiveFraction", ...
    "meanAbsRawAction", "minAbsRawAction", "p05AbsRawAction", ...
    "medianAbsRawAction", "p95AbsRawAction", "maxAbsRawAction", ...
    "meanAbsEffectiveAction", "meanAbsPwm", "meanMargin", ...
    "p05Margin", "medianMargin", "p95Margin"]);
end

function [curve, decisions] = buildThresholdCurves( ...
        components, actuator, options)
variants = ["control", "candidate"];
curveParts = cell(numel(variants), 1);
decisionRows = cell(numel(variants), 1);
ungatedPwm = mapUngatedPwm(abs(double(components.rawAction)), actuator);
for variantIdx = 1:numel(variants)
    variant = variants(variantIdx);
    variantRows = components.variant == variant;
    restRows = variantRows & components.phase == "steadyRest";
    movementRows = variantRows & components.phase == "movement";
    rest = components(restRows, :);
    movement = components(movementRows, :);
    if isempty(rest) || isempty(movement)
        error("analyzeNoGloveStage7gActionMargins:EmptyStratum", ...
            "Variant %s lacks rest or movement rows.", variant);
    end
    magnitudes = unique([abs(double(rest.rawAction)); ...
        abs(double(movement.rawAction))]);
    above = min(1, magnitudes+max(1e-12, eps(magnitudes)));
    thresholds = unique([0; actuator.activationThreshold; 1; ...
        magnitudes; above]);
    currentMovementActive = abs(double(movement.pwm)) > 0;
    motor2Rows = movement.motor == 2;
    currentMotor2Active = currentMovementActive & motor2Rows;
    if ~any(currentMovementActive) || ~any(currentMotor2Active)
        error("analyzeNoGloveStage7gActionMargins:MovementDenominator", ...
            "Current movement commands must include all motors.");
    end
    restGroups = findgroups(rest.windowIndex);
    restUngatedPwm = ungatedPwm(restRows);
    rowCount = numel(thresholds);
    restComponent = zeros(rowCount, 1);
    restWindow = zeros(rowCount, 1);
    restMeanPwm = zeros(rowCount, 1);
    movementLoss = zeros(rowCount, 1);
    motor2Loss = zeros(rowCount, 1);
    for thresholdIdx = 1:rowCount
        threshold = thresholds(thresholdIdx);
        restActive = abs(double(rest.rawAction)) >= threshold;
        restComponent(thresholdIdx) = mean(restActive);
        anyByWindow = splitapply(@any, restActive, restGroups);
        restWindow(thresholdIdx) = mean(anyByWindow);
        restMeanPwm(thresholdIdx) = mean( ...
            restUngatedPwm.*double(restActive));
        movementActive = abs(double(movement.rawAction)) >= threshold;
        lost = currentMovementActive & ~movementActive;
        movementLoss(thresholdIdx) = sum(lost)/sum(currentMovementActive);
        motor2Loss(thresholdIdx) = sum(lost & motor2Rows)/ ...
            sum(currentMotor2Active);
    end
    feasible = restWindow <= options.maximumRestWindowActiveFraction & ...
        movementLoss <= options.maximumMovementCommandLoss & ...
        motor2Loss <= options.maximumMotor2CommandLoss;
    restOnly = restWindow <= options.maximumRestWindowActiveFraction;
    curveParts{variantIdx} = table(repmat(variant, rowCount, 1), ...
        thresholds, restComponent, restWindow, restMeanPwm, ...
        movementLoss, motor2Loss, feasible, restOnly, ...
        'VariableNames', ["variant", "activationThreshold", ...
        "restComponentActiveFraction", "restWindowActiveFraction", ...
        "restMeanAbsPwm", "movementCommandLossFraction", ...
        "motor2CommandLossFraction", "feasible", "restGatePassed"]);
    feasibleThreshold = minimumOrNaN(thresholds(feasible));
    restThreshold = minimumOrNaN(thresholds(restOnly));
    [movementLossAtRest, motor2LossAtRest, restPwmAtRest] = ...
        metricsAtThreshold(thresholds, restThreshold, movementLoss, ...
        motor2Loss, restMeanPwm);
    currentIdx = find(thresholds == actuator.activationThreshold, 1);
    decisionRows{variantIdx} = table(variant, ...
        restComponent(currentIdx), restWindow(currentIdx), ...
        restMeanPwm(currentIdx), any(feasible), feasibleThreshold, ...
        any(restOnly), restThreshold, movementLossAtRest, ...
        motor2LossAtRest, restPwmAtRest, ...
        'VariableNames', ["variant", ...
        "currentRestComponentActiveFraction", ...
        "currentRestWindowActiveFraction", "currentRestMeanAbsPwm", ...
        "feasibleThresholdExists", "minimumFeasibleThreshold", ...
        "restOnlyThresholdExists", "minimumRestOnlyThreshold", ...
        "movementCommandLossAtRestThreshold", ...
        "motor2CommandLossAtRestThreshold", ...
        "restMeanAbsPwmAtRestThreshold"]);
end
curve = vertcat(curveParts{:});
decisions = vertcat(decisionRows{:});
end

function pwm = mapUngatedPwm(magnitudes, actuator)
levels = sort(unique(abs(double(actuator.commandLevels(:)))));
levels = levels(levels > 0);
pwm = zeros(size(magnitudes));
for idx = 1:numel(magnitudes)
    [~, nearest] = min(abs(levels-magnitudes(idx)*actuator.maxPwm));
    pwm(idx) = levels(nearest);
end
end

function value = minimumOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = min(values);
end
end

function [movement, motor2, pwm] = metricsAtThreshold( ...
        thresholds, selected, movementValues, motor2Values, pwmValues)
if isnan(selected)
    movement = NaN;
    motor2 = NaN;
    pwm = NaN;
    return;
end
idx = find(thresholds == selected, 1);
movement = movementValues(idx);
motor2 = motor2Values(idx);
pwm = pwmValues(idx);
end
