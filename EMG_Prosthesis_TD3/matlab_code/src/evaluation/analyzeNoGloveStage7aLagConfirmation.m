function analysis = analyzeNoGloveStage7aLagConfirmation( ...
        componentTable, splitName, options)
%analyzeNoGloveStage7aLagConfirmation held-out causal lag audit.
%
% Lags are selected only on training repetitions and evaluated on the held
% out repetition. Every candidate uses the same fixed interior support, so
% lag selection cannot improve merely by cropping different endpoints.
% Positive lag means a delayed response: q(t+lag) is compared with qRef(t).

arguments
    componentTable table
    splitName (1, 1) string
    options.targetMotors (1, :) double = [2 3]
    options.targetRegimes (1, :) string = ["opening" "closing"]
    options.maxLagSteps (1, 1) double ...
        {mustBeInteger, mustBePositive} = 5
    options.activeVelocityThreshold (1, 1) double ...
        {mustBePositive} = 0.005
    options.minimumSamplesPerFold (1, 1) double ...
        {mustBeInteger, mustBePositive} = 10
    options.minimumBenefitFraction (1, 1) double ...
        {mustBeInRange(options.minimumBenefitFraction, 0, 1)} = 0.05
    options.minimumMaterialFoldFraction (1, 1) double ...
        {mustBeInRange(options.minimumMaterialFoldFraction, 0, 1)} = 2/3
    options.minimumSignConsistency (1, 1) double ...
        {mustBeInRange(options.minimumSignConsistency, 0, 1)} = 0.80
    options.maximumBoundaryFraction (1, 1) double ...
        {mustBeInRange(options.maximumBoundaryFraction, 0, 1)} = 0.50
    options.periodSec (1, 1) double {mustBePositive} = 0.2
end

validateInputs(componentTable, splitName, options);
sources = unique(string(componentTable.commandSource), "stable");
folds = unique(double(componentTable.repetitionId), "sorted");
lags = (-options.maxLagSteps:options.maxLagSteps)';

lagRows = repmat(emptyLagRow(), ...
    numel(sources) * numel(options.targetMotors) * ...
    numel(options.targetRegimes) * numel(folds) * numel(lags), 1);
foldRows = repmat(emptyFoldRow(), ...
    numel(sources) * numel(options.targetMotors) * ...
    numel(options.targetRegimes) * numel(folds), 1);
lagRowIdx = 0;
foldRowIdx = 0;

for sourceIdx = 1:numel(sources)
    source = sources(sourceIdx);
    for motorIdx = 1:numel(options.targetMotors)
        motor = options.targetMotors(motorIdx);
        sourceMotor = componentTable( ...
            string(componentTable.commandSource) == source & ...
            componentTable.motor == motor, :);
        for regimeIdx = 1:numel(options.targetRegimes)
            regime = options.targetRegimes(regimeIdx);
            for foldIdx = 1:numel(folds)
                fold = folds(foldIdx);
                training = sourceMotor(sourceMotor.repetitionId ~= fold, :);
                evaluation = sourceMotor(sourceMotor.repetitionId == fold, :);
                trainingEpisodes = unique(training.episode);
                evaluationEpisodes = unique(evaluation.episode);
                if isempty(trainingEpisodes) || isempty(evaluationEpisodes)
                    error("analyzeNoGloveStage7aLagConfirmation:EmptyFold", ...
                        "Every repetition must define training and evaluation data.");
                end

                currentLagRows = repmat(emptyLagRow(), numel(lags), 1);
                for lagIdx = 1:numel(lags)
                    lag = lags(lagIdx);
                    metrics = calculateAlignedMetrics(training, regime, lag, ...
                        options.maxLagSteps, options.activeVelocityThreshold);
                    lagRowIdx = lagRowIdx + 1;
                    row = emptyLagRow();
                    row.commandSource = source;
                    row.motor = motor;
                    row.regime = regime;
                    row.heldOutRepetition = fold;
                    row.lagSteps = lag;
                    row.lagSec = lag * options.periodSec;
                    row.absoluteLagSteps = abs(lag);
                    row.trainingEpisodeCount = numel(trainingEpisodes);
                    row.sampleCount = metrics.sampleCount;
                    row.zeroLagMse = metrics.zeroLagMse;
                    row.lagMse = metrics.lagMse;
                    row.improvementFraction = metrics.improvementFraction;
                    row.hasMinimumSamples = metrics.sampleCount >= ...
                        options.minimumSamplesPerFold;
                    lagRows(lagRowIdx) = row;
                    currentLagRows(lagIdx) = row;
                end

                validRows = currentLagRows([currentLagRows.hasMinimumSamples]);
                if isempty(validRows)
                    error("analyzeNoGloveStage7aLagConfirmation:TooFewSamples", ...
                        "Fold %g source %s motor %d regime %s has too few samples.", ...
                        fold, source, motor, regime);
                end
                selected = chooseLag(struct2table(validRows));
                evaluationMetrics = calculateAlignedMetrics( ...
                    evaluation, regime, selected.lagSteps, ...
                    options.maxLagSteps, options.activeVelocityThreshold);
                fullEndpoint = calculateFullEndpointMetrics(evaluation, ...
                    regime, options.activeVelocityThreshold);
                if evaluationMetrics.sampleCount < ...
                        options.minimumSamplesPerFold
                    error("analyzeNoGloveStage7aLagConfirmation:TooFewSamples", ...
                        "Held-out fold %g has too few samples.", fold);
                end

                foldRowIdx = foldRowIdx + 1;
                foldRow = emptyFoldRow();
                foldRow.commandSource = source;
                foldRow.motor = motor;
                foldRow.regime = regime;
                foldRow.heldOutRepetition = fold;
                foldRow.trainingEpisodeCount = numel(trainingEpisodes);
                foldRow.evaluationEpisodeCount = numel(evaluationEpisodes);
                foldRow.selectedLagSteps = selected.lagSteps;
                foldRow.selectedLagSec = selected.lagSteps * options.periodSec;
                foldRow.selectedAtBoundary = ...
                    abs(selected.lagSteps) == options.maxLagSteps;
                foldRow.trainingSampleCount = selected.sampleCount;
                foldRow.trainingZeroLagMse = selected.zeroLagMse;
                foldRow.trainingSelectedLagMse = selected.lagMse;
                foldRow.trainingImprovementFraction = ...
                    selected.improvementFraction;
                foldRow.evaluationSampleCount = ...
                    evaluationMetrics.sampleCount;
                foldRow.evaluationZeroLagSquaredSum = ...
                    evaluationMetrics.zeroLagSquaredSum;
                foldRow.evaluationSelectedLagSquaredSum = ...
                    evaluationMetrics.lagSquaredSum;
                foldRow.evaluationZeroLagMse = ...
                    evaluationMetrics.zeroLagMse;
                foldRow.evaluationSelectedLagMse = ...
                    evaluationMetrics.lagMse;
                foldRow.evaluationImprovementFraction = ...
                    evaluationMetrics.improvementFraction;
                foldRow.evaluationFullEndpointSampleCount = ...
                    fullEndpoint.sampleCount;
                foldRow.evaluationFullEndpointSquaredSum = ...
                    fullEndpoint.squaredSum;
                foldRow.evaluationFullEndpointMse = fullEndpoint.mse;
                foldRows(foldRowIdx) = foldRow;
            end
        end
    end
end

calibrationLagTable = struct2table(lagRows);
foldEvaluationTable = struct2table(foldRows);
confirmationSummary = summarizeConfirmation(foldEvaluationTable, options);
sourceDecision = summarizeSourceDecision( ...
    sources, confirmationSummary, options);
primaryDecision = sourceDecision(sourceDecision.commandSource == "Agent200", :);
if height(primaryDecision) ~= 1
    error("analyzeNoGloveStage7aLagConfirmation:MissingPrimary", ...
        "Expected exactly one Agent200 source decision.");
end

analysis = struct( ...
    "schemaVersion", 1, ...
    "stage", "7A", ...
    "split", splitName, ...
    "commandSources", sources, ...
    "heldOutFoldVariable", "repetitionId", ...
    "heldOutRepetitions", folds, ...
    "targetMotors", options.targetMotors, ...
    "targetRegimes", options.targetRegimes, ...
    "maxLagSteps", options.maxLagSteps, ...
    "periodSec", options.periodSec, ...
    "positiveLagMeaning", "response delayed: q(t+lag) versus qRef(t)", ...
    "commonInteriorSupport", true, ...
    "fullEndpointErrorRetained", true, ...
    "calibrationLagTable", calibrationLagTable, ...
    "foldEvaluationTable", foldEvaluationTable, ...
    "confirmationSummary", confirmationSummary, ...
    "sourceDecision", sourceDecision, ...
    "primaryDecision", primaryDecision, ...
    "causalCompensationGatePassed", ...
        primaryDecision.causalCompensationCandidate, ...
    "compensationInterventionExecuted", false, ...
    "filteredReferenceInterventionExecuted", false, ...
    "dtwCalculated", false, ...
    "dtwRewardUsed", false, ...
    "agentLoaded", false, ...
    "reinforcementLearningInvoked", false, ...
    "simulatorInvoked", false, ...
    "rewardInvoked", false, ...
    "hardwareUsed", false);
end

function validateInputs(values, splitName, options)
required = ["split", "commandSource", "episode", "repetitionId", ...
    "step", "motor", "qAfter", "qReference", "referenceVelocity"];
missing = setdiff(required, string(values.Properties.VariableNames));
if ~isempty(missing)
    error("analyzeNoGloveStage7aLagConfirmation:MissingVariable", ...
        "componentTable is missing: %s.", strjoin(missing, ", "));
end
if isempty(values) || any(string(values.split) ~= splitName)
    error("analyzeNoGloveStage7aLagConfirmation:InvalidSplit", ...
        "componentTable must contain only split %s.", splitName);
end
numericFields = ["episode", "repetitionId", "step", "motor", ...
    "qAfter", "qReference", "referenceVelocity"];
for fieldIdx = 1:numel(numericFields)
    fieldName = numericFields(fieldIdx);
    fieldValue = values.(fieldName);
    if ~isnumeric(fieldValue) || ~isreal(fieldValue) || ...
            any(~isfinite(fieldValue), "all")
        error("analyzeNoGloveStage7aLagConfirmation:NonfiniteData", ...
            "%s must be finite real numeric data.", fieldName);
    end
end
if numel(unique(values.repetitionId)) < 3 || ...
        any(values.repetitionId < 1 | fix(values.repetitionId) ~= ...
        values.repetitionId)
    error("analyzeNoGloveStage7aLagConfirmation:InvalidFolds", ...
        "At least three positive integer repetitions are required.");
end
if numel(unique(string(values.commandSource))) < 1 || ...
        any(strlength(string(values.commandSource)) == 0)
    error("analyzeNoGloveStage7aLagConfirmation:InvalidSource", ...
        "commandSource must be nonempty.");
end
if numel(unique(options.targetMotors)) ~= numel(options.targetMotors) || ...
        any(~ismember(options.targetMotors, 1:4)) || ...
        any(fix(options.targetMotors) ~= options.targetMotors)
    error("analyzeNoGloveStage7aLagConfirmation:InvalidMotors", ...
        "targetMotors must be unique integers in 1:4.");
end
validRegimes = ["opening", "hold", "closing"];
if numel(unique(options.targetRegimes)) ~= numel(options.targetRegimes) || ...
        any(~ismember(options.targetRegimes, validRegimes))
    error("analyzeNoGloveStage7aLagConfirmation:InvalidRegimes", ...
        "targetRegimes must be unique opening, hold or closing values.");
end
end

function metrics = calculateAlignedMetrics( ...
        values, regime, lag, maxLag, velocityThreshold)
episodes = unique(double(values.episode), "stable");
responseCells = cell(numel(episodes), 1);
referenceCells = cell(numel(episodes), 1);
zeroResponseCells = cell(numel(episodes), 1);
for episodeIdx = 1:numel(episodes)
    episodeRows = sortrows(values(values.episode == episodes(episodeIdx), :), ...
        "step");
    validateEpisodeRows(episodeRows, maxLag);
    stepCount = height(episodeRows);
    referenceIndices = (1+maxLag):(stepCount-maxLag);
    regimeMask = classifyRegime( ...
        episodeRows.referenceVelocity(referenceIndices), ...
        velocityThreshold) == regime;
    responseIndices = referenceIndices + lag;
    responseCells{episodeIdx} = ...
        double(episodeRows.qAfter(responseIndices(regimeMask)));
    referenceCells{episodeIdx} = ...
        double(episodeRows.qReference(referenceIndices(regimeMask)));
    zeroResponseCells{episodeIdx} = ...
        double(episodeRows.qAfter(referenceIndices(regimeMask)));
end
response = vertcat(responseCells{:});
reference = vertcat(referenceCells{:});
zeroResponse = vertcat(zeroResponseCells{:});
if isempty(response)
    metrics = emptyMetrics();
    return;
end
lagSquared = (response-reference).^2;
zeroSquared = (zeroResponse-reference).^2;
metrics = struct( ...
    "sampleCount", numel(response), ...
    "lagSquaredSum", sum(lagSquared), ...
    "zeroLagSquaredSum", sum(zeroSquared), ...
    "lagMse", mean(lagSquared), ...
    "zeroLagMse", mean(zeroSquared), ...
    "improvementFraction", safeReduction(mean(zeroSquared), mean(lagSquared)));
end

function metrics = calculateFullEndpointMetrics( ...
        values, regime, velocityThreshold)
episodes = unique(double(values.episode), "stable");
squaredCells = cell(numel(episodes), 1);
for episodeIdx = 1:numel(episodes)
    episodeRows = sortrows(values(values.episode == episodes(episodeIdx), :), ...
        "step");
    validateEpisodeRows(episodeRows, 0);
    regimeMask = classifyRegime(episodeRows.referenceVelocity, ...
        velocityThreshold) == regime;
    squaredCells{episodeIdx} = double( ...
        episodeRows.qAfter(regimeMask)-episodeRows.qReference(regimeMask)).^2;
end
squared = vertcat(squaredCells{:});
if isempty(squared)
    metrics = struct("sampleCount", 0, "squaredSum", 0, "mse", NaN);
else
    metrics = struct("sampleCount", numel(squared), ...
        "squaredSum", sum(squared), "mse", mean(squared));
end
end

function validateEpisodeRows(rows, maxLag)
if isempty(rows) || height(rows) <= 2*maxLag
    error("analyzeNoGloveStage7aLagConfirmation:EpisodeTooShort", ...
        "Every episode must be longer than twice maxLagSteps.");
end
steps = double(rows.step(:));
if ~isequal(steps, (1:height(rows))')
    error("analyzeNoGloveStage7aLagConfirmation:NoncontiguousSteps", ...
        "Every source-motor episode must have contiguous unique steps.");
end
if numel(unique(rows.repetitionId)) ~= 1
    error("analyzeNoGloveStage7aLagConfirmation:MixedRepetition", ...
        "One episode cannot cross repetition folds.");
end
end

function regime = classifyRegime(velocity, threshold)
regime = repmat("hold", size(velocity));
regime(velocity >= threshold) = "closing";
regime(velocity <= -threshold) = "opening";
end

function selected = chooseLag(values)
maximum = max(values.improvementFraction);
candidates = values(values.improvementFraction == maximum, :);
candidates = sortrows(candidates, ["absoluteLagSteps", "lagSteps"]);
selected = candidates(1, :);
end

function summary = summarizeConfirmation(foldTable, options)
keys = unique(foldTable(:, ["commandSource", "motor", "regime"]), ...
    "rows", "stable");
rows = repmat(emptySummaryRow(), height(keys), 1);
for keyIdx = 1:height(keys)
    values = foldTable( ...
        foldTable.commandSource == keys.commandSource(keyIdx) & ...
        foldTable.motor == keys.motor(keyIdx) & ...
        foldTable.regime == keys.regime(keyIdx), :);
    zeroSquaredSum = sum(values.evaluationZeroLagSquaredSum);
    selectedSquaredSum = sum(values.evaluationSelectedLagSquaredSum);
    sampleCount = sum(values.evaluationSampleCount);
    fullSquaredSum = sum(values.evaluationFullEndpointSquaredSum);
    fullSampleCount = sum(values.evaluationFullEndpointSampleCount);
    signs = sign(values.selectedLagSteps);
    signCounts = [sum(signs == -1), sum(signs == 0), sum(signs == 1)];
    [dominantCount, dominantIdx] = max(signCounts);
    dominantSign = [-1 0 1];
    heldOutImprovement = safeReduction( ...
        zeroSquaredSum/sampleCount, selectedSquaredSum/sampleCount);
    materialFoldFraction = mean(values.evaluationImprovementFraction >= ...
        options.minimumBenefitFraction);
    dominantSignFraction = dominantCount / height(values);
    boundaryFraction = mean(values.selectedAtBoundary);
    fixedLagConfirmed = heldOutImprovement >= ...
        options.minimumBenefitFraction && ...
        materialFoldFraction >= options.minimumMaterialFoldFraction && ...
        dominantSignFraction >= options.minimumSignConsistency && ...
        boundaryFraction <= options.maximumBoundaryFraction && ...
        dominantSign(dominantIdx) ~= 0;
    causalCandidate = fixedLagConfirmed && dominantSign(dominantIdx) > 0;
    [classification, recommendation] = classifyConfirmation( ...
        heldOutImprovement, materialFoldFraction, dominantSignFraction, ...
        boundaryFraction, dominantSign(dominantIdx), options, ...
        fixedLagConfirmed, causalCandidate);

    row = emptySummaryRow();
    row.commandSource = keys.commandSource(keyIdx);
    row.motor = keys.motor(keyIdx);
    row.regime = keys.regime(keyIdx);
    row.foldCount = height(values);
    row.evaluationEpisodeCount = sum(values.evaluationEpisodeCount);
    row.evaluationSampleCount = sampleCount;
    row.fullEndpointSampleCount = fullSampleCount;
    row.fullEndpointMse = fullSquaredSum / fullSampleCount;
    row.commonSupportZeroLagMse = zeroSquaredSum / sampleCount;
    row.heldOutSelectedLagMse = selectedSquaredSum / sampleCount;
    row.heldOutImprovementFraction = heldOutImprovement;
    row.medianSelectedLagSteps = median(values.selectedLagSteps);
    row.minimumSelectedLagSteps = min(values.selectedLagSteps);
    row.maximumSelectedLagSteps = max(values.selectedLagSteps);
    row.dominantLagSign = dominantSign(dominantIdx);
    row.dominantSignFraction = dominantSignFraction;
    row.boundarySelectionFraction = boundaryFraction;
    row.materialFoldFraction = materialFoldFraction;
    row.fixedLagConfirmed = fixedLagConfirmed;
    row.causalCompensationCandidate = causalCandidate;
    row.classification = classification;
    row.recommendation = recommendation;
    rows(keyIdx) = row;
end
summary = struct2table(rows);
end

function [classification, recommendation] = classifyConfirmation( ...
        benefit, materialFolds, signConsistency, boundaryFraction, ...
        dominantSign, options, fixedLagConfirmed, causalCandidate)
if causalCandidate
    classification = "positiveDelayConfirmed";
    recommendation = ...
        "Authorize a separate causal predictor/filter intervention, not DTW.";
elseif fixedLagConfirmed && dominantSign < 0
    classification = "negativeLagPattern";
    recommendation = ...
        "Do not call this plant delay; inspect target shape and temporal labels.";
elseif boundaryFraction > options.maximumBoundaryFraction
    classification = "boundaryUnresolved";
    recommendation = ...
        "Do not compensate; the optimum is not localized inside the lag grid.";
elseif signConsistency < options.minimumSignConsistency
    classification = "inconsistentAcrossFolds";
    recommendation = ...
        "Do not compensate; lag sign is not reproducible across repetitions.";
elseif benefit < options.minimumBenefitFraction || ...
        materialFolds < options.minimumMaterialFoldFraction
    classification = "noHeldOutMaterialBenefit";
    recommendation = ...
        "Close the fixed-lag hypothesis for this motor-regime under this corpus.";
else
    classification = "gateFailed";
    recommendation = "Do not run a compensation intervention.";
end
end

function decision = summarizeSourceDecision(sources, summary, options)
rows = repmat(emptySourceDecisionRow(), numel(sources), 1);
for sourceIdx = 1:numel(sources)
    values = summary(summary.commandSource == sources(sourceIdx), :);
    candidateCount = sum(values.causalCompensationCandidate);
    confirmedCount = sum(values.fixedLagConfirmed);
    unresolvedCount = sum(values.classification == "boundaryUnresolved" | ...
        values.classification == "inconsistentAcrossFolds");
    if candidateCount > 0
        classification = "targetedCausalCandidate";
        recommendation = ...
            "Stop and authorize a separate target-only causal intervention.";
    elseif unresolvedCount > 0
        classification = "temporalPatternUnresolved";
        recommendation = ...
            "Do not compensate or use DTW; obtain designed excitation evidence.";
    else
        classification = "fixedLagHypothesisRejected";
        recommendation = ...
            "Return to controller and safety diagnosis without temporal reward.";
    end
    row = emptySourceDecisionRow();
    row.commandSource = sources(sourceIdx);
    row.motorRegimeCount = height(values);
    row.confirmedFixedLagCount = confirmedCount;
    row.causalCandidateCount = candidateCount;
    row.unresolvedCount = unresolvedCount;
    row.minimumBenefitFraction = options.minimumBenefitFraction;
    row.causalCompensationCandidate = candidateCount > 0;
    row.classification = classification;
    row.recommendation = recommendation;
    rows(sourceIdx) = row;
end
decision = struct2table(rows);
end

function value = safeReduction(baseline, candidate)
if baseline == 0
    if candidate == 0
        value = 0;
    else
        value = -Inf;
    end
else
    value = (baseline-candidate)/baseline;
end
end

