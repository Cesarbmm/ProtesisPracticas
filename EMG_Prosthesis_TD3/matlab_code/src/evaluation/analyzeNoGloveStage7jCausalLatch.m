function analysis = analyzeNoGloveStage7jCausalLatch(windows, options)
%analyzeNoGloveStage7jCausalLatch replays a causal hold latch offline.

arguments
    windows table
    options.velocityTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.entryPositionMseTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.farCorrectionMse (1, 1) double ...
        {mustBePositive} = 2.5e-3
    options.minimumRestCoverage (1, 1) double ...
        {mustBeInRange(options.minimumRestCoverage, 0, 1)} = 0.90
    options.maximumFarCorrectionExposure (1, 1) double ...
        {mustBeInRange(options.maximumFarCorrectionExposure, 0, 1)} = 0.05
end

validateWindows(windows, options);
windowAudit = replayCorpus(windows, options);
segmentAudit = buildSegmentAudit(windowAudit, options);
restEpisodeAudit = buildRestEpisodeAudit(windowAudit);
sourceSummary = buildSourceSummary(windowAudit, options);
variantSummary = buildVariantSummary( ...
    windowAudit, restEpisodeAudit, options);

prefixCheckCount = numel(unique(windowAudit.variant+"|"+ ...
    windowAudit.source+"|"+string(windowAudit.episode)));
prefixMismatchCount = sum(windowAudit.prefixMismatch);
if prefixMismatchCount ~= 0
    error("analyzeNoGloveStage7jCausalLatch:FutureLeakage", ...
        "Prefix replay changed before the future boundary.");
end
candidate = variantSummary(variantSummary.variant == "candidate", :);
if height(candidate) ~= 1
    error("analyzeNoGloveStage7jCausalLatch:CandidateDecision", ...
        "Expected one candidate summary row.");
end
checks = struct( ...
    "integrity", true, ...
    "restCoverage", candidate.latchedRestCoverage >= ...
        options.minimumRestCoverage, ...
    "farCorrectionExposure", candidate.latchedFarCorrectionExposure <= ...
        options.maximumFarCorrectionExposure, ...
    "noPrematureCorrectionLatch", ...
        candidate.prematureLatchWindowCount == 0, ...
    "prefixCausal", prefixMismatchCount == 0, ...
    "addsMemorySupport", candidate.recoveredWindowCount > 0);
if ~checks.integrity || ~checks.prefixCausal
    classification = "latchedHoldAuditInvalid";
elseif ~checks.restCoverage
    classification = "latchedHoldCoverageInsufficient";
elseif ~checks.farCorrectionExposure
    classification = "latchedHoldNotSeparableFromFarCorrection";
elseif ~checks.noPrematureCorrectionLatch
    classification = "latchedHoldPrematureCorrectionExposure";
elseif ~checks.addsMemorySupport
    classification = "latchAddsNoSupport";
else
    classification = "offlineLatchedHoldContractSupported";
end
gateChecks = table( ...
    ["integrity"; "restCoverage"; "farCorrectionExposure"; ...
    "noPrematureCorrectionLatch"; "prefixCausal"; ...
    "addsMemorySupport"], ...
    [double(checks.integrity); candidate.latchedRestCoverage; ...
    candidate.latchedFarCorrectionExposure; ...
    candidate.prematureLatchWindowCount; ...
    prefixMismatchCount; candidate.recoveredWindowCount], ...
    [1; options.minimumRestCoverage; ...
    options.maximumFarCorrectionExposure; 0; 0; 1], ...
    ["equal"; "greaterOrEqual"; "lessOrEqual"; ...
    "equal"; "equal"; "greaterOrEqual"], ...
    logical([checks.integrity; checks.restCoverage; ...
    checks.farCorrectionExposure; checks.noPrematureCorrectionLatch; ...
    checks.prefixCausal; checks.addsMemorySupport]), ...
    'VariableNames', ["check", "observed", "threshold", ...
    "comparison", "passed"]);
contractSupported = all(gateChecks.passed);
memoryRequired = any(windowAudit.recoveredByMemory);
sourceDecision = table(classification, contractSupported, ...
    candidate.latchedRestCoverage, ...
    candidate.latchedFarCorrectionExposure, ...
    candidate.recoveredWindowCount, ...
    candidate.prematureLatchWindowCount, prefixCheckCount, ...
    prefixMismatchCount, memoryRequired, "intentHoldMarkov61", 61, ...
    false, false, ...
    'VariableNames', ["classification", "contractSupported", ...
    "candidateRestCoverage", "candidateFarCorrectionExposure", ...
    "candidateRecoveredWindowCount", ...
    "candidatePrematureLatchWindowCount", "prefixCheckCount", ...
    "prefixMismatchCount", "explicitMemoryRequired", ...
    "proposedObservationVariant", "proposedObservationDimension", ...
    "observationVariantImplemented", "behavioralAblationAuthorized"]);

analysis = struct("schemaVersion", 1, "stage", "7J", ...
    "windowAudit", windowAudit, "segmentAudit", segmentAudit, ...
    "restEpisodeAudit", restEpisodeAudit, ...
    "sourceSummary", sourceSummary, ...
    "variantSummary", variantSummary, "gateChecks", gateChecks, ...
    "sourceDecision", sourceDecision, ...
    "classification", classification, ...
    "contractSupported", contractSupported, "checks", checks, ...
    "thresholds", struct( ...
        "velocityTolerance", options.velocityTolerance, ...
        "entryPositionMseTolerance", ...
            options.entryPositionMseTolerance, ...
        "farCorrectionMse", options.farCorrectionMse, ...
        "minimumRestCoverage", options.minimumRestCoverage, ...
        "maximumFarCorrectionExposure", ...
            options.maximumFarCorrectionExposure, ...
        "nOn", 1, "nOff", 1), ...
    "prefixCheckCount", prefixCheckCount, ...
    "prefixMismatchCount", prefixMismatchCount, ...
    "explicitMemoryRequired", memoryRequired, ...
    "proposedObservationVariant", "intentHoldMarkov61", ...
    "proposedObservationDimension", 61, ...
    "observationVariantImplemented", false, ...
    "behavioralInterventionExecuted", false, ...
    "rootCauseIdentified", false, ...
    "policyChanged", false, "rewardChanged", false, ...
    "referenceChanged", false, "stateChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "simulatorInvoked", false, ...
    "runTraining", false, "agentLoaded", false, ...
    "envCreated", false, "rewardFunctionInvoked", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false);
end

function validateWindows(windows, options)
required = ["variant", "source", "episode", "repetitionId", ...
    "step", "windowIndex", "effectiveAction", "pwm", ...
    "safetyIntervention", "holdPositionMse", ...
    "holdVelocityMaxAbs", "stopped", "eligible"];
if isempty(windows) || ~all(ismember(required, ...
        string(windows.Properties.VariableNames))) || ...
        ~isequal(sort(unique(string(windows.variant)))', ...
        ["candidate", "control"]) || ...
        ~all(ismember(["training", "acceptance", "steadyRest"], ...
        unique(string(windows.source))))
    error("analyzeNoGloveStage7jCausalLatch:InvalidCorpus", ...
        "The frozen 7I window corpus is incomplete.");
end
numeric = [double(windows.episode); double(windows.repetitionId); ...
    double(windows.step); double(windows.windowIndex); ...
    double(windows.holdPositionMse); ...
    double(windows.holdVelocityMaxAbs); ...
    double(windows.effectiveAction(:)); double(windows.pwm(:)); ...
    double(windows.safetyIntervention(:))];
expectedStopped = windows.holdVelocityMaxAbs <= ...
    options.velocityTolerance;
expectedEligible = expectedStopped & windows.holdPositionMse <= ...
    options.entryPositionMseTolerance;
if any(~isfinite(numeric)) || any(windows.holdPositionMse < 0) || ...
        any(windows.holdVelocityMaxAbs < 0) || ...
        any(windows.safetyIntervention < 0, "all") || ...
        ~isequal(logical(windows.stopped), expectedStopped) || ...
        ~isequal(logical(windows.eligible), expectedEligible) || ...
        size(windows.effectiveAction, 2) ~= 4 || ...
        size(windows.pwm, 2) ~= 4 || ...
        size(windows.safetyIntervention, 2) ~= 4
    error("analyzeNoGloveStage7jCausalLatch:InvalidCorpus", ...
        "The frozen 7I values do not replay the instant hold contract.");
end
end

function audit = replayCorpus(windows, options)
count = height(windows);
latch = false(count, 1);
entry = false(count, 1);
release = false(count, 1);
segmentId = zeros(count, 1);
segmentFarStarted = false(count, 1);
segmentConverged = false(count, 1);
beforeFarConvergence = false(count, 1);
premature = false(count, 1);
prefixMismatch = false(count, 1);
keys = windows.variant+"|"+windows.source+"|"+ ...
    string(windows.episode);
[groups, uniqueKeys] = findgroups(keys);
for groupIdx = 1:numel(uniqueKeys)
    indices = find(groups == groupIdx);
    [steps, order] = sort(double(windows.step(indices)));
    indices = indices(order);
    if ~isequal(steps', 1:numel(indices))
        error("analyzeNoGloveStage7jCausalLatch:StepOrder", ...
            "Episode steps are not contiguous.");
    end
    replay = replayEpisode(logical(windows.stopped(indices)), ...
        logical(windows.eligible(indices)), ...
        double(windows.holdPositionMse(indices)), ...
        options.farCorrectionMse);
    latch(indices) = replay.latch;
    entry(indices) = replay.entry;
    release(indices) = replay.release;
    segmentId(indices) = replay.segmentId;
    segmentFarStarted(indices) = replay.segmentFarStarted;
    segmentConverged(indices) = replay.segmentConverged;
    beforeFarConvergence(indices) = replay.beforeFarConvergence;
    premature(indices) = replay.premature;
    cut = max(1, floor(numel(indices)/2));
    prefix = replayEpisode(logical(windows.stopped(indices(1:cut))), ...
        logical(windows.eligible(indices(1:cut))), ...
        double(windows.holdPositionMse(indices(1:cut))), ...
        options.farCorrectionMse);
    mismatch = ~isequal(prefix.latch, replay.latch(1:cut)) || ...
        ~isequal(prefix.entry, replay.entry(1:cut)) || ...
        ~isequal(prefix.release, replay.release(1:cut)) || ...
        ~isequal(prefix.segmentId, replay.segmentId(1:cut)) || ...
        ~isequal(prefix.segmentFarStarted, ...
            replay.segmentFarStarted(1:cut)) || ...
        ~isequal(prefix.segmentConverged, ...
            replay.segmentConverged(1:cut));
    prefixMismatch(indices(1)) = mismatch;
end
loggedActionL2 = mean(double(windows.effectiveAction).^2, 2);
meanAbsPwm = mean(abs(double(windows.pwm)), 2);
maxAbsPwm = max(abs(double(windows.pwm)), [], 2);
safetyComponentCount = sum(double(windows.safetyIntervention) > 0, 2);
currentEligible = logical(windows.eligible);
recovered = latch & ~currentEligible;
audit = table(string(windows.variant), string(windows.source), ...
    double(windows.episode), double(windows.repetitionId), ...
    double(windows.step), double(windows.windowIndex), ...
    double(windows.holdPositionMse), ...
    double(windows.holdVelocityMaxAbs), logical(windows.stopped), ...
    currentEligible, latch, entry, release, segmentId, ...
    segmentFarStarted, segmentConverged, beforeFarConvergence, ...
    premature, recovered, loggedActionL2, ...
    double(currentEligible).*loggedActionL2, ...
    double(latch).*loggedActionL2, meanAbsPwm, maxAbsPwm, ...
    safetyComponentCount, safetyComponentCount > 0, prefixMismatch, ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "step", "windowIndex", "holdPositionMse", ...
    "holdVelocityMaxAbs", "stopped", "currentEligible", ...
    "latchActive", "latchEntry", "latchRelease", ...
    "stoppedSegmentId", "segmentFarStarted", ...
    "segmentConverged", "beforeFarConvergence", ...
    "prematureLatch", "recoveredByMemory", "loggedActionL2", ...
    "currentHoldActionExposure", "latchedHoldActionExposure", ...
    "meanAbsPwm", "maxAbsPwm", "safetyComponentCount", ...
    "anySafetyIntervention", "prefixMismatch"]);
end

function replay = replayEpisode(stopped, eligible, mse, farThreshold)
count = numel(stopped);
latch = false(count, 1);
entry = false(count, 1);
release = false(count, 1);
segmentId = zeros(count, 1);
segmentFarStarted = false(count, 1);
segmentConverged = false(count, 1);
beforeFarConvergence = false(count, 1);
premature = false(count, 1);
previousLatch = false;
inStoppedSegment = false;
currentSegment = 0;
currentSegmentFar = false;
currentSegmentConverged = false;
for idx = 1:count
    if ~stopped(idx)
        latch(idx) = false;
        release(idx) = previousLatch;
        inStoppedSegment = false;
        currentSegmentFar = false;
        currentSegmentConverged = false;
    else
        if ~inStoppedSegment
            currentSegment = currentSegment+1;
            currentSegmentFar = mse(idx) >= farThreshold;
            currentSegmentConverged = false;
            inStoppedSegment = true;
        end
        if eligible(idx)
            currentSegmentConverged = true;
        end
        latch(idx) = previousLatch || eligible(idx);
        entry(idx) = latch(idx) && ~previousLatch;
        segmentId(idx) = currentSegment;
        segmentFarStarted(idx) = currentSegmentFar;
        segmentConverged(idx) = currentSegmentConverged;
        beforeFarConvergence(idx) = currentSegmentFar && ...
            ~currentSegmentConverged;
        premature(idx) = latch(idx) && beforeFarConvergence(idx);
    end
    previousLatch = latch(idx);
end
replay = struct("latch", latch, "entry", entry, ...
    "release", release, "segmentId", segmentId, ...
    "segmentFarStarted", segmentFarStarted, ...
    "segmentConverged", segmentConverged, ...
    "beforeFarConvergence", beforeFarConvergence, ...
    "premature", premature);
end

function audit = buildSegmentAudit(windows, options)
stopped = windows(windows.stopped, :);
keys = stopped.variant+"|"+stopped.source+"|"+ ...
    string(stopped.episode)+"|"+string(stopped.stoppedSegmentId);
[groups, uniqueKeys] = findgroups(keys);
parts = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = stopped(groups == groupIdx, :);
    [~, order] = sort(values.step);
    values = values(order, :);
    convergence = values.step(values.segmentConverged);
    firstConvergenceStep = NaN;
    if ~isempty(convergence)
        firstConvergenceStep = min(convergence);
    end
    farRows = values.holdPositionMse >= options.farCorrectionMse;
    parts{groupIdx} = table(values.variant(1), values.source(1), ...
        values.episode(1), values.repetitionId(1), ...
        values.stoppedSegmentId(1), min(values.step), max(values.step), ...
        height(values), values.holdPositionMse(1), ...
        values.segmentFarStarted(1), any(values.segmentConverged), ...
        firstConvergenceStep, any(values.latchActive), ...
        sum(values.beforeFarConvergence), ...
        sum(values.prematureLatch), mean(values.latchActive), ...
        sum(farRows), sum(farRows & values.latchActive), ...
        'VariableNames', ["variant", "source", "episode", ...
        "repetitionId", "stoppedSegmentId", "startStep", ...
        "endStep", "windowCount", "startPositionMse", ...
        "farStarted", "converged", "firstConvergenceStep", ...
        "latchEverActive", "preconvergenceWindowCount", ...
        "prematureLatchWindowCount", "latchFraction", ...
        "farWindowCount", "latchedFarWindowCount"]);
end
audit = vertcat(parts{:});
end

function audit = buildRestEpisodeAudit(windows)
rest = windows(windows.source == "steadyRest", :);
keys = rest.variant+"|"+string(rest.episode);
[groups, uniqueKeys] = findgroups(keys);
parts = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = rest(groups == groupIdx, :);
    parts{groupIdx} = table(values.variant(1), values.episode(1), ...
        values.repetitionId(1), height(values), ...
        mean(values.currentEligible), mean(values.latchActive), ...
        sum(values.recoveredByMemory), all(values.latchActive), ...
        sum(values.latchEntry), sum(values.latchRelease), ...
        mean(values.latchedHoldActionExposure), ...
        mean(values.recoveredByMemory & values.anySafetyIntervention), ...
        'VariableNames', ["variant", "episode", "repetitionId", ...
        "windowCount", "currentCoverage", "latchedCoverage", ...
        "recoveredWindowCount", "fullLatchedCoverage", ...
        "entryCount", "releaseCount", ...
        "meanLatchedActionExposure", ...
        "recoveredSafetyWindowFraction"]);
end
audit = vertcat(parts{:});
end

function summary = buildSourceSummary(windows, options)
variants = ["control", "candidate"];
sources = ["training", "acceptance", "steadyRest"];
parts = cell(0, 1);
for variant = variants
    for source = sources
        values = windows(windows.variant == variant & ...
            windows.source == source, :);
        far = values.stopped & ...
            values.holdPositionMse >= options.farCorrectionMse;
        parts{end+1, 1} = table(variant, source, height(values), ...
            numel(unique(values.episode)), mean(values.currentEligible), ...
            mean(values.latchActive), sum(values.recoveredByMemory), ...
            meanOrNaN(values.latchActive(far)), sum(far), ...
            sum(values.prematureLatch), sum(values.latchEntry), ...
            sum(values.latchRelease), ...
            mean(values.currentHoldActionExposure), ...
            mean(values.latchedHoldActionExposure), ...
            meanOrNaN(values.meanAbsPwm(values.recoveredByMemory)), ...
            meanOrNaN(values.anySafetyIntervention( ...
                values.recoveredByMemory)), ...
            'VariableNames', ["variant", "source", "windowCount", ...
            "episodeCount", "currentCoverage", "latchedCoverage", ...
            "recoveredWindowCount", "latchedFarExposure", ...
            "farWindowCount", "prematureLatchWindowCount", ...
            "entryCount", "releaseCount", ...
            "meanCurrentHoldActionExposure", ...
            "meanLatchedHoldActionExposure", ...
            "recoveredMeanAbsPwm", ...
            "recoveredSafetyWindowFraction"]); %#ok<AGROW>
    end
end
summary = vertcat(parts{:});
end

function summary = buildVariantSummary(windows, restEpisodes, options)
variants = ["control", "candidate"];
parts = cell(2, 1);
for idx = 1:2
    variant = variants(idx);
    values = windows(windows.variant == variant, :);
    rest = values(values.source == "steadyRest", :);
    far = values.stopped & ...
        ismember(values.source, ["training", "acceptance"]) & ...
        values.holdPositionMse >= options.farCorrectionMse;
    episodes = restEpisodes(restEpisodes.variant == variant, :);
    recovered = values.recoveredByMemory;
    parts{idx} = table(variant, height(values), ...
        mean(rest.currentEligible), mean(rest.latchActive), ...
        mean(rest.latchActive)-mean(rest.currentEligible), ...
        sum(recovered), mean(recovered), ...
        mean(values.currentEligible(far)), ...
        mean(values.latchActive(far)), sum(far), ...
        sum(values.prematureLatch), sum(values.latchEntry), ...
        sum(values.latchRelease), ...
        mean(episodes.fullLatchedCoverage), ...
        min(episodes.latchedCoverage), ...
        mean(values.currentHoldActionExposure), ...
        mean(values.latchedHoldActionExposure), ...
        meanOrNaN(values.meanAbsPwm(recovered)), ...
        meanOrNaN(values.anySafetyIntervention(recovered)), ...
        any(recovered), ...
        'VariableNames', ["variant", "windowCount", ...
        "currentRestCoverage", "latchedRestCoverage", ...
        "restCoverageGain", "recoveredWindowCount", ...
        "recoveredWindowFraction", "currentFarCorrectionExposure", ...
        "latchedFarCorrectionExposure", "farCorrectionWindowCount", ...
        "prematureLatchWindowCount", "entryCount", ...
        "releaseCount", "fullCoverageRestEpisodeFraction", ...
        "minimumRestEpisodeCoverage", ...
        "meanCurrentHoldActionExposure", ...
        "meanLatchedHoldActionExposure", ...
        "recoveredMeanAbsPwm", ...
        "recoveredSafetyWindowFraction", ...
        "explicitMemoryRequired"]);
end
summary = vertcat(parts{:});
end

function value = meanOrNaN(values)
if isempty(values)
    value = NaN;
else
    value = mean(double(values));
end
end
