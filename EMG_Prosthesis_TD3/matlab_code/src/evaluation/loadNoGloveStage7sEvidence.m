function data = loadNoGloveStage7sEvidence( ...
        stage7rRunRoot, stage7qRunRoot, stage7pRunRoot, stage7nRunRoot)
%loadNoGloveStage7sEvidence validates all frozen 7S parents.

arguments
    stage7rRunRoot (1, 1) string
    stage7qRunRoot (1, 1) string
    stage7pRunRoot (1, 1) string
    stage7nRunRoot (1, 1) string
end

manifestPath = fullfile(stage7rRunRoot, "manifest.json");
resultsPath = fullfile(stage7rRunRoot, "stage7r_results.mat");
if ~isfile(manifestPath) || ~isfile(resultsPath)
    error("loadNoGloveStage7sEvidence:MissingStage7r", ...
        "Canonical ETAPA 7R artifacts are missing.");
end
expectedManifestHash = ...
    "5111367127942D80D97BA299F47872019548CFF2126B4D75B33F161C36F90847";
expectedResultsHash = ...
    "7F07C0ACB45A339BB9C339E68F9689E3E5EE23103963354ACA568AB9AB2899F1";
actualManifestHash = localFileSha256(manifestPath);
actualResultsHash = localFileSha256(resultsPath);
manifest = jsondecode(fileread(manifestPath));
if actualManifestHash ~= expectedManifestHash || ...
        actualResultsHash ~= expectedResultsHash || ...
        string(manifest.stage) ~= "7R" || ...
        string(manifest.result) ~= "PASS" || ...
        string(manifest.scientificResult) ~= ...
        "insufficientMatchedSupport" || ...
        string(manifest.stateDecision) ~= "intentMarkov60" || ...
        string(manifest.state62Disposition) ~= "provisionallyRejected" || ...
        logical(manifest.hardwareUsed) || logical(manifest.trainingUsed)
    error("loadNoGloveStage7sEvidence:Stage7rChanged", ...
        "ETAPA 7R does not match the preregistered parent.");
end
parent7r = load(resultsPath, "analysis", "pairSet", "manifest");
if ~all(isfield(parent7r, ["analysis", "pairSet", "manifest"])) || ...
        string(parent7r.analysis.scientificResult) ~= ...
        "insufficientMatchedSupport" || ...
        parent7r.pairSet.primaryComponentCount ~= 2064 || ...
        ~isequal(size(parent7r.pairSet.emgScale), [1, 40]) || ...
        ~isequal(size(parent7r.pairSet.contextScale), [1, 20]) || ...
        any(~isfinite([parent7r.pairSet.emgScale, ...
        parent7r.pairSet.contextScale])) || ...
        any([parent7r.pairSet.emgScale, ...
        parent7r.pairSet.contextScale] <= 0)
    error("loadNoGloveStage7sEvidence:InvalidStage7rResults", ...
        "ETAPA 7R MAT evidence violates its frozen contract.");
end

data = loadNoGloveStage7rEvidence( ...
    stage7qRunRoot, stage7pRunRoot, stage7nRunRoot);
controlRoot = string(data.stage7n.manifest.controlRunRoot);
profilePath = fullfile(controlRoot, "seed_11", ...
    "effective_training_profile.mat");
expectedProfileHash = ...
    "1E3853E96D93E656845A123E6C100B0037460A1A2D2EEC386C03C17DAE909A6E";
actualProfileHash = localFileSha256(profilePath);
profileData = load(profilePath, "profile");
if actualProfileHash ~= expectedProfileHash || ...
        ~isfield(profileData, "profile")
    error("loadNoGloveStage7sEvidence:ProfileChanged", ...
        "The frozen control60 profile changed.");
end
profile = profileData.profile;
requiredProfile = ["referenceSource", "observationVariant", ...
    "rewardType", "actionInterfaceVariant", "simMotors", ...
    "connect_glove", "intentCalibration", "intentExpectedContext", ...
    "simulationPositionSafety", "td3", "td3Residual"];
if ~all(isfield(profile, cellstr(requiredProfile))) || ...
        string(profile.referenceSource) ~= "emgIntent" || ...
        string(profile.observationVariant) ~= "intentMarkov60" || ...
        string(profile.rewardType) ~= "trackingIntentActionRateReward" || ...
        string(profile.actionInterfaceVariant) ~= "baselineQuantized" || ...
        ~logical(profile.simMotors) || logical(profile.connect_glove) || ...
        string(profile.intentCalibration.contentSha256) ~= ...
        "9c2ff4aba271c337df076874b5ff7ed08a4a07bcf7970f358c886e05e15e43a2" || ...
        ~logical(profile.simulationPositionSafety.enabled) || ...
        logical(profile.td3.useRecurrent) || ...
        logical(profile.td3Residual.enabled)
    error("loadNoGloveStage7sEvidence:UnsafeFrozenProfile", ...
        "The frozen control60 profile is not the preregistered profile.");
end

matlabRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
normPath = fullfile(matlabRoot, "config", "normValues.mat");
expectedNormHash = ...
    "7DDA997F59E1327C8A4EF9CDDE07463506754FB73A52001E983B3A3877B017B2";
actualNormHash = localFileSha256(normPath);
if actualNormHash ~= expectedNormHash
    error("loadNoGloveStage7sEvidence:NormalizationChanged", ...
        "normValues.mat changed after preregistration.");
end

checkpointRows = sortrows(data.checkpointTable, "episode");
agent200Row = checkpointRows(checkpointRows.episode == 200, :);
if height(agent200Row) ~= 1 || ...
        string(agent200Row.checkpointSha256) ~= ...
        "440F003450A368A13A0E5DACB04FD7755BB929033EB879B217E47F32B5AA185E"
    error("loadNoGloveStage7sEvidence:Agent200Changed", ...
        "The frozen Agent200 checkpoint changed.");
end
acceptanceMask = data.primaryCorpus.metadata.source == "acceptance";
if sum(acceptanceMask) ~= 3050 || ...
        numel(unique(data.primaryCorpus.metadata.episode(acceptanceMask))) ~= 50
    error("loadNoGloveStage7sEvidence:AcceptanceChanged", ...
        "The frozen Agent200 acceptance corpus changed.");
end

data.stage7r = struct( ...
    "runRoot", stage7rRunRoot, "manifest", manifest, ...
    "manifestSha256", actualManifestHash, ...
    "resultsSha256", actualResultsHash, "validated", true);
data.stage7rAnalysis = parent7r.analysis;
data.frozenEmgScale = double(parent7r.pairSet.emgScale);
data.frozenContextScale = double(parent7r.pairSet.contextScale);
data.profile = profile;
data.profilePath = string(profilePath);
data.profileSha256 = actualProfileHash;
data.normPath = string(normPath);
data.normSha256 = actualNormHash;
data.agent200Row = agent200Row;
data.acceptanceMask = acceptanceMask;
data.agentCheckpointsLoaded = false;
data.agent7250Loaded = false;
end

function hash = localFileSha256(filePath)
if ~isfile(filePath)
    error("loadNoGloveStage7sEvidence:MissingFile", ...
        "Missing file: %s", filePath);
end
escaped = strrep(char(filePath), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("loadNoGloveStage7sEvidence:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = string(strtrim(output));
end
