function analysis = analyzeNoGloveStage7rEmgAttribution( ...
        pairSet, sharedEvaluations, options)
%analyzeNoGloveStage7rEmgAttribution fits real-pair incremental models.

arguments
    pairSet (1, 1) struct
    sharedEvaluations struct
    options.ridgeLambda (1, 1) double {mustBePositive} = 1
    options.signActionTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-3
end

validateInputs(pairSet, sharedEvaluations);
contract = getNoGloveWmoosFeatureContract();
familyDefinitions = buildFamilyDefinitions(contract);
channelDefinitions = buildChannelDefinitions(contract);
familyModelSummary = buildModelSummary(pairSet, sharedEvaluations, ...
    familyDefinitions, options);
channelModelSummary = buildModelSummary(pairSet, sharedEvaluations, ...
    channelDefinitions, options);
decision = classifyNoGloveStage7rEvidence( ...
    pairSet.supportSummary, familyModelSummary);
pairActionTable = buildPairActionTable(pairSet, sharedEvaluations);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7R", "result", "PASS", ...
    "scientificResult", decision.scientificResult, ...
    "stateDecision", "intentMarkov60", ...
    "state62Disposition", "provisionallyRejected", ...
    "featureContract", contract, ...
    "pairTable", pairSet.table, ...
    "pairActionTable", pairActionTable, ...
    "supportSummary", pairSet.supportSummary, ...
    "gridSummary", pairSet.gridSummary, ...
    "familyModelSummary", familyModelSummary, ...
    "channelModelSummary", channelModelSummary, ...
    "familyDecisionAudit", decision.familyAudit, ...
    "allEmgDecisionAudit", decision.allEmgAudit, ...
    "supportDecisionAudit", decision.supportAudit, ...
    "primaryComponentCount", pairSet.primaryComponentCount, ...
    "pairCount", pairSet.pairCount, ...
    "stateCounterfactualUsed", false, "hybridStateUsed", false, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "hardwareUsed", false, ...
    "futureLeakageUsed", false, "rewardChanged", false, ...
    "quantizationChanged", false, "td3Changed", false, ...
    "simulatorChanged", false, "safetyChanged", false, ...
    "gateChanged", false);
end

function validateInputs(pairSet, evaluations)
required = ["table", "deltaContext", "deltaEmg", ...
    "supportSummary", "gridSummary", "statesEvaluated", ...
    "primaryComponentCount", "stateCounterfactualUsed", ...
    "hybridStateUsed"];
requiredEvaluation = ["episode", "raw", "effective", "pwm"];
if ~all(isfield(pairSet, cellstr(required))) || ...
        numel(evaluations) ~= 4 || ...
        ~all(isfield(evaluations, cellstr(requiredEvaluation))) || ...
        pairSet.stateCounterfactualUsed || pairSet.hybridStateUsed || ...
        size(pairSet.deltaContext, 1) ~= height(pairSet.table) || ...
        size(pairSet.deltaEmg, 1) ~= height(pairSet.table) || ...
        size(pairSet.deltaContext, 2) ~= 20 || ...
        size(pairSet.deltaEmg, 2) ~= 40 || ...
        ~isequal(sort([evaluations.episode]), [50, 100, 150, 200])
    error("analyzeNoGloveStage7rEmgAttribution:InvalidContract", ...
        "Pair set or shared checkpoint evaluations are invalid.");
end
stateCount = size(pairSet.statesEvaluated, 1);
for idx = 1:numel(evaluations)
    if ~isequal(size(evaluations(idx).raw), [stateCount, 4]) || ...
            any(~isfinite([evaluations(idx).raw(:); ...
            evaluations(idx).effective(:); evaluations(idx).pwm(:)]))
        error("analyzeNoGloveStage7rEmgAttribution:InvalidActions", ...
            "Checkpoint actions must align to all real states.");
    end
end
end

function definitions = buildFamilyDefinitions(contract)
names = ["allEmg"; contract.families.family];
indices = cell(numel(names), 1);
indices{1} = 1:40;
for idx = 1:height(contract.families)
    indices{idx+1} = contract.families.firstIndex(idx): ...
        contract.families.lastIndex(idx);
end
definitions = table(names, indices, ...
    'VariableNames', ["name", "indices"]);
end

function definitions = buildChannelDefinitions(contract)
names = "channel"+string(contract.channels.channel);
indices = cell(8, 1);
for channel = 1:8
    indices{channel} = channel+(0:4)*8;
end
definitions = table(names, indices, ...
    'VariableNames', ["name", "indices"]);
end

function summary = buildModelSummary(pairSet, evaluations, ...
        definitions, options)
pairs = pairSet.table;
sources = ["ALL"; unique(pairs.source, "stable")];
maximumRows = numel(evaluations)*4*2*numel(sources)*height(definitions);
parts = cell(maximumRows, 1);
cursor = 0;
for evalIdx = 1:numel(evaluations)
    evaluation = evaluations(evalIdx);
    for motor = 1:4
        for pairMode = ["withinEpisode", "crossEpisode"]
            for source = sources'
                mask = pairs.motor == motor & pairs.pairMode == pairMode;
                if source ~= "ALL"
                    mask = mask & pairs.source == source;
                end
                rows = find(mask);
                if isempty(rows)
                    continue;
                end
                query = pairs.queryRow(rows);
                donor = pairs.donorRow(rows);
                response = evaluation.raw(query, motor) - ...
                    evaluation.raw(donor, motor);
                fold = pairs.fold(rows);
                context = pairSet.deltaContext(rows, :);
                contextMetrics = crossValidatedRidge( ...
                    context, response, fold, options);
                for definitionIdx = 1:height(definitions)
                    cursor = cursor+1;
                    indices = definitions.indices{definitionIdx};
                    emg = pairSet.deltaEmg(rows, indices);
                    permutedRows = pairs.permutedPairRow(rows);
                    permutedEmg = pairSet.deltaEmg(permutedRows, indices);
                    augmented = crossValidatedRidge( ...
                        [context, emg], response, fold, options);
                    permuted = crossValidatedRidge( ...
                        [context, permutedEmg], response, fold, options);
                    queryEpisodes = pairs.source(rows)+":"+ ...
                        compose("%05d", pairs.queryEpisode(rows));
                    donorEpisodes = pairs.source(rows)+":"+ ...
                        compose("%05d", pairs.donorEpisode(rows));
                    parts{cursor} = table(evaluation.episode, motor, ...
                        pairMode, source, definitions.name(definitionIdx), ...
                        numel(rows), numel(unique(queryEpisodes)), ...
                        numel(unique(donorEpisodes)), numel(unique(fold)), ...
                        mean(abs(response)), contextMetrics.r2, ...
                        augmented.r2, augmented.r2-contextMetrics.r2, ...
                        permuted.r2, permuted.r2-contextMetrics.r2, ...
                        augmented.r2-permuted.r2, ...
                        contextMetrics.correlation, augmented.correlation, ...
                        contextMetrics.meanAbsoluteError, ...
                        augmented.meanAbsoluteError, ...
                        contextMetrics.signAccuracy, ...
                        augmented.signAccuracy, ...
                        augmented.signAccuracy-contextMetrics.signAccuracy, ...
                        'VariableNames', ["checkpointEpisode", "motor", ...
                        "pairMode", "source", "family", "pairCount", ...
                        "uniqueQueryEpisodeCount", ...
                        "uniqueDonorEpisodeCount", "observedFoldCount", ...
                        "meanAbsoluteActionDifference", "contextR2", ...
                        "augmentedR2", "incrementalR2", "permutedR2", ...
                        "permutedIncrementalR2", "permutationMargin", ...
                        "contextPredictionCorrelation", ...
                        "augmentedPredictionCorrelation", ...
                        "contextMeanAbsoluteError", ...
                        "augmentedMeanAbsoluteError", ...
                        "contextSignAccuracy", "augmentedSignAccuracy", ...
                        "signAccuracyGain"]);
                end
            end
        end
    end
end
summary = vertcat(parts{1:cursor});
end

function metrics = crossValidatedRidge(predictors, response, fold, options)
foldValues = unique(fold, "sorted")';
prediction = nan(size(response));
if numel(foldValues) < 2
    metrics = emptyMetrics();
    return;
end
for foldIdx = foldValues
    test = fold == foldIdx;
    train = ~test;
    if ~any(test) || ~any(train)
        metrics = emptyMetrics();
        return;
    end
    centerX = mean(predictors(train, :), 1);
    scaleX = std(predictors(train, :), 0, 1);
    scaleX(scaleX < 1e-8) = 1;
    xTrain = (predictors(train, :)-centerX)./scaleX;
    xTest = (predictors(test, :)-centerX)./scaleX;
    centerY = mean(response(train));
    yTrain = response(train)-centerY;
    beta = (xTrain'*xTrain + ...
        options.ridgeLambda*eye(size(xTrain, 2))) \ (xTrain'*yTrain);
    prediction(test) = centerY+xTest*beta;
end
total = sum((response-mean(response)).^2);
if total == 0
    r2 = NaN;
else
    r2 = 1-sum((response-prediction).^2)/total;
end
eligibleSign = abs(response) >= options.signActionTolerance;
if any(eligibleSign)
    signAccuracy = mean(sign(prediction(eligibleSign)) == ...
        sign(response(eligibleSign)));
else
    signAccuracy = NaN;
end
metrics = struct("r2", r2, ...
    "correlation", localCorrelation(response, prediction), ...
    "meanAbsoluteError", mean(abs(response-prediction)), ...
    "signAccuracy", signAccuracy);
end

function metrics = emptyMetrics()
metrics = struct("r2", NaN, "correlation", NaN, ...
    "meanAbsoluteError", NaN, "signAccuracy", NaN);
end

function value = localCorrelation(a, b)
a = double(a(:));
b = double(b(:));
if numel(a) < 2 || std(a) == 0 || std(b) == 0 || ...
        any(~isfinite([a; b]))
    value = NaN;
else
    a = a-mean(a);
    b = b-mean(b);
    value = sum(a.*b)/sqrt(sum(a.^2)*sum(b.^2));
end
end

function tableValue = buildPairActionTable(pairSet, evaluations)
pairs = pairSet.table;
parts = cell(numel(evaluations), 1);
for evalIdx = 1:numel(evaluations)
    evaluation = evaluations(evalIdx);
    linearQuery = sub2ind(size(evaluation.raw), ...
        pairs.queryRow, pairs.motor);
    linearDonor = sub2ind(size(evaluation.raw), ...
        pairs.donorRow, pairs.motor);
    queryRaw = evaluation.raw(linearQuery);
    donorRaw = evaluation.raw(linearDonor);
    queryEffective = evaluation.effective(linearQuery);
    donorEffective = evaluation.effective(linearDonor);
    queryPwm = evaluation.pwm(linearQuery);
    donorPwm = evaluation.pwm(linearDonor);
    parts{evalIdx} = table( ...
        repmat(evaluation.episode, height(pairs), 1), ...
        pairs.pairRow, pairs.motor, pairs.pairMode, pairs.source, ...
        pairs.fold, pairs.queryRow, pairs.donorRow, ...
        queryRaw, donorRaw, queryRaw-donorRaw, ...
        queryEffective, donorEffective, ...
        queryEffective-donorEffective, queryPwm, donorPwm, ...
        queryPwm-donorPwm, ...
        'VariableNames', ["checkpointEpisode", "pairRow", "motor", ...
        "pairMode", "source", "fold", "queryRow", "donorRow", ...
        "queryRawAction", "donorRawAction", "deltaRawAction", ...
        "queryEffectiveAction", "donorEffectiveAction", ...
        "deltaEffectiveAction", "queryPwm", "donorPwm", ...
        "deltaPwm"]);
end
tableValue = vertcat(parts{:});
end
