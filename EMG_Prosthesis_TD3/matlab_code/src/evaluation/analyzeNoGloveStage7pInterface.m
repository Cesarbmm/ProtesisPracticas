function analysis = analyzeNoGloveStage7pInterface( ...
        corpus, actuator, options)
%analyzeNoGloveStage7pInterface audits quantizer, gate and safety offline.

arguments
    corpus (1, 1) struct
    actuator (1, 1) struct
    options.thresholdNeighborhood (1, 1) double ...
        {mustBePositive} = 0.01
    options.crossingEpsilon (1, 1) double {mustBePositive} = 1e-6
    options.positionBoundaryTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-9
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
    options.minimumQuantizerExposure (1, 1) double ...
        {mustBeInRange(options.minimumQuantizerExposure, 0, 1)} = 0.01
    options.minimumGateInactiveReference (1, 1) double ...
        {mustBeInRange(options.minimumGateInactiveReference, 0, 1)} = 0.10
    options.minimumGateNonzeroPwm (1, 1) double ...
        {mustBeInRange(options.minimumGateNonzeroPwm, 0, 1)} = 0.10
end

requiredCorpus = ["rawAction", "effectiveAction", "pwm", ...
    "qBefore", "qAfter", "qReference", "vReference", ...
    "referenceActive", "zeroControlDemand", ...
    "safetyIntervention", "metadata"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
if ~all(isfield(corpus, cellstr(requiredCorpus))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator)))
    error("analyzeNoGloveStage7pInterface:InvalidContract", ...
        "Corpus or actuator contract are incomplete.");
end
validateArrays(corpus);
theta = double(actuator.activationThreshold);
if options.thresholdNeighborhood >= theta || ...
        options.crossingEpsilon >= options.thresholdNeighborhood
    error("analyzeNoGloveStage7pInterface:InvalidNeighborhood", ...
        "The threshold neighborhood or epsilon is invalid.");
end

raw = double(corpus.rawAction);
effective = double(corpus.effectiveAction);
pwm = double(corpus.pwm);
count = size(raw, 1);
metadata = corpus.metadata;

rawCf = raw;
magnitude = abs(raw);
distance = abs(magnitude-theta);
near = distance <= options.thresholdNeighborhood;
inactive = magnitude < theta;
direction = sign(raw);
rawCf(near & inactive) = direction(near & inactive).*theta;
rawCf(near & ~inactive) = direction(near & ~inactive).* ...
    (theta-options.crossingEpsilon);
[effectiveCf, pwmCf] = quantizeRows(rawCf, actuator);

windowIndex = repelem(metadata.windowIndex, 4);
rowId = repelem(metadata.rowId, 4);
source = repelem(metadata.source, 4);
episode = repelem(metadata.episode, 4);
step = repelem(metadata.step, 4);
gateContext = repelem(metadata.gateContext, 4);
gateActive = repelem(metadata.gateActive, 4);
activeMotorCount = repelem(metadata.activeMotorCount, 4);
partialMotorReference = repelem(metadata.partialMotorReference, 4);
motor = repmat((1:4)', count, 1);
qBefore = reshape(corpus.qBefore', [], 1);
qAfter = reshape(corpus.qAfter', [], 1);
qReference = reshape(corpus.qReference', [], 1);
vReference = reshape(corpus.vReference', [], 1);
referenceActive = reshape(corpus.referenceActive', [], 1);
zeroControlDemand = reshape(corpus.zeroControlDemand', [], 1);
rawValue = reshape(raw', [], 1);
effectiveValue = reshape(effective', [], 1);
pwmValue = reshape(pwm', [], 1);
safetyCount = reshape(corpus.safetyIntervention', [], 1);
distanceValue = reshape(distance', [], 1);
nearValue = reshape(near', [], 1);
rawCfValue = reshape(rawCf', [], 1);
effectiveCfValue = reshape(effectiveCf', [], 1);
pwmCfValue = reshape(pwmCf', [], 1);

notNear = ~nearValue;
rawCfValue(notNear) = NaN;
effectiveCfValue(notNear) = NaN;
pwmCfValue(notNear) = NaN;
deltaRaw = rawCfValue-rawValue;
deltaEffective = effectiveCfValue-effectiveValue;
deltaPwm = pwmCfValue-pwmValue;
zeroTo64 = nearValue & abs(pwmValue) == 0 & abs(pwmCfValue) == 64;
sixtyFourToZero = nearValue & abs(pwmValue) == 64 & ...
    abs(pwmCfValue) == 0;
amplification = abs(deltaEffective)./abs(deltaRaw);

atLower = qBefore <= options.positionBoundaryTolerance;
atUpper = qBefore >= 1-options.positionBoundaryTolerance;
atBoundary = atLower | atUpper;
outwardAtBoundary = (atLower & pwmValue < 0) | ...
    (atUpper & pwmValue > 0);
safetyIntervened = safetyCount > 0;
safetyAttribution = repmat("none", numel(rawValue), 1);
safetyAttribution(safetyIntervened & ~atBoundary) = "interior";
safetyAttribution(safetyIntervened & atBoundary) = "boundaryOther";
safetyAttribution(safetyIntervened & outwardAtBoundary) = ...
    "outwardBoundary";
actionRegion = repmat("higherLevel", numel(rawValue), 1);
actionRegion(abs(pwmValue) == 0) = "inactive";
actionRegion(abs(pwmValue) == 64) = "minimum64";

componentTable = table(windowIndex, rowId, source, episode, step, ...
    gateContext, gateActive, activeMotorCount, partialMotorReference, ...
    motor, qBefore, qAfter, qReference, vReference, ...
    referenceActive, zeroControlDemand, rawValue, effectiveValue, ...
    pwmValue, actionRegion, abs(effectiveValue) >= ...
        options.saturationThreshold, ...
    distanceValue, nearValue, rawCfValue, effectiveCfValue, ...
    pwmCfValue, deltaRaw, deltaEffective, deltaPwm, zeroTo64, ...
    sixtyFourToZero, amplification, ...
    abs(effectiveValue-rawValue), safetyCount, safetyIntervened, ...
    atLower, atUpper, atBoundary, outwardAtBoundary, ...
    safetyAttribution, ...
    'VariableNames', ["windowIndex", "rowId", "source", ...
    "episode", "step", "gateContext", "gateActive", ...
    "activeMotorCount", "partialMotorReference", "motor", ...
    "qBefore", "qAfter", "qReference", "vReference", ...
    "referenceActive", "zeroControlDemand", "rawAction", ...
    "effectiveAction", "pwm", "actionRegion", "saturated", ...
    "distanceToThreshold", "nearThreshold", ...
    "counterfactualRawAction", "counterfactualEffectiveAction", ...
    "counterfactualPwm", "deltaRaw", "deltaEffective", ...
    "deltaPwm", "zeroTo64", "sixtyFourToZero", ...
    "effectiveToRawAmplification", "absoluteInterfaceDistortion", ...
    "safetyInterventionCount", "safetyIntervened", ...
    "atLower", "atUpper", "atBoundary", ...
    "outwardAtBoundary", "safetyAttribution"]);

canonicalSweep = buildCanonicalSweep(actuator, options);
canonicalPass = verifyCanonicalSweep(canonicalSweep, actuator);
nearCount = sum(componentTable.nearThreshold);
nearCounterfactualPass = nearCount > 0 && ...
    all(componentTable.zeroTo64(componentTable.nearThreshold) | ...
        componentTable.sixtyFourToZero( ...
            componentTable.nearThreshold)) && ...
    all(abs(abs(componentTable.deltaPwm( ...
        componentTable.nearThreshold))-64) <= 0) && ...
    all(abs(abs(componentTable.deltaEffective( ...
        componentTable.nearThreshold))-64/actuator.maxPwm) <= 1e-12);

interfaceSummary = summarizeInterface(componentTable);
levelSignSummary = summarizeLevelSign(componentTable, actuator);
gateMotorSummary = summarizeGateMotors(componentTable);
gateWindowSummary = summarizeGateWindows(metadata);
safetySummary = summarizeSafety(componentTable);
safetyContextSummary = summarizeSafetyContext(componentTable);

nearFraction = mean(componentTable.nearThreshold);
gateRows = componentTable.gateContext == "gateActive";
gateInactiveReferenceFraction = safeFraction( ...
    sum(gateRows & ~componentTable.referenceActive), sum(gateRows));
gateInactiveRows = gateRows & ~componentTable.referenceActive;
gateInactiveReferenceNonzeroPwmFraction = safeFraction( ...
    sum(gateInactiveRows & componentTable.pwm ~= 0), ...
    sum(gateInactiveRows));
selection = selectFutureAblation(canonicalPass, ...
    nearCounterfactualPass, nearFraction, ...
    gateInactiveReferenceFraction, ...
    gateInactiveReferenceNonzeroPwmFraction, options);

interventionSamples = sum(componentTable.safetyInterventionCount);
interventionSteps = sum(componentTable.safetyIntervened);
interiorInterventionFraction = safeFraction(sum( ...
    componentTable.safetyInterventionCount( ...
        componentTable.safetyAttribution == "interior")), ...
    interventionSamples);
decisionAudit = table(canonicalPass, nearCounterfactualPass, ...
    nearFraction, options.minimumQuantizerExposure, ...
    gateInactiveReferenceFraction, ...
    options.minimumGateInactiveReference, ...
    gateInactiveReferenceNonzeroPwmFraction, ...
    options.minimumGateNonzeroPwm, selection, ...
    'VariableNames', ["canonicalDiscontinuityPassed", ...
    "nearCounterfactualPassed", "nearThresholdFraction", ...
    "minimumQuantizerExposure", ...
    "gateInactiveReferenceFraction", ...
    "minimumGateInactiveReference", ...
    "gateInactiveReferenceNonzeroPwmFraction", ...
    "minimumGateNonzeroPwm", "selection"]);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7P", ...
    "result", "PASS", "stateDecision", "intentMarkov60", ...
    "state62Disposition", "provisionallyRejected", ...
    "futureAblationSelection", selection, ...
    "componentTable", componentTable, ...
    "canonicalSweep", canonicalSweep, ...
    "interfaceSummary", interfaceSummary, ...
    "levelSignSummary", levelSignSummary, ...
    "gateMotorSummary", gateMotorSummary, ...
    "gateWindowSummary", gateWindowSummary, ...
    "safetySummary", safetySummary, ...
    "safetyContextSummary", safetyContextSummary, ...
    "decisionAudit", decisionAudit, ...
    "nearThresholdComponentCount", nearCount, ...
    "nearThresholdFraction", nearFraction, ...
    "canonicalDiscontinuityPassed", canonicalPass, ...
    "nearCounterfactualPassed", nearCounterfactualPass, ...
    "gateInactiveReferenceFraction", ...
        gateInactiveReferenceFraction, ...
    "gateInactiveReferenceNonzeroPwmFraction", ...
        gateInactiveReferenceNonzeroPwmFraction, ...
    "safetyInterventionComponentStepCount", interventionSteps, ...
    "safetyInterventionSampleCount", interventionSamples, ...
    "interiorInterventionSampleFraction", ...
        interiorInterventionFraction, ...
    "thresholdNeighborhood", options.thresholdNeighborhood, ...
    "crossingEpsilon", options.crossingEpsilon, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "hardwareUsed", false, ...
    "quantizationChanged", false, "safetyChanged", false, ...
    "gateChanged", false, "pilotAuthorized", false);
end

function summary = summarizeLevelSign(components, actuator)
sources = ["ALL"; unique(components.source, "stable")];
levels = sort(unique(abs(double(actuator.commandLevels(:)))));
signs = [-1, 0, 1];
rows = cell(numel(sources)*4*numel(levels)*numel(signs), 1);
cursor = 0;
for source = sources'
    for motor = 1:4
        eligible = (source == "ALL" | components.source == source) & ...
            components.motor == motor;
        denominator = sum(eligible);
        for level = levels'
            for signValue = signs
                cursor = cursor+1;
                count = sum(eligible & abs(components.pwm) == level & ...
                    sign(components.pwm) == signValue);
                rows{cursor} = table(source, motor, level, signValue, ...
                    count, safeFraction(count, denominator), ...
                    'VariableNames', ["source", "motor", ...
                    "pwmMagnitude", "pwmSign", "componentCount", ...
                    "fraction"]);
            end
        end
    end
end
summary = vertcat(rows{:});
end

function validateArrays(corpus)
names = ["rawAction", "effectiveAction", "pwm", "qBefore", ...
    "qAfter", "qReference", "vReference", "referenceActive", ...
    "zeroControlDemand", "safetyIntervention"];
count = size(corpus.rawAction, 1);
if count == 0 || height(corpus.metadata) ~= count
    error("analyzeNoGloveStage7pInterface:InvalidArrays", ...
        "The corpus must contain aligned windows.");
end
for name = names
    value = corpus.(name);
    if ~isequal(size(value), [count, 4]) || ...
            any(~isfinite(double(value)), "all")
        error("analyzeNoGloveStage7pInterface:InvalidArrays", ...
            "Corpus array %s must be finite N-by-4.", name);
    end
end
end

function [effective, pwm] = quantizeRows(raw, actuator)
effective = zeros(size(raw));
pwm = zeros(size(raw));
for rowIdx = 1:size(raw, 1)
    [e, p] = quantizeBaselineAction(raw(rowIdx, :), ...
        actuator.maxPwm, actuator.activationThreshold, ...
        actuator.commandLevels);
    effective(rowIdx, :) = double(e(:))';
    pwm(rowIdx, :) = double(p(:))';
end
end

function sweep = buildCanonicalSweep(actuator, options)
theta = actuator.activationThreshold;
offset = [-options.thresholdNeighborhood, ...
    -options.thresholdNeighborhood/2, -options.crossingEpsilon, ...
    0, options.thresholdNeighborhood/2, ...
    options.thresholdNeighborhood];
offsetLabel = ["minusNeighborhood", "minusHalfNeighborhood", ...
    "minusEpsilon", "threshold", "plusHalfNeighborhood", ...
    "plusNeighborhood"];
rows = cell(4*2*numel(offset), 1);
cursor = 0;
for motor = 1:4
    for signValue = [-1, 1]
        for offsetIdx = 1:numel(offset)
            raw = zeros(1, 4);
            raw(motor) = signValue*(theta+offset(offsetIdx));
            [effective, pwm] = quantizeBaselineAction(raw, ...
                actuator.maxPwm, actuator.activationThreshold, ...
                actuator.commandLevels);
            cursor = cursor+1;
            rows{cursor} = table(motor, signValue, offset(offsetIdx), ...
                offsetLabel(offsetIdx), raw(motor), ...
                double(effective(motor)), double(pwm(motor)), ...
                'VariableNames', ["motor", "sign", "offset", ...
                "offsetLabel", "rawAction", "effectiveAction", "pwm"]);
        end
    end
end
sweep = vertcat(rows{:});
end

function passed = verifyCanonicalSweep(sweep, actuator)
below = sweep.offsetLabel == "minusEpsilon";
at = sweep.offsetLabel == "threshold";
passed = all(abs(sweep.pwm(below)) == 0) && ...
    all(abs(sweep.pwm(at)) == 64) && ...
    all(abs(sweep.effectiveAction(at)) == 64/actuator.maxPwm);
end

function summary = summarizeInterface(components)
sources = ["ALL"; unique(components.source, "stable")];
rows = cell(numel(sources)*4, 1);
cursor = 0;
for source = sources'
    sourceMask = source == "ALL" | components.source == source;
    for motor = 1:4
        values = components(sourceMask & components.motor == motor, :);
        cursor = cursor+1;
        near = values.nearThreshold;
        amp = values.effectiveToRawAmplification(near);
        rows{cursor} = table(source, motor, height(values), ...
            mean(values.actionRegion == "inactive"), ...
            mean(values.actionRegion == "minimum64"), ...
            mean(values.actionRegion == "higherLevel"), ...
            mean(values.saturated), mean(values.nearThreshold), ...
            mean(values.absoluteInterfaceDistortion), ...
            sum(near), mean(values.zeroTo64), ...
            mean(values.sixtyFourToZero), ...
            safeMean(amp), safeMedian(amp), safeMaximum(amp), ...
            'VariableNames', ["source", "motor", "componentCount", ...
            "inactiveFraction", "minimum64Fraction", ...
            "higherLevelFraction", "saturationFraction", ...
            "nearThresholdFraction", "meanAbsoluteInterfaceDistortion", ...
            "counterfactualCount", "zeroTo64Fraction", ...
            "sixtyFourToZeroFraction", "meanAmplification", ...
            "medianAmplification", "maximumAmplification"]);
    end
end
summary = vertcat(rows{:});
end

function summary = summarizeGateMotors(components)
sources = ["ALL"; unique(components.source, "stable")];
contexts = unique(components.gateContext, "stable");
rows = cell(numel(sources)*numel(contexts)*4, 1);
cursor = 0;
for source = sources'
    for context = contexts'
        for motor = 1:4
            mask = (source == "ALL" | components.source == source) & ...
                components.gateContext == context & ...
                components.motor == motor;
            if ~any(mask)
                continue;
            end
            values = components(mask, :);
            zeroDemand = values.zeroControlDemand;
            cursor = cursor+1;
            rows{cursor} = table(source, context, motor, height(values), ...
                mean(values.referenceActive), ...
                mean(values.activeMotorCount), ...
                mean(values.partialMotorReference), ...
                mean(values.pwm ~= 0), mean(values.saturated), ...
                mean(values.nearThreshold), ...
                mean(values.safetyIntervened), ...
                sum(values.safetyInterventionCount), ...
                mean(zeroDemand), safeFraction(sum( ...
                    zeroDemand & values.pwm ~= 0), sum(zeroDemand)), ...
                'VariableNames', ["source", "gateContext", "motor", ...
                "componentCount", "referenceActiveFraction", ...
                "meanActiveMotorCount", ...
                "partialMotorReferenceFraction", ...
                "nonzeroPwmFraction", "saturationFraction", ...
                "nearThresholdFraction", ...
                "safetyInterventionStepFraction", ...
                "safetyInterventionSampleCount", ...
                "zeroControlDemandFraction", ...
                "nonzeroPwmFractionOfZeroControlDemand"]);
        end
    end
end
summary = vertcat(rows{1:cursor});
end

function summary = summarizeGateWindows(metadata)
sources = ["ALL"; unique(metadata.source, "stable")];
rows = cell(numel(sources)*5, 1);
cursor = 0;
for source = sources'
    sourceMask = source == "ALL" | metadata.source == source;
    active = metadata(sourceMask & metadata.gateContext == "gateActive", :);
    for motorCount = 0:4
        cursor = cursor+1;
        count = sum(active.activeMotorCount == motorCount);
        rows{cursor} = table(source, motorCount, count, ...
            safeFraction(count, height(active)), ...
            'VariableNames', ["source", "activeMotorCount", ...
            "windowCount", "fractionOfGateActiveWindows"]);
    end
end
summary = vertcat(rows{:});
end

function summary = summarizeSafety(components)
sources = ["ALL"; unique(components.source, "stable")];
attributions = ["outwardBoundary", "boundaryOther", "interior"];
rows = cell(numel(sources)*4*numel(attributions), 1);
cursor = 0;
for source = sources'
    for motor = 1:4
        eligible = (source == "ALL" | components.source == source) & ...
            components.motor == motor;
        totalComponents = sum(eligible);
        totalSamples = sum(components.safetyInterventionCount(eligible));
        for attribution = attributions
            mask = eligible & ...
                components.safetyAttribution == attribution;
            cursor = cursor+1;
            sampleCount = sum(components.safetyInterventionCount(mask));
            rows{cursor} = table(source, motor, attribution, ...
                totalComponents, sum(mask), sampleCount, ...
                safeFraction(sum(mask), totalComponents), ...
                safeFraction(sampleCount, totalSamples), ...
                safeMean(abs(components.pwm(mask))), ...
                safeFraction(sum(components.saturated(mask)), sum(mask)), ...
                safeFraction(sum(components.zeroControlDemand(mask)), ...
                    sum(mask)), ...
                'VariableNames', ["source", "motor", "attribution", ...
                "eligibleComponentCount", "interventionStepCount", ...
                "interventionSampleCount", ...
                "interventionStepFraction", ...
                "interventionSampleFraction", "meanAbsPwm", ...
                "saturationFraction", "zeroControlDemandFraction"]);
        end
    end
end
summary = vertcat(rows{:});
end

function summary = summarizeSafetyContext(components)
sources = ["ALL"; unique(components.source, "stable")];
contexts = unique(components.gateContext, "stable");
attributions = ["outwardBoundary", "boundaryOther", "interior"];
rows = cell(numel(sources)*numel(contexts)*4*numel(attributions), 1);
cursor = 0;
for source = sources'
    for context = contexts'
        for motor = 1:4
            eligible = (source == "ALL" | ...
                components.source == source) & ...
                components.gateContext == context & ...
                components.motor == motor;
            if ~any(eligible)
                continue;
            end
            totalComponents = sum(eligible);
            totalSamples = sum( ...
                components.safetyInterventionCount(eligible));
            for attribution = attributions
                mask = eligible & ...
                    components.safetyAttribution == attribution;
                cursor = cursor+1;
                sampleCount = sum( ...
                    components.safetyInterventionCount(mask));
                rows{cursor} = table(source, context, motor, attribution, ...
                    totalComponents, sum(mask), sampleCount, ...
                    safeFraction(sum(mask), totalComponents), ...
                    safeFraction(sampleCount, totalSamples), ...
                    safeMean(abs(components.pwm(mask))), ...
                    safeFraction(sum(components.zeroControlDemand(mask)), ...
                        sum(mask)), ...
                    'VariableNames', ["source", "gateContext", ...
                    "motor", "attribution", "eligibleComponentCount", ...
                    "interventionStepCount", "interventionSampleCount", ...
                    "interventionStepFraction", ...
                    "interventionSampleFractionWithinContext", ...
                    "meanAbsPwm", "zeroControlDemandFraction"]);
            end
        end
    end
end
summary = vertcat(rows{1:cursor});
end

function selection = selectFutureAblation(canonicalPass, crossingPass, ...
        exposure, gateInactive, gateNonzero, options)
if canonicalPass && crossingPass && ...
        exposure >= options.minimumQuantizerExposure
    selection = "quantizerPriority";
elseif gateInactive >= options.minimumGateInactiveReference && ...
        gateNonzero >= options.minimumGateNonzeroPwm
    selection = "gatePriority";
else
    selection = "noAblationSupported";
end
end

function value = safeFraction(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator/denominator;
end
end

function value = safeMean(values)
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = safeMedian(values)
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end

function value = safeMaximum(values)
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end
