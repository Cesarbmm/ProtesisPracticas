function corpus = loadNoGloveStage7pInterfaceCorpus( ...
        sources, actuator, options)
%loadNoGloveStage7pInterfaceCorpus loads frozen Agent200 state-60 logs.

arguments
    sources (1, 1) struct
    actuator (1, 1) struct
    options.referenceVelocityThreshold (1, 1) double ...
        {mustBeNonnegative} = 0.005
    options.positionErrorTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.replayTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
end

requiredSources = ["acceptance", "steadyRest"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
if ~all(isfield(sources, cellstr(requiredSources))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator)))
    error("loadNoGloveStage7pInterfaceCorpus:InvalidContract", ...
        "Sources or actuator contract are incomplete.");
end

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
stateParts = cell(numel(requiredSources), 1);
rawParts = cell(numel(requiredSources), 1);
effectiveParts = cell(numel(requiredSources), 1);
pwmParts = cell(numel(requiredSources), 1);
qAfterParts = cell(numel(requiredSources), 1);
safetyParts = cell(numel(requiredSources), 1);
metadataParts = cell(numel(requiredSources), 1);
inventoryParts = cell(numel(requiredSources), 1);
alignmentParts = cell(numel(requiredSources), 1);
for sourceIdx = 1:numel(requiredSources)
    source = requiredSources(sourceIdx);
    [stateParts{sourceIdx}, rawParts{sourceIdx}, ...
        effectiveParts{sourceIdx}, pwmParts{sourceIdx}, ...
        qAfterParts{sourceIdx}, safetyParts{sourceIdx}, ...
        metadataParts{sourceIdx}, inventoryParts{sourceIdx}, ...
        alignmentParts{sourceIdx}] = loadDirectory( ...
        string(sources.(source)), source, layout, actuator, options);
end

states = vertcat(stateParts{:});
rawAction = vertcat(rawParts{:});
effectiveAction = vertcat(effectiveParts{:});
pwm = vertcat(pwmParts{:});
qAfter = vertcat(qAfterParts{:});
safetyIntervention = vertcat(safetyParts{:});
metadata = vertcat(metadataParts{:});
metadata.windowIndex = (1:height(metadata))';
metadata = movevars(metadata, "windowIndex", "Before", 1);
inventory = vertcat(inventoryParts{:});
alignment = vertcat(alignmentParts{:});

qBefore = states(:, layout.encoder);
qReference = states(:, layout.referencePosition);
vReference = states(:, layout.referenceVelocity);
referenceActive = abs(vReference) >= options.referenceVelocityThreshold;
zeroControlDemand = ~referenceActive & ...
    abs(qReference-qBefore) <= options.positionErrorTolerance;

corpus = struct( ...
    "schemaVersion", 1, "stateDecision", "intentMarkov60", ...
    "states", states, "rawAction", rawAction, ...
    "effectiveAction", effectiveAction, "pwm", pwm, ...
    "qBefore", qBefore, "qAfter", qAfter, ...
    "qReference", qReference, "vReference", vReference, ...
    "referenceActive", referenceActive, ...
    "zeroControlDemand", zeroControlDemand, ...
    "safetyIntervention", safetyIntervention, ...
    "metadata", metadata, "inventory", inventory, ...
    "alignmentAudit", alignment, ...
    "windowCount", size(states, 1), ...
    "componentCount", numel(rawAction), ...
    "referenceVelocityThreshold", ...
        options.referenceVelocityThreshold, ...
    "positionErrorTolerance", options.positionErrorTolerance, ...
    "futureLeakageUsed", false, "trainingLogsUsed", false);
end

function [states, raw, effective, pwm, qAfter, safety, metadata, ...
        inventory, alignment] = loadDirectory( ...
        directory, source, layout, actuator, options)
if ~isfolder(directory)
    error("loadNoGloveStage7pInterfaceCorpus:MissingDirectory", ...
        "Source directory does not exist: %s", directory);
end
files = dir(fullfile(directory, "episode*.mat"));
if isempty(files)
    error("loadNoGloveStage7pInterfaceCorpus:NoEpisodes", ...
        "No episode files found under %s.", directory);
end
numbers = arrayfun(@(value) parseEpisode(value.name), files);
[numbers, order] = sort(numbers);
files = files(order);
if numel(unique(numbers)) ~= numel(numbers)
    error("loadNoGloveStage7pInterfaceCorpus:DuplicateEpisode", ...
        "Episode numbers must be unique within %s.", directory);
end

stateCells = cell(numel(files), 1);
rawCells = cell(numel(files), 1);
effectiveCells = cell(numel(files), 1);
pwmCells = cell(numel(files), 1);
qAfterCells = cell(numel(files), 1);
safetyCells = cell(numel(files), 1);
metadataCells = cell(numel(files), 1);
inventoryRows = repmat(struct("source", "", "episode", 0, ...
    "filePath", "", "stepCount", 0), numel(files), 1);
alignmentRows = repmat(struct("source", "", "episode", 0, ...
    "referenceMaximumError", 0, "nextStateMaximumError", 0, ...
    "provenancePositionMaximumError", 0, ...
    "provenanceVelocityMaximumError", 0, ...
    "effectiveActionMaximumError", 0, "pwmMismatchCount", 0), ...
    numel(files), 1);

for fileIdx = 1:numel(files)
    path = string(fullfile(files(fileIdx).folder, files(fileIdx).name));
    fields = ["stateLog", "actionLog", "actionSatLog", ...
        "actionPwmLog", "trackingPredictionHistory", ...
        "referenceHistory", "positionSafetyInterventionLog", ...
        "intentProvenanceLog", "referenceSource", ...
        "observationVariant", "stateLength", ...
        "simulationPositionSafety"];
    available = string(who("-file", path));
    if ~all(ismember(fields, available))
        error("loadNoGloveStage7pInterfaceCorpus:MissingField", ...
            "Episode %s is missing required fields.", path);
    end
    data = load(path, fields{:});
    validateEpisodeContract(data, path, layout.totalLength);
    state = double(data.stateLog);
    action = double(data.actionLog);
    effectiveValue = double(data.actionSatLog);
    pwmValue = double(data.actionPwmLog);
    after = double(data.trackingPredictionHistory);
    reference = double(data.referenceHistory);
    safetyValue = double(data.positionSafetyInterventionLog);
    count = size(state, 1);
    matrices = {action, effectiveValue, pwmValue, after, reference, ...
        safetyValue};
    if size(state, 2) ~= layout.totalLength || count == 0 || ...
            any(cellfun(@(value) ~isequal(size(value), [count, 4]), ...
                matrices)) || any(~isfinite([state(:); action(:); ...
                effectiveValue(:); pwmValue(:); after(:); ...
                reference(:); safetyValue(:)])) || ...
            any(safetyValue < 0 | fix(safetyValue) ~= safetyValue, "all")
        error("loadNoGloveStage7pInterfaceCorpus:InvalidArrays", ...
            "Episode %s has invalid or misaligned arrays.", path);
    end

    qBefore = state(:, layout.encoder);
    qReference = state(:, layout.referencePosition);
    vReference = state(:, layout.referenceVelocity);
    referenceError = max(abs(reference-qReference), [], "all");
    nextError = 0;
    if count > 1
        nextError = max(abs(after(1:end-1, :) - ...
            qBefore(2:end, :)), [], "all");
    end
    if referenceError > options.replayTolerance || ...
            nextError > options.replayTolerance
        error("loadNoGloveStage7pInterfaceCorpus:TemporalAlignment", ...
            "Episode %s violates state/action temporal alignment.", path);
    end

    replayEffective = zeros(count, 4);
    replayPwm = zeros(count, 4);
    for rowIdx = 1:count
        [e, p] = quantizeBaselineAction(action(rowIdx, :), ...
            actuator.maxPwm, actuator.activationThreshold, ...
            actuator.commandLevels);
        replayEffective(rowIdx, :) = double(e(:))';
        replayPwm(rowIdx, :) = double(p(:))';
    end
    effectiveError = max(abs(replayEffective-effectiveValue), [], "all");
    pwmMismatch = sum(replayPwm ~= pwmValue, "all");
    if effectiveError > options.replayTolerance || pwmMismatch ~= 0
        error("loadNoGloveStage7pInterfaceCorpus:QuantizationReplay", ...
            "Episode %s does not replay baselineQuantized.", path);
    end

    [gateContext, gateActive, isRest, countdown, activity, ...
        sourceTransitionStep, zeroReason, provenanceErrors] = ...
        replayProvenance(data.intentProvenanceLog, qReference, ...
        vReference, path, options.replayTolerance);
    activeMotorCount = sum(abs(vReference) >= ...
        options.referenceVelocityThreshold, 2);
    partialMotorReference = gateActive & activeMotorCount > 0 & ...
        activeMotorCount < 4;
    rowId = source + ":" + compose("%05d", numbers(fileIdx)) + ...
        ":" + compose("%03d", (1:count)');
    metadataCells{fileIdx} = table(rowId, ...
        repmat(source, count, 1), ...
        repmat(numbers(fileIdx), count, 1), (1:count)', ...
        gateContext, gateActive, isRest, countdown, activity, ...
        sourceTransitionStep, zeroReason, activeMotorCount, ...
        partialMotorReference, ...
        'VariableNames', ["rowId", "source", "episode", "step", ...
        "gateContext", "gateActive", "isRest", ...
        "lowActivityCountdown", "activity", ...
        "sourceTransitionStep", "zeroReferenceReason", ...
        "activeMotorCount", "partialMotorReference"]);

    stateCells{fileIdx} = state;
    rawCells{fileIdx} = action;
    effectiveCells{fileIdx} = effectiveValue;
    pwmCells{fileIdx} = pwmValue;
    qAfterCells{fileIdx} = after;
    safetyCells{fileIdx} = safetyValue;
    inventoryRows(fileIdx) = struct("source", source, ...
        "episode", numbers(fileIdx), "filePath", path, ...
        "stepCount", count);
    alignmentRows(fileIdx) = struct("source", source, ...
        "episode", numbers(fileIdx), ...
        "referenceMaximumError", referenceError, ...
        "nextStateMaximumError", nextError, ...
        "provenancePositionMaximumError", ...
            provenanceErrors.position, ...
        "provenanceVelocityMaximumError", ...
            provenanceErrors.velocity, ...
        "effectiveActionMaximumError", effectiveError, ...
        "pwmMismatchCount", pwmMismatch);
end

states = vertcat(stateCells{:});
raw = vertcat(rawCells{:});
effective = vertcat(effectiveCells{:});
pwm = vertcat(pwmCells{:});
qAfter = vertcat(qAfterCells{:});
safety = vertcat(safetyCells{:});
metadata = vertcat(metadataCells{:});
inventory = struct2table(inventoryRows);
alignment = struct2table(alignmentRows);
end

function validateEpisodeContract(data, path, expectedStateLength)
if string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= expectedStateLength || ...
        ~isstruct(data.simulationPositionSafety) || ...
        ~logical(data.simulationPositionSafety.enabled) || ...
        ~iscell(data.intentProvenanceLog) || ...
        numel(data.intentProvenanceLog) ~= size(data.stateLog, 1)
    error("loadNoGloveStage7pInterfaceCorpus:EpisodeContract", ...
        "Episode %s violates the frozen state-60 contract.", path);
end
end

function [context, gateActive, isRest, countdown, activity, ...
        sourceStep, zeroReason, errors] = replayProvenance( ...
        provenance, qReference, vReference, path, tolerance)
count = size(qReference, 1);
context = repmat("initialRest", count, 1);
gateActive = false(count, 1);
isRest = true(count, 1);
countdown = false(count, 1);
activity = nan(count, 1);
sourceStep = zeros(count, 1);
zeroReason = repmat("resetInitial", count, 1);
positionErrors = zeros(max(0, count-1), 1);
velocityErrors = zeros(max(0, count-1), 1);
required = ["schemaVersion", "transitionStep", "activity", ...
    "gateActive", "isRest", "lowActivityCountdown", ...
    "referencePositionAfter", "referenceVelocityAfter", ...
    "zeroReferenceReason"];
for stateIdx = 2:count
    item = provenance{stateIdx-1};
    if ~isstruct(item) || ~isscalar(item) || ...
            ~all(isfield(item, cellstr(required))) || ...
            double(item.schemaVersion) ~= 1 || ...
            double(item.transitionStep) ~= stateIdx-1
        error("loadNoGloveStage7pInterfaceCorpus:ProvenanceContract", ...
            "Episode %s has invalid provenance before state %d.", ...
            path, stateIdx);
    end
    positionErrors(stateIdx-1) = max(abs( ...
        double(item.referencePositionAfter(:))' - ...
        qReference(stateIdx, :)));
    velocityErrors(stateIdx-1) = max(abs( ...
        double(item.referenceVelocityAfter(:))' - ...
        vReference(stateIdx, :)));
    gateActive(stateIdx) = logical(item.gateActive);
    isRest(stateIdx) = logical(item.isRest);
    countdown(stateIdx) = logical(item.lowActivityCountdown);
    activity(stateIdx) = double(item.activity);
    sourceStep(stateIdx) = double(item.transitionStep);
    zeroReason(stateIdx) = string(item.zeroReferenceReason);
    if countdown(stateIdx)
        context(stateIdx) = "lowActivityCountdown";
    elseif isRest(stateIdx)
        context(stateIdx) = "declaredRest";
    elseif gateActive(stateIdx)
        context(stateIdx) = "gateActive";
    else
        error("loadNoGloveStage7pInterfaceCorpus:GateState", ...
            "Episode %s state %d has an impossible gate state.", ...
            path, stateIdx);
    end
end
errors = struct("position", max([0; positionErrors]), ...
    "velocity", max([0; velocityErrors]));
if errors.position > tolerance || errors.velocity > tolerance
    error("loadNoGloveStage7pInterfaceCorpus:ProvenanceAlignment", ...
        "Episode %s provenance is not aligned to state_t.", path);
end
end

function episode = parseEpisode(name)
token = regexp(name, '^episode(\d+)\.mat$', 'tokens', 'once');
if isempty(token)
    error("loadNoGloveStage7pInterfaceCorpus:EpisodeName", ...
        "Unexpected episode file %s.", name);
end
episode = str2double(token{1});
end
