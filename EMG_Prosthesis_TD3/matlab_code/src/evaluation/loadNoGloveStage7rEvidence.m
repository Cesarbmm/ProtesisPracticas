function data = loadNoGloveStage7rEvidence( ...
        stage7qRunRoot, stage7pRunRoot, stage7nRunRoot)
%loadNoGloveStage7rEvidence validates frozen 7Q states and actor outputs.

arguments
    stage7qRunRoot (1, 1) string
    stage7pRunRoot (1, 1) string
    stage7nRunRoot (1, 1) string
end

manifestPath = fullfile(stage7qRunRoot, "manifest.json");
resultsPath = fullfile(stage7qRunRoot, "stage7q_results.mat");
if ~isfile(manifestPath) || ~isfile(resultsPath)
    error("loadNoGloveStage7rEvidence:MissingParent", ...
        "Canonical ETAPA 7Q artifacts are missing.");
end
expectedManifestHash = ...
    "4ECA54839AC8CF60A48B5F6E13ABDEB386BEDA9A851C7421EE782F50D6EDF57F";
expectedResultsHash = ...
    "D7F63CA60A8F4556DED3ECF9669D15B3C5E01886F1D34A40A778C5BDEDECF56F";
actualManifestHash = localFileSha256(manifestPath);
actualResultsHash = localFileSha256(resultsPath);
manifest = jsondecode(fileread(manifestPath));
validManifest = actualManifestHash == expectedManifestHash && ...
    actualResultsHash == expectedResultsHash && ...
    string(manifest.stage) == "7Q" && ...
    string(manifest.result) == "PASS" && ...
    string(manifest.scientificResult) == "distributedOrUnresolved" && ...
    string(manifest.stateDecision) == "intentMarkov60" && ...
    string(manifest.state62Disposition) == "provisionallyRejected" && ...
    double(manifest.primaryComponentCount) == 2064 && ...
    ~logical(manifest.hardwareUsed) && ~logical(manifest.trainingUsed) && ...
    ~logical(manifest.simulationUsed) && ...
    ~logical(manifest.stateCounterfactualUsed);
if ~validManifest
    error("loadNoGloveStage7rEvidence:ParentChanged", ...
        "ETAPA 7Q does not match the preregistered parent.");
end

parent = load(resultsPath, "sharedEvaluations", "analysis", "manifest");
if ~all(isfield(parent, cellstr( ...
        ["sharedEvaluations", "analysis", "manifest"]))) || ...
        string(parent.analysis.scientificResult) ~= ...
            "distributedOrUnresolved" || ...
        parent.analysis.primaryComponentCount ~= 2064 || ...
        parent.analysis.stateCounterfactualUsed || ...
        ~isequal(sort([parent.sharedEvaluations.episode]), ...
            [50, 100, 150, 200])
    error("loadNoGloveStage7rEvidence:InvalidResults", ...
        "ETAPA 7Q MAT evidence violates its frozen contract.");
end

checkpointData = loadNoGloveStage7qCheckpointSet( ...
    stage7pRunRoot, stage7nRunRoot);
states = checkpointData.primaryCorpus.states;
for idx = 1:numel(parent.sharedEvaluations)
    evaluation = parent.sharedEvaluations(idx);
    if ~isequal(size(evaluation.raw), [size(states, 1), 4]) || ...
            ~isequal(size(evaluation.effective), [size(states, 1), 4]) || ...
            ~isequal(size(evaluation.pwm), [size(states, 1), 4]) || ...
            any(~isfinite([evaluation.raw(:); ...
            evaluation.effective(:); evaluation.pwm(:)]))
        error("loadNoGloveStage7rEvidence:ActionAlignment", ...
            "A frozen checkpoint output is nonfinite or misaligned.");
    end
end
agent200Idx = find([parent.sharedEvaluations.episode] == 200, 1);
agent200 = parent.sharedEvaluations(agent200Idx);
if max(abs(agent200.raw-checkpointData.primaryCorpus.rawAction), ...
        [], "all") > 1e-5 || ...
        any(agent200.pwm ~= checkpointData.primaryCorpus.pwm, "all")
    error("loadNoGloveStage7rEvidence:Agent200Replay", ...
        "Frozen ETAPA 7Q Agent200 outputs no longer replay ETAPA 7P.");
end

data = checkpointData;
data.stage7q = struct("runRoot", stage7qRunRoot, ...
    "manifestSha256", actualManifestHash, ...
    "resultsSha256", actualResultsHash, ...
    "manifest", manifest, "validated", true);
data.sharedEvaluations = parent.sharedEvaluations;
data.stage7qAnalysis = parent.analysis;
data.agentCheckpointsLoaded = false;
data.state62Loaded = false;
data.agent7250Loaded = false;
end

function hash = localFileSha256(filePath)
escaped = strrep(char(filePath), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("loadNoGloveStage7rEvidence:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = string(strtrim(output));
end
