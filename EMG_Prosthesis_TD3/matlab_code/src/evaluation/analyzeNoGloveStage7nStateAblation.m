function analysis = analyzeNoGloveStage7nStateAblation( ...
        checkpointSummary, runAudit, options)
%analyzeNoGloveStage7nStateAblation applies the pre-registered 7N gate.

arguments
    checkpointSummary table
    runAudit (1, 1) struct
    options.maximumRatio (1, 1) double {mustBePositive} = 1.05
    options.maximumDeltaActionL2 (1, 1) double ...
        {mustBeNonnegative} = 0.257108
    options.maximumSaturation (1, 1) double ...
        {mustBeInRange(options.maximumSaturation, 0, 1)} = 0.196043
    options.maximumRestSaturation (1, 1) double ...
        {mustBeInRange(options.maximumRestSaturation, 0, 1)} = 0
    options.maximumRestWindowCommandFraction (1, 1) double ...
        {mustBeInRange(options.maximumRestWindowCommandFraction, 0, 1)} = 0.01
    options.maximumRestFalseActivation (1, 1) double ...
        {mustBeInRange(options.maximumRestFalseActivation, 0, 1)} = 0.01
    options.tolerance (1, 1) double {mustBeNonnegative} = 1e-12
end

requiredColumns = ["variant", "episode", "acceptanceAllFinite", ...
    "restAllFinite", "acceptancePositionViolations", ...
    "restPositionViolations", "trackingMse", "trackingMae", ...
    "actionL2", "deltaActionL2", "saturationFraction", ...
    "restWindowAnyCommandFraction", "restSaturationFraction", ...
    "restFalseActivationFraction", "motor2FunctionalFlagCount", ...
    "otherMotorFunctionalFlagCount", ...
    "acceptanceSafetyInterventions", "restSafetyInterventions", ...
    "declaredRestReplayMismatchCount", ...
    "holdLatchReplayMismatchCount", "farStartedLatchCount", ...
    "prematureHoldLatchCount"];
if ~all(ismember(requiredColumns, string(checkpointSummary.Properties.VariableNames)))
    error("analyzeNoGloveStage7nStateAblation:MissingColumn", ...
        "Checkpoint summary does not satisfy the ETAPA 7N contract.");
end
requiredAudit = ["trainingEpisodeCountControl", ...
    "trainingEpisodeCountCandidate", "checkpointCountControl", ...
    "checkpointCountCandidate", "allCheckpointsEvaluated", ...
    "freshPolicies", "historicalAgentLoaded", "hardwareUsed", ...
    "trainingAllFinite", "trainingPositionViolationCountControl", ...
    "trainingPositionViolationCountCandidate", ...
    "trainingSafetyInterventionCountControl", ...
    "trainingSafetyInterventionCountCandidate", ...
    "initializationReproducible", "profileMatched", ...
    "datasetContentsMatched"];
if ~all(isfield(runAudit, cellstr(requiredAudit)))
    error("analyzeNoGloveStage7nStateAblation:MissingAudit", ...
        "Run audit is incomplete.");
end

expectedEpisodes = [50; 100; 150; 200];
controlRows = sortrows(checkpointSummary( ...
    checkpointSummary.variant == "control60", :), "episode");
candidateRows = sortrows(checkpointSummary( ...
    checkpointSummary.variant == "candidate62", :), "episode");
coverage = height(controlRows) == 4 && height(candidateRows) == 4 && ...
    isequal(controlRows.episode, expectedEpisodes) && ...
    isequal(candidateRows.episode, expectedEpisodes);
if ~coverage
    error("analyzeNoGloveStage7nStateAblation:CheckpointCoverage", ...
        "Expected checkpoints 50/100/150/200 for both variants.");
end
control = controlRows(controlRows.episode == 200, :);
candidate = candidateRows(candidateRows.episode == 200, :);
tol = options.tolerance;

trackingRatio = safeRatio(candidate.trackingMse, control.trackingMse);
actionRatio = safeRatio(candidate.actionL2, control.actionL2);
deltaRatio = safeRatio(candidate.deltaActionL2, control.deltaActionL2);
saturationRatio = safeRatio(candidate.saturationFraction, ...
    control.saturationFraction);
candidateSafety = runAudit.trainingSafetyInterventionCountCandidate + ...
    candidate.acceptanceSafetyInterventions + ...
    candidate.restSafetyInterventions;
controlSafety = runAudit.trainingSafetyInterventionCountControl + ...
    control.acceptanceSafetyInterventions + ...
    control.restSafetyInterventions;

checks = struct( ...
    "executionContract", coverage && runAudit.allCheckpointsEvaluated && ...
        runAudit.trainingEpisodeCountControl == 200 && ...
        runAudit.trainingEpisodeCountCandidate == 200 && ...
        runAudit.checkpointCountControl == 4 && ...
        runAudit.checkpointCountCandidate == 4 && ...
        runAudit.freshPolicies && ~runAudit.historicalAgentLoaded && ...
        ~runAudit.hardwareUsed && runAudit.initializationReproducible && ...
        runAudit.profileMatched && runAudit.datasetContentsMatched, ...
    "finite", runAudit.trainingAllFinite && ...
        all(controlRows.acceptanceAllFinite) && ...
        all(controlRows.restAllFinite) && ...
        all(candidateRows.acceptanceAllFinite) && ...
        all(candidateRows.restAllFinite), ...
    "positionLimits", ...
        runAudit.trainingPositionViolationCountControl == 0 && ...
        runAudit.trainingPositionViolationCountCandidate == 0 && ...
        all(controlRows.acceptancePositionViolations == 0) && ...
        all(controlRows.restPositionViolations == 0) && ...
        all(candidateRows.acceptancePositionViolations == 0) && ...
        all(candidateRows.restPositionViolations == 0), ...
    "state62CausalReplay", ...
        all(candidateRows.declaredRestReplayMismatchCount == 0) && ...
        all(candidateRows.holdLatchReplayMismatchCount == 0), ...
    "state62FarStarted", ...
        all(candidateRows.farStartedLatchCount == 0) && ...
        all(candidateRows.prematureHoldLatchCount == 0), ...
    "trackingNoninferiority", trackingRatio <= options.maximumRatio+tol, ...
    "actionL2Noninferiority", actionRatio <= options.maximumRatio+tol, ...
    "deltaActionNoninferiority", deltaRatio <= options.maximumRatio+tol, ...
    "deltaActionAbsolute", candidate.deltaActionL2 <= ...
        options.maximumDeltaActionL2+tol, ...
    "saturationNoninferiority", saturationRatio <= ...
        options.maximumRatio+tol, ...
    "saturationAbsolute", candidate.saturationFraction <= ...
        options.maximumSaturation+tol, ...
    "restSaturation", candidate.restSaturationFraction <= ...
        options.maximumRestSaturation+tol, ...
    "restWindowCommands", candidate.restWindowAnyCommandFraction <= ...
        options.maximumRestWindowCommandFraction+tol, ...
    "restFalseActivation", candidate.restFalseActivationFraction <= ...
        options.maximumRestFalseActivation+tol, ...
    "motor2Functional", candidate.motor2FunctionalFlagCount == 0, ...
    "otherMotorsFunctional", candidate.otherMotorFunctionalFlagCount == 0, ...
    "safetyInterventionsNotWorse", candidateSafety <= controlSafety);
gatePassed = all(struct2array(checks));
classification = classifyChecks(checks, gatePassed);
names = string(fieldnames(checks));
passed = cellfun(@(name) logical(checks.(name)), cellstr(names));
gateChecks = table(names, passed, ...
    'VariableNames', ["check", "passed"]);

perCheckpoint = table(expectedEpisodes, ...
    safeRatios(candidateRows.trackingMse, controlRows.trackingMse), ...
    safeRatios(candidateRows.actionL2, controlRows.actionL2), ...
    safeRatios(candidateRows.deltaActionL2, controlRows.deltaActionL2), ...
    safeRatios(candidateRows.saturationFraction, ...
        controlRows.saturationFraction), ...
    'VariableNames', ["episode", "trackingMseRatio", "actionL2Ratio", ...
    "deltaActionL2Ratio", "saturationRatio"]);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7N", ...
    "primaryCheckpointEpisode", 200, ...
    "gatePassed", gatePassed, "classification", classification, ...
    "checks", checks, "gateChecks", gateChecks, ...
    "checkpointSummary", checkpointSummary, ...
    "perCheckpointComparison", perCheckpoint, ...
    "primaryComparison", struct( ...
        "trackingMseRatio", trackingRatio, ...
        "actionL2Ratio", actionRatio, ...
        "deltaActionL2Ratio", deltaRatio, ...
        "saturationRatio", saturationRatio, ...
        "controlSafetyInterventions", controlSafety, ...
        "candidateSafetyInterventions", candidateSafety), ...
    "thresholds", struct( ...
        "maximumRatio", options.maximumRatio, ...
        "maximumDeltaActionL2", options.maximumDeltaActionL2, ...
        "maximumSaturation", options.maximumSaturation, ...
        "maximumRestSaturation", options.maximumRestSaturation, ...
        "maximumRestWindowCommandFraction", ...
            options.maximumRestWindowCommandFraction, ...
        "maximumRestFalseActivation", ...
            options.maximumRestFalseActivation), ...
    "rootCauseIdentified", false, "pilotAuthorized", false, ...
    "longCampaignAuthorized", false, "dtwCalculated", false, ...
    "hardwareUsed", false);
end

function ratios = safeRatios(numerator, denominator)
ratios = zeros(size(numerator));
for idx = 1:numel(numerator)
    ratios(idx) = safeRatio(numerator(idx), denominator(idx));
end
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    if numerator == 0
        value = 1;
    else
        value = Inf;
    end
else
    value = numerator/denominator;
end
end

function classification = classifyChecks(checks, gatePassed)
if gatePassed
    classification = "state62BehavioralSmokeSupported";
elseif ~checks.executionContract
    classification = "executionInvalid";
elseif ~checks.finite || ~checks.positionLimits
    classification = "safetyOrFiniteFailure";
elseif ~checks.state62CausalReplay || ~checks.state62FarStarted
    classification = "state62SemanticFailure";
elseif ~checks.trackingNoninferiority
    classification = "trackingNoninferiorityFailed";
elseif ~checks.actionL2Noninferiority || ...
        ~checks.deltaActionNoninferiority || ...
        ~checks.deltaActionAbsolute || ...
        ~checks.saturationNoninferiority || ...
        ~checks.saturationAbsolute || ...
        ~checks.safetyInterventionsNotWorse
    classification = "actionRegularityGateFailed";
elseif ~checks.restSaturation || ~checks.restWindowCommands || ...
        ~checks.restFalseActivation
    classification = "restGateFailed";
elseif ~checks.motor2Functional || ~checks.otherMotorsFunctional
    classification = "functionalGateFailed";
else
    classification = "state62SmokeUnresolved";
end
end
