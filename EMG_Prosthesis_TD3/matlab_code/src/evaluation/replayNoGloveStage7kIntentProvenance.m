function analysis = replayNoGloveStage7kIntentProvenance( ...
        episodeAudit, windows, latchAudit, profiles, options)
%replayNoGloveStage7kIntentProvenance attributes frozen zero-v_ref states.

arguments
    episodeAudit table
    windows table
    latchAudit table
    profiles (1, 1) struct
    options.replayTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.zeroVelocityTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.farCorrectionMse (1, 1) double ...
        {mustBePositive} = 2.5e-3
    options.expectedEpisodeCount (1, 1) double ...
        {mustBePositive, mustBeInteger} = 548
    options.expectedWindowCount (1, 1) double ...
        {mustBePositive, mustBeInteger} = 31220
end

validateInputs(episodeAudit, windows, latchAudit, profiles, options);
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
decisionParts = cell(height(episodeAudit), 1);
transitionParts = cell(height(episodeAudit), 1);
episodeParts = cell(height(episodeAudit), 1);
for episodeIdx = 1:height(episodeAudit)
    variant = string(episodeAudit.variant(episodeIdx));
    source = string(episodeAudit.source(episodeIdx));
    episode = double(episodeAudit.episode(episodeIdx));
    repetitionId = double(episodeAudit.repetitionId(episodeIdx));
    path = string(episodeAudit.episodePath(episodeIdx));
    profile = profiles.(char(variant));
    [decisionParts{episodeIdx}, transitionParts{episodeIdx}, ...
        episodeParts{episodeIdx}] = replayEpisode(path, variant, source, ...
        episode, repetitionId, windows, latchAudit, profile, layout, ...
        options);
end
decisionAudit = vertcat(decisionParts{:});
transitionAudit = vertcat(transitionParts{:});
episodeReplayAudit = vertcat(episodeParts{:});
provenanceSummary = buildProvenanceSummary(decisionAudit);
segmentProvenanceAudit = buildSegmentProvenance(decisionAudit);

maximumPositionReplayError = max( ...
    episodeReplayAudit.maximumPositionReplayError);
maximumVelocityReplayError = max( ...
    episodeReplayAudit.maximumVelocityReplayError);
maximumReferenceHistoryError = max( ...
    episodeReplayAudit.maximumReferenceHistoryError);
finalGateMismatchCount = sum(~episodeReplayAudit.finalGateStateMatches);
checksumMismatchCount = sum(~episodeReplayAudit.calibrationChecksumMatches);
alignmentMismatchCount = sum( ...
    episodeReplayAudit.shiftedAlignmentMismatchCount);
stopped = decisionAudit.stopped;
stoppedCount = sum(stopped);
labeledStopped = stopped & decisionAudit.provenance ~= "" & ...
    decisionAudit.provenance ~= "movingReference";
stoppedLabelCoverage = sum(labeledStopped)/stoppedCount;
unresolvedCount = sum(stopped & ...
    decisionAudit.provenance == "unresolvedActiveZero");
fullyRestExplained = all(ismember(decisionAudit.provenance(stopped), ...
    ["episodeInitialization", "decoderRest"]));
integrity = maximumPositionReplayError <= options.replayTolerance && ...
    maximumVelocityReplayError <= options.replayTolerance && ...
    maximumReferenceHistoryError <= options.replayTolerance && ...
    finalGateMismatchCount == 0 && checksumMismatchCount == 0 && ...
    alignmentMismatchCount == 0 && ...
    height(decisionAudit) == options.expectedWindowCount && ...
    height(episodeReplayAudit) == options.expectedEpisodeCount;
if ~integrity || stoppedLabelCoverage ~= 1
    classification = "intentProvenanceReplayInvalid";
elseif unresolvedCount > 0
    classification = "zeroReferenceProvenanceUnresolved";
elseif fullyRestExplained
    classification = "zeroReferenceFullyExplainedByRestGate";
else
    classification = "zeroReferenceMixedCausalMechanisms";
end
gateChecks = table( ...
    ["episodeCount"; "decisionWindowCount"; ...
    "positionReplayError"; "velocityReplayError"; ...
    "referenceHistoryError"; "finalGateMismatchCount"; ...
    "calibrationChecksumMismatchCount"; ...
    "shiftedAlignmentMismatchCount"; "stoppedLabelCoverage"; ...
    "unresolvedActiveZeroCount"], ...
    [height(episodeReplayAudit); height(decisionAudit); ...
    maximumPositionReplayError; maximumVelocityReplayError; ...
    maximumReferenceHistoryError; finalGateMismatchCount; ...
    checksumMismatchCount; alignmentMismatchCount; ...
    stoppedLabelCoverage; unresolvedCount], ...
    [options.expectedEpisodeCount; options.expectedWindowCount; ...
    options.replayTolerance; options.replayTolerance; ...
    options.replayTolerance; 0; 0; 0; 1; 0], ...
    ["equal"; "equal"; "lessOrEqual"; "lessOrEqual"; ...
    "lessOrEqual"; "equal"; "equal"; "equal"; "equal"; "equal"], ...
    [height(episodeReplayAudit) == options.expectedEpisodeCount; ...
    height(decisionAudit) == options.expectedWindowCount; ...
    maximumPositionReplayError <= options.replayTolerance; ...
    maximumVelocityReplayError <= options.replayTolerance; ...
    maximumReferenceHistoryError <= options.replayTolerance; ...
    finalGateMismatchCount == 0; checksumMismatchCount == 0; ...
    alignmentMismatchCount == 0; stoppedLabelCoverage == 1; ...
    unresolvedCount == 0], ...
    'VariableNames', ["check", "observed", "threshold", ...
    "comparison", "passed"]);
sourceDecision = table(classification, all(gateChecks.passed), ...
    stoppedCount, stoppedLabelCoverage, unresolvedCount, ...
    fullyRestExplained, sum(decisionAudit.recoveredByMemory), ...
    sum(decisionAudit.latchedFarCorrection), ...
    sum(decisionAudit.latchedFarCorrection & ...
        decisionAudit.segmentFarStarted), ...
    sum(decisionAudit.latchedFarCorrection & ...
        ~decisionAudit.segmentFarStarted), ...
    all(~episodeReplayAudit.directProvenanceLogPresent), true, true, ...
    false, false, ...
    'VariableNames', ["classification", "replayGatePassed", ...
    "stoppedWindowCount", "stoppedLabelCoverage", ...
    "unresolvedActiveZeroCount", "fullyRestGateExplained", ...
    "recoveredMemoryWindowCount", "latchedFarWindowCount", ...
    "latchedFarFromFarStartedSegmentCount", ...
    "latchedFarFromNearStartedSegmentCount", ...
    "directPerStepLabelAbsentInFrozenInputs", ...
    "offlineReconstructionAvailable", "futureDirectLoggingRequired", ...
    "latchContractReauthorized", "rootCauseIdentified"]);

analysis = struct("schemaVersion", 1, "stage", "7K", ...
    "decisionAudit", decisionAudit, ...
    "transitionAudit", transitionAudit, ...
    "episodeReplayAudit", episodeReplayAudit, ...
    "provenanceSummary", provenanceSummary, ...
    "segmentProvenanceAudit", segmentProvenanceAudit, ...
    "gateChecks", gateChecks, "sourceDecision", sourceDecision, ...
    "classification", classification, ...
    "replayGatePassed", all(gateChecks.passed), ...
    "thresholds", struct("replayTolerance", options.replayTolerance, ...
        "zeroVelocityTolerance", options.zeroVelocityTolerance, ...
        "farCorrectionMse", options.farCorrectionMse), ...
    "directPerStepLabelAbsentInFrozenInputs", ...
        all(~episodeReplayAudit.directProvenanceLogPresent), ...
    "futureDirectLoggingRequired", true, ...
    "loggingInstrumentationImplemented", true, ...
    "loggingAffectsObservation", false, ...
    "loggingAffectsReward", false, ...
    "latchContractReauthorized", false, ...
    "behavioralInterventionExecuted", false, ...
    "rootCauseIdentified", false, "policyChanged", false, ...
    "stateChanged", false, "rewardChanged", false, ...
    "referenceChanged", false, "quantizationChanged", false, ...
    "simulatorChanged", false, "safetyLayerChanged", false, ...
    "runTraining", false, "agentLoaded", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false);
end

function validateInputs(episodeAudit, windows, latchAudit, profiles, options)
episodeRequired = ["variant", "source", "episode", "repetitionId", ...
    "episodePath"];
windowRequired = ["variant", "source", "episode", "repetitionId", ...
    "step", "windowIndex", "holdPositionMse", "stopped"];
latchRequired = ["variant", "source", "episode", "repetitionId", ...
    "step", "windowIndex", "latchActive", "recoveredByMemory", ...
    "stoppedSegmentId", "segmentFarStarted"];
if height(episodeAudit) ~= options.expectedEpisodeCount || ...
        height(windows) ~= options.expectedWindowCount || ...
        height(latchAudit) ~= options.expectedWindowCount
    error("replayNoGloveStage7kIntentProvenance:InvalidInput", ...
        "Episode/window dimensions do not match the declared fixture.");
end
if ~all(ismember(episodeRequired, ...
        string(episodeAudit.Properties.VariableNames))) || ...
        ~all(ismember(windowRequired, ...
        string(windows.Properties.VariableNames))) || ...
        ~all(ismember(latchRequired, ...
        string(latchAudit.Properties.VariableNames)))
    error("replayNoGloveStage7kIntentProvenance:InvalidInput", ...
        "Frozen 7I/7J table schemas are incomplete.");
end
if ~isfield(profiles, "control") || ~isfield(profiles, "candidate")
    error("replayNoGloveStage7kIntentProvenance:InvalidInput", ...
        "Control and candidate profiles are required.");
end
windowKeys = rowKeys(windows);
latchKeys = rowKeys(latchAudit);
if ~isequal(windowKeys, latchKeys)
    error("replayNoGloveStage7kIntentProvenance:KeyMismatch", ...
        "7I windows and 7J latch rows do not align exactly.");
end
end

function [decisionAudit, transitionAudit, episodeAudit] = replayEpisode( ...
        path, variant, source, episode, repetitionId, windows, latchAudit, ...
        profile, layout, options)
required = ["stateLog", "emgLog", "referenceHistory", ...
    "referenceHistoryCount", "intentTarget", "intentVelocity", ...
    "intentGateState", "intentCalibrationContentSha256", ...
    "referenceSource", "observationVariant", "stateLength", ...
    "repetitionId"];
available = string(who("-file", path));
if ~all(ismember(required, available))
    error("replayNoGloveStage7kIntentProvenance:EpisodeContract", ...
        "Episode %s lacks frozen intent replay fields.", path);
end
directLogPresent = ismember("intentProvenanceLog", available);
requiredCell = cellstr(required);
data = load(path, requiredCell{:});
state = double(data.stateLog);
stepCount = size(state, 1);
if string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= 60 || ...
        double(data.repetitionId) ~= repetitionId || ...
        ~iscell(data.emgLog) || numel(data.emgLog) ~= stepCount || ...
        double(data.referenceHistoryCount) ~= stepCount || ...
        size(data.referenceHistory, 1) ~= stepCount
    error("replayNoGloveStage7kIntentProvenance:EpisodeContract", ...
        "Episode %s violates the frozen timing contract.", path);
end
rows = windows.variant == variant & windows.source == source & ...
    windows.episode == episode;
latchRows = latchAudit.variant == variant & ...
    latchAudit.source == source & latchAudit.episode == episode;
episodeWindows = windows(rows, :);
episodeLatch = latchAudit(latchRows, :);
[~, windowOrder] = sort(episodeWindows.step);
[~, latchOrder] = sort(episodeLatch.step);
episodeWindows = episodeWindows(windowOrder, :);
episodeLatch = episodeLatch(latchOrder, :);
if height(episodeWindows) ~= stepCount || ...
        height(episodeLatch) ~= stepCount || ...
        ~isequal(rowKeys(episodeWindows), rowKeys(episodeLatch))
    error("replayNoGloveStage7kIntentProvenance:EpisodeRows", ...
        "Episode %s does not align with 7I/7J rows.", path);
end

calibration = profile.intentCalibration;
expected = profile.intentExpectedContext;
checksumMatches = string(data.intentCalibrationContentSha256) == ...
    string(calibration.contentSha256);
qState = state(:, layout.referencePosition);
vState = state(:, layout.referenceVelocity);
historyError = max(abs(double(data.referenceHistory)-qState), [], "all");
qCurrent = qState(1, :);
vCurrent = vState(1, :);
if max(abs(vCurrent)) > options.zeroVelocityTolerance
    error("replayNoGloveStage7kIntentProvenance:InitialVelocity", ...
        "Episode %s does not start at zero v_ref.", path);
end
gateState = struct("isActive", false, "onCount", 0, "offCount", 0);

provenance = strings(stepCount, 1);
transitionStepForDecision = zeros(stepCount, 1);
activity = nan(stepCount, 1);
gateActive = false(stepCount, 1);
isRest = false(stepCount, 1);
countdown = false(stepCount, 1);
desiredMaxAbs = nan(stepCount, 1);
positionLimitedAny = false(stepCount, 1);
rateLimitedAny = false(stepCount, 1);
provenance(1) = "episodeInitialization";
isRest(1) = true;

transitionReason = strings(stepCount, 1);
transitionActivity = zeros(stepCount, 1);
transitionGateActive = false(stepCount, 1);
transitionRest = false(stepCount, 1);
transitionCountdown = false(stepCount, 1);
transitionDesired = zeros(stepCount, 1);
transitionOutputVelocity = zeros(stepCount, 1);
transitionPositionLimited = false(stepCount, 1);
transitionRateLimited = false(stepCount, 1);
nextStateAvailable = false(stepCount, 1);
outputDecisionStep = nan(stepCount, 1);
positionError = zeros(stepCount, 1);
velocityError = zeros(stepCount, 1);
unshiftedPositionError = zeros(stepCount, 1);
unshiftedVelocityError = zeros(stepCount, 1);

for transitionIdx = 1:stepCount
    emg = double(data.emgLog{transitionIdx});
    [desiredVelocity, ~, nextGateState, details] = ...
        mapEmgToIntentVelocity(emg, calibration, expected, gateState);
    if size(desiredVelocity, 1) ~= 1 || ...
            details.discardedSampleCount ~= 0
        error("replayNoGloveStage7kIntentProvenance:EmgAlignment", ...
            "Episode %s transition %d is not one causal window.", ...
            path, transitionIdx);
    end
    [qNext, vNext, ~, referenceDiagnostics] = ...
        updateIntentReference(qCurrent, desiredVelocity, calibration, ...
            details.isRest, vCurrent);
    reason = classifyIntentZeroReferenceReason( ...
        vNext(end, :), desiredVelocity(end, :), details, ...
        referenceDiagnostics, options.zeroVelocityTolerance);
    transitionReason(transitionIdx) = reason;
    transitionActivity(transitionIdx) = details.activity(end);
    transitionGateActive(transitionIdx) = details.gateActive(end);
    transitionRest(transitionIdx) = details.isRest(end);
    transitionCountdown(transitionIdx) = ...
        details.lowActivityCountdown(end);
    transitionDesired(transitionIdx) = ...
        max(abs(desiredVelocity(end, :)));
    transitionOutputVelocity(transitionIdx) = max(abs(vNext(end, :)));
    transitionPositionLimited(transitionIdx) = ...
        any(referenceDiagnostics.positionLimited(end, :));
    transitionRateLimited(transitionIdx) = any( ...
        referenceDiagnostics.brakingLimited(end, :) | ...
        referenceDiagnostics.accelerationLimited(end, :));
    if transitionIdx < stepCount
        observedQ = qState(transitionIdx+1, :);
        observedV = vState(transitionIdx+1, :);
        nextStateAvailable(transitionIdx) = true;
        outputDecisionStep(transitionIdx) = transitionIdx+1;
        provenance(transitionIdx+1) = reason;
        transitionStepForDecision(transitionIdx+1) = transitionIdx;
        activity(transitionIdx+1) = details.activity(end);
        gateActive(transitionIdx+1) = details.gateActive(end);
        isRest(transitionIdx+1) = details.isRest(end);
        countdown(transitionIdx+1) = details.lowActivityCountdown(end);
        desiredMaxAbs(transitionIdx+1) = ...
            max(abs(desiredVelocity(end, :)));
        positionLimitedAny(transitionIdx+1) = ...
            transitionPositionLimited(transitionIdx);
        rateLimitedAny(transitionIdx+1) = ...
            transitionRateLimited(transitionIdx);
    else
        observedQ = double(data.intentTarget(:)');
        observedV = double(data.intentVelocity(:)');
    end
    positionError(transitionIdx) = ...
        max(abs(qNext(end, :)-observedQ));
    velocityError(transitionIdx) = ...
        max(abs(vNext(end, :)-observedV));
    unshiftedPositionError(transitionIdx) = ...
        max(abs(qNext(end, :)-qState(transitionIdx, :)));
    unshiftedVelocityError(transitionIdx) = ...
        max(abs(vNext(end, :)-vState(transitionIdx, :)));
    qCurrent = qNext(end, :);
    vCurrent = vNext(end, :);
    gateState = nextGateState;
end

gateMatches = isequaln(gateState, data.intentGateState);
shiftedMismatch = positionError > options.replayTolerance | ...
    velocityError > options.replayTolerance;
stopped = max(abs(vState), [], 2) <= options.zeroVelocityTolerance;
farCorrection = ismember(source, ["training", "acceptance"]) & ...
    stopped & episodeWindows.holdPositionMse >= options.farCorrectionMse;
latchedFar = farCorrection & episodeLatch.latchActive;
decisionAudit = table(repmat(variant, stepCount, 1), ...
    repmat(source, stepCount, 1), repmat(episode, stepCount, 1), ...
    repmat(repetitionId, stepCount, 1), double(episodeWindows.step), ...
    double(episodeWindows.windowIndex), max(abs(vState), [], 2), ...
    stopped, provenance, transitionStepForDecision, activity, ...
    gateActive, isRest, countdown, desiredMaxAbs, ...
    positionLimitedAny, rateLimitedAny, ...
    logical(episodeLatch.latchActive), ...
    logical(episodeLatch.recoveredByMemory), farCorrection, latchedFar, ...
    double(episodeLatch.stoppedSegmentId), ...
    logical(episodeLatch.segmentFarStarted), ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "step", "windowIndex", ...
    "referenceVelocityMaxAbs", "stopped", "provenance", ...
    "sourceTransitionStep", "activity", "gateActive", "isRest", ...
    "lowActivityCountdown", "desiredVelocityMaxAbs", ...
    "positionLimitedAny", "rateLimitedAny", "latchActive", ...
    "recoveredByMemory", "farCorrection", ...
    "latchedFarCorrection", "stoppedSegmentId", ...
    "segmentFarStarted"]);
transitionAudit = table(repmat(variant, stepCount, 1), ...
    repmat(source, stepCount, 1), repmat(episode, stepCount, 1), ...
    repmat(repetitionId, stepCount, 1), (1:stepCount)', ...
    outputDecisionStep, nextStateAvailable, transitionReason, ...
    transitionActivity, transitionGateActive, transitionRest, ...
    transitionCountdown, transitionDesired, transitionOutputVelocity, ...
    transitionPositionLimited, transitionRateLimited, positionError, ...
    velocityError, unshiftedPositionError, unshiftedVelocityError, ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "transitionStep", "outputDecisionStep", ...
    "nextStateAvailable", "provenance", "activity", ...
    "gateActive", "isRest", "lowActivityCountdown", ...
    "desiredVelocityMaxAbs", "outputVelocityMaxAbs", ...
    "positionLimitedAny", "rateLimitedAny", ...
    "shiftedPositionReplayError", "shiftedVelocityReplayError", ...
    "unshiftedPositionDifference", "unshiftedVelocityDifference"]);
episodeAudit = table(variant, source, episode, repetitionId, stepCount, ...
    path, directLogPresent, checksumMatches, historyError, ...
    max(positionError), max(velocityError), sum(shiftedMismatch), ...
    gateMatches, max(unshiftedPositionError), ...
    max(unshiftedVelocityError), ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "stepCount", "episodePath", ...
    "directProvenanceLogPresent", "calibrationChecksumMatches", ...
    "maximumReferenceHistoryError", "maximumPositionReplayError", ...
    "maximumVelocityReplayError", "shiftedAlignmentMismatchCount", ...
    "finalGateStateMatches", "maximumUnshiftedPositionDifference", ...
    "maximumUnshiftedVelocityDifference"]);
end

function summary = buildProvenanceSummary(decisions)
variants = ["control", "candidate"];
sources = ["training", "acceptance", "steadyRest"];
reasons = unique(decisions.provenance);
parts = cell(0, 1);
for variant = variants
    for source = sources
        base = decisions.variant == variant & decisions.source == source;
        for reason = reasons'
            rows = base & decisions.provenance == reason;
            parts{end+1, 1} = table(variant, source, reason, ...
                sum(rows), mean(rows(base)), sum(rows & decisions.stopped), ...
                sum(rows & decisions.recoveredByMemory), ...
                sum(rows & decisions.latchedFarCorrection), ...
                'VariableNames', ["variant", "source", "provenance", ...
                "windowCount", "sourceWindowFraction", ...
                "stoppedWindowCount", "recoveredMemoryWindowCount", ...
                "latchedFarWindowCount"]); %#ok<AGROW>
        end
    end
end
summary = vertcat(parts{:});
end

function audit = buildSegmentProvenance(decisions)
stopped = decisions(decisions.stopped, :);
keys = stopped.variant+"|"+stopped.source+"|"+ ...
    string(stopped.episode)+"|"+string(stopped.stoppedSegmentId);
[groups, uniqueKeys] = findgroups(keys);
parts = cell(numel(uniqueKeys), 1);
for groupIdx = 1:numel(uniqueKeys)
    values = stopped(groups == groupIdx, :);
    [~, order] = sort(values.step);
    values = values(order, :);
    parts{groupIdx} = table(values.variant(1), values.source(1), ...
        values.episode(1), values.repetitionId(1), ...
        values.stoppedSegmentId(1), values.step(1), height(values), ...
        values.segmentFarStarted(1), values.provenance(1), ...
        sum(values.provenance == "episodeInitialization"), ...
        sum(values.provenance == "decoderRest"), ...
        sum(values.provenance == "activeCountdownZero"), ...
        sum(values.provenance == "activeSynergyZero"), ...
        sum(values.provenance == "mechanicalPositionLimitZero"), ...
        sum(values.provenance == "mechanicalRateLimitZero"), ...
        sum(values.provenance == "unresolvedActiveZero"), ...
        sum(values.recoveredByMemory), ...
        sum(values.latchedFarCorrection), ...
        'VariableNames', ["variant", "source", "episode", ...
        "repetitionId", "stoppedSegmentId", "startStep", ...
        "windowCount", "farStarted", "startProvenance", ...
        "initializationWindowCount", "decoderRestWindowCount", ...
        "activeCountdownZeroWindowCount", ...
        "activeSynergyZeroWindowCount", ...
        "positionLimitZeroWindowCount", "rateLimitZeroWindowCount", ...
        "unresolvedWindowCount", "recoveredMemoryWindowCount", ...
        "latchedFarWindowCount"]);
end
audit = vertcat(parts{:});
end

function keys = rowKeys(value)
keys = string(value.variant)+"|"+string(value.source)+"|"+ ...
    string(value.episode)+"|"+string(value.repetitionId)+"|"+ ...
    string(value.step)+"|"+string(value.windowIndex);
end
