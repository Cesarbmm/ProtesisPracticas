function summary = summarizeNoGloveStage7nEpisodes( ...
        episodeDirectory, observationVariant, options)
%summarizeNoGloveStage7nEpisodes audits PWM and state-62 semantics.

arguments
    episodeDirectory (1, 1) string
    observationVariant (1, 1) string
    options.holdPositionMseTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-4
    options.numericTolerance (1, 1) double {mustBeNonnegative} = 1e-12
end

allowed = ["intentMarkov60", "intentDeclaredRestHoldMarkov62"];
if ~any(observationVariant == allowed)
    error("summarizeNoGloveStage7nEpisodes:InvalidVariant", ...
        "Unsupported observation variant %s.", observationVariant);
end
layout = buildObservationLayout(observationVariant, 40, 3, 4);
files = dir(fullfile(episodeDirectory, "episode*.mat"));
if isempty(files)
    error("summarizeNoGloveStage7nEpisodes:NoEpisodes", ...
        "No episode files found in %s.", episodeDirectory);
end
[~, order] = sort({files.name});
files = files(order);

pwmParts = cell(numel(files), 1);
actionParts = cell(numel(files), 1);
declaredParts = cell(numel(files), 1);
latchParts = cell(numel(files), 1);
farStartedParts = cell(numel(files), 1);
prematureParts = cell(numel(files), 1);
farLatchParts = cell(numel(files), 1);
declaredMismatchCount = 0;
latchMismatchCount = 0;
allFinite = true;
windowCount = 0;

for fileIdx = 1:numel(files)
    path = fullfile(files(fileIdx).folder, files(fileIdx).name);
    data = load(path, "stateLog", "actionSatLog", "actionPwmLog", ...
        "intentProvenanceLog", "referenceSource", ...
        "observationVariant", "stateLength");
    required = ["stateLog", "actionSatLog", "actionPwmLog", ...
        "intentProvenanceLog", "referenceSource", ...
        "observationVariant", "stateLength"];
    if ~all(isfield(data, cellstr(required))) || ...
            string(data.referenceSource) ~= "emgIntent" || ...
            string(data.observationVariant) ~= observationVariant || ...
            double(data.stateLength) ~= layout.totalLength
        error("summarizeNoGloveStage7nEpisodes:EpisodeContract", ...
            "Episode %s violates the ETAPA 7N contract.", path);
    end
    state = double(data.stateLog);
    action = double(data.actionSatLog);
    pwm = double(data.actionPwmLog);
    count = size(state, 1);
    if size(state, 2) ~= layout.totalLength || ...
            ~isequal(size(action), [count, 4]) || ...
            ~isequal(size(pwm), [count, 4]) || ...
            ~iscell(data.intentProvenanceLog) || ...
            numel(data.intentProvenanceLog) ~= count
        error("summarizeNoGloveStage7nEpisodes:EpisodeArrays", ...
            "Episode %s contains invalid or misaligned arrays.", path);
    end
    allFinite = allFinite && ...
        all(isfinite([state(:); action(:); pwm(:)]));
    windowCount = windowCount + count;
    pwmParts{fileIdx} = pwm;
    actionParts{fileIdx} = action;

    if observationVariant == "intentDeclaredRestHoldMarkov62"
        declared = validateBit(state(:, layout.declaredRest), ...
            "declaredRest", path, options.numericTolerance);
        latch = validateBit(state(:, layout.holdLatch), ...
            "holdLatch", path, options.numericTolerance);
        positionMse = mean((state(:, layout.encoder) - ...
            state(:, layout.referencePosition)).^2, 2);
        expectedDeclared = true(count, 1);
        expectedLatch = false(count, 1);
        expectedDeclared(1) = true;
        expectedLatch(1) = positionMse(1) <= ...
            options.holdPositionMseTolerance + options.numericTolerance;
        provenance = data.intentProvenanceLog;
        for stepIdx = 2:count
            item = provenance{stepIdx-1};
            fields = ["schemaVersion", "declaredRestAfter", ...
                "holdLatchAfter", "holdPositionMseAfter"];
            if ~isstruct(item) || ~isscalar(item) || ...
                    ~all(isfield(item, cellstr(fields))) || ...
                    double(item.schemaVersion) ~= 2
                error("summarizeNoGloveStage7nEpisodes:Provenance", ...
                    "Episode %s lacks state-62 provenance at step %d.", ...
                    path, stepIdx-1);
            end
            expectedDeclared(stepIdx) = logical(item.declaredRestAfter);
            expectedLatch(stepIdx) = logical(item.holdLatchAfter);
            if abs(double(item.holdPositionMseAfter) - ...
                    positionMse(stepIdx)) > options.numericTolerance
                error("summarizeNoGloveStage7nEpisodes:PositionMseReplay", ...
                    "Episode %s has a position-MSE mismatch at step %d.", ...
                    path, stepIdx);
            end
        end
        declaredMismatchCount = declaredMismatchCount + ...
            sum(declared ~= expectedDeclared);
        latchMismatchCount = latchMismatchCount + ...
            sum(latch ~= expectedLatch);
        rising = declared & [true; ~declared(1:end-1)];
        farStarted = rising & positionMse > ...
            options.holdPositionMseTolerance + options.numericTolerance;
        % The 7M recurrence intentionally keeps an already active latch
        % while declared rest continues, even if position later drifts.
        % Premature means activation at a far-start transition only.
        farLatch = latch & positionMse > ...
            options.holdPositionMseTolerance + options.numericTolerance;
        premature = farStarted & latch;
        declaredParts{fileIdx} = declared;
        latchParts{fileIdx} = latch;
        farStartedParts{fileIdx} = farStarted;
        prematureParts{fileIdx} = premature;
        farLatchParts{fileIdx} = farLatch;
    else
        declaredParts{fileIdx} = false(count, 1);
        latchParts{fileIdx} = false(count, 1);
        farStartedParts{fileIdx} = false(count, 1);
        prematureParts{fileIdx} = false(count, 1);
        farLatchParts{fileIdx} = false(count, 1);
    end
end

pwm = vertcat(pwmParts{:});
action = vertcat(actionParts{:});
declared = vertcat(declaredParts{:});
latch = vertcat(latchParts{:});
farStarted = vertcat(farStartedParts{:});
premature = vertcat(prematureParts{:});
farLatch = vertcat(farLatchParts{:});
componentCommand = abs(pwm) > options.numericTolerance;
windowCommand = any(componentCommand, 2);
isState62 = observationVariant == "intentDeclaredRestHoldMarkov62";

summary = struct( ...
    "schemaVersion", 1, "episodeDirectory", episodeDirectory, ...
    "episodeCount", numel(files), "windowCount", windowCount, ...
    "observationVariant", observationVariant, ...
    "stateLength", layout.totalLength, "allFinite", allFinite, ...
    "commandComponentFraction", mean(componentCommand, "all"), ...
    "windowAnyCommandFraction", mean(windowCommand), ...
    "meanAbsPwm", mean(abs(pwm), "all"), ...
    "saturationFraction", mean(abs(action) >= 0.95, "all"), ...
    "commandComponentFractionByMotor", mean(componentCommand, 1), ...
    "meanAbsPwmByMotor", mean(abs(pwm), 1), ...
    "saturationFractionByMotor", mean(abs(action) >= 0.95, 1), ...
    "declaredRestFraction", conditionalValue(isState62, mean(declared)), ...
    "declaredRestCount", conditionalValue(isState62, sum(declared)), ...
    "holdLatchFraction", conditionalValue(isState62, mean(latch)), ...
    "holdLatchCount", conditionalValue(isState62, sum(latch)), ...
    "declaredRestReplayMismatchCount", declaredMismatchCount, ...
    "holdLatchReplayMismatchCount", latchMismatchCount, ...
    "farStartedCount", conditionalValue(isState62, sum(farStarted)), ...
    "farStartedLatchCount", conditionalValue(isState62, ...
        sum(farStarted & latch)), ...
    "prematureHoldLatchCount", conditionalValue(isState62, ...
        sum(premature)), ...
    "holdLatchFarFromTargetCount", conditionalValue(isState62, ...
        sum(farLatch)), ...
    "latchActiveWindowAnyCommandFraction", conditionalMean( ...
        windowCommand, latch, isState62), ...
    "latchInactiveWindowAnyCommandFraction", conditionalMean( ...
        windowCommand, ~latch, isState62));
end

function bit = validateBit(values, label, path, tolerance)
if any(~isfinite(values)) || ...
        any(abs(values-round(values)) > tolerance) || ...
        any(values < -tolerance | values > 1+tolerance)
    error("summarizeNoGloveStage7nEpisodes:InvalidBit", ...
        "Episode %s contains invalid %s values.", path, label);
end
bit = logical(round(values));
end

function value = conditionalValue(condition, trueValue)
if condition
    value = trueValue;
else
    value = NaN;
end
end

function value = conditionalMean(values, mask, enabled)
if ~enabled || ~any(mask)
    value = NaN;
else
    value = mean(values(mask));
end
end
