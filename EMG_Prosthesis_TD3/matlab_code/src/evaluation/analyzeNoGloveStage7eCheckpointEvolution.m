function analysis = analyzeNoGloveStage7eCheckpointEvolution( ...
        training, checkpoints, actuator, rewardWeights, options)
%analyzeNoGloveStage7eCheckpointEvolution audits rest commands over time.
%
% Every frozen checkpoint is evaluated on the same recorded
% preActivationHold corpus. Historical training actions and rewards remain a
% separate observational stream because they include a changing policy and
% training exploration.

arguments
    training struct
    checkpoints struct
    actuator struct
    rewardWeights struct
    options.referenceTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.rewardTolerance (1, 1) double ...
        {mustBeNonnegative} = 1e-12
    options.falseActivationLimit (1, 1) double ...
        {mustBeInRange(options.falseActivationLimit, 0, 1)} = 0.01
    options.materialRelativeAttenuation (1, 1) double ...
        {mustBeInRange(options.materialRelativeAttenuation, 0, 1)} = 0.25
    options.saturationThreshold (1, 1) double ...
        {mustBeInRange(options.saturationThreshold, 0, 1)} = 0.95
end

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
validateInputs(training, checkpoints, actuator, rewardWeights, ...
    options, layout);

checkpointCount = numel(checkpoints);
stateCount = size(training.state, 1);
raw = nan(stateCount, 4, checkpointCount);
effective = nan(size(raw));
pwm = nan(size(raw));
for checkpointIdx = 1:checkpointCount
    raw(:, :, checkpointIdx) = evaluateCheckpoint( ...
        checkpoints(checkpointIdx).evaluator, training.state);
    [effective(:, :, checkpointIdx), pwm(:, :, checkpointIdx)] = ...
        quantizeRows(raw(:, :, checkpointIdx), actuator);
end

checkpointSummary = summarizeCheckpoints( ...
    checkpoints, raw, effective, pwm, options);
checkpointMotorSummary = summarizeCheckpointMotors( ...
    checkpoints, raw, effective, pwm, options);
checkpointEpisodeSummary = summarizeCheckpointEpisodes( ...
    training, checkpoints, raw, effective, pwm, options);
checkpointTrend = buildCheckpointTrend(checkpointSummary);
checkpointActionComponents = buildCheckpointActionComponents( ...
    training, checkpoints, raw, effective, pwm, options);

[historicalSummary, historicalMotorSummary] = ...
    summarizeHistoricalTrainingBehavior(training, checkpoints, options);
blockEndReplayComparison = compareHistoricalWithBlockEndCheckpoint( ...
    training, checkpoints, raw, effective, pwm, options);

[rewardAuditTable, rewardSummary, rewardEpisodeSummary, rewardAudit] = ...
    auditRecordedReward(training, checkpoints, rewardWeights, options);
decision = classifyEvolution(checkpointSummary, options);

analysis = struct( ...
    "schemaVersion", 1, "stage", "7E", ...
    "observationVariant", "intentMarkov60", ...
    "stateCorpusContract", ...
        "sameRecordedTrainingPreActivationHoldStatesForEveryCheckpoint", ...
    "historicalActionContract", ...
        "changingTrainingPolicyPlusExplorationNotDeterministicCheckpoint", ...
    "rewardAuditContract", ...
        "recordedTermsOnlyNoDynamicCounterfactual", ...
    "checkpointCount", checkpointCount, ...
    "trainingEpisodeCount", numel(unique(training.episode)), ...
    "trainingStateCount", stateCount, ...
    "checkpointSummary", checkpointSummary, ...
    "checkpointMotorSummary", checkpointMotorSummary, ...
    "checkpointEpisodeSummary", checkpointEpisodeSummary, ...
    "checkpointTrend", checkpointTrend, ...
    "checkpointActionComponents", checkpointActionComponents, ...
    "historicalSummary", historicalSummary, ...
    "historicalMotorSummary", historicalMotorSummary, ...
    "blockEndReplayComparison", blockEndReplayComparison, ...
    "rewardAuditTable", rewardAuditTable, ...
    "rewardSummary", rewardSummary, ...
    "rewardEpisodeSummary", rewardEpisodeSummary, ...
    "rewardAudit", rewardAudit, ...
    "sourceDecision", decision, ...
    "rootCauseIdentified", false, ...
    "checkpointSelectedAsWinner", false, ...
    "historicalActionInterpretedAsDeterministicActor", false, ...
    "explorationEffectIsolated", false, ...
    "counterfactualRewardCalculated", false, ...
    "standardizedEmgUsedAsPhysicalAmplitude", false, ...
    "behavioralInterventionExecuted", false, ...
    "compensationInterventionExecuted", false, ...
    "filteredReferenceInterventionExecuted", false, ...
    "dtwCalculated", false, "dtwRewardUsed", false, ...
    "runTraining", false, "agent7250Loaded", false, ...
    "envCreated", false, "simulatorInvoked", false, ...
    "rewardFunctionInvoked", false, "hardwareUsed", false);
end

function validateInputs(training, checkpoints, actuator, weights, ...
        options, layout)
requiredTraining = ["state", "episode", "step", ...
    "previousReferencePosition", "historicalRawAction", ...
    "historicalEffectiveAction", "historicalPwm", ...
    "recordedReward", "recordedRewardVector", "rewardInfo"];
requiredCheckpoint = ["label", "episode", "evaluator"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
requiredWeights = ["position", "velocity", "action", "deltaAction", ...
    "saturation", "softActionLimit"];
if ~all(isfield(training, cellstr(requiredTraining))) || ...
        ~all(isfield(checkpoints, cellstr(requiredCheckpoint))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator))) || ...
        ~all(isfield(weights, cellstr(requiredWeights)))
    error("analyzeNoGloveStage7eCheckpointEvolution:MissingField", ...
        "Training, checkpoint, actuator or reward contract is incomplete.");
end
stateCount = size(training.state, 1);
if isempty(training.state) || size(training.state, 2) ~= layout.totalLength || ...
        ~isreal(training.state) || any(~isfinite(training.state), "all") || ...
        numel(training.episode) ~= stateCount || ...
        numel(training.step) ~= stateCount || ...
        ~isequal(size(training.previousReferencePosition), [stateCount, 4]) || ...
        ~isequal(size(training.historicalRawAction), [stateCount, 4]) || ...
        ~isequal(size(training.historicalEffectiveAction), [stateCount, 4]) || ...
        ~isequal(size(training.historicalPwm), [stateCount, 4]) || ...
        numel(training.recordedReward) ~= stateCount || ...
        ~isequal(size(training.recordedRewardVector), [stateCount, 4]) || ...
        height(training.rewardInfo) ~= stateCount || ...
        any(~isfinite(training.historicalRawAction), "all") || ...
        any(~isfinite(training.historicalEffectiveAction), "all") || ...
        any(~isfinite(training.historicalPwm), "all") || ...
        any(~isfinite(training.recordedReward), "all") || ...
        any(~isfinite(training.recordedRewardVector), "all")
    error("analyzeNoGloveStage7eCheckpointEvolution:InvalidTraining", ...
        "Training arrays must be finite, aligned and use intentMarkov60.");
end
if any(abs(training.state(:, layout.referenceVelocity)) > ...
        options.referenceTolerance, "all") || ...
        any(abs(training.state(:, layout.referencePosition)- ...
        training.previousReferencePosition) > ...
        options.referenceTolerance, "all")
    error("analyzeNoGloveStage7eCheckpointEvolution:NonholdState", ...
        "Every state must be a causal zero-v_ref reference hold.");
end
checkpointEpisodes = double([checkpoints.episode]);
checkpointLabels = string({checkpoints.label});
if numel(checkpoints) ~= 4 || ...
        ~isequal(checkpointEpisodes, [50 100 150 200]) || ...
        ~isequal(checkpointLabels, ["Agent50" "Agent100" ...
        "Agent150" "Agent200"]) || ...
        any(arrayfun(@(x) ~isa(x.evaluator, "function_handle"), checkpoints))
    error("analyzeNoGloveStage7eCheckpointEvolution:CheckpointOrder", ...
        "The frozen sequence must be Agent50/100/150/200.");
end
if any(training.episode < 1) || any(training.episode > 200) || ...
        ~all(ismember(1:4, unique(ceil(training.episode/50))'))
    error("analyzeNoGloveStage7eCheckpointEvolution:EpisodeCoverage", ...
        "Training states must cover all four 50-episode blocks.");
end
requiredReward = ["trackingMse", "trackingMae", "velocityMse", ...
    "actionL2", "smoothnessPenalty", "deltaActionL2", ...
    "saturationFraction", "softSaturationPenalty", ...
    "saturationPenalty", "referenceSource"];
if ~all(ismember(requiredReward, ...
        string(training.rewardInfo.Properties.VariableNames))) || ...
        any(string(training.rewardInfo.referenceSource) ~= "emgIntent")
    error("analyzeNoGloveStage7eCheckpointEvolution:RewardSchema", ...
        "Recorded rewardInfo does not satisfy the causal intent schema.");
end
weightValues = struct2array(weights);
if ~isnumeric(weightValues) || any(~isfinite(weightValues)) || ...
        any(weightValues < 0)
    error("analyzeNoGloveStage7eCheckpointEvolution:RewardWeights", ...
        "Reward weights must be finite and nonnegative.");
end
end

function action = evaluateCheckpoint(evaluator, state)
action = double(evaluator(double(state)));
if ~isequal(size(action), [size(state, 1), 4]) || ...
        ~isreal(action) || any(~isfinite(action), "all")
    error("analyzeNoGloveStage7eCheckpointEvolution:ActorOutput", ...
        "Every checkpoint must return a finite N-by-4 action matrix.");
end
end

function tableValue = summarizeCheckpoints( ...
        checkpoints, raw, effective, pwm, options)
rows = cell(numel(checkpoints), 1);
for checkpointIdx = 1:numel(checkpoints)
    rows{checkpointIdx} = actionSummaryRow( ...
        string(checkpoints(checkpointIdx).label), ...
        checkpoints(checkpointIdx).episode, ...
        raw(:, :, checkpointIdx), effective(:, :, checkpointIdx), ...
        pwm(:, :, checkpointIdx), options);
end
tableValue = vertcat(rows{:});
end

function row = actionSummaryRow(label, episode, raw, effective, pwm, options)
active = abs(effective) > 0;
row = table(label, episode, size(raw, 1), numel(raw), ...
    mean(active, "all"), mean(any(active, 2)), ...
    mean(abs(raw), "all"), mean(abs(effective), "all"), ...
    mean(abs(pwm), "all"), ...
    mean(abs(effective) >= options.saturationThreshold, "all"), ...
    'VariableNames', ["checkpoint", "checkpointEpisode", ...
    "stateCount", "componentCount", "commandActiveFraction", ...
    "windowAnyCommandFraction", "meanAbsRawAction", ...
    "meanAbsEffectiveAction", "meanAbsPwm", "saturationFraction"]);
end

function tableValue = summarizeCheckpointMotors( ...
        checkpoints, raw, effective, pwm, options)
rows = cell(numel(checkpoints)*4, 1);
cursor = 0;
for checkpointIdx = 1:numel(checkpoints)
    for motor = 1:4
        cursor = cursor+1;
        active = abs(effective(:, motor, checkpointIdx)) > 0;
        rows{cursor} = table(string(checkpoints(checkpointIdx).label), ...
            checkpoints(checkpointIdx).episode, motor, size(raw, 1), ...
            mean(active), mean(abs(raw(:, motor, checkpointIdx))), ...
            mean(abs(effective(:, motor, checkpointIdx))), ...
            mean(abs(pwm(:, motor, checkpointIdx))), ...
            mean(abs(effective(:, motor, checkpointIdx)) >= ...
                options.saturationThreshold), ...
            'VariableNames', ["checkpoint", "checkpointEpisode", ...
            "motor", "stateCount", "commandActiveFraction", ...
            "meanAbsRawAction", "meanAbsEffectiveAction", ...
            "meanAbsPwm", "saturationFraction"]);
    end
end
tableValue = vertcat(rows{:});
end

function tableValue = summarizeCheckpointEpisodes( ...
        training, checkpoints, raw, effective, pwm, options)
episodes = unique(training.episode(:))';
rows = cell(numel(checkpoints)*numel(episodes), 1);
cursor = 0;
for checkpointIdx = 1:numel(checkpoints)
    for episode = episodes
        cursor = cursor+1;
        mask = training.episode == episode;
        active = abs(effective(mask, :, checkpointIdx)) > 0;
        rows{cursor} = table(string(checkpoints(checkpointIdx).label), ...
            checkpoints(checkpointIdx).episode, episode, sum(mask), ...
            mean(active, "all"), mean(any(active, 2)), ...
            mean(abs(raw(mask, :, checkpointIdx)), "all"), ...
            mean(abs(pwm(mask, :, checkpointIdx)), "all"), ...
            mean(abs(effective(mask, :, checkpointIdx)) >= ...
                options.saturationThreshold, "all"), ...
            'VariableNames', ["checkpoint", "checkpointEpisode", ...
            "trainingEpisode", "stateCount", "commandActiveFraction", ...
            "windowAnyCommandFraction", "meanAbsRawAction", ...
            "meanAbsPwm", "saturationFraction"]);
    end
end
tableValue = vertcat(rows{:});
end

function value = buildCheckpointTrend(summary)
pairs = [1 2; 2 3; 3 4; 1 4];
rows = cell(size(pairs, 1), 1);
for pairIdx = 1:size(pairs, 1)
    from = summary(pairs(pairIdx, 1), :);
    to = summary(pairs(pairIdx, 2), :);
    relativePwmChange = (to.meanAbsPwm-from.meanAbsPwm) / ...
        max(from.meanAbsPwm, eps);
    rows{pairIdx} = table(from.checkpoint, to.checkpoint, ...
        to.commandActiveFraction-from.commandActiveFraction, ...
        to.windowAnyCommandFraction-from.windowAnyCommandFraction, ...
        to.meanAbsRawAction-from.meanAbsRawAction, ...
        to.meanAbsPwm-from.meanAbsPwm, relativePwmChange, ...
        to.saturationFraction-from.saturationFraction, ...
        'VariableNames', ["fromCheckpoint", "toCheckpoint", ...
        "deltaCommandActiveFraction", "deltaWindowAnyCommandFraction", ...
        "deltaMeanAbsRawAction", "deltaMeanAbsPwm", ...
        "relativeMeanAbsPwmChange", "deltaSaturationFraction"]);
end
value = vertcat(rows{:});
end

function value = buildCheckpointActionComponents( ...
        training, checkpoints, raw, effective, pwm, options)
stateCount = size(training.state, 1);
rowsPerCheckpoint = stateCount*4;
checkpointColumn = strings(rowsPerCheckpoint*numel(checkpoints), 1);
checkpointEpisode = zeros(size(checkpointColumn));
trainingEpisode = zeros(size(checkpointColumn));
step = zeros(size(checkpointColumn));
motor = zeros(size(checkpointColumn));
rawAction = zeros(size(checkpointColumn));
effectiveAction = zeros(size(checkpointColumn));
pwmAction = zeros(size(checkpointColumn));
active = false(size(checkpointColumn));
saturated = false(size(checkpointColumn));
cursor = 0;
[stateRow, localMotor] = ndgrid((1:stateCount)', 1:4);
stateRow = stateRow(:);
localMotor = localMotor(:);
for checkpointIdx = 1:numel(checkpoints)
    rows = cursor+(1:rowsPerCheckpoint);
    linear = sub2ind([stateCount, 4], stateRow, localMotor);
    checkpointColumn(rows) = string(checkpoints(checkpointIdx).label);
    checkpointEpisode(rows) = checkpoints(checkpointIdx).episode;
    trainingEpisode(rows) = training.episode(stateRow);
    step(rows) = training.step(stateRow);
    motor(rows) = localMotor;
    rawSlice = raw(:, :, checkpointIdx);
    effectiveSlice = effective(:, :, checkpointIdx);
    pwmSlice = pwm(:, :, checkpointIdx);
    rawAction(rows) = rawSlice(linear);
    effectiveAction(rows) = effectiveSlice(linear);
    pwmAction(rows) = pwmSlice(linear);
    active(rows) = abs(effectiveAction(rows)) > 0;
    saturated(rows) = abs(effectiveAction(rows)) >= ...
        options.saturationThreshold;
    cursor = cursor+rowsPerCheckpoint;
end
value = table(checkpointColumn, checkpointEpisode, trainingEpisode, ...
    step, motor, rawAction, effectiveAction, pwmAction, active, saturated, ...
    'VariableNames', ["checkpoint", "checkpointEpisode", ...
    "trainingEpisode", "step", "motor", "rawAction", ...
    "effectiveAction", "pwm", "active", "saturated"]);
end

function [summary, motorSummary] = summarizeHistoricalTrainingBehavior( ...
        training, checkpoints, options)
summaryRows = cell(numel(checkpoints)+1, 1);
motorRows = cell((numel(checkpoints)+1)*4, 1);
allMasks = cell(numel(checkpoints)+1, 1);
labels = strings(numel(checkpoints)+1, 1);
starts = zeros(numel(checkpoints)+1, 1);
ends = zeros(numel(checkpoints)+1, 1);
for blockIdx = 1:numel(checkpoints)
    starts(blockIdx) = 1+50*(blockIdx-1);
    ends(blockIdx) = checkpoints(blockIdx).episode;
    labels(blockIdx) = sprintf("episodes%03dto%03d", ...
        starts(blockIdx), ends(blockIdx));
    allMasks{blockIdx} = training.episode >= starts(blockIdx) & ...
        training.episode <= ends(blockIdx);
end
starts(end) = 1;
ends(end) = 200;
labels(end) = "allEpisodes";
allMasks{end} = true(size(training.episode));
motorCursor = 0;
for groupIdx = 1:numel(allMasks)
    mask = allMasks{groupIdx};
    summaryRows{groupIdx} = historicalSummaryRow( ...
        labels(groupIdx), starts(groupIdx), ends(groupIdx), ...
        training.historicalRawAction(mask, :), ...
        training.historicalEffectiveAction(mask, :), ...
        training.historicalPwm(mask, :), options);
    for motor = 1:4
        motorCursor = motorCursor+1;
        active = abs(training.historicalEffectiveAction(mask, motor)) > 0;
        motorRows{motorCursor} = table(labels(groupIdx), ...
            starts(groupIdx), ends(groupIdx), motor, sum(mask), ...
            mean(active), ...
            mean(abs(training.historicalRawAction(mask, motor))), ...
            mean(abs(training.historicalEffectiveAction(mask, motor))), ...
            mean(abs(training.historicalPwm(mask, motor))), ...
            mean(abs(training.historicalEffectiveAction(mask, motor)) >= ...
                options.saturationThreshold), ...
            'VariableNames', ["episodeBlock", "episodeStart", ...
            "episodeEnd", "motor", "stateCount", ...
            "commandActiveFraction", "meanAbsRawAction", ...
            "meanAbsEffectiveAction", "meanAbsPwm", ...
            "saturationFraction"]);
    end
end
summary = vertcat(summaryRows{:});
motorSummary = vertcat(motorRows{:});
end

function row = historicalSummaryRow(label, first, last, ...
        raw, effective, pwm, options)
active = abs(effective) > 0;
row = table(label, first, last, size(raw, 1), numel(raw), ...
    mean(active, "all"), mean(any(active, 2)), ...
    mean(abs(raw), "all"), mean(abs(effective), "all"), ...
    mean(abs(pwm), "all"), ...
    mean(abs(effective) >= options.saturationThreshold, "all"), ...
    'VariableNames', ["episodeBlock", "episodeStart", "episodeEnd", ...
    "stateCount", "componentCount", "commandActiveFraction", ...
    "windowAnyCommandFraction", "meanAbsRawAction", ...
    "meanAbsEffectiveAction", "meanAbsPwm", "saturationFraction"]);
end

function value = compareHistoricalWithBlockEndCheckpoint( ...
        training, checkpoints, raw, effective, pwm, options)
rows = cell(numel(checkpoints)*5, 1);
cursor = 0;
for checkpointIdx = 1:numel(checkpoints)
    first = 1+50*(checkpointIdx-1);
    last = checkpoints(checkpointIdx).episode;
    mask = training.episode >= first & training.episode <= last;
    for motor = 0:4
        cursor = cursor+1;
        if motor == 0
            historicRaw = training.historicalRawAction(mask, :);
            historicEffective = training.historicalEffectiveAction(mask, :);
            historicPwm = training.historicalPwm(mask, :);
            checkpointRaw = raw(mask, :, checkpointIdx);
            checkpointEffective = effective(mask, :, checkpointIdx);
            checkpointPwm = pwm(mask, :, checkpointIdx);
        else
            historicRaw = training.historicalRawAction(mask, motor);
            historicEffective = training.historicalEffectiveAction(mask, motor);
            historicPwm = training.historicalPwm(mask, motor);
            checkpointRaw = raw(mask, motor, checkpointIdx);
            checkpointEffective = effective(mask, motor, checkpointIdx);
            checkpointPwm = pwm(mask, motor, checkpointIdx);
        end
        rows{cursor} = table(string(checkpoints(checkpointIdx).label), ...
            first, last, motor, numel(historicRaw), ...
            mean(abs(historicRaw), "all"), ...
            mean(abs(checkpointRaw), "all"), ...
            mean(abs(historicRaw-checkpointRaw), "all"), ...
            mean(abs(historicEffective) > 0, "all"), ...
            mean(abs(checkpointEffective) > 0, "all"), ...
            mean(historicEffective == checkpointEffective, "all"), ...
            mean(historicPwm == checkpointPwm, "all"), ...
            mean(abs(historicEffective) >= ...
                options.saturationThreshold, "all"), ...
            mean(abs(checkpointEffective) >= ...
                options.saturationThreshold, "all"), ...
            'VariableNames', ["blockEndCheckpoint", "episodeStart", ...
            "episodeEnd", "motor", "componentCount", ...
            "historicalMeanAbsRawAction", ...
            "checkpointMeanAbsRawAction", "rawActionMae", ...
            "historicalCommandActiveFraction", ...
            "checkpointCommandActiveFraction", ...
            "effectiveActionExactFraction", "pwmExactFraction", ...
            "historicalSaturationFraction", ...
            "checkpointSaturationFraction"]);
    end
end
value = vertcat(rows{:});
end

function [auditTable, summary, episodeSummary, audit] = ...
        auditRecordedReward(training, checkpoints, weights, options)
info = training.rewardInfo;
positionCost = weights.position*double(info.trackingMse);
velocityCost = weights.velocity*double(info.velocityMse);
actionCost = weights.action*double(info.actionL2);
deltaActionCost = weights.deltaAction*double(info.deltaActionL2);
saturationCost = weights.saturation*double(info.softSaturationPenalty);
totalCost = positionCost+velocityCost+actionCost+ ...
    deltaActionCost+saturationCost;
reconstructedReward = -totalCost;
rewardVectorMean = mean(training.recordedRewardVector, 2);
rewardError = abs(training.recordedReward-reconstructedReward);
rewardVectorError = abs(training.recordedReward-rewardVectorMean);
smoothnessError = abs(double(info.smoothnessPenalty)-deltaActionCost);
saturationError = abs(double(info.saturationPenalty)-saturationCost);
maxError = max([rewardError; rewardVectorError; ...
    smoothnessError; saturationError]);
if maxError > options.rewardTolerance
    error("analyzeNoGloveStage7eCheckpointEvolution:RewardMismatch", ...
        "Recorded reward terms differ from the configured formula by %.17g.", ...
        maxError);
end
auditTable = table(training.episode, training.step, ...
    training.recordedReward, rewardVectorMean, reconstructedReward, ...
    rewardError, rewardVectorError, positionCost, velocityCost, ...
    actionCost, deltaActionCost, saturationCost, totalCost, ...
    double(info.trackingMse), double(info.velocityMse), ...
    double(info.actionL2), double(info.deltaActionL2), ...
    double(info.saturationFraction), ...
    double(info.softSaturationPenalty), ...
    'VariableNames', ["trainingEpisode", "step", "recordedReward", ...
    "rewardVectorMean", "reconstructedReward", ...
    "rewardAbsoluteError", "rewardVectorAbsoluteError", ...
    "positionCost", "velocityCost", "actionCost", ...
    "deltaActionCost", "saturationCost", "totalCost", ...
    "trackingMse", "velocityMse", "actionL2", "deltaActionL2", ...
    "saturationFraction", "softSaturationPenalty"]);

summaryRows = cell(numel(checkpoints)+1, 1);
for groupIdx = 1:(numel(checkpoints)+1)
    if groupIdx <= numel(checkpoints)
        first = 1+50*(groupIdx-1);
        last = checkpoints(groupIdx).episode;
        label = sprintf("episodes%03dto%03d", first, last);
        mask = training.episode >= first & training.episode <= last;
    else
        first = 1;
        last = 200;
        label = "allEpisodes";
        mask = true(size(training.episode));
    end
    summaryRows{groupIdx} = rewardSummaryRow( ...
        label, first, last, mask, training.recordedReward, ...
        positionCost, velocityCost, actionCost, deltaActionCost, ...
        saturationCost, totalCost);
end
summary = vertcat(summaryRows{:});

episodes = unique(training.episode(:))';
episodeRows = cell(numel(episodes), 1);
for episodeIdx = 1:numel(episodes)
    episode = episodes(episodeIdx);
    mask = training.episode == episode;
    episodeRows{episodeIdx} = rewardSummaryRow( ...
        sprintf("episode%05d", episode), episode, episode, mask, ...
        training.recordedReward, positionCost, velocityCost, ...
        actionCost, deltaActionCost, saturationCost, totalCost);
end
episodeSummary = vertcat(episodeRows{:});
audit = table(max(rewardError), max(rewardVectorError), ...
    max(smoothnessError), max(saturationError), maxError, false, ...
    'VariableNames', ["maximumRewardReconstructionError", ...
    "maximumRewardVectorMeanError", "maximumSmoothnessTermError", ...
    "maximumSaturationTermError", "maximumAuditError", ...
    "counterfactualRewardCalculated"]);
end

function row = rewardSummaryRow(label, first, last, mask, reward, ...
        positionCost, velocityCost, actionCost, deltaCost, satCost, totalCost)
meanTotal = mean(totalCost(mask));
row = table(string(label), first, last, sum(mask), ...
    mean(reward(mask)), mean(positionCost(mask)), ...
    mean(velocityCost(mask)), mean(actionCost(mask)), ...
    mean(deltaCost(mask)), mean(satCost(mask)), meanTotal, ...
    mean(positionCost(mask))/max(meanTotal, eps), ...
    mean(actionCost(mask))/max(meanTotal, eps), ...
    mean(deltaCost(mask))/max(meanTotal, eps), ...
    mean(satCost(mask))/max(meanTotal, eps), ...
    'VariableNames', ["episodeBlock", "episodeStart", "episodeEnd", ...
    "stateCount", "meanRecordedReward", "meanPositionCost", ...
    "meanVelocityCost", "meanActionCost", "meanDeltaActionCost", ...
    "meanSaturationCost", "meanTotalCost", ...
    "positionCostFraction", "actionCostFraction", ...
    "deltaActionCostFraction", "saturationCostFraction"]);
end

function decision = classifyEvolution(summary, options)
early = summary(1, :);
final = summary(end, :);
earlyActive = early.windowAnyCommandFraction > ...
    options.falseActivationLimit;
finalActive = final.windowAnyCommandFraction > ...
    options.falseActivationLimit;
laterActive = any(summary.windowAnyCommandFraction(2:end) > ...
    options.falseActivationLimit);
relativePwmReduction = (early.meanAbsPwm-final.meanAbsPwm) / ...
    max(early.meanAbsPwm, eps);
materialAttenuation = relativePwmReduction >= ...
    options.materialRelativeAttenuation;
if earlyActive && finalActive && materialAttenuation
    classification = "attenuatesButPersists";
elseif earlyActive
    classification = "presentFromEarlyCheckpoint";
elseif laterActive
    classification = "emergesDuringTraining";
else
    classification = "checkpointEvolutionUnresolved";
end
activeIdx = find(summary.windowAnyCommandFraction > ...
    options.falseActivationLimit, 1, "first");
firstActiveCheckpoint = "none";
if ~isempty(activeIdx)
    firstActiveCheckpoint = summary.checkpoint(activeIdx);
end
decision = table(classification, firstActiveCheckpoint, ...
    earlyActive, laterActive, finalActive, ...
    early.commandActiveFraction, final.commandActiveFraction, ...
    early.windowAnyCommandFraction, final.windowAnyCommandFraction, ...
    early.meanAbsPwm, final.meanAbsPwm, relativePwmReduction, ...
    materialAttenuation, options.materialRelativeAttenuation, false, ...
    'VariableNames', ["classification", "firstActiveCheckpoint", ...
    "earlyCheckpointActive", "laterCheckpointActive", ...
    "finalCheckpointActive", "earlyCommandActiveFraction", ...
    "finalCommandActiveFraction", ...
    "earlyWindowAnyCommandFraction", ...
    "finalWindowAnyCommandFraction", "earlyMeanAbsPwm", ...
    "finalMeanAbsPwm", "relativeMeanAbsPwmReduction", ...
    "materialAttenuation", "materialAttenuationThreshold", ...
    "rootCauseIdentified"]);
end

function [effective, pwm] = quantizeRows(actions, actuator)
effective = nan(size(actions));
pwm = nan(size(actions));
for rowIdx = 1:size(actions, 1)
    [effectiveRow, pwmRow] = quantizeBaselineAction( ...
        actions(rowIdx, :), actuator.maxPwm, ...
        actuator.activationThreshold, actuator.commandLevels);
    effective(rowIdx, :) = double(effectiveRow(:))';
    pwm(rowIdx, :) = double(pwmRow(:))';
end
end
