function result = evaluateNoGloveStage7oCheckpoint( ...
        agent, checkpointEpisode, corpus, actuator, options)
%evaluateNoGloveStage7oCheckpoint evaluates one frozen 62-input actor.

arguments
    agent
    checkpointEpisode (1, 1) double {mustBeInteger, mustBePositive}
    corpus (1, 1) struct
    actuator (1, 1) struct
    options.primaryEpisode (1, 1) double ...
        {mustBeInteger, mustBePositive} = 200
    options.rawTolerance (1, 1) double {mustBeNonnegative} = 1e-6
    options.gradientFiniteDifferenceStep (1, 1) double ...
        {mustBePositive} = 1e-2
end

requiredCorpus = ["states", "prefix60", "loggedActions", "metadata"];
requiredActuator = ["maxPwm", "activationThreshold", "commandLevels"];
if ~all(isfield(corpus, cellstr(requiredCorpus))) || ...
        ~all(isfield(actuator, cellstr(requiredActuator)))
    error("evaluateNoGloveStage7oCheckpoint:InvalidInput", ...
        "Corpus or actuator contract is incomplete.");
end
states = double(corpus.states);
metadata = corpus.metadata;
if size(states, 2) ~= 62 || size(states, 1) ~= height(metadata) || ...
        ~isequal(states(:, 1:60), double(corpus.prefix60))
    error("evaluateNoGloveStage7oCheckpoint:CorpusAlignment", ...
        "Counterfactual corpus must preserve an exact 60-value prefix.");
end

states00 = states;
states10 = states;
states11 = states;
states01 = states;
states00(:, 61:62) = repmat([0, 0], size(states, 1), 1);
states10(:, 61:62) = repmat([1, 0], size(states, 1), 1);
states11(:, 61:62) = repmat([1, 1], size(states, 1), 1);
states01(:, 61:62) = repmat([0, 1], size(states, 1), 1);
if ~isequal(states00(:, 1:60), states10(:, 1:60), ...
        states11(:, 1:60), states01(:, 1:60))
    error("evaluateNoGloveStage7oCheckpoint:PrefixChanged", ...
        "A counterfactual changed one of the first 60 dimensions.");
end

actor = getActor(agent);
model = getModel(actor);
raw = struct( ...
    "s00", evaluateFrozenActorModel62(model, states00), ...
    "s10", evaluateFrozenActorModel62(model, states10), ...
    "s11", evaluateFrozenActorModel62(model, states11), ...
    "s01", evaluateFrozenActorModel62(model, states01), ...
    "observed", evaluateFrozenActorModel62(model, states));
quantized = struct();
names = string(fieldnames(raw));
for nameIdx = 1:numel(names)
    name = names(nameIdx);
    [quantized.(name).effective, quantized.(name).pwm] = ...
        quantizeRows(raw.(name), actuator);
end
gradients = evaluateFrozenActorBitGradients(model, states, [61, 62]);

effectParts = { ...
    buildEffectRows("restEffect", true, raw.s00, raw.s10, ...
        quantized.s00, quantized.s10); ...
    buildEffectRows("latchEffect", true, raw.s10, raw.s11, ...
        quantized.s10, quantized.s11); ...
    buildEffectRows("oodInvalid01", false, raw.s00, raw.s01, ...
        quantized.s00, quantized.s01)};
effects = vertcat(effectParts{:});
gradientRows = buildGradientRows(gradients);

evaluationMask = metadata.source ~= "training";
replayAudit = struct( ...
    "evaluatedRowCount", sum(evaluationMask), ...
    "serialSavedMaximumError", NaN, ...
    "batchSerialMaximumError", NaN, ...
    "batchSerialPwmMismatchCount", NaN);
if checkpointEpisode == options.primaryEpisode && any(evaluationMask)
    serial = evaluateFrozenActor62States(actor, states(evaluationMask, :));
    saved = double(corpus.loggedActions(evaluationMask, :));
    batch = raw.observed(evaluationMask, :);
    [~, serialPwm] = quantizeRows(serial, actuator);
    [~, batchPwm] = quantizeRows(batch, actuator);
    replayAudit.serialSavedMaximumError = ...
        max(abs(serial-saved), [], "all");
    replayAudit.batchSerialMaximumError = ...
        max(abs(batch-serial), [], "all");
    replayAudit.batchSerialPwmMismatchCount = ...
        sum(batchPwm ~= serialPwm, "all");
end
gradientAudit = auditGradients(model, states, ...
    options.gradientFiniteDifferenceStep);

result = struct( ...
    "checkpointEpisode", checkpointEpisode, ...
    "primary", checkpointEpisode == options.primaryEpisode, ...
    "effects", effects, "gradients", gradientRows, ...
    "raw", raw, "quantized", quantized, ...
    "replayAudit", replayAudit, "gradientAudit", gradientAudit, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "hardwareUsed", false);

    function rows = buildEffectRows(contrast, causalValid, ...
            rawOff, rawOn, quantOff, quantOn)
        count = size(states, 1);
        rowCount = count*4;
        corpusRow = repelem(metadata.corpusRow, 4);
        rowId = repelem(metadata.rowId, 4);
        source = repelem(metadata.source, 4);
        context = repelem(metadata.context, 4);
        motor = repmat((1:4)', count, 1);
        rawOffValue = reshape(rawOff', rowCount, 1);
        rawOnValue = reshape(rawOn', rowCount, 1);
        effectiveOff = reshape(quantOff.effective', rowCount, 1);
        effectiveOn = reshape(quantOn.effective', rowCount, 1);
        pwmOff = reshape(quantOff.pwm', rowCount, 1);
        pwmOn = reshape(quantOn.pwm', rowCount, 1);
        deltaRaw = rawOnValue-rawOffValue;
        deltaAbsRaw = abs(rawOnValue)-abs(rawOffValue);
        deltaAbsPwm = abs(pwmOn)-abs(pwmOff);
        rows = table( ...
            repmat(checkpointEpisode, rowCount, 1), ...
            repmat(checkpointEpisode == options.primaryEpisode, ...
                rowCount, 1), ...
            corpusRow, rowId, source, context, motor, ...
            repmat(string(contrast), rowCount, 1), ...
            repmat(causalValid, rowCount, 1), ...
            causalValid & context ~= "uncategorized", ...
            rawOffValue, rawOnValue, deltaRaw, deltaAbsRaw, ...
            effectiveOff, effectiveOn, pwmOff, pwmOn, deltaAbsPwm, ...
            abs(deltaRaw) > options.rawTolerance, ...
            deltaAbsRaw < -options.rawTolerance, ...
            deltaAbsRaw > options.rawTolerance, ...
            pwmOn ~= pwmOff, abs(pwmOn) ~= abs(pwmOff), ...
            abs(pwmOff) == 0 & abs(pwmOn) == 64, ...
            abs(pwmOff) == 64 & abs(pwmOn) == 0, ...
            abs(effectiveOff) < 0.95 & abs(effectiveOn) >= 0.95, ...
            abs(effectiveOff) >= 0.95 & abs(effectiveOn) < 0.95, ...
            deltaAbsPwm < 0, deltaAbsPwm > 0, ...
            'VariableNames', ["checkpointEpisode", "primary", ...
            "corpusRow", "rowId", "source", "context", "motor", ...
            "contrast", "causalValid", "classificationEligible", ...
            "rawOff", "rawOn", "deltaRaw", "deltaAbsRaw", ...
            "effectiveOff", "effectiveOn", "pwmOff", "pwmOn", ...
            "deltaAbsPwm", "rawChanged", "rawMagnitudeReduced", ...
            "rawMagnitudeIncreased", "pwmChanged", ...
            "quantizationLevelChanged", "zeroTo64", ...
            "sixtyFourToZero", "saturationEntry", "saturationExit", ...
            "beneficialPwm", "adversePwm"]);
    end

    function rows = buildGradientRows(values)
        count = size(states, 1);
        bitNames = ["declaredRest", "holdLatch"];
        parts = cell(8, 1);
        cursor = 0;
        for bitIdx = 1:2
            for motorIdx = 1:4
                cursor = cursor+1;
                parts{cursor} = table( ...
                    repmat(checkpointEpisode, count, 1), ...
                    repmat(checkpointEpisode == options.primaryEpisode, ...
                        count, 1), metadata.corpusRow, metadata.rowId, ...
                    metadata.source, metadata.context, ...
                    repmat(motorIdx, count, 1), ...
                    repmat(bitNames(bitIdx), count, 1), ...
                    repmat(60+bitIdx, count, 1), ...
                    states(:, 60+bitIdx), values(:, motorIdx, bitIdx), ...
                    'VariableNames', ["checkpointEpisode", "primary", ...
                    "corpusRow", "rowId", "source", "context", ...
                    "motor", "bit", "inputIndex", "observedBit", ...
                    "gradient"]);
            end
        end
        rows = vertcat(parts{:});
    end
end

function [effective, pwm] = quantizeRows(raw, actuator)
effective = nan(size(raw));
pwm = nan(size(raw));
for rowIdx = 1:size(raw, 1)
    [effectiveRow, pwmRow] = quantizeBaselineAction( ...
        raw(rowIdx, :), actuator.maxPwm, ...
        actuator.activationThreshold, actuator.commandLevels);
    effective(rowIdx, :) = double(effectiveRow(:))';
    pwm(rowIdx, :) = double(pwmRow(:))';
end
end

function audit = auditGradients(model, states, step)
sampleCount = min(8, size(states, 1));
indices = unique(round(linspace(1, size(states, 1), sampleCount)));
sample = states(indices, :);
analytic = evaluateFrozenActorBitGradients(model, sample, [61, 62]);
finite = nan(size(analytic));
for bitIdx = 1:2
    plus = sample;
    minus = sample;
    plus(:, 60+bitIdx) = plus(:, 60+bitIdx)+step;
    minus(:, 60+bitIdx) = minus(:, 60+bitIdx)-step;
    finite(:, :, bitIdx) = ( ...
        evaluateFrozenActorModel62(model, plus) - ...
        evaluateFrozenActorModel62(model, minus))./(2*step);
end
errorValue = abs(analytic-finite);
absoluteTolerance = 1e-4;
relativeTolerance = 5e-2;
tolerance = max(absoluteTolerance, relativeTolerance.*abs(analytic));
audit = struct( ...
    "sampleCount", numel(indices), "step", step, ...
    "absoluteTolerance", absoluteTolerance, ...
    "relativeTolerance", relativeTolerance, ...
    "maximumAbsoluteError", max(errorValue, [], "all"), ...
    "maximumTolerance", max(tolerance, [], "all"), ...
    "withinTolerance", all(errorValue <= tolerance, "all"));
end
