function analysis = analyzeNoGloveStage6BoundaryDiagnostics( ...
        episodeDirectory, splitName, options)
%analyzeNoGloveStage6BoundaryDiagnostics attributes ETAPA 6 failures offline.
%
% stateLog(t) is the observation visible before action_t. The actuator
% command is actionPwmLog(t), and trackingPredictionHistory(t) is the
% encoder read after that action. No simulator, agent or reward is invoked.

arguments
    episodeDirectory (1, 1) string
    splitName (1, 1) string
    options.positionMin (1, 4) double = zeros(1, 4)
    options.positionMax (1, 4) double = ones(1, 4)
    options.positionTolerance (1, 1) double {mustBeNonnegative} = 1e-9
    options.activeVelocityThreshold (1, 1) double {mustBeNonnegative} = 0.005
    options.motionTolerance (1, 1) double {mustBeNonnegative} = 1e-4
    options.positionErrorTolerance (1, 1) double {mustBeNonnegative} = 1e-4
    options.saturationThreshold (1, 1) double {mustBeInRange( ...
        options.saturationThreshold, 0, 1)} = 0.95
end

if ~isfolder(episodeDirectory)
    error("analyzeNoGloveStage6BoundaryDiagnostics:DirectoryNotFound", ...
        "Episode directory not found: %s", episodeDirectory);
end
if ismissing(splitName) || strlength(splitName) == 0
    error("analyzeNoGloveStage6BoundaryDiagnostics:InvalidSplit", ...
        "splitName must be nonempty.");
end
if any(options.positionMax <= options.positionMin)
    error("analyzeNoGloveStage6BoundaryDiagnostics:InvalidPositionLimits", ...
        "Each positionMax must exceed positionMin.");
end

episodeFiles = dir(fullfile(episodeDirectory, "episode*.mat"));
if isempty(episodeFiles)
    error("analyzeNoGloveStage6BoundaryDiagnostics:NoEpisodes", ...
        "No episode files found in %s.", episodeDirectory);
end
[~, fileOrder] = sort({episodeFiles.name});
episodeFiles = episodeFiles(fileOrder);

layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
componentTables = cell(numel(episodeFiles), 1);
nextAlignmentMax = 0;
referenceAlignmentMax = 0;
for episodeIdx = 1:numel(episodeFiles)
    episodePath = string(fullfile(episodeFiles(episodeIdx).folder, ...
        episodeFiles(episodeIdx).name));
    [componentTables{episodeIdx}, alignment] = analyzeEpisode( ...
        episodePath, splitName, episodeIdx, layout, options);
    nextAlignmentMax = max(nextAlignmentMax, alignment.nextStateMaxAbs);
    referenceAlignmentMax = max( ...
        referenceAlignmentMax, alignment.referenceMaxAbs);
end

componentTable = vertcat(componentTables{:});
motorSummary = summarizeByMotor(componentTable);
conditionSummary = summarizeByCondition(componentTable);
hypothesisEvidence = buildHypothesisEvidence(motorSummary);

analysis = struct( ...
    "schemaVersion", 1, ...
    "split", splitName, ...
    "episodeDirectory", episodeDirectory, ...
    "episodeCount", numel(episodeFiles), ...
    "componentCount", height(componentTable), ...
    "nextStateAlignmentMaxAbs", nextAlignmentMax, ...
    "referenceAlignmentMaxAbs", referenceAlignmentMax, ...
    "options", options, ...
    "componentTable", componentTable, ...
    "motorSummary", motorSummary, ...
    "conditionSummary", conditionSummary, ...
    "hypothesisEvidence", hypothesisEvidence);
end

function [componentTable, alignment] = analyzeEpisode( ...
        episodePath, splitName, episodeIdx, layout, options)
required = [ ...
    "stateLog", "trackingPredictionHistory", "referenceHistory", ...
    "actionPwmLog", "actionSatLog", ...
    "positionSafetyInterventionLog", "simulationPositionSafety", ...
    "referenceSource", "observationVariant", "stateLength"];
available = string(who("-file", episodePath));
if ~all(ismember(required, available))
    missing = setdiff(required, available);
    error("analyzeNoGloveStage6BoundaryDiagnostics:MissingEpisodeField", ...
        "Episode %s is missing: %s.", episodePath, strjoin(missing, ", "));
end
data = load(episodePath, required{:});
if string(data.referenceSource) ~= "emgIntent" || ...
        string(data.observationVariant) ~= "intentMarkov60" || ...
        double(data.stateLength) ~= layout.totalLength || ...
        ~logical(data.simulationPositionSafety.enabled)
    error("analyzeNoGloveStage6BoundaryDiagnostics:IncompatibleEpisode", ...
        "Episode %s is not a position-limited intentMarkov60 episode.", ...
        episodePath);
end

state = double(data.stateLog);
qAfter = double(data.trackingPredictionHistory);
referenceHistory = double(data.referenceHistory);
pwm = double(data.actionPwmLog);
effectiveAction = double(data.actionSatLog);
safetyCount = double(data.positionSafetyInterventionLog);
stepCount = size(state, 1);
matrices = {qAfter, referenceHistory, pwm, effectiveAction, safetyCount};
if size(state, 2) ~= layout.totalLength || stepCount == 0 || ...
        any(cellfun(@(value) ~isequal(size(value), [stepCount, 4]), matrices))
    error("analyzeNoGloveStage6BoundaryDiagnostics:DimensionMismatch", ...
        "Episode %s contains temporally incompatible logs.", episodePath);
end
critical = [state(:); qAfter(:); referenceHistory(:); pwm(:); ...
    effectiveAction(:); safetyCount(:)];
if any(~isfinite(critical))
    error("analyzeNoGloveStage6BoundaryDiagnostics:NonfiniteData", ...
        "Episode %s contains NaN or Inf.", episodePath);
end
if any(safetyCount < 0 | fix(safetyCount) ~= safetyCount, "all") || ...
        any(abs(pwm) > 255, "all") || ...
        any(abs(effectiveAction) > 1 + 1e-12, "all")
    error("analyzeNoGloveStage6BoundaryDiagnostics:InvalidActuatorLog", ...
        "Episode %s contains invalid PWM, action or safety counts.", episodePath);
end

qBefore = state(:, layout.encoder);
qReference = state(:, layout.referencePosition);
vReference = state(:, layout.referenceVelocity);
referenceError = abs(referenceHistory - qReference);
alignment.referenceMaxAbs = max(referenceError, [], "all");
if alignment.referenceMaxAbs > 1e-12
    error("analyzeNoGloveStage6BoundaryDiagnostics:ReferenceMisalignment", ...
        "Episode %s does not use the reference visible before action_t.", ...
        episodePath);
end
if stepCount > 1
    nextError = abs(qAfter(1:end-1, :) - qBefore(2:end, :));
    alignment.nextStateMaxAbs = max(nextError, [], "all");
else
    alignment.nextStateMaxAbs = 0;
end
if alignment.nextStateMaxAbs > 1e-12
    error("analyzeNoGloveStage6BoundaryDiagnostics:NextStateMisalignment", ...
        "Episode %s does not align encoder_(t+1) with action_t.", episodePath);
end

qMin = options.positionMin;
qMax = options.positionMax;
if any(qBefore < qMin - options.positionTolerance | ...
        qBefore > qMax + options.positionTolerance, "all") || ...
        any(qAfter < qMin - options.positionTolerance | ...
        qAfter > qMax + options.positionTolerance, "all") || ...
        any(qReference < qMin - options.positionTolerance | ...
        qReference > qMax + options.positionTolerance, "all")
    error("analyzeNoGloveStage6BoundaryDiagnostics:PositionOutOfRange", ...
        "Episode %s violates the configured normalized position limits.", ...
        episodePath);
end

deltaQ = qAfter - qBefore;
referenceDirection = thresholdDirection( ...
    vReference, options.activeVelocityThreshold);
motionDirection = thresholdDirection(deltaQ, options.motionTolerance);
positionError = qReference - qBefore;
positionErrorDirection = thresholdDirection( ...
    positionError, options.positionErrorTolerance);
commandDirection = sign(pwm);
activeReference = referenceDirection ~= 0;
activePositionError = positionErrorDirection ~= 0;
zeroReference = ~activeReference;
zeroControlDemand = zeroReference & ~activePositionError;
atLower = qBefore <= qMin + options.positionTolerance;
atUpper = qBefore >= qMax - options.positionTolerance;
atBoundary = atLower | atUpper;
safetyIntervened = safetyCount > 0;
saturated = abs(effectiveAction) >= options.saturationThreshold;
noMotionActive = activeReference & motionDirection == 0;
wrongMotionActive = activeReference & motionDirection ~= 0 & ...
    motionDirection ~= referenceDirection;
wrongCommandDirectionActive = activeReference & commandDirection ~= 0 & ...
    commandDirection ~= referenceDirection;
wrongCommandPositionError = activePositionError & commandDirection ~= 0 & ...
    commandDirection ~= positionErrorDirection;
alignedCommandActive = activeReference & ...
    commandDirection == referenceDirection;
responseOpposesCommand = commandDirection ~= 0 & motionDirection ~= 0 & ...
    motionDirection ~= commandDirection;
outwardCommandAtBoundary = ...
    (atLower & commandDirection < 0) | ...
    (atUpper & commandDirection > 0);
referenceAtLower = qReference <= qMin + options.positionTolerance;
referenceAtUpper = qReference >= qMax - options.positionTolerance;
outwardReferenceAtLimit = ...
    (referenceAtLower & referenceDirection < 0) | ...
    (referenceAtUpper & referenceDirection > 0);
boundaryContext = atBoundary | safetyIntervened;
noMotionBoundaryOrSafety = noMotionActive & boundaryContext;
noMotionInteriorZeroPwm = noMotionActive & ~boundaryContext & pwm == 0;
noMotionInteriorNonzeroPwm = noMotionActive & ~boundaryContext & pwm ~= 0;
wrongMotionWrongCommand = wrongMotionActive & ...
    wrongCommandDirectionActive;
wrongMotionAlignedCommand = wrongMotionActive & alignedCommandActive;
wrongMotionZeroCommand = wrongMotionActive & commandDirection == 0;

[stepGrid, motorGrid] = ndgrid((1:stepCount)', 1:4);
componentCount = stepCount * 4;
boundaryState = repmat("interior", componentCount, 1);
boundaryState(atLower(:)) = "lower";
boundaryState(atUpper(:)) = "upper";
componentTable = table( ...
    repmat(splitName, componentCount, 1), ...
    repmat(episodeIdx, componentCount, 1), stepGrid(:), motorGrid(:), ...
    qBefore(:), qAfter(:), qReference(:), vReference(:), ...
    referenceDirection(:), positionError(:), positionErrorDirection(:), ...
    boundaryState, atLower(:), atUpper(:), atBoundary(:), ...
    pwm(:), commandDirection(:), effectiveAction(:), ...
    deltaQ(:), motionDirection(:), safetyCount(:), safetyIntervened(:), ...
    activeReference(:), activePositionError(:), zeroReference(:), ...
    zeroControlDemand(:), saturated(:), ...
    noMotionActive(:), wrongMotionActive(:), ...
    wrongCommandDirectionActive(:), wrongCommandPositionError(:), ...
    alignedCommandActive(:), responseOpposesCommand(:), ...
    outwardCommandAtBoundary(:), outwardReferenceAtLimit(:), ...
    noMotionBoundaryOrSafety(:), noMotionInteriorZeroPwm(:), ...
    noMotionInteriorNonzeroPwm(:), wrongMotionWrongCommand(:), ...
    wrongMotionAlignedCommand(:), wrongMotionZeroCommand(:), ...
    'VariableNames', { ...
    'split', 'episode', 'step', 'motor', 'qBefore', 'qAfter', ...
    'qReference', 'vReference', 'referenceDirection', 'positionError', ...
    'positionErrorDirection', 'boundaryState', 'atLower', 'atUpper', ...
    'atBoundary', 'appliedPwm', 'commandDirection', 'effectiveAction', ...
    'deltaQ', 'motionDirection', 'safetyInterventionCount', ...
    'safetyIntervened', 'activeReference', 'activePositionError', ...
    'zeroReference', 'zeroControlDemand', 'saturated', ...
    'noMotionActive', 'wrongMotionActive', ...
    'wrongCommandDirectionActive', 'wrongCommandPositionError', ...
    'alignedCommandActive', 'responseOpposesCommand', ...
    'outwardCommandAtBoundary', 'outwardReferenceAtLimit', ...
    'noMotionBoundaryOrSafety', 'noMotionInteriorZeroPwm', ...
    'noMotionInteriorNonzeroPwm', 'wrongMotionWrongCommand', ...
    'wrongMotionAlignedCommand', 'wrongMotionZeroCommand'});
end

function direction = thresholdDirection(value, threshold)
direction = zeros(size(value));
direction(value >= threshold) = 1;
direction(value <= -threshold) = -1;
end

function summary = summarizeByMotor(componentTable)
motors = unique(componentTable.motor);
rows = repmat(emptyMotorRow(), numel(motors), 1);
for rowIdx = 1:numel(motors)
    motor = motors(rowIdx);
    values = componentTable(componentTable.motor == motor, :);
    activeCount = sum(values.activeReference);
    positionErrorCount = sum(values.activePositionError);
    zeroCount = sum(values.zeroReference);
    zeroControlCount = sum(values.zeroControlDemand);
    noMotionCount = sum(values.noMotionActive);
    wrongMotionCount = sum(values.wrongMotionActive);
    row = emptyMotorRow();
    row.split = values.split(1);
    row.motor = motor;
    row.totalComponentSteps = height(values);
    row.activeReferenceSteps = activeCount;
    row.activePositionErrorSteps = positionErrorCount;
    row.zeroReferenceSteps = zeroCount;
    row.zeroControlDemandSteps = zeroControlCount;
    row.lowerBoundarySteps = sum(values.atLower);
    row.upperBoundarySteps = sum(values.atUpper);
    row.safetyInterventionSteps = sum(values.safetyIntervened);
    row.safetyInterventionSampleCount = ...
        sum(values.safetyInterventionCount);
    row.outwardCommandAtBoundarySteps = ...
        sum(values.outwardCommandAtBoundary);
    row.outwardReferenceAtLimitSteps = ...
        sum(values.outwardReferenceAtLimit);
    row.saturatedSteps = sum(values.saturated);
    row.saturatedZeroReferenceSteps = ...
        sum(values.saturated & values.zeroReference);
    row.nonzeroPwmZeroReferenceSteps = ...
        sum(values.appliedPwm ~= 0 & values.zeroReference);
    row.nonzeroPwmZeroControlDemandSteps = ...
        sum(values.appliedPwm ~= 0 & values.zeroControlDemand);
    row.saturatedZeroControlDemandSteps = ...
        sum(values.saturated & values.zeroControlDemand);
    row.noMotionActiveSteps = noMotionCount;
    row.noMotionBoundaryOrSafetySteps = ...
        sum(values.noMotionBoundaryOrSafety);
    row.noMotionInteriorZeroPwmSteps = ...
        sum(values.noMotionInteriorZeroPwm);
    row.noMotionInteriorNonzeroPwmSteps = ...
        sum(values.noMotionInteriorNonzeroPwm);
    row.wrongMotionActiveSteps = wrongMotionCount;
    row.wrongMotionWrongCommandSteps = ...
        sum(values.wrongMotionWrongCommand);
    row.wrongMotionAlignedCommandSteps = ...
        sum(values.wrongMotionAlignedCommand);
    row.wrongMotionZeroCommandSteps = ...
        sum(values.wrongMotionZeroCommand);
    row.wrongCommandDirectionActiveSteps = ...
        sum(values.wrongCommandDirectionActive);
    row.wrongCommandPositionErrorSteps = ...
        sum(values.wrongCommandPositionError);
    row.movingWithNonzeroCommandSteps = sum( ...
        values.commandDirection ~= 0 & values.motionDirection ~= 0);
    row.responseOpposesCommandSteps = sum(values.responseOpposesCommand);
    row.noMotionFractionOfActive = safeFraction(noMotionCount, activeCount);
    row.noMotionBoundaryFraction = safeFraction( ...
        row.noMotionBoundaryOrSafetySteps, noMotionCount);
    row.wrongMotionFractionOfActive = safeFraction( ...
        wrongMotionCount, activeCount);
    row.wrongCommandFractionOfActive = safeFraction( ...
        row.wrongCommandDirectionActiveSteps, activeCount);
    row.wrongCommandPositionErrorFraction = safeFraction( ...
        row.wrongCommandPositionErrorSteps, positionErrorCount);
    row.responseOpposesCommandFraction = safeFraction( ...
        row.responseOpposesCommandSteps, row.movingWithNonzeroCommandSteps);
    row.saturatedFractionOfZeroReference = safeFraction( ...
        row.saturatedZeroReferenceSteps, zeroCount);
    row.nonzeroPwmFractionOfZeroControlDemand = safeFraction( ...
        row.nonzeroPwmZeroControlDemandSteps, zeroControlCount);
    row.saturatedFractionOfZeroControlDemand = safeFraction( ...
        row.saturatedZeroControlDemandSteps, zeroControlCount);
    rows(rowIdx) = row;
end
summary = struct2table(rows);
end

function row = emptyMotorRow()
row = struct( ...
    "split", "", "motor", 0, "totalComponentSteps", 0, ...
    "activeReferenceSteps", 0, "activePositionErrorSteps", 0, ...
    "zeroReferenceSteps", 0, "zeroControlDemandSteps", 0, ...
    "lowerBoundarySteps", 0, "upperBoundarySteps", 0, ...
    "safetyInterventionSteps", 0, ...
    "safetyInterventionSampleCount", 0, ...
    "outwardCommandAtBoundarySteps", 0, ...
    "outwardReferenceAtLimitSteps", 0, "saturatedSteps", 0, ...
    "saturatedZeroReferenceSteps", 0, ...
    "nonzeroPwmZeroReferenceSteps", 0, ...
    "nonzeroPwmZeroControlDemandSteps", 0, ...
    "saturatedZeroControlDemandSteps", 0, ...
    "noMotionActiveSteps", 0, ...
    "noMotionBoundaryOrSafetySteps", 0, ...
    "noMotionInteriorZeroPwmSteps", 0, ...
    "noMotionInteriorNonzeroPwmSteps", 0, ...
    "wrongMotionActiveSteps", 0, "wrongMotionWrongCommandSteps", 0, ...
    "wrongMotionAlignedCommandSteps", 0, ...
    "wrongMotionZeroCommandSteps", 0, ...
    "wrongCommandDirectionActiveSteps", 0, ...
    "wrongCommandPositionErrorSteps", 0, ...
    "movingWithNonzeroCommandSteps", 0, ...
    "responseOpposesCommandSteps", 0, ...
    "noMotionFractionOfActive", NaN, "noMotionBoundaryFraction", NaN, ...
    "wrongMotionFractionOfActive", NaN, ...
    "wrongCommandFractionOfActive", NaN, ...
    "wrongCommandPositionErrorFraction", NaN, ...
    "responseOpposesCommandFraction", NaN, ...
    "saturatedFractionOfZeroReference", NaN, ...
    "nonzeroPwmFractionOfZeroControlDemand", NaN, ...
    "saturatedFractionOfZeroControlDemand", NaN);
end

function summary = summarizeByCondition(componentTable)
keys = {'split', 'motor', 'referenceDirection', 'boundaryState', ...
    'safetyIntervened', 'commandDirection'};
[group, identifiers] = findgroups(componentTable(:, keys));
summary = identifiers;
summary.componentCount = splitapply(@numel, componentTable.motor, group);
summary.meanAbsPwm = splitapply(@mean, ...
    abs(componentTable.appliedPwm), group);
summary.meanDeltaQ = splitapply(@mean, componentTable.deltaQ, group);
summary.meanAbsDeltaQ = splitapply(@mean, ...
    abs(componentTable.deltaQ), group);
summary.noMotionFraction = splitapply(@mean, ...
    double(componentTable.motionDirection == 0), group);
summary.wrongMotionFractionOfActive = splitapply( ...
    @fractionAmongEligible, double(componentTable.wrongMotionActive), ...
    double(componentTable.activeReference), group);
summary.saturationFraction = splitapply(@mean, ...
    double(componentTable.saturated), group);
summary = sortrows(summary, keys);
end

function value = fractionAmongEligible(event, eligible)
value = safeFraction(sum(event), sum(eligible));
end

function evidence = buildHypothesisEvidence(motorSummary)
mechanisms = [ ...
    "boundary_or_safety_limited_no_motion", ...
    "interior_zero_pwm_no_motion", ...
    "interior_nonzero_pwm_no_motion", ...
    "command_opposes_velocity_reference", ...
    "command_opposes_position_error", ...
    "response_opposes_command", ...
    "reference_velocity_outward_at_limit", ...
    "outward_command_at_encoder_limit", ...
    "saturated_action_with_zero_reference", ...
    "nonzero_pwm_with_zero_control_demand", ...
    "saturated_action_with_zero_control_demand"];
interpretations = [ ...
    "No motion coincides with an encoder limit or safety intervention.", ...
    "No motion occurs in the interior while quantized PWM is zero.", ...
    "No motion occurs in the interior despite nonzero PWM.", ...
    "PWM sign opposes the signed reference velocity.", ...
    "PWM sign opposes the current q_ref-q tracking error.", ...
    "Measured motion sign opposes the sign of nonzero PWM.", ...
    "Signed reference velocity points beyond its own position limit.", ...
    "PWM points outward while the encoder is already at a limit.", ...
    "Effective action saturates while signed reference velocity is zero.", ...
    "PWM is nonzero while both v_ref and q_ref-q are effectively zero.", ...
    "Action saturates while both v_ref and q_ref-q are effectively zero."];
rows = repmat(struct( ...
    "split", "", "motor", 0, "mechanism", "", ...
    "evidenceCount", 0, "eligibleCount", 0, ...
    "evidenceFraction", NaN, "observed", false, ...
    "interpretation", ""), height(motorSummary) * numel(mechanisms), 1);
rowIdx = 0;
for motorRowIdx = 1:height(motorSummary)
    motorRow = motorSummary(motorRowIdx, :);
    counts = [ ...
        motorRow.noMotionBoundaryOrSafetySteps, ...
        motorRow.noMotionInteriorZeroPwmSteps, ...
        motorRow.noMotionInteriorNonzeroPwmSteps, ...
        motorRow.wrongCommandDirectionActiveSteps, ...
        motorRow.wrongCommandPositionErrorSteps, ...
        motorRow.responseOpposesCommandSteps, ...
        motorRow.outwardReferenceAtLimitSteps, ...
        motorRow.outwardCommandAtBoundarySteps, ...
        motorRow.saturatedZeroReferenceSteps, ...
        motorRow.nonzeroPwmZeroControlDemandSteps, ...
        motorRow.saturatedZeroControlDemandSteps];
    eligible = [ ...
        motorRow.noMotionActiveSteps, ...
        motorRow.noMotionActiveSteps, ...
        motorRow.noMotionActiveSteps, ...
        motorRow.activeReferenceSteps, ...
        motorRow.activePositionErrorSteps, ...
        motorRow.movingWithNonzeroCommandSteps, ...
        motorRow.activeReferenceSteps, ...
        motorRow.totalComponentSteps, ...
        motorRow.zeroReferenceSteps, ...
        motorRow.zeroControlDemandSteps, ...
        motorRow.zeroControlDemandSteps];
    for mechanismIdx = 1:numel(mechanisms)
        rowIdx = rowIdx + 1;
        rows(rowIdx).split = motorRow.split;
        rows(rowIdx).motor = motorRow.motor;
        rows(rowIdx).mechanism = mechanisms(mechanismIdx);
        rows(rowIdx).evidenceCount = counts(mechanismIdx);
        rows(rowIdx).eligibleCount = eligible(mechanismIdx);
        rows(rowIdx).evidenceFraction = safeFraction( ...
            counts(mechanismIdx), eligible(mechanismIdx));
        rows(rowIdx).observed = counts(mechanismIdx) > 0;
        rows(rowIdx).interpretation = interpretations(mechanismIdx);
    end
end
evidence = struct2table(rows);
end

function value = safeFraction(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator / denominator;
end
end
