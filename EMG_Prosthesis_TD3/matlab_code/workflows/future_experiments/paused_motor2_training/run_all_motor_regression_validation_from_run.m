function results = run_all_motor_regression_validation_from_run(resultsRoot, options)
%run_all_motor_regression_validation_from_run validates all motors post-run.
%
% This workflow does not train. It reads a completed
% motor2_conversion_fix_ablation run, recomputes per-motor diagnostics for
% selected final tests, and compares baseline conversion against the
% experimental motor2Calibrated conversion.

arguments
    resultsRoot (1, 1) string
    options = struct()
end

paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = char(paths.matlabRoot);
cd(matlabRoot);
addpath(genpath(matlabRoot));

options = localNormalizeOptions(options);
if ~isfolder(resultsRoot)
    error("Results root not found: %s", resultsRoot);
end

summaryRoot = fullfile(resultsRoot, "summary");
ensureDirectoryExists(summaryRoot);

bySeedTable = localBuildBySeedTable(resultsRoot, options.configLabels);
summaryTable = localBuildSummaryTable(bySeedTable);
comparisonTable = localBuildComparisonTable(summaryTable, options);

bySeedCsvPath = fullfile(summaryRoot, "all_motor_regression_validation_by_seed.csv");
summaryCsvPath = fullfile(summaryRoot, "all_motor_regression_validation_summary.csv");
comparisonCsvPath = fullfile(summaryRoot, ...
    "baseline_vs_motor2_calibrated_all_motor_comparison.csv");
markdownPath = fullfile(summaryRoot, "all_motor_regression_validation.md");

writetable(bySeedTable, bySeedCsvPath);
writetable(summaryTable, summaryCsvPath);
writetable(comparisonTable, comparisonCsvPath);
localWriteTextFile(markdownPath, localBuildMarkdown(resultsRoot, comparisonTable));

results = struct();
results.resultsRoot = string(resultsRoot);
results.summaryRoot = string(summaryRoot);
results.bySeedTable = bySeedTable;
results.summaryTable = summaryTable;
results.comparisonTable = comparisonTable;
results.paths = struct( ...
    "bySeedCsv", string(bySeedCsvPath), ...
    "summaryCsv", string(summaryCsvPath), ...
    "comparisonCsv", string(comparisonCsvPath), ...
    "markdown", string(markdownPath));
end

function options = localNormalizeOptions(options)
defaults = struct( ...
    "configLabels", [ ...
        "baseline_quantized_conversion_baseline", ...
        "baseline_quantized_conversion_motor2_calibrated"], ...
    "maxTrackingRegression", 1.10, ...
    "minRangeRatio", 0.90, ...
    "maxSaturationRegression", 1.15, ...
    "saturationFloor", 0.02);

fields = fieldnames(defaults);
for i = 1:numel(fields)
    if ~isfield(options, fields{i}) || isempty(options.(fields{i}))
        options.(fields{i}) = defaults.(fields{i});
    end
end
options.configLabels = string(options.configLabels);
options.maxTrackingRegression = double(options.maxTrackingRegression);
options.minRangeRatio = double(options.minRangeRatio);
options.maxSaturationRegression = double(options.maxSaturationRegression);
options.saturationFloor = double(options.saturationFloor);
end

function bySeedTable = localBuildBySeedTable(resultsRoot, configLabels)
seedTables = cell(numel(configLabels), 1);
totalRows = 0;
for configIdx = 1:numel(configLabels)
    configLabel = configLabels(configIdx);
    summaryPath = fullfile(resultsRoot, configLabel, "summary", ...
        "benchmark_seeded_summary.csv");
    if ~isfile(summaryPath)
        error("Config summary not found: %s", summaryPath);
    end
    seedTables{configIdx} = readtable(summaryPath, "TextType", "string");
    totalRows = totalRows + 4 * height(seedTables{configIdx});
end

rows = cell(totalRows, 1);
rowIdx = 0;
for configIdx = 1:numel(configLabels)
    configLabel = configLabels(configIdx);
    seedTable = seedTables{configIdx};
    for seedIdx = 1:height(seedTable)
        diagnostic = analyzeMotor2Diagnostic(seedTable.finalTestRunDir(seedIdx), "");
        metricsByMotor = diagnostic.metricsByMotor;
        for motorRowIdx = 1:height(metricsByMotor)
            rowIdx = rowIdx + 1;
            rows{rowIdx} = struct( ...
                "configLabel", configLabel, ...
                "seed", double(seedTable.seed(seedIdx)), ...
                "motor", double(metricsByMotor.motor(motorRowIdx)), ...
                "selectedCheckpointEpisode", ...
                    double(seedTable.selectedCheckpointEpisode(seedIdx)), ...
                "trackingMSE", double(metricsByMotor.trackingMSE(motorRowIdx)), ...
                "trackingMAE", double(metricsByMotor.trackingMAE(motorRowIdx)), ...
                "responseRange", double(metricsByMotor.responseRange(motorRowIdx)), ...
                "targetRange", double(metricsByMotor.targetRange(motorRowIdx)), ...
                "actionL2", double(metricsByMotor.actionL2(motorRowIdx)), ...
                "actionRange", double(metricsByMotor.actionRange(motorRowIdx)), ...
                "saturationFraction", ...
                    double(metricsByMotor.saturationFraction(motorRowIdx)), ...
                "flatResponse", logical(metricsByMotor.flatResponse(motorRowIdx)), ...
                "actionNoMotion", logical(metricsByMotor.actionNoMotion(motorRowIdx)), ...
                "highActionFlatResponse", ...
                    logical(metricsByMotor.highActionFlatResponse(motorRowIdx)), ...
                "finalTestRunDir", string(seedTable.finalTestRunDir(seedIdx)));
        end
    end
end
bySeedTable = struct2table(vertcat(rows{:}));
end

function summaryTable = localBuildSummaryTable(bySeedTable)
configLabels = unique(bySeedTable.configLabel, "stable");
rows = cell(numel(configLabels) * 4, 1);
rowIdx = 0;
for configIdx = 1:numel(configLabels)
    for motorIdx = 1:4
        subset = bySeedTable(bySeedTable.configLabel == configLabels(configIdx) & ...
            bySeedTable.motor == motorIdx, :);
        rowIdx = rowIdx + 1;
        rows{rowIdx} = struct( ...
            "configLabel", configLabels(configIdx), ...
            "motor", motorIdx, ...
            "numSeeds", height(subset), ...
            "trackingMSE", mean(subset.trackingMSE, "omitnan"), ...
            "trackingMAE", mean(subset.trackingMAE, "omitnan"), ...
            "responseRange", mean(subset.responseRange, "omitnan"), ...
            "targetRange", mean(subset.targetRange, "omitnan"), ...
            "actionL2", mean(subset.actionL2, "omitnan"), ...
            "actionRange", mean(subset.actionRange, "omitnan"), ...
            "saturationFraction", mean(subset.saturationFraction, "omitnan"), ...
            "flatResponseCount", sum(subset.flatResponse), ...
            "actionNoMotionCount", sum(subset.actionNoMotion), ...
            "highActionFlatResponseCount", ...
                sum(subset.highActionFlatResponse));
    end
end
summaryTable = struct2table(vertcat(rows{:}));
end

function comparisonTable = localBuildComparisonTable(summaryTable, options)
baseline = summaryTable(summaryTable.configLabel == options.configLabels(1), :);
calibrated = summaryTable(summaryTable.configLabel == options.configLabels(2), :);
if isempty(baseline) || isempty(calibrated)
    error("Baseline and calibrated rows are required for comparison.");
end

rows = cell(4, 1);
for motorIdx = 1:4
    baseRow = baseline(baseline.motor == motorIdx, :);
    calRow = calibrated(calibrated.motor == motorIdx, :);
    trackingRegression = calRow.trackingMSE > ...
        options.maxTrackingRegression * baseRow.trackingMSE;
    rangeRegression = calRow.responseRange < ...
        options.minRangeRatio * baseRow.responseRange;
    saturationRegression = calRow.saturationFraction > max( ...
        options.saturationFloor, ...
        options.maxSaturationRegression * baseRow.saturationFraction);
    flatRegression = calRow.flatResponseCount > baseRow.flatResponseCount;
    actionNoMotionRegression = calRow.actionNoMotionCount > ...
        baseRow.actionNoMotionCount;
    highActionFlatRegression = calRow.highActionFlatResponseCount > ...
        baseRow.highActionFlatResponseCount;

    rows{motorIdx} = struct( ...
        "motor", motorIdx, ...
        "baselineTrackingMSE", baseRow.trackingMSE, ...
        "calibratedTrackingMSE", calRow.trackingMSE, ...
        "trackingMSEDelta", calRow.trackingMSE - baseRow.trackingMSE, ...
        "baselineResponseRange", baseRow.responseRange, ...
        "calibratedResponseRange", calRow.responseRange, ...
        "responseRangeDelta", calRow.responseRange - baseRow.responseRange, ...
        "baselineSaturation", baseRow.saturationFraction, ...
        "calibratedSaturation", calRow.saturationFraction, ...
        "saturationDelta", calRow.saturationFraction - baseRow.saturationFraction, ...
        "baselineFlatFlags", baseRow.flatResponseCount, ...
        "calibratedFlatFlags", calRow.flatResponseCount, ...
        "baselineActionNoMotionFlags", baseRow.actionNoMotionCount, ...
        "calibratedActionNoMotionFlags", calRow.actionNoMotionCount, ...
        "baselineHighActionFlatFlags", baseRow.highActionFlatResponseCount, ...
        "calibratedHighActionFlatFlags", calRow.highActionFlatResponseCount, ...
        "trackingRegression", trackingRegression, ...
        "rangeRegression", rangeRegression, ...
        "saturationRegression", saturationRegression, ...
        "flatRegression", flatRegression, ...
        "actionNoMotionRegression", actionNoMotionRegression, ...
        "highActionFlatRegression", highActionFlatRegression, ...
        "anyRegression", trackingRegression || rangeRegression || ...
            saturationRegression || flatRegression || actionNoMotionRegression || ...
            highActionFlatRegression);
end
comparisonTable = struct2table(vertcat(rows{:}));
end

function markdownText = localBuildMarkdown(resultsRoot, comparisonTable)
lines = strings(0, 1);
lines(end+1) = "# All-motor regression validation";
lines(end+1) = "";
lines(end+1) = sprintf("Run: `%s`", string(resultsRoot));
lines(end+1) = "";
lines(end+1) = "| Motor | Baseline MSE | Cal MSE | Baseline range | Cal range | Baseline sat | Cal sat | Flat B/C | No-motion B/C | High-action-flat B/C | Regression |";
lines(end+1) = "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |";
for i = 1:height(comparisonTable)
    lines(end+1) = sprintf("| M%d | %.6f | %.6f | %.6f | %.6f | %.6f | %.6f | %d/%d | %d/%d | %d/%d | %d |", ...
        comparisonTable.motor(i), ...
        comparisonTable.baselineTrackingMSE(i), ...
        comparisonTable.calibratedTrackingMSE(i), ...
        comparisonTable.baselineResponseRange(i), ...
        comparisonTable.calibratedResponseRange(i), ...
        comparisonTable.baselineSaturation(i), ...
        comparisonTable.calibratedSaturation(i), ...
        comparisonTable.baselineFlatFlags(i), ...
        comparisonTable.calibratedFlatFlags(i), ...
        comparisonTable.baselineActionNoMotionFlags(i), ...
        comparisonTable.calibratedActionNoMotionFlags(i), ...
        comparisonTable.baselineHighActionFlatFlags(i), ...
        comparisonTable.calibratedHighActionFlatFlags(i), ...
        comparisonTable.anyRegression(i)); %#ok<AGROW>
end
markdownText = strjoin(lines, newline);
end

function localWriteTextFile(filePath, textValue)
fid = fopen(filePath, "w");
if fid < 0
    error("Unable to write file: %s", filePath);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s\n", string(textValue));
end
