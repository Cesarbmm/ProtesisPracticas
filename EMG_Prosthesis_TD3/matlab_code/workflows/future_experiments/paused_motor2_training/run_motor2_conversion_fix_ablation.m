function results = run_motor2_conversion_fix_ablation(options)
%run_motor2_conversion_fix_ablation runs a short conversion-fix ablation.
%
% This launcher is simulation-only. It compares baseline conversion and the
% experimental motor2Calibrated conversion with baseline and calibrated
% quantized actions. Defaults are intentionally short.

arguments
    options = struct()
end

paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = char(paths.matlabRoot);
workspaceRoot = char(paths.workspaceRoot);
cd(matlabRoot);
addpath(genpath(matlabRoot));
clearConfigurablesOverride();

baseConfigs = configurables();
options = localNormalizeOptions(options, baseConfigs, workspaceRoot);
ensureDirectoryExists(options.resultsRoot);
ensureDirectoryExists(options.summaryRoot);
ensureDirectoryExists(options.figuresRoot);

configs = localBuildConfigs(options);
seedTables = cell(numel(configs), 1);
configResults = cell(numel(configs), 1);

for configIdx = 1:numel(configs)
    [seedTables{configIdx}, configResults{configIdx}] = localRunConfig( ...
        configs(configIdx), options);
end

perSeedTable = vertcat(seedTables{:});
summaryTable = localSummarize(perSeedTable);
summaryTable.acceptedConversion = localEvaluateAcceptance(summaryTable);

summaryCsvPath = fullfile(options.summaryRoot, ...
    "motor2_conversion_fix_ablation_summary.csv");
summaryTxtPath = fullfile(options.summaryRoot, ...
    "motor2_conversion_fix_ablation_summary.txt");
matPath = fullfile(options.summaryRoot, ...
    "motor2_conversion_fix_ablation_results.mat");
motor2FigurePath = fullfile(options.figuresRoot, ...
    "motor2_fix_ablation_summary.png");
regressionFigurePath = fullfile(options.figuresRoot, ...
    "all_motor_regression_summary.png");

writetable(summaryTable, summaryCsvPath);
localWriteTextFile(summaryTxtPath, localBuildSummaryText(options, summaryTable));
localCreateMotor2SummaryFigure(summaryTable, motor2FigurePath);
localCreateAllMotorFigure(summaryTable, regressionFigurePath);
visualFigures = localCopyCuratedVisualTests(configResults, options.figuresRoot);

results = struct();
results.resultsRoot = string(options.resultsRoot);
results.summaryRoot = string(options.summaryRoot);
results.figuresRoot = string(options.figuresRoot);
results.options = options;
results.configResults = configResults;
results.perSeedTable = perSeedTable;
results.summaryTable = summaryTable;
results.visualFigures = visualFigures;
results.figurePaths = struct( ...
    "motor2Summary", string(motor2FigurePath), ...
    "allMotorRegression", string(regressionFigurePath));

save(matPath, "results", "perSeedTable", "summaryTable", ...
    "options", "configResults", "visualFigures");
end

