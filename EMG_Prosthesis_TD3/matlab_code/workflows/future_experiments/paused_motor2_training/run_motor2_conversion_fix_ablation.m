function visualFigures = localCopyCuratedVisualTests(configResults, figuresRoot)
maxCount = 0;
for i = 1:numel(configResults)
    result = configResults{i};
    if isfield(result, "perSeedTable")
        maxCount = maxCount + height(result.perSeedTable);
    end
end

visualFigures = strings(maxCount, 1);
figureIdx = 0;
for i = 1:numel(configResults)
    result = configResults{i};
    if ~isfield(result, "perSeedTable")
        continue;
    end
    for rowIdx = 1:height(result.perSeedTable)
        sourcePath = string(result.perSeedTable.visualTestFigurePath(rowIdx));
        if strlength(sourcePath) == 0 || ~isfile(sourcePath)
            continue;
        end
        seedLabel = string(result.perSeedTable.seedLabel(rowIdx));
        configLabel = string(result.perSeedTable.configLabel(rowIdx));
        targetPath = fullfile(figuresRoot, seedLabel + "_" + ...
            configLabel + "_visual_test.png");
        copyfile(sourcePath, targetPath);
        figureIdx = figureIdx + 1;
        visualFigures(figureIdx, 1) = string(targetPath);
    end
end
visualFigures = visualFigures(1:figureIdx);
end

function levelsByMotor = localNormalizeActionLevelsByMotor(levelsByMotor, fallbackLevels)
if iscell(levelsByMotor)
    tmp = struct();
    for motorIdx = 1:min(4, numel(levelsByMotor))
        tmp.(sprintf("m%d", motorIdx)) = double(levelsByMotor{motorIdx}(:))';
    end
    levelsByMotor = tmp;
end
if ~isstruct(levelsByMotor)
    levelsByMotor = struct();
end
for motorIdx = 1:4
    fieldName = sprintf("m%d", motorIdx);
    if ~isfield(levelsByMotor, fieldName) || isempty(levelsByMotor.(fieldName))
        levelsByMotor.(fieldName) = fallbackLevels;
    else
        levelsByMotor.(fieldName) = double(levelsByMotor.(fieldName)(:))';
    end
end
end

