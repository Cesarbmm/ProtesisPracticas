function summaryTable = localSummarize(perSeedTable)
labels = unique(string(perSeedTable.configLabel), "stable");
rows = cell(numel(labels), 1);
for i = 1:numel(labels)
    subset = perSeedTable(string(perSeedTable.configLabel) == labels(i), :);
    row = struct( ...
        "configLabel", labels(i), ...
        "numSeeds", height(subset), ...
        "trackingMSE", mean(double(subset.trackingMSE), "omitnan"), ...
        "trackingMAE", mean(double(subset.trackingMAE), "omitnan"), ...
        "actionL2", mean(double(subset.actionL2), "omitnan"), ...
        "saturationFraction", mean(double(subset.saturationFraction), "omitnan"), ...
        "deltaActionL2", mean(double(subset.deltaActionL2), "omitnan"), ...
        "motor2_flat_response_count", sum(logical(subset.motor2_flat_response)), ...
        "motor2_action_no_motion_count", ...
            sum(logical(subset.motor2_action_no_motion)));
    for motorIdx = 1:4
        row.(sprintf("trackingMSE_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("trackingMSE_motor%d", motorIdx))), "omitnan");
        row.(sprintf("trackingMAE_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("trackingMAE_motor%d", motorIdx))), "omitnan");
        row.(sprintf("actionL2_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("actionL2_motor%d", motorIdx))), "omitnan");
        row.(sprintf("actionRange_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("actionRange_motor%d", motorIdx))), "omitnan");
        row.(sprintf("saturationFraction_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("saturationFraction_motor%d", motorIdx))), "omitnan");
        row.(sprintf("responseRange_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("responseRange_motor%d", motorIdx))), "omitnan");
        row.(sprintf("targetRange_motor%d", motorIdx)) = mean(double( ...
            subset.(sprintf("targetRange_motor%d", motorIdx))), "omitnan");
        row.(sprintf("flat_response_count_motor%d", motorIdx)) = ...
            localOptionalLogicalCount(subset, sprintf("flat_response_motor%d", motorIdx));
        row.(sprintf("action_no_motion_count_motor%d", motorIdx)) = ...
            localOptionalLogicalCount(subset, sprintf("action_no_motion_motor%d", motorIdx));
        row.(sprintf("high_action_flat_response_count_motor%d", motorIdx)) = ...
            localOptionalLogicalCount(subset, ...
            sprintf("high_action_flat_response_motor%d", motorIdx));
    end
    rows{i} = row;
end
summaryTable = struct2table(vertcat(rows{:}));
end

function accepted = localEvaluateAcceptance(summaryTable)
accepted = false(height(summaryTable), 1);
baseline = summaryTable(string(summaryTable.configLabel) == ...
    "baseline_quantized_conversion_baseline", :);
if isempty(baseline)
    return;
end

for i = 1:height(summaryTable)
    if string(summaryTable.configLabel(i)) == ...
            "baseline_quantized_conversion_baseline"
        continue;
    end
    motor2RangePass = summaryTable.responseRange_motor2(i) >= 0.17 || ...
        summaryTable.responseRange_motor2(i) >= ...
            0.40 * summaryTable.targetRange_motor2(i);
    motor2Improved = ...
        summaryTable.motor2_flat_response_count(i) == 0 && ...
        summaryTable.motor2_action_no_motion_count(i) == 0 && ...
        motor2RangePass && ...
        summaryTable.trackingMSE_motor2(i) <= baseline.trackingMSE_motor2;
    globalOk = summaryTable.trackingMSE(i) <= 1.10 * baseline.trackingMSE;
    allMotorsOk = true;
    for motorIdx = 1:4
        trackingField = sprintf("trackingMSE_motor%d", motorIdx);
        rangeField = sprintf("responseRange_motor%d", motorIdx);
        saturationField = sprintf("saturationFraction_motor%d", motorIdx);
        flatField = sprintf("flat_response_count_motor%d", motorIdx);
        noMotionField = sprintf("action_no_motion_count_motor%d", motorIdx);
        highActionFlatField = sprintf( ...
            "high_action_flat_response_count_motor%d", motorIdx);
        allMotorsOk = allMotorsOk && ...
            summaryTable.(trackingField)(i) <= 1.10 * baseline.(trackingField) && ...
            summaryTable.(rangeField)(i) >= 0.90 * baseline.(rangeField) && ...
            summaryTable.(saturationField)(i) <= max(0.02, ...
                1.15 * baseline.(saturationField)) && ...
            summaryTable.(flatField)(i) <= baseline.(flatField) && ...
            summaryTable.(noMotionField)(i) <= baseline.(noMotionField) && ...
            summaryTable.(highActionFlatField)(i) <= ...
                baseline.(highActionFlatField);
    end
    accepted(i) = motor2Improved && globalOk && allMotorsOk;
end
end

function value = localOptionalLogicalCount(tableValue, fieldName)
if ismember(fieldName, string(tableValue.Properties.VariableNames))
    value = sum(logical(tableValue.(fieldName)));
else
    value = 0;
end
end

