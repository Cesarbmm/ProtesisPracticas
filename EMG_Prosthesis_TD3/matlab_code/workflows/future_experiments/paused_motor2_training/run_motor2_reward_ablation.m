function results = run_motor2_reward_ablation(options)
%run_motor2_reward_ablation runs short TD3 ablations focused on motor 2.

arguments
    options = struct()
end

options = localNormalizeOptions(options);

paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = char(paths.matlabRoot);
workspaceRoot = char(paths.workspaceRoot);
cd(matlabRoot);
addpath(genpath(matlabRoot));
clearConfigurablesOverride();

resultsRoot = localResolveResultsRoot(options.resultsRoot, workspaceRoot);
summaryRoot = fullfile(resultsRoot, "summary");
figuresRoot = fullfile(resultsRoot, "figures");
ensureDirectoryExists(resultsRoot);
ensureDirectoryExists(summaryRoot);
ensureDirectoryExists(figuresRoot);

configs = localBuildAblationConfigs(options.mode, options.configNames);
seedTables = cell(numel(configs), 1);
configResults = cell(numel(configs), 1);

for configIdx = 1:numel(configs)
    cfg = configs(configIdx);
    configRoot = fullfile(resultsRoot, char(cfg.label));
    runOptions = struct( ...
        "seeds", options.seeds, ...
        "trainingEpisodes", options.trainingEpisodes, ...
        "trainingSaveEvery", options.trainingSaveEvery, ...
        "episodeSaveFreq", options.episodeSaveFreq, ...
        "auditFastSimulations", options.auditFastSimulations, ...
        "auditFullSimulations", options.auditFullSimulations, ...
        "auditTopK", options.auditTopK, ...
        "finalTestEpisodes", options.finalTestEpisodes, ...
        "plotEpisodeOnTest", options.plotEpisodeOnTest, ...
        "useGpu", options.useGpu, ...
        "selectionMode", options.selectionMode, ...
        "rewardType", cfg.rewardType, ...
        "rewardMotorWeights", cfg.rewardMotorWeights, ...
        "rewardActionMotorWeights", cfg.rewardActionMotorWeights, ...
        "rewardDeltaActionMotorWeights", cfg.rewardDeltaActionMotorWeights, ...
        "quantizeCommandsForSimulation", cfg.quantizeCommandsForSimulation, ...
        "actionCommandLevels", cfg.actionCommandLevels, ...
        "configLabel", cfg.label, ...
        "runMotor2SanityCheck", false, ...
        "evaluateReferenceCheckpoints", false, ...
        "generateReport", false, ...
        "compileReport", false, ...
        "resultsRoot", string(configRoot));
    configResults{configIdx} = run_benchmark_td3_seeded_retrain_motor2_diagnostic(runOptions);
    seedTables{configIdx} = configResults{configIdx}.perSeedTable;
end

perSeedTable = vertcat(seedTables{:});
ablationSummary = localSummarizeAblations(perSeedTable);
referenceTable = localBuildReferenceTable(ablationSummary);

summaryCsvPath = fullfile(summaryRoot, "ablation_summary.csv");
motor2FigurePath = fullfile(figuresRoot, "ablation_motor2_summary.png");
comparisonFigurePath = fullfile(figuresRoot, "ablation_final_comparison.png");
writetable(ablationSummary, summaryCsvPath);
writetable(referenceTable, fullfile(summaryRoot, "ablation_final_comparison.csv"));
localCreateMotor2SummaryFigure(ablationSummary, motor2FigurePath);
localCreateFinalComparisonFigure(referenceTable, comparisonFigurePath);
localWriteTextFile(fullfile(summaryRoot, "ablation_summary.txt"), ...
    localBuildSummaryText(options, ablationSummary, resultsRoot));

results = struct();
results.resultsRoot = string(resultsRoot);
results.summaryRoot = string(summaryRoot);
results.figuresRoot = string(figuresRoot);
results.options = options;
results.configs = configs;
results.configResults = configResults;
results.perSeedTable = perSeedTable;
results.ablationSummary = ablationSummary;
results.referenceTable = referenceTable;
results.figurePaths = struct( ...
    "motor2Summary", string(motor2FigurePath), ...
    "finalComparison", string(comparisonFigurePath));

save(fullfile(summaryRoot, "ablation_results.mat"), ...
    "results", "perSeedTable", "ablationSummary", "referenceTable", ...
    "options", "configResults");
end

function options = localNormalizeOptions(options)
defaults = struct( ...
    "mode", "standard", ...
    "seeds", [11 22 55], ...
    "trainingEpisodes", 3000, ...
    "trainingSaveEvery", 100, ...
    "episodeSaveFreq", 100, ...
    "auditFastSimulations", 5, ...
    "auditFullSimulations", 10, ...
    "auditTopK", 5, ...
    "finalTestEpisodes", 20, ...
    "plotEpisodeOnTest", true, ...
    "useGpu", true, ...
    "selectionMode", "motor2_aware", ...
    "configNames", string.empty(1, 0), ...
    "resultsRoot", "");

fields = fieldnames(defaults);
for i = 1:numel(fields)
    if ~isfield(options, fields{i}) || isempty(options.(fields{i}))
        options.(fields{i}) = defaults.(fields{i});
    end
end

options.mode = lower(string(options.mode));
options.seeds = double(options.seeds(:))';
options.trainingEpisodes = double(options.trainingEpisodes);
options.trainingSaveEvery = double(options.trainingSaveEvery);
options.episodeSaveFreq = double(options.episodeSaveFreq);
options.auditFastSimulations = max(1, double(options.auditFastSimulations));
options.auditFullSimulations = max(1, double(options.auditFullSimulations));
options.auditTopK = max(1, double(options.auditTopK));
options.finalTestEpisodes = max(1, double(options.finalTestEpisodes));
options.plotEpisodeOnTest = logical(options.plotEpisodeOnTest);
options.useGpu = logical(options.useGpu);
options.selectionMode = lower(string(options.selectionMode));
options.configNames = string(options.configNames);
options.resultsRoot = string(options.resultsRoot);
end

function configs = localBuildAblationConfigs(mode, requestedNames)
baseLevels = [0 64 96 128 160 192 224 255];
allConfigs = [ ...
    struct( ...
        "label", "baseline_current", ...
        "rewardType", "trackingMseActionRateReward", ...
        "rewardMotorWeights", [1 2 1 1], ...
        "rewardActionMotorWeights", [1 1 1 1], ...
        "rewardDeltaActionMotorWeights", [1 1 1 1], ...
        "quantizeCommandsForSimulation", true, ...
        "actionCommandLevels", baseLevels), ...
    struct( ...
        "label", "motor2_weight_2", ...
        "rewardType", "trackingMseActionRateMotorWeightedReward", ...
        "rewardMotorWeights", [1 2 1 1], ...
        "rewardActionMotorWeights", [1 1 1 1], ...
        "rewardDeltaActionMotorWeights", [1 1 1 1], ...
        "quantizeCommandsForSimulation", true, ...
        "actionCommandLevels", baseLevels), ...
    struct( ...
        "label", "motor2_weight_3", ...
        "rewardType", "trackingMseActionRateMotorWeightedReward", ...
        "rewardMotorWeights", [1 3 1 1], ...
        "rewardActionMotorWeights", [1 1 1 1], ...
        "rewardDeltaActionMotorWeights", [1 1 1 1], ...
        "quantizeCommandsForSimulation", true, ...
        "actionCommandLevels", baseLevels), ...
    struct( ...
        "label", "motor2_weight_2_low_action_motor2", ...
        "rewardType", "trackingMseActionRateMotorWeightedReward", ...
        "rewardMotorWeights", [1 2 1 1], ...
        "rewardActionMotorWeights", [1 0.5 1 1], ...
        "rewardDeltaActionMotorWeights", [1 0.5 1 1], ...
        "quantizeCommandsForSimulation", true, ...
        "actionCommandLevels", baseLevels), ...
    struct( ...
        "label", "continuous_action_baseline", ...
        "rewardType", "trackingMseActionRateReward", ...
        "rewardMotorWeights", [1 2 1 1], ...
        "rewardActionMotorWeights", [1 1 1 1], ...
        "rewardDeltaActionMotorWeights", [1 1 1 1], ...
        "quantizeCommandsForSimulation", false, ...
        "actionCommandLevels", baseLevels)];

if ~isempty(requestedNames)
    keep = ismember(string({allConfigs.label}), requestedNames);
    configs = allConfigs(keep);
elseif mode == "smoke"
    configs = allConfigs(1:2);
else
    configs = allConfigs;
end

if isempty(configs)
    error("No ablation configs selected.");
end
end

function summaryTable = localSummarizeAblations(perSeedTable)
configLabels = unique(string(perSeedTable.configLabel), "stable");
rows = cell(numel(configLabels), 1);
for i = 1:numel(configLabels)
    idx = string(perSeedTable.configLabel) == configLabels(i);
    subset = perSeedTable(idx, :);
    nSeeds = height(subset);
    flatCount = sum(logical(subset.motor2_flat_response));
    actionNoMotionCount = sum(logical(subset.motor2_action_no_motion));
    rows{i} = struct( ...
        "configLabel", configLabels(i), ...
        "numSeeds", nSeeds, ...
        "trackingMSE", mean(double(subset.trackingMSE), "omitnan"), ...
        "trackingMAE", mean(double(subset.trackingMAE), "omitnan"), ...
        "actionL2", mean(double(subset.actionL2), "omitnan"), ...
        "saturationFraction", mean(double(subset.saturationFraction), "omitnan"), ...
        "deltaActionL2", mean(double(subset.deltaActionL2), "omitnan"), ...
        "trackingMSE_motor2", mean(double(subset.trackingMSE_motor2), "omitnan"), ...
        "responseRange_motor2", mean(double(subset.responseRange_motor2), "omitnan"), ...
        "targetRange_motor2", mean(double(subset.targetRange_motor2), "omitnan"), ...
        "motor2_flat_response_count", flatCount, ...
        "motor2_action_no_motion_count", actionNoMotionCount, ...
        "motor2_tracking_outlier_count", sum(logical(subset.motor2_tracking_outlier)));
end
summaryTable = struct2table(vertcat(rows{:}));
summaryTable.acceptedShortCampaign = localEvaluateAcceptance(summaryTable);
end

function accepted = localEvaluateAcceptance(summaryTable)
accepted = false(height(summaryTable), 1);
baselineIdx = find(string(summaryTable.configLabel) == "baseline_current", 1);
if isempty(baselineIdx)
    baselineTracking = summaryTable.trackingMSE(1);
    baselineMotor2 = summaryTable.trackingMSE_motor2(1);
else
    baselineTracking = summaryTable.trackingMSE(baselineIdx);
    baselineMotor2 = summaryTable.trackingMSE_motor2(baselineIdx);
end

for i = 1:height(summaryTable)
    maxFlagCount = max(1, floor(summaryTable.numSeeds(i) / 3));
    responseOk = summaryTable.responseRange_motor2(i) >= 0.20 || ...
        summaryTable.responseRange_motor2(i) >= 0.50 * summaryTable.targetRange_motor2(i);
    accepted(i) = ...
        summaryTable.motor2_flat_response_count(i) <= maxFlagCount && ...
        summaryTable.motor2_action_no_motion_count(i) <= maxFlagCount && ...
        responseOk && ...
        summaryTable.trackingMSE_motor2(i) <= baselineMotor2 && ...
        summaryTable.trackingMSE(i) <= 1.10 * baselineTracking;
end
end

function referenceTable = localBuildReferenceTable(ablationSummary)
benchmark = getAgent7250Benchmark();
rows = cell(height(ablationSummary) + 1, 1);
rows{1} = struct( ...
    "candidateLabel", "Agent7250", ...
    "trackingMSE", benchmark.trackingMse, ...
    "trackingMAE", benchmark.trackingMae, ...
    "actionL2", benchmark.actionL2, ...
    "saturationFraction", benchmark.saturationFraction, ...
    "deltaActionL2", benchmark.deltaActionL2, ...
    "trackingMSE_motor2", NaN, ...
    "responseRange_motor2", NaN);
for i = 1:height(ablationSummary)
    rows{i+1} = struct( ...
        "candidateLabel", string(ablationSummary.configLabel(i)), ...
        "trackingMSE", double(ablationSummary.trackingMSE(i)), ...
        "trackingMAE", double(ablationSummary.trackingMAE(i)), ...
        "actionL2", double(ablationSummary.actionL2(i)), ...
        "saturationFraction", double(ablationSummary.saturationFraction(i)), ...
        "deltaActionL2", double(ablationSummary.deltaActionL2(i)), ...
        "trackingMSE_motor2", double(ablationSummary.trackingMSE_motor2(i)), ...
        "responseRange_motor2", double(ablationSummary.responseRange_motor2(i)));
end
referenceTable = struct2table(vertcat(rows{:}));
end

function localCreateMotor2SummaryFigure(summaryTable, figurePath)
f = figure("Visible", "off", "Color", "w", "Position", [100 100 1500 900]);
tiledlayout(f, 2, 2, "TileSpacing", "compact", "Padding", "compact");
labels = categorical(string(summaryTable.configLabel));
localBar(nexttile, labels, summaryTable.trackingMSE_motor2, "Motor 2 tracking MSE");
localBar(nexttile, labels, summaryTable.responseRange_motor2, "Motor 2 response range");
localBar(nexttile, labels, summaryTable.motor2_flat_response_count, "Motor 2 flat flags");
localBar(nexttile, labels, summaryTable.motor2_action_no_motion_count, "Motor 2 action-no-motion flags");
sgtitle(f, "Motor 2 ablation summary");
localEnsureParentDirectoryExists(figurePath);
exportgraphics(f, figurePath, "Resolution", 220);
close(f);
end

function localCreateFinalComparisonFigure(referenceTable, figurePath)
metrics = ["trackingMSE", "saturationFraction", "actionL2", "trackingMSE_motor2", "responseRange_motor2"];
labels = categorical(string(referenceTable.candidateLabel));
f = figure("Visible", "off", "Color", "w", "Position", [100 100 1600 900]);
tiledlayout(f, 2, 3, "TileSpacing", "compact", "Padding", "compact");
for i = 1:numel(metrics)
    localBar(nexttile, labels, double(referenceTable.(metrics(i))), metrics(i));
end
sgtitle(f, "Ablation final comparison");
localEnsureParentDirectoryExists(figurePath);
exportgraphics(f, figurePath, "Resolution", 220);
close(f);
end

function localBar(ax, labels, values, plotTitle)
bar(ax, labels, values, "FaceColor", [0.12 0.47 0.71], "FaceAlpha", 0.85);
grid(ax, "on");
title(ax, plotTitle, "Interpreter", "none");
set(ax, "XTickLabelRotation", 35);
end

function textValue = localBuildSummaryText(options, summaryTable, resultsRoot)
lines = strings(0, 1);
lines(end+1) = "Motor 2 reward ablation";
lines(end+1) = "=======================";
lines(end+1) = "";
lines(end+1) = sprintf("Results root: %s", string(resultsRoot));
lines(end+1) = sprintf("Seeds: %s", mat2str(options.seeds));
lines(end+1) = sprintf("Training episodes: %d", round(options.trainingEpisodes));
lines(end+1) = sprintf("Final test episodes: %d", round(options.finalTestEpisodes));
lines(end+1) = sprintf("Selection mode: %s", string(options.selectionMode));
lines(end+1) = "";
for i = 1:height(summaryTable)
    lines(end+1) = sprintf( ...
        "%s | motor2MSE %.6f | motor2Range %.6f | flat %d | actionNoMotion %d | accepted %d", ...
        string(summaryTable.configLabel(i)), summaryTable.trackingMSE_motor2(i), ...
        summaryTable.responseRange_motor2(i), summaryTable.motor2_flat_response_count(i), ...
        summaryTable.motor2_action_no_motion_count(i), summaryTable.acceptedShortCampaign(i)); %#ok<AGROW>
end
textValue = strjoin(lines, newline);
end

function resultsRoot = localResolveResultsRoot(requestedRoot, workspaceRoot)
requestedRoot = string(requestedRoot);
if strlength(requestedRoot) > 0
    baseRoot = char(requestedRoot);
else
    baseRoot = fullfile(workspaceRoot, "Agentes", "motor2_reward_ablation", ...
        string(datetime("now", "Format", "yy-MM-dd_HH-mm-ss")));
end
resultsRoot = localMakeUniqueDirectoryPath(baseRoot);
end

function uniquePath = localMakeUniqueDirectoryPath(basePath)
basePath = char(string(basePath));
if ~exist(basePath, "dir")
    uniquePath = basePath;
    return;
end
for i = 1:999
    candidatePath = sprintf("%s_%02d", basePath, i);
    if ~exist(candidatePath, "dir")
        uniquePath = candidatePath;
        return;
    end
end
error("Could not create a unique results directory for %s", basePath);
end

function localEnsureParentDirectoryExists(filePath)
[parentDir, ~, ~] = fileparts(char(string(filePath)));
if strlength(string(parentDir)) > 0
    ensureDirectoryExists(parentDir);
end
end

function localWriteTextFile(filePath, textValue)
fid = fopen(filePath, "w");
if fid < 0
    error("Could not open %s for writing.", filePath);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s", textValue);
end
