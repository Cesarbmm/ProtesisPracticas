    "seedResults", {data.seedResults});
end

function assertBoundedFreshSmoke(report, expectedVariant, expectedLength)
m = report.manifest;
checkpointEpisodes = sort(double(report.checkpointTable.episode));
valid = string(m.phase) == "smoke" && m.protocol.episodes == 200 && ...
    isequal(double(m.seeds), 11) && m.newTraining && ...
    strlength(string(m.checkpointLoadedForTraining)) == 0 && ...
    ~m.agent7250Loaded && ~m.agent7250UsedAsStartingPoint && ...
    m.simMotors && ~m.hardwareUsed && m.positionSafetyAblation && ...
    string(m.referenceSource) == "emgIntent" && ...
    string(m.observationVariant) == expectedVariant && ...
    double(m.stateLength) == expectedLength && ...
    string(m.rewardType) == "trackingIntentActionRateReward" && ...
    string(m.actionInterfaceVariant) == "baselineQuantized" && ...
    m.intentRewardActionWeight == 0.05 && ...
    ~m.intentHoldRewardEnabled && height(report.checkpointTable) == 4 && ...
    isequal(checkpointEpisodes(:), [50; 100; 150; 200]);
if ~valid
    error("run_no_glove_stage7n_state_ablation:ChildInvariant", ...
        "A child run violates the pre-registered fresh smoke contract.");
end
end

function [audit, profiles] = auditProfiles(controlReport, candidateReport)
controlPath = fullfile(controlReport.outputPath, ...
    "seed_11", "effective_training_profile.mat");
candidatePath = fullfile(candidateReport.outputPath, ...
    "seed_11", "effective_training_profile.mat");
controlData = load(controlPath, "profile");
candidateData = load(candidatePath, "profile");
profiles = struct("control", controlData.profile, ...
    "candidate", candidateData.profile);
normalizedControl = normalizeProfile(profiles.control);
normalizedCandidate = normalizeProfile(profiles.candidate);
audit = struct( ...
    "controlObservationVariant", ...
        string(profiles.control.observationVariant), ...
    "candidateObservationVariant", ...
        string(profiles.candidate.observationVariant), ...
    "equalExceptObservationAndOutputPaths", ...
        isequaln(normalizedControl, normalizedCandidate), ...
    "sameRandomSeed", ...
        profiles.control.randomSeed == profiles.candidate.randomSeed, ...
    "sameEpisodeBudget", profiles.control.trainingMaxEpisodes == ...
        profiles.candidate.trainingMaxEpisodes, ...
    "sameCheckpointCadence", ...
        profiles.control.trainingSaveAgentEvery == ...
        profiles.candidate.trainingSaveAgentEvery, ...
    "sameReward", rewardSettingsEqual( ...
        profiles.control, profiles.candidate), ...
    "sameSafety", isequaln(profiles.control.simulationPositionSafety, ...
        profiles.candidate.simulationPositionSafety), ...
    "profileMatched", false);
audit.profileMatched = audit.equalExceptObservationAndOutputPaths && ...
    audit.sameRandomSeed && audit.sameEpisodeBudget && ...
    audit.sameCheckpointCadence && audit.sameReward && audit.sameSafety;
if ~audit.profileMatched
    error("run_no_glove_stage7n_state_ablation:ProfileMismatch", ...
        "Profiles differ beyond observation variant and output paths.");
end
end

function profile = normalizeProfile(profile)
profile.observationVariant = "<ablated-observation>";
profile.dataset_folder = "<matched-dataset-folder>";
profile = rmfield(profile, "agents_directory");
end

function equal = rewardSettingsEqual(a, b)
fields = ["rewardType", "intentRewardPositionWeight", ...
    "intentRewardVelocityWeight", "intentRewardActionWeight", ...
    "intentRewardDeltaActionWeight", ...
    "intentRewardSaturationWeight", "intentRewardSoftActionLimit"];
equal = all(arrayfun(@(name) isequaln(a.(name), b.(name)), fields));
end

function audit = auditDatasets(control, candidate)
names = ["trainingDatasetPath", "evaluationDatasetPath", ...
    "restDatasetPath"];
equal = false(1, numel(names));
for idx = 1:numel(names)
    a = load(string(control.(names(idx))), "emgs", "metadata");
    b = load(string(candidate.(names(idx))), "emgs", "metadata");
    equal(idx) = isequaln(a.emgs, b.emgs) && ...
        isequaln(a.metadata, b.metadata);
end
audit = struct( ...
    "trainingDatasetContentEqual", equal(1), ...
    "evaluationDatasetContentEqual", equal(2), ...
    "restDatasetContentEqual", equal(3), ...
    "calibrationContentSha256Equal", ...
        string(control.calibrationContentSha256) == ...
        string(candidate.calibrationContentSha256), ...
    "allDatasetContentsEqual", all(equal));
if ~audit.allDatasetContentsEqual || ...
        ~audit.calibrationContentSha256Equal
    error("run_no_glove_stage7n_state_ablation:DatasetMismatch", ...
        "The child runs did not use identical corpus contents.");
end
end

