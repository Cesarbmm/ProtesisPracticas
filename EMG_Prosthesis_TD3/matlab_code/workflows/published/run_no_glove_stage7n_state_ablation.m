function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7n_state_ablation:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct( ...
    "resultsRoot", "", ...
    "stage7mRunRoot", ...
        "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7m_artifacts\stage7m_final\2026-08-29_00-58-24-394", ...
    "completedControlRunRoot", "", ...
    "completedCandidateRunRoot", "", ...
    "evaluationSeed", 7601, ...
    "acceptanceSimulations", 50, ...
    "restSimulations", 24);
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7n_state_ablation:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
stringFields = ["resultsRoot", "stage7mRunRoot", ...
    "completedControlRunRoot", "completedCandidateRunRoot"];
for idx = 1:numel(stringFields)
    name = stringFields(idx);
    options.(name) = string(options.(name));
    if ~isscalar(options.(name)) || ismissing(options.(name))
        error("run_no_glove_stage7n_state_ablation:InvalidStringOption", ...
            "%s must be a scalar string.", name);
    end
end
numericFields = ["evaluationSeed", "acceptanceSimulations", ...
    "restSimulations"];
for idx = 1:numel(numericFields)
    name = numericFields(idx);
    value = options.(name);
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || ...
            value <= 0 || fix(value) ~= value
        error("run_no_glove_stage7n_state_ablation:InvalidCount", ...
            "%s must be a positive integer.", name);
    end
end
if options.evaluationSeed ~= 7601 || ...
        options.acceptanceSimulations ~= 50 || ...
        options.restSimulations ~= 24
    error("run_no_glove_stage7n_state_ablation:ProtocolChanged", ...
        "ETAPA 7N requires seed 7601 and 50/24 evaluations.");
end
end

function audit = validateStage7mParent(runRoot)
manifestPath = fullfile(runRoot, "manifest.json");
if ~isfile(manifestPath)
    error("run_no_glove_stage7n_state_ablation:MissingStage7m", ...
        "ETAPA 7M manifest not found at %s.", manifestPath);
end
expectedHash = ...
    "CDB80438A5BE67E90F2BD58699C38C989815265B26B7F95CC28EA1ED674C7812";
actualHash = fileSha256(manifestPath);
manifest = jsondecode(fileread(manifestPath));
valid = actualHash == expectedHash && string(manifest.stage) == "7M" && ...
    string(manifest.result) == "PASS" && ...
    string(manifest.scientificResult) == ...
        "intentDeclaredRestHoldMarkov62Implemented" && ...
    logical(manifest.observationVariantImplemented) && ...
    ~logical(manifest.hardwareUsed) && ~logical(manifest.dtwCalculated);
if ~valid
    error("run_no_glove_stage7n_state_ablation:Stage7mChanged", ...
        "ETAPA 7M does not match the pre-registered parent.");
end
audit = struct("runRoot", runRoot, "manifestPath", manifestPath, ...
    "manifestSha256", actualHash, ...
    "implementationCommit", string(manifest.gitCommit), ...
    "scientificResult", string(manifest.scientificResult), ...
    "validated", true);
end

