    profiles.candidate, "candidate62_replay", ...
    fullfile(runRoot, "candidate62_initial_actor_replay.bin"));
controlReproducible = parametersEqual(controlFirst, controlSecond);
candidateReproducible = parametersEqual(candidateFirst, candidateSecond);
arrays = [controlRows; candidateRows];
audit = struct( ...
    "randomSeed", 11, ...
    "controlActorLearnableArrayCount", numel(controlFirst), ...
    "candidateActorLearnableArrayCount", numel(candidateFirst), ...
    "controlActorParameterCount", countParameters(controlFirst), ...
    "candidateActorParameterCount", countParameters(candidateFirst), ...
    "controlActorSha256", fileSha256(fullfile( ...
        runRoot, "control60_initial_actor.bin")), ...
    "candidateActorSha256", fileSha256(fullfile( ...
        runRoot, "candidate62_initial_actor.bin")), ...
    "controlReplaySha256", fileSha256(fullfile( ...
        runRoot, "control60_initial_actor_replay.bin")), ...
    "candidateReplaySha256", fileSha256(fullfile( ...
        runRoot, "candidate62_initial_actor_replay.bin")), ...
    "controlInitializationReproducible", controlReproducible, ...
    "candidateInitializationReproducible", candidateReproducible, ...
    "initializationReproducible", ...
        controlReproducible && candidateReproducible, ...
    "tensorIdentityRequiredAcrossVariants", false);
if ~audit.initializationReproducible || ...
        audit.controlActorSha256 ~= audit.controlReplaySha256 || ...
        audit.candidateActorSha256 ~= audit.candidateReplaySha256
    error("run_no_glove_stage7n_state_ablation:InitializationMismatch", ...
        "Fresh actor initialization is not reproducible by seed.");
end
end

function [parameters, rows] = initializeActor(profile, label, binaryPath)
clearConfigurablesOverride();
setConfigurablesOverride(profile);
rng(double(profile.randomSeed), "twister");
agent = agentNoGloveIntentTd3( ...
    Env.defineObservationInfo(), Env.defineActionInfo());
parameters = getLearnableParameters(getActor(agent));
clearConfigurablesOverride();
fid = fopen(binaryPath, "wb");
if fid < 0
    error("run_no_glove_stage7n_state_ablation:BinaryWrite", ...
        "Could not create %s.", binaryPath);
end
cleanup = onCleanup(@() fclose(fid));
rowParts = cell(numel(parameters), 1);
for idx = 1:numel(parameters)
    value = numericParameter(parameters{idx});
    dimensions = size(value);
    fwrite(fid, uint64(numel(dimensions)), "uint64");
    fwrite(fid, uint64(dimensions), "uint64");
    fwrite(fid, value(:), "double");
    rowParts{idx} = table(string(label), idx, ...
        string(mat2str(dimensions)), numel(value), ...
        'VariableNames', ["variant", "arrayIndex", ...
        "dimensions", "parameterCount"]);
end
rows = vertcat(rowParts{:});
end

function value = numericParameter(value)
if isa(value, "dlarray")
    value = extractdata(value);
end
if ~isnumeric(value)
    error("run_no_glove_stage7n_state_ablation:LearnableType", ...
        "Actor learnables must be numeric or dlarray.");
end
value = double(value);
end

function equal = parametersEqual(a, b)
if numel(a) ~= numel(b)
    equal = false;
    return;
end
equal = true;
for idx = 1:numel(a)
    if ~isequaln(numericParameter(a{idx}), numericParameter(b{idx}))
        equal = false;
        return;
    end
end
end

function count = countParameters(parameters)
count = 0;
for idx = 1:numel(parameters)
    count = count + numel(numericParameter(parameters{idx}));
end
end

function [summaryTable, motorTable] = evaluateAllCheckpoints( ...
        label, childReport, profile, runRoot, acceptanceCount, ...
        restCount, evaluationSeed)
inventory = sortrows(childReport.checkpointTable, "episode");
rowParts = cell(height(inventory), 1);
motorParts = cell(height(inventory), 1);
for idx = 1:height(inventory)
    episode = double(inventory.episode(idx));
    checkpointPath = string(inventory.checkpointPath(idx));
    base = fullfile(runRoot, "checkpoint_evaluations", label, ...
        sprintf("episode_%03d", episode));
    acceptanceDir = runEvaluation(profile, checkpointPath, ...
        string(childReport.manifest.evaluationDatasetPath), ...
        fullfile(base, "acceptance"), evaluationSeed, acceptanceCount);
    restDir = runEvaluation(profile, checkpointPath, ...
        string(childReport.manifest.restDatasetPath), ...
        fullfile(base, "steady_rest"), evaluationSeed, restCount);
    [rowParts{idx}, motorParts{idx}] = summarizeCheckpoint( ...
        label, episode, checkpointPath, ...
        string(inventory.checkpointSha256(idx)), ...
        acceptanceDir, restDir, profile, ...
        double(childReport.manifest.restFalseActivationFraction));
end
summaryTable = vertcat(rowParts{:});
motorTable = vertcat(motorParts{:});
end

