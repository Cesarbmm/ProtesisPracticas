evaluationProfile.flagSaveTraining = true;
evaluationProfile.episode_save_freq = 1;
evaluationProfile.plotEpisodeOnTest = false;
evaluationProfile.simOpts = rlSimulationOptions( ...
    "MaxSteps", evaluationProfile.maxNumberStepsInEpisodes, ...
    "NumSimulations", simulationCount, "StopOnError", "on", ...
    "UseParallel", false);
evaluationProfile.agents_directory = @(agent_id, variant) fullfile( ...
    evaluationBase, string(datetime("now", "Format", "yy-MM-dd HH m s")));
setConfigurablesOverride(evaluationProfile);
evaluationCleanup = onCleanup(@() clearConfigurablesOverride());
