function configsToRun = localSelectInitialConfigs(allConfigs, options)
if ~isempty(options.configNames)
    keep = ismember(string({allConfigs.label}), options.configNames);
    configsToRun = allConfigs(keep);
    if isempty(configsToRun)
        error("No calibrated action ablation configs selected.");
    end
    return;
end

configsToRun = allConfigs(1:3);
end

function [seedTables, configResults] = localRunConfig( ...
        cfg, options, resultsRoot, seedTables, configResults)
configRoot = fullfile(resultsRoot, char(cfg.label));
runOptions = struct( ...
    "seeds", options.seeds, ...
    "trainingEpisodes", options.trainingEpisodes, ...
    "trainingSaveEvery", options.trainingSaveEvery, ...
    "episodeSaveFreq", options.episodeSaveFreq, ...
    "auditFastSimulations", options.auditFastSimulations, ...
    "auditFullSimulations", options.auditFullSimulations, ...
    "auditTopK", options.auditTopK, ...
    "finalTestEpisodes", options.finalTestEpisodes, ...
    "plotEpisodeOnTest", options.plotEpisodeOnTest, ...
    "useGpu", options.useGpu, ...
    "selectionMode", options.selectionMode, ...
    "rewardType", cfg.rewardType, ...
    "rewardMotorWeights", cfg.rewardMotorWeights, ...
    "rewardActionMotorWeights", cfg.rewardActionMotorWeights, ...
    "rewardDeltaActionMotorWeights", cfg.rewardDeltaActionMotorWeights, ...
    "quantizeCommandsForSimulation", cfg.quantizeCommandsForSimulation, ...
    "actionInterfaceVariant", cfg.actionInterfaceVariant, ...
    "actionCommandLevels", cfg.actionCommandLevels, ...
    "actionCommandLevelsByMotor", cfg.actionCommandLevelsByMotor, ...
    "configLabel", cfg.label, ...
    "runMotor2SanityCheck", false, ...
    "evaluateReferenceCheckpoints", false, ...
    "generateReport", false, ...
    "compileReport", false, ...
    "resultsRoot", string(configRoot));

result = run_benchmark_td3_seeded_retrain_motor2_diagnostic(runOptions);
configResults{end+1, 1} = result;
seedTables{end+1, 1} = result.perSeedTable;
end

function levelsByMotor = localNormalizeActionLevelsByMotor(levelsByMotor, fallbackLevels)
if iscell(levelsByMotor)
    tmp = struct();
    for motorIdx = 1:min(4, numel(levelsByMotor))
        tmp.(sprintf("m%d", motorIdx)) = double(levelsByMotor{motorIdx}(:))';
    end
    levelsByMotor = tmp;
end
if ~isstruct(levelsByMotor)
    levelsByMotor = struct();
end
for motorIdx = 1:4
    fieldName = sprintf("m%d", motorIdx);
    if ~isfield(levelsByMotor, fieldName) || isempty(levelsByMotor.(fieldName))
        levelsByMotor.(fieldName) = fallbackLevels;
    else
        levelsByMotor.(fieldName) = double(levelsByMotor.(fieldName)(:))';
    end
end
end

function shouldRun = localShouldRunWeighted(summaryTable)
baseline = summaryTable(string(summaryTable.configLabel) == "baseline_current", :);
calibrated = summaryTable(string(summaryTable.configLabel) == ...
    "motor_calibrated_quantized", :);
if isempty(baseline) || isempty(calibrated)
    shouldRun = false;
    return;
end

improvesFlags = calibrated.motor2_flat_response_count < ...
    baseline.motor2_flat_response_count || ...
    calibrated.motor2_action_no_motion_count < ...
    baseline.motor2_action_no_motion_count;
improvesRange = calibrated.responseRange_motor2 > baseline.responseRange_motor2;
trackingOk = calibrated.trackingMSE_motor2 <= 1.10 * baseline.trackingMSE_motor2;
shouldRun = (improvesFlags || improvesRange) && trackingOk;
end

function summaryTable = localSummarizeAblations(perSeedTable)
configLabels = unique(string(perSeedTable.configLabel), "stable");
rows = cell(numel(configLabels), 1);
for i = 1:numel(configLabels)
    idx = string(perSeedTable.configLabel) == configLabels(i);
    subset = perSeedTable(idx, :);
    rows{i} = struct( ...
        "configLabel", configLabels(i), ...
        "numSeeds", height(subset), ...
        "trackingMSE", mean(double(subset.trackingMSE), "omitnan"), ...
        "trackingMAE", mean(double(subset.trackingMAE), "omitnan"), ...
        "actionL2", mean(double(subset.actionL2), "omitnan"), ...
        "saturationFraction", mean(double(subset.saturationFraction), "omitnan"), ...
        "deltaActionL2", mean(double(subset.deltaActionL2), "omitnan"), ...
        "trackingMSE_motor2", mean(double(subset.trackingMSE_motor2), "omitnan"), ...
        "responseRange_motor2", mean(double(subset.responseRange_motor2), "omitnan"), ...
        "targetRange_motor2", mean(double(subset.targetRange_motor2), "omitnan"), ...
        "motor2_flat_response_count", sum(logical(subset.motor2_flat_response)), ...
        "motor2_action_no_motion_count", sum(logical(subset.motor2_action_no_motion)), ...
        "motor2_tracking_outlier_count", sum(logical(subset.motor2_tracking_outlier)));
end
summaryTable = struct2table(vertcat(rows{:}));
summaryTable.acceptedCalibration = localEvaluateAcceptance(summaryTable);
end

function accepted = localEvaluateAcceptance(summaryTable)
accepted = false(height(summaryTable), 1);
baseline = summaryTable(string(summaryTable.configLabel) == "baseline_current", :);
if isempty(baseline)
    return;
end

for i = 1:height(summaryTable)
    if string(summaryTable.configLabel(i)) == "baseline_current"
        continue;
    end
    accepted(i) = ...
        summaryTable.motor2_flat_response_count(i) <= ...
            baseline.motor2_flat_response_count && ...
        summaryTable.motor2_action_no_motion_count(i) <= ...
            baseline.motor2_action_no_motion_count && ...
        summaryTable.responseRange_motor2(i) > baseline.responseRange_motor2 && ...
        summaryTable.trackingMSE_motor2(i) <= baseline.trackingMSE_motor2 && ...
        summaryTable.trackingMSE(i) <= 1.10 * baseline.trackingMSE && ...
        summaryTable.saturationFraction(i) <= 1.15 * baseline.saturationFraction;
end
end

function referenceTable = localBuildReferenceTable(ablationSummary)
benchmark = getAgent7250Benchmark();
rows = cell(height(ablationSummary) + 1, 1);
rows{1} = struct( ...
    "candidateLabel", "Agent7250", ...
    "trackingMSE", benchmark.trackingMse, ...
    "trackingMAE", benchmark.trackingMae, ...
    "actionL2", benchmark.actionL2, ...
    "saturationFraction", benchmark.saturationFraction, ...
    "deltaActionL2", benchmark.deltaActionL2, ...
    "trackingMSE_motor2", NaN, ...
    "responseRange_motor2", NaN);
for i = 1:height(ablationSummary)
    rows{i+1} = struct( ...
        "candidateLabel", string(ablationSummary.configLabel(i)), ...
        "trackingMSE", double(ablationSummary.trackingMSE(i)), ...
        "trackingMAE", double(ablationSummary.trackingMAE(i)), ...
        "actionL2", double(ablationSummary.actionL2(i)), ...
        "saturationFraction", double(ablationSummary.saturationFraction(i)), ...
        "deltaActionL2", double(ablationSummary.deltaActionL2(i)), ...
        "trackingMSE_motor2", double(ablationSummary.trackingMSE_motor2(i)), ...
        "responseRange_motor2", double(ablationSummary.responseRange_motor2(i)));
end
referenceTable = struct2table(vertcat(rows{:}));
end

function localCreateMotor2SummaryFigure(summaryTable, figurePath)
[figureDir, ~, ~] = fileparts(figurePath);
if strlength(string(figureDir)) > 0 && ~exist(figureDir, "dir")
    mkdir(figureDir);
end

labels = string(summaryTable.configLabel);
f = figure("Visible", "off", "Color", "w", "Position", [100 100 1400 850]);
tiledlayout(f, 1, 3, "TileSpacing", "compact", "Padding", "compact");

bar(nexttile, categorical(labels), summaryTable.trackingMSE_motor2);
title("Motor 2 tracking MSE");
grid on;

bar(nexttile, categorical(labels), summaryTable.responseRange_motor2);
title("Motor 2 response range");
grid on;

bar(nexttile, categorical(labels), [ ...
    summaryTable.motor2_flat_response_count, ...
    summaryTable.motor2_action_no_motion_count]);
title("Motor 2 flags");
legend(["flat", "action-no-motion"], "Location", "best");
grid on;

sgtitle(f, "Calibrated action ablation - motor 2");
exportgraphics(f, figurePath, "Resolution", 220);
close(f);
end

function localCreateFinalComparisonFigure(referenceTable, figurePath)
[figureDir, ~, ~] = fileparts(figurePath);
if strlength(string(figureDir)) > 0 && ~exist(figureDir, "dir")
    mkdir(figureDir);
end

labels = string(referenceTable.candidateLabel);
f = figure("Visible", "off", "Color", "w", "Position", [100 100 1400 850]);
tiledlayout(f, 1, 3, "TileSpacing", "compact", "Padding", "compact");

bar(nexttile, categorical(labels), referenceTable.trackingMSE);
title("Global tracking MSE");
grid on;

bar(nexttile, categorical(labels), referenceTable.saturationFraction);
title("Saturation fraction");
grid on;

bar(nexttile, categorical(labels), referenceTable.responseRange_motor2);
title("Motor 2 response range");
