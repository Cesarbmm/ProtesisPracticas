function results = run_motor2_calibrated_action_ablation(options)
%run_motor2_calibrated_action_ablation tests calibrated action quantization.
%
% This launcher is simulation-only. It does not promote the calibrated
% interface; it compares it against current baseline action handling.

arguments
    options = struct()
end

paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = char(paths.matlabRoot);
workspaceRoot = char(paths.workspaceRoot);
cd(matlabRoot);
addpath(genpath(matlabRoot));
clearConfigurablesOverride();

baseConfigs = configurables();
options = localNormalizeOptions(options, baseConfigs);

resultsRoot = localResolveResultsRoot(options.resultsRoot, workspaceRoot);
summaryRoot = fullfile(resultsRoot, "summary");
figuresRoot = fullfile(resultsRoot, "figures");
ensureDirectoryExists(resultsRoot);
ensureDirectoryExists(summaryRoot);
ensureDirectoryExists(figuresRoot);

allConfigs = localBuildAblationConfigs(options);
configsToRun = localSelectInitialConfigs(allConfigs, options);
seedTables = {};
configResults = {};
skippedConfigs = strings(0, 1);

for configIdx = 1:numel(configsToRun)
    [seedTables, configResults] = localRunConfig( ...
        configsToRun(configIdx), options, resultsRoot, seedTables, configResults);
end

if isempty(options.configNames)
    partialSummary = localSummarizeAblations(vertcat(seedTables{:}));
    weightedConfig = allConfigs(string({allConfigs.label}) == "motor_calibrated_weighted");
    if options.forceWeightedCalibrated || localShouldRunWeighted(partialSummary)
        [seedTables, configResults] = localRunConfig( ...
            weightedConfig, options, resultsRoot, seedTables, configResults);
    else
        skippedConfigs(end+1, 1) = "motor_calibrated_weighted";
    end
end

perSeedTable = vertcat(seedTables{:});
ablationSummary = localSummarizeAblations(perSeedTable);
referenceTable = localBuildReferenceTable(ablationSummary);

summaryCsvPath = fullfile(summaryRoot, "calibrated_action_ablation_summary.csv");
summaryTxtPath = fullfile(summaryRoot, "calibrated_action_ablation_summary.txt");
matPath = fullfile(summaryRoot, "calibrated_action_ablation_results.mat");
motor2FigurePath = fullfile(figuresRoot, "calibrated_action_ablation_motor2.png");
comparisonFigurePath = fullfile(figuresRoot, ...
    "calibrated_action_ablation_final_comparison.png");

writetable(ablationSummary, summaryCsvPath);
writetable(referenceTable, fullfile(summaryRoot, ...
    "calibrated_action_ablation_final_comparison.csv"));
localCreateMotor2SummaryFigure(ablationSummary, motor2FigurePath);
localCreateFinalComparisonFigure(referenceTable, comparisonFigurePath);
localWriteTextFile(summaryTxtPath, localBuildSummaryText( ...
    options, ablationSummary, skippedConfigs, resultsRoot));

results = struct();
results.resultsRoot = string(resultsRoot);
results.summaryRoot = string(summaryRoot);
results.figuresRoot = string(figuresRoot);
results.options = options;
results.configResults = configResults;
results.perSeedTable = perSeedTable;
results.ablationSummary = ablationSummary;
results.referenceTable = referenceTable;
results.skippedConfigs = skippedConfigs;
results.figurePaths = struct( ...
    "motor2Summary", string(motor2FigurePath), ...
    "finalComparison", string(comparisonFigurePath));

save(matPath, "results", "perSeedTable", "ablationSummary", ...
    "referenceTable", "options", "configResults", "skippedConfigs");
end

function options = localNormalizeOptions(options, baseConfigs)
defaults = struct( ...
    "seeds", [11 22 55], ...
    "trainingEpisodes", 3000, ...
    "trainingSaveEvery", 100, ...
    "episodeSaveFreq", 100, ...
    "auditFastSimulations", 5, ...
    "auditFullSimulations", 10, ...
    "auditTopK", 5, ...
    "finalTestEpisodes", 20, ...
    "plotEpisodeOnTest", true, ...
    "useGpu", true, ...
    "selectionMode", "motor2_aware", ...
    "forceWeightedCalibrated", false, ...
    "configNames", string.empty(1, 0), ...
    "resultsRoot", "", ...
    "actionCommandLevels", baseConfigs.actionCommandLevels, ...
    "actionCommandLevelsByMotor", baseConfigs.actionCommandLevelsByMotor);

fields = fieldnames(defaults);
for i = 1:numel(fields)
    if ~isfield(options, fields{i}) || isempty(options.(fields{i}))
        options.(fields{i}) = defaults.(fields{i});
    end
end

options.seeds = double(options.seeds(:))';
options.trainingEpisodes = double(options.trainingEpisodes);
options.trainingSaveEvery = double(options.trainingSaveEvery);
options.episodeSaveFreq = double(options.episodeSaveFreq);
options.auditFastSimulations = max(1, double(options.auditFastSimulations));
options.auditFullSimulations = max(1, double(options.auditFullSimulations));
options.auditTopK = max(1, double(options.auditTopK));
options.finalTestEpisodes = max(1, double(options.finalTestEpisodes));
options.plotEpisodeOnTest = logical(options.plotEpisodeOnTest);
options.useGpu = logical(options.useGpu);
options.selectionMode = lower(string(options.selectionMode));
options.forceWeightedCalibrated = logical(options.forceWeightedCalibrated);
options.configNames = string(options.configNames);
options.resultsRoot = string(options.resultsRoot);
options.actionCommandLevels = double(options.actionCommandLevels(:))';
options.actionCommandLevelsByMotor = localNormalizeActionLevelsByMotor( ...
    options.actionCommandLevelsByMotor, options.actionCommandLevels);

if isempty(options.seeds)
    error("options.seeds must contain at least one seed.");
end
if ~ismember(options.selectionMode, ["global", "motor2_aware"])
    error("Unsupported selectionMode '%s'.", options.selectionMode);
end
end

