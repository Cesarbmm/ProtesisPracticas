sgtitle(f, "Calibrated action ablation final comparison");
exportgraphics(f, figurePath, "Resolution", 220);
close(f);
end

function text = localBuildSummaryText(options, summaryTable, skippedConfigs, resultsRoot)
lines = strings(0, 1);
lines(end+1) = "Motor 2 calibrated action ablation";
lines(end+1) = "Results root: " + string(resultsRoot);
lines(end+1) = "Seeds: " + mat2str(options.seeds);
lines(end+1) = "Training episodes: " + string(options.trainingEpisodes);
lines(end+1) = "Final test episodes: " + string(options.finalTestEpisodes);
lines(end+1) = "Selection mode: " + string(options.selectionMode);
if ~isempty(skippedConfigs)
    lines(end+1) = "Skipped configs: " + strjoin(skippedConfigs.', ", ");
end
lines(end+1) = "";
for i = 1:height(summaryTable)
    lines(end+1) = sprintf( ...
        "%s: trackingMSE=%.6f, motor2MSE=%.6f, motor2Range=%.6f, flat=%d, actionNoMotion=%d, accepted=%d", ...
        string(summaryTable.configLabel(i)), ...
        summaryTable.trackingMSE(i), ...
        summaryTable.trackingMSE_motor2(i), ...
        summaryTable.responseRange_motor2(i), ...
        summaryTable.motor2_flat_response_count(i), ...
        summaryTable.motor2_action_no_motion_count(i), ...
        summaryTable.acceptedCalibration(i));
end
text = strjoin(lines, newline);
end

function localWriteTextFile(filePath, text)
fid = fopen(filePath, "w");
if fid < 0
    error("Could not write %s", filePath);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s\n", text);
end

function resultsRoot = localResolveResultsRoot(resultsRootOption, workspaceRoot)
if strlength(string(resultsRootOption)) > 0
    resultsRoot = char(string(resultsRootOption));
else
    resultsRoot = fullfile(workspaceRoot, "Agentes", ...
        "motor2_calibrated_action_ablation", ...
        string(datetime("now", "Format", "yy-MM-dd_HH-mm-ss")));
end
end
