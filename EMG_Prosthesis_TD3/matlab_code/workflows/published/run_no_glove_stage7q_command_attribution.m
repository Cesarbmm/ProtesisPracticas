    fullfile(runRoot, "gradient_components.csv"));
writetable(analysis.gradientSummary, ...
    fullfile(runRoot, "gradient_block_summary.csv"));
writetable(analysis.associationSummary, ...
    fullfile(runRoot, "block_association_summary.csv"));
writetable(analysis.temporalSummary, ...
    fullfile(runRoot, "temporal_contribution_summary.csv"));
writetable(analysis.priorActionSummary, ...
    fullfile(runRoot, "prior_action_summary.csv"));
writetable(analysis.sharedCheckpointSummary, ...
    fullfile(runRoot, "shared_checkpoint_summary.csv"));
writetable(analysis.ownCheckpointSummary, ...
    fullfile(runRoot, "own_checkpoint_summary.csv"));
writetable(analysis.blockDecisionAudit, ...
    fullfile(runRoot, "block_decision_audit.csv"));
writetable(analysis.decisionAudit, ...
    fullfile(runRoot, "decision_audit.csv"));

operationalChecks = struct( ...
    "stage7pValidated", data.stage7p.validated, ...
    "stage7nValidated", data.stage7n.validated, ...
    "allCheckpointHashesMatched", all( ...
        data.checkpointInventory.expectedSha256 == ...
        data.checkpointInventory.actualSha256), ...
    "state60Selected", analysis.stateDecision == "intentMarkov60", ...
    "state62Rejected", analysis.state62Disposition == ...
        "provisionallyRejected", ...
    "primaryCohortMatched", analysis.primaryComponentCount == 2064, ...
    "allReplayPassed", all(replayAudit.batchSavedMaximumError <= 1e-5) && ...
        all(replayAudit.serialBatchSampleMaximumError <= 1e-5) && ...
        all(replayAudit.pwmMismatchCount == 0), ...
    "allGradientAuditsPassed", all(gradientAudit.withinTolerance), ...
    "trainingLogsExcluded", ~data.trainingLogsUsed, ...
    "stateCounterfactualExcluded", ~analysis.stateCounterfactualUsed, ...
    "futureLeakageExcluded", ~analysis.futureLeakageUsed, ...
    "rewardUnchanged", true, "quantizationUnchanged", true, ...
    "td3Unchanged", true, "simulatorUnchanged", true, ...
    "safetyUnchanged", true, "gateUnchanged", true, ...
    "noTraining", true, "noEnvironment", true, ...
    "noSimulation", true, "noHardware", true, "noDtw", true);
if ~all(struct2array(operationalChecks))
    error("run_no_glove_stage7q_command_attribution:OperationalGate", ...
        "An ETAPA 7Q operational invariant failed.");
end
writetable(struct2table(operationalChecks), ...
    fullfile(runRoot, "operational_checks.csv"));

[gitCommit, gitDirty, gitTrackedDirty, gitStatus] = getGitState(repoRoot);
agent7250Path = getAgent7250CheckpointPath();
manifest = struct( ...
    "stage", "7Q", "schemaVersion", 1, "result", "PASS", ...
    "scientificResult", analysis.scientificResult, ...
    "stateDecision", analysis.stateDecision, ...
    "state62Disposition", analysis.state62Disposition, ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", gitTrackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", "run_no_glove_stage7q_command_attribution", ...
    "preregistrationCommit", "61766bf3", ...
    "parentStage7p", compactParent(data.stage7p), ...
    "parentStage7n", compactParent(data.stage7n), ...
    "checkpoints", table2struct(data.checkpointInventory), ...
    "primaryComponentCount", analysis.primaryComponentCount, ...
    "primaryWindowCount", analysis.primaryWindowCount, ...
    "agent200OutwardComponentCount", ...
        analysis.agent200OutwardComponentCount, ...
    "decisionThresholds", decisionThresholds(), ...
    "operationalChecks", operationalChecks, ...
    "rewardChanged", false, "quantizationChanged", false, ...
    "td3Changed", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "restGateChanged", false, ...
    "trainingUsed", false, "environmentUsed", false, ...
    "simulationUsed", false, "simMotors", true, ...
    "hardwareUsed", false, "myoUsed", false, ...
    "gloveUsed", false, "dtwCalculated", false, ...
    "stateCounterfactualUsed", false, ...
    "agent7250Loaded", false, "agent7250Used", false, ...
    "agent7250CheckpointPath", agent7250Path, ...
    "agent7250CheckpointSha256", fileSha256(agent7250Path), ...
    "state62CheckpointLoaded", false, ...
    "smokeAuthorized", false, "smokeExecuted", false, ...
    "pilotAuthorized", false, "pilotExecuted", false, ...
    "campaignAuthorized", false, "campaignExecuted", false, ...
    "futureAblationExecuted", false, ...
