checkpointRows = data.checkpointTable;
sharedEvaluations = repmat(struct("episode", 0, "raw", [], ...
    "effective", [], "pwm", [], "gradients", []), 4, 1);
replayParts = cell(4, 1);
gradientAuditParts = cell(4, 1);
for checkpointIdx = 1:4
    checkpointEpisode = double(checkpointRows.episode(checkpointIdx));
    checkpointPath = string(checkpointRows.checkpointPath(checkpointIdx));
    agent = loadSavedAgent(checkpointPath);
    actor = getActor(agent);
    model = getModel(actor);
    raw = evaluateFrozenActorModelStates(model, states);
    gradients = evaluateFrozenActorStateGradients(model, states, ...
        "batchSize", options.gradientBatchSize);
    [effective, pwm] = quantizeRows(raw, data.actuator);
    sharedEvaluations(checkpointIdx) = struct( ...
        "episode", checkpointEpisode, "raw", raw, ...
        "effective", effective, "pwm", pwm, ...
        "gradients", gradients);

    own = data.ownCorpora(checkpointIdx).corpus;
    ownBatch = evaluateFrozenActorModelStates(model, own.states);
    [~, ownBatchPwm] = quantizeRows(ownBatch, data.actuator);
    sampleIndices = unique(round(linspace(1, size(own.states, 1), 8)));
    serialSample = evaluateFrozenActorStates(actor, ...
        own.states(sampleIndices, :));
    replayParts{checkpointIdx} = table(checkpointEpisode, ...
        size(own.states, 1), numel(sampleIndices), ...
        max(abs(ownBatch-own.rawAction), [], "all"), ...
        max(abs(serialSample-ownBatch(sampleIndices, :)), [], "all"), ...
        sum(ownBatchPwm ~= own.pwm, "all"), ...
        'VariableNames', ["checkpointEpisode", "evaluatedWindowCount", ...
        "serialSampleCount", "batchSavedMaximumError", ...
        "serialBatchSampleMaximumError", "pwmMismatchCount"]);
    gradientAuditParts{checkpointIdx} = auditGradients( ...
        model, states, gradients, checkpointEpisode, ...
        options.gradientFiniteDifferenceStep);
    clear agent actor model raw effective pwm gradients ownBatch ownBatchPwm
end
replayAudit = vertcat(replayParts{:});
gradientAudit = vertcat(gradientAuditParts{:});
writetable(replayAudit, fullfile(runRoot, "actor_replay_audit.csv"));
writetable(gradientAudit, fullfile(runRoot, "gradient_audit.csv"));
if any(replayAudit.batchSavedMaximumError > 1e-5) || ...
        any(replayAudit.serialBatchSampleMaximumError > 1e-5) || ...
        any(replayAudit.pwmMismatchCount ~= 0) || ...
        any(~gradientAudit.withinTolerance)
    error("run_no_glove_stage7q_command_attribution:ReplayGate", ...
        "Actor replay or gradient audit failed.");
end

analysis = analyzeNoGloveStage7qAttribution( ...
    data.primaryCorpus, sharedEvaluations, data.ownCorpora);
inputInventory = buildInputInventory(data, options);
