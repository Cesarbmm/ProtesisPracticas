function [effective, pwm] = quantizeRows(raw, actuator)
effective = zeros(size(raw));
pwm = zeros(size(raw));
for row = 1:size(raw, 1)
    [effectiveValue, pwmValue] = quantizeBaselineAction(raw(row, :), ...
        actuator.maxPwm, actuator.activationThreshold, ...
        actuator.commandLevels);
    effective(row, :) = double(effectiveValue(:))';
    pwm(row, :) = double(pwmValue(:))';
end
end

function audit = auditGradients(model, states, fullGradients, ...
        checkpointEpisode, step)
indices = unique(round(linspace(1, size(states, 1), 8)));
analytic = fullGradients(indices, :, :);
finite = nan(size(analytic));
forwardSlope = nan(size(analytic));
backwardSlope = nan(size(analytic));
base = evaluateFrozenActorModelStates(model, states(indices, :));
for inputIdx = 1:60
    plus = states(indices, :);
    minus = states(indices, :);
    plus(:, inputIdx) = plus(:, inputIdx)+step;
    minus(:, inputIdx) = minus(:, inputIdx)-step;
    plusValue = evaluateFrozenActorModelStates(model, plus);
    minusValue = evaluateFrozenActorModelStates(model, minus);
    finite(:, :, inputIdx) = (plusValue-minusValue)./(2*step);
    forwardSlope(:, :, inputIdx) = (plusValue-base)./step;
    backwardSlope(:, :, inputIdx) = (base-minusValue)./step;
end
errorValue = abs(analytic-finite);
absoluteTolerance = 2e-4;
relativeTolerance = 5e-2;
tolerance = max(absoluteTolerance, relativeTolerance.*abs(analytic));
centralFailure = errorValue > tolerance;
nonsmooth = abs(forwardSlope-backwardSlope) > absoluteTolerance;
oneSidedError = min(abs(analytic-forwardSlope), ...
    abs(analytic-backwardSlope));
nonsmoothException = centralFailure & nonsmooth & ...
    oneSidedError <= tolerance;
unexplainedFailure = centralFailure & ~nonsmoothException;
audit = table(checkpointEpisode, numel(indices), step, ...
    absoluteTolerance, relativeTolerance, ...
    max(errorValue, [], "all"), max(tolerance, [], "all"), ...
    sum(centralFailure, "all"), sum(nonsmoothException, "all"), ...
    sum(unexplainedFailure, "all"), ~any(unexplainedFailure, "all"), ...
    'VariableNames', ["checkpointEpisode", "sampleCount", "step", ...
    "absoluteTolerance", "relativeTolerance", ...
    "maximumAbsoluteError", "maximumTolerance", ...
    "centralFailureCount", "nonsmoothExceptionCount", ...
    "unexplainedFailureCount", "withinTolerance"]);
end

function inventory = buildInputInventory(data, options)
category = strings(0, 1);
checkpointEpisode = zeros(0, 1);
source = strings(0, 1);
episode = zeros(0, 1);
filePath = strings(0, 1);
bytes = zeros(0, 1);
sha256 = strings(0, 1);
parentPaths = [ ...
    fullfile(options.stage7pRunRoot, "manifest.json"); ...
    fullfile(options.stage7pRunRoot, "stage7p_results.mat"); ...
    fullfile(options.stage7nRunRoot, "manifest.json"); ...
    fullfile(options.stage7nRunRoot, "checkpoint_summary.csv")];
for idx = 1:numel(parentPaths)
    [category, checkpointEpisode, source, episode, filePath, ...
        bytes, sha256] = appendInventory(category, checkpointEpisode, ...
        source, episode, filePath, bytes, sha256, "parent", 0, ...
        "", 0, parentPaths(idx));
end
for idx = 1:height(data.checkpointInventory)
    [category, checkpointEpisode, source, episode, filePath, ...
        bytes, sha256] = appendInventory(category, checkpointEpisode, ...
        source, episode, filePath, bytes, sha256, "checkpoint", ...
        data.checkpointInventory.episode(idx), "", 0, ...
        data.checkpointInventory.checkpointPath(idx));
end
for corpusIdx = 1:numel(data.ownCorpora)
    rows = data.ownCorpora(corpusIdx).corpus.inventory;
    for row = 1:height(rows)
        [category, checkpointEpisode, source, episode, filePath, ...
            bytes, sha256] = appendInventory(category, ...
            checkpointEpisode, source, episode, filePath, bytes, ...
            sha256, "episode", data.ownCorpora(corpusIdx).episode, ...
            rows.source(row), rows.episode(row), rows.filePath(row));
    end
end
inventory = table(category, checkpointEpisode, source, episode, ...
    filePath, bytes, sha256);
end

function [category, checkpointEpisode, source, episode, filePath, ...
        bytes, sha256] = appendInventory(category, checkpointEpisode, ...
        source, episode, filePath, bytes, sha256, newCategory, ...
        newCheckpoint, newSource, newEpisode, newPath)
info = dir(newPath);
category(end+1, 1) = string(newCategory);
checkpointEpisode(end+1, 1) = double(newCheckpoint);
source(end+1, 1) = string(newSource);
episode(end+1, 1) = double(newEpisode);
filePath(end+1, 1) = string(newPath);
bytes(end+1, 1) = info.bytes;
sha256(end+1, 1) = fileSha256(newPath);
end

