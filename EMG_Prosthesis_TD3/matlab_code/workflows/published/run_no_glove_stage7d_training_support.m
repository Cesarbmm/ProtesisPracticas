function [inventory, hashes] = validateQueryInventory(pathValue)
inventory = readtable(pathValue, "Delimiter", ",", "TextType", "string", ...
    "VariableNamingRule", "preserve");
required = ["fileName", "path", "sha256", "bytes"];
if ~all(ismember(required, string(inventory.Properties.VariableNames))) || ...
        height(inventory) ~= 16 || numel(unique(inventory.path)) ~= 16
    error("run_no_glove_stage7d_training_support:InvalidQueryInventory", ...
        "The ETAPA 7C inventory must contain 16 unique episodes.");
end
hashes = hashPaths(inventory.path);
if any(hashes ~= upper(inventory.sha256))
    error("run_no_glove_stage7d_training_support:QueryHashMismatch", ...
        "An ETAPA 7B query episode changed.");
end
end

function [inventory, hashes] = buildTrainingInventory(trainingRoot)
files = dir(fullfile(trainingRoot, "episode*.mat"));
names = string({files.name});
[names, order] = sort(names);
files = files(order);
names = names(:);
files = files(:);
if numel(files) ~= 200 || names(1) ~= "episode00001.mat" || ...
        names(end) ~= "episode00200.mat"
    error("run_no_glove_stage7d_training_support:TrainingCoverage", ...
        "Exactly the 200 published training episodes are required.");
end
path = strings(numel(files), 1);
bytes = zeros(numel(files), 1);
for fileIdx = 1:numel(files)
    expected = sprintf("episode%05d.mat", fileIdx);
    if names(fileIdx) ~= expected
        error("run_no_glove_stage7d_training_support:TrainingOrder", ...
            "Training episode sequence is incomplete at %d.", fileIdx);
    end
    path(fileIdx) = fullfile(files(fileIdx).folder, files(fileIdx).name);
    bytes(fileIdx) = files(fileIdx).bytes;
end
hashes = hashPaths(path);
inventory = table(names, path, hashes, bytes, ...
    'VariableNames', ["fileName", "path", "sha256", "bytes"]);
end

function query = loadQueryStates(inventory, options)
rowCount = height(inventory)*options.preRestWindows;
state = nan(rowCount, 60);
rawAction = nan(rowCount, 4);
episode = zeros(rowCount, 1);
step = zeros(rowCount, 1);
cursor = 0;
for episodeIdx = 1:height(inventory)
    required = ["stateLog", "actionLog", "referenceSource", ...
        "observationVariant", "stateLength"];
    available = string(who("-file", inventory.path(episodeIdx)));
    if ~all(ismember(required, available))
        error("run_no_glove_stage7d_training_support:IncompleteQuery", ...
            "Query episode %d is incomplete.", episodeIdx);
    end
    requiredCell = cellstr(required);
    loaded = load(inventory.path(episodeIdx), requiredCell{:});
    x = double(loaded.stateLog);
    u = double(loaded.actionLog);
    rows = cursor+(1:options.preRestWindows);
    if size(x, 2) ~= 60 || size(x, 1) < options.preRestWindows || ...
            ~isequal(size(u, 1), size(x, 1)) || size(u, 2) ~= 4 || ...
            string(loaded.referenceSource) ~= "emgIntent" || ...
            string(loaded.observationVariant) ~= "intentMarkov60" || ...
            double(loaded.stateLength) ~= 60 || ...
            any(~isfinite(x), "all") || any(~isfinite(u), "all") || ...
            any(abs(x(1:options.preRestWindows, 57:60)) > ...
                options.referenceTolerance, "all") || ...
            any(abs(x(1:options.preRestWindows, 53:56)- ...
                x(1, 53:56)) > options.referenceTolerance, "all")
        error("run_no_glove_stage7d_training_support:InvalidQuery", ...
            "Query episode %d is not the validated pre-rest contract.", ...
            episodeIdx);
    end
    state(rows, :) = x(1:options.preRestWindows, :);
    rawAction(rows, :) = u(1:options.preRestWindows, :);
    episode(rows) = episodeIdx;
    step(rows) = (1:options.preRestWindows)';
    cursor = cursor+options.preRestWindows;
end
query = struct("state", state, "rawAction", rawAction, ...
    "episode", episode, "step", step);
end

function [training, audit] = loadTrainingStates(inventory, options)
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
stateCells = cell(height(inventory), 1);
previousCells = cell(height(inventory), 1);
episodeCells = cell(height(inventory), 1);
stepCells = cell(height(inventory), 1);
phaseCells = cell(height(inventory), 1);
auditRows = repmat(struct("episode", 0, "stepCount", 0, ...
    "eligibleStateCount", 0, "preActivationStateCount", 0, ...
    "postActivationStateCount", 0, "firstActiveStep", 0, ...
    "temporalPreviousActionMaximumError", NaN), height(inventory), 1);
for episodeIdx = 1:height(inventory)
    required = ["stateLog", "actionSatLog", "referenceSource", ...
        "observationVariant", "stateLength"];
    available = string(who("-file", inventory.path(episodeIdx)));
    if ~all(ismember(required, available))
        error("run_no_glove_stage7d_training_support:IncompleteTraining", ...
            "Training episode %d is incomplete.", episodeIdx);
    end
    requiredCell = cellstr(required);
    loaded = load(inventory.path(episodeIdx), requiredCell{:});
    x = double(loaded.stateLog);
    effective = double(loaded.actionSatLog);
    stepCount = size(x, 1);
    temporalError = max(abs(x(2:end, ...
        layout.previousEffectiveAction)-effective(1:end-1, :)), [], "all");
    if stepCount < 3 || size(x, 2) ~= 60 || ...
            ~isequal(size(effective), [stepCount, 4]) || ...
            string(loaded.referenceSource) ~= "emgIntent" || ...
            string(loaded.observationVariant) ~= "intentMarkov60" || ...
            double(loaded.stateLength) ~= 60 || ...
            any(~isfinite(x), "all") || any(~isfinite(effective), "all") || ...
            temporalError > options.replayTolerance
        error("run_no_glove_stage7d_training_support:InvalidTraining", ...
            "Training episode %d violates the state-log contract.", ...
            episodeIdx);
    end
    vRef = x(:, layout.referenceVelocity);
    qRef = x(:, layout.referencePosition);
    heldFromPrior = [false; max(abs(diff(qRef, 1, 1)), [], 2) <= ...
        options.referenceTolerance];
    zeroVelocity = max(abs(vRef), [], 2) <= options.referenceTolerance;
    eligible = heldFromPrior & zeroVelocity;
    firstActive = find(~zeroVelocity, 1, "first");
    if isempty(firstActive)
        error("run_no_glove_stage7d_training_support:NoActiveReference", ...
            "Training episode %d contains no active reference.", episodeIdx);
    end
    pre = eligible & (1:stepCount)' < firstActive;
    post = eligible & (1:stepCount)' > firstActive;
    if ~any(pre) || ~any(post)
        error("run_no_glove_stage7d_training_support:MissingHoldPhase", ...
            "Training episode %d lacks a reference-hold phase.", episodeIdx);
    end
    eligibleSteps = find(eligible);
    phase = repmat("postActivationHold", numel(eligibleSteps), 1);
    phase(eligibleSteps < firstActive) = "preActivationHold";
    stateCells{episodeIdx} = x(eligible, :);
    previousCells{episodeIdx} = qRef(eligibleSteps-1, :);
    episodeCells{episodeIdx} = repmat(episodeIdx, numel(eligibleSteps), 1);
    stepCells{episodeIdx} = eligibleSteps;
    phaseCells{episodeIdx} = phase;
    auditRows(episodeIdx) = struct("episode", episodeIdx, ...
        "stepCount", stepCount, ...
        "eligibleStateCount", sum(eligible), ...
        "preActivationStateCount", sum(pre), ...
        "postActivationStateCount", sum(post), ...
        "firstActiveStep", firstActive, ...
        "temporalPreviousActionMaximumError", temporalError);
end
training = struct("state", vertcat(stateCells{:}), ...
    "episode", vertcat(episodeCells{:}), ...
    "step", vertcat(stepCells{:}), ...
    "previousReferencePosition", vertcat(previousCells{:}), ...
    "phase", vertcat(phaseCells{:}));
audit = struct2table(auditRows);
end

