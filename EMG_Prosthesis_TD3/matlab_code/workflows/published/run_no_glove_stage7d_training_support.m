function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7d_training_support:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("stage7cRunRoot", "", "resultsRoot", "", ...
    "preRestWindows", 8, "referenceTolerance", 1e-12, ...
    "replayTolerance", 1e-12, "scaleTolerance", 1e-12, ...
    "distanceTolerance", 1e-12, "supportQuantile", 0.95, ...
    "minimumSupportFraction", 0.75, ...
    "falseActivationLimit", 0.01, ...
    "materialRawActionDelta", 0.05, ...
    "minimumMaterialBiasFraction", 0.25, ...
    "minimumBiasActiveReduction", 0.50, ...
    "saturationThreshold", 0.95);
unknown = setdiff(string(fieldnames(options)), ...
    string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7d_training_support:UnknownOption", ...
        "Unknown option(s): %s.", strjoin(unknown, ", "));
end
fields = fieldnames(defaults);
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.stage7cRunRoot = string(options.stage7cRunRoot);
options.resultsRoot = string(options.resultsRoot);
if strlength(options.stage7cRunRoot) == 0
    error("run_no_glove_stage7d_training_support:MissingInput", ...
        "stage7cRunRoot is required.");
end
numericFields = setdiff(string(fieldnames(defaults)), ...
    ["stage7cRunRoot", "resultsRoot"]);
for fieldIdx = 1:numel(numericFields)
    value = options.(numericFields(fieldIdx));
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || value < 0
        error("run_no_glove_stage7d_training_support:InvalidOption", ...
            "%s must be a finite nonnegative scalar.", ...
            numericFields(fieldIdx));
    end
end
if fix(options.preRestWindows) ~= options.preRestWindows || ...
        options.preRestWindows < 2 || options.supportQuantile < 0.5 || ...
        options.supportQuantile > 1 || ...
        options.minimumSupportFraction > 1 || ...
        options.falseActivationLimit > 1 || ...
        options.materialRawActionDelta <= 0 || ...
        options.minimumMaterialBiasFraction > 1 || ...
        options.minimumBiasActiveReduction > 1 || ...
        options.saturationThreshold > 1
    error("run_no_glove_stage7d_training_support:InvalidOption", ...
        "ETAPA 7D option bounds are invalid.");
end
end

function [manifest, paths] = validateStage7c(runRoot)
paths = struct( ...
    "stage7cManifest", fullfile(runRoot, "manifest.json"), ...
    "stage7cResults", fullfile(runRoot, "stage7c_results.mat"), ...
    "queryInventory", fullfile(runRoot, "episode_input_hashes.csv"));
fields = fieldnames(paths);
for fieldIdx = 1:numel(fields)
    if ~isfile(paths.(fields{fieldIdx}))
        error("run_no_glove_stage7d_training_support:Stage7cNotFound", ...
            "Missing ETAPA 7C input %s.", paths.(fields{fieldIdx}));
    end
end
manifest = jsondecode(fileread(paths.stage7cManifest));
required = ["stage", "result", "scientificResult", ...
    "rootCauseIdentified", "inputStage7bRunRoot", ...
    "inputStage7bManifestPath", "inputStage7bManifestSha256After", ...
    "inputStage7bResultsSha256After", "inputEpisodeCount", ...
    "preRestStateCount", "replayMaximumAbsoluteError", ...
    "agentCheckpointPath", "agentCheckpointSha256After", ...
    "agentFrozen", "runTraining", "agent7250Loaded", ...
    "envCreated", "simulatorInvoked", "rewardInvoked", ...
    "dtwCalculated", "hardwareUsed", "artifactHashes"];
if ~all(isfield(manifest, cellstr(required)))
    error("run_no_glove_stage7d_training_support:InvalidStage7c", ...
        "ETAPA 7C manifest contract is incomplete.");
end
valid = string(manifest.stage) == "7C" && ...
    string(manifest.result) == "PASS" && ...
    string(manifest.scientificResult) == ...
        "restCommandAtObservedEmgOnlyStateUnresolved" && ...
    ~logical(manifest.rootCauseIdentified) && ...
    double(manifest.inputEpisodeCount) == 16 && ...
    double(manifest.preRestStateCount) == 128 && ...
    double(manifest.replayMaximumAbsoluteError) == 0 && ...
    logical(manifest.agentFrozen) && ~logical(manifest.runTraining) && ...
    ~logical(manifest.agent7250Loaded) && ~logical(manifest.envCreated) && ...
    ~logical(manifest.simulatorInvoked) && ~logical(manifest.rewardInvoked) && ...
    ~logical(manifest.dtwCalculated) && ~logical(manifest.hardwareUsed);
if ~valid
    error("run_no_glove_stage7d_training_support:IncompatibleStage7c", ...
        "ETAPA 7D requires the canonical unresolved ETAPA 7C evidence.");
end
if fileSha256(paths.stage7cResults) ~= findArtifactHash( ...
        manifest.artifactHashes, "stage7c_results.mat")
    error("run_no_glove_stage7d_training_support:Stage7cHashMismatch", ...
        "stage7c_results.mat does not match its manifest.");
end
paths.stage7bManifest = string(manifest.inputStage7bManifestPath);
paths.stage7bResults = fullfile(string(manifest.inputStage7bRunRoot), ...
    "stage7b_results.mat");
paths.effectiveProfile = fullfile(string(manifest.inputStage7bRunRoot), ...
    "effective_evaluation_profile.mat");
if fileSha256(paths.stage7bManifest) ~= upper(string( ...
        manifest.inputStage7bManifestSha256After)) || ...
        fileSha256(paths.stage7bResults) ~= upper(string( ...
        manifest.inputStage7bResultsSha256After)) || ...
        ~isfile(paths.effectiveProfile)
    error("run_no_glove_stage7d_training_support:Stage7bHashMismatch", ...
        "ETAPA 7B evidence behind ETAPA 7C is unavailable or changed.");
end
stage7b = jsondecode(fileread(paths.stage7bManifest));
if fileSha256(paths.effectiveProfile) ~= findArtifactHash( ...
        stage7b.artifactHashes, "effective_evaluation_profile.mat")
    error("run_no_glove_stage7d_training_support:ProfileHashMismatch", ...
        "The ETAPA 7B effective profile changed.");
end
end

