function [queryEvaluator, trainingEvaluator, biaslessEvaluator, ...
        batchCrosscheckEvaluator, audit] = ...
        buildActorEvaluators(agent)
actor = getActor(agent);
model = getModel(actor);
learnables = model.Learnables;
biasRows = learnables.Parameter == "Bias";
if sum(biasRows) ~= 3
    error("run_no_glove_stage7d_training_support:UnexpectedActor", ...
        "Agent200 actor must contain exactly three bias vectors.");
end
layer = learnables.Layer(biasRows);
parameterCount = zeros(sum(biasRows), 1);
l1Norm = zeros(sum(biasRows), 1);
l2Norm = zeros(sum(biasRows), 1);
maximumAbsoluteValue = zeros(sum(biasRows), 1);
values = learnables.Value(biasRows);
for rowIdx = 1:numel(values)
    value = double(extractdata(values{rowIdx}));
    parameterCount(rowIdx) = numel(value);
    l1Norm(rowIdx) = sum(abs(value), "all");
    l2Norm(rowIdx) = norm(value(:), 2);
    maximumAbsoluteValue(rowIdx) = max(abs(value), [], "all");
end
parameterTable = table(layer, parameterCount, l1Norm, l2Norm, ...
    maximumAbsoluteValue);

parameters = getLearnableParameters(actor);
for parameterIdx = find(biasRows)'
    parameters{parameterIdx} = zeros(size(parameters{parameterIdx}), ...
        "like", parameters{parameterIdx});
end
biaslessActor = setLearnableParameters(actor, parameters);
queryEvaluator = @(states) evaluateFrozenActorStates(actor, states);
trainingEvaluator = queryEvaluator;
biaslessEvaluator = @(states) ...
    evaluateFrozenActorStates(biaslessActor, states);
batchCrosscheckEvaluator = @(states) ...
    evaluateFrozenActorModelStates(model, states);
zeroState = zeros(1, 60);
audit = struct("parameterTable", parameterTable, ...
    "zeroInputOriginalAction", queryEvaluator(zeroState), ...
    "zeroInputBiaslessAction", biaslessEvaluator(zeroState));
end

function audit = buildEvaluationRouteAudit(query, serialEvaluator, ...
        batchEvaluator, actuator)
serialAction = serialEvaluator(query.state);
batchAction = batchEvaluator(query.state);
[serialEffective, serialPwm] = quantizeLocal(serialAction, actuator);
[batchEffective, batchPwm] = quantizeLocal(batchAction, actuator);
serialReplayError = max(abs(serialAction-query.rawAction), [], "all");
batchDifference = max(abs(batchAction-serialAction), [], "all");
if serialReplayError > 1e-12 || batchDifference > 1e-6
    error("run_no_glove_stage7d_training_support:ActorRouteMismatch", ...
        "Actor evaluation routes exceed their numeric audit tolerance.");
end
batchQuantizationMismatch = sum(serialEffective ~= batchEffective, "all") + ...
    sum(serialPwm ~= batchPwm, "all");
if batchQuantizationMismatch ~= 0
    error("run_no_glove_stage7d_training_support:BatchQuantizationMismatch", ...
        "Vectorized evaluation changes a query PWM decision.");
end
route = ["queryReplay"; "queryBatchCrosscheck"; "trainingSupport"];
evaluator = ["getActionPerRecordedState"; ...
    "dlnetworkPredictCB"; "getActionPerRecordedState"];
stateCount = [size(query.state, 1); size(query.state, 1); NaN];
comparison = ["savedStage7bActionLog"; ...
    "serialGetAction"; "noSavedAgent200Action"];
maximumAbsoluteDifference = [serialReplayError; batchDifference; NaN];
quantizationMismatchCount = [0; batchQuantizationMismatch; NaN];
audit = table(route, evaluator, stateCount, comparison, ...
    maximumAbsoluteDifference, quantizationMismatchCount);
end

function [effective, pwm] = quantizeLocal(actions, actuator)
effective = zeros(size(actions));
pwm = zeros(size(actions));
for rowIdx = 1:size(actions, 1)
    [effectiveRow, pwmRow] = quantizeBaselineAction( ...
        actions(rowIdx, :), actuator.maxPwm, ...
        actuator.activationThreshold, actuator.commandLevels);
    effective(rowIdx, :) = double(effectiveRow(:))';
    pwm(rowIdx, :) = double(pwmRow(:))';
end
end

function actuator = loadActuatorContract(pathValue, manifest)
loaded = load(pathValue, "evaluationProfile");
if ~isfield(loaded, "evaluationProfile")
    error("run_no_glove_stage7d_training_support:MissingProfile", ...
        "ETAPA 7B profile is incomplete.");
end
profile = loaded.evaluationProfile;
required = ["run_training", "newTraining", "agentFile", ...
    "simMotors", "connect_glove", "referenceSource", ...
    "observationVariant", "rewardType", "actionInterfaceVariant", ...
    "quantizeCommandsForSimulation", "speeds", ...
    "actionCommandActivationThreshold", "actionCommandLevels"];
if ~all(isfield(profile, cellstr(required))) || ...
        logical(profile.run_training) || logical(profile.newTraining) || ...
        string(profile.agentFile) ~= string(manifest.agentCheckpointPath) || ...
        ~logical(profile.simMotors) || logical(profile.connect_glove) || ...
        string(profile.referenceSource) ~= "emgIntent" || ...
        string(profile.observationVariant) ~= "intentMarkov60" || ...
        string(profile.rewardType) ~= "trackingIntentActionRateReward" || ...
        string(profile.actionInterfaceVariant) ~= "baselineQuantized" || ...
        ~logical(profile.quantizeCommandsForSimulation)
    error("run_no_glove_stage7d_training_support:ProfileDrift", ...
        "Policy, reference, interface or simulator safety contract drifted.");
end
actuator = struct("maxPwm", max(abs(double(profile.speeds))), ...
    "activationThreshold", ...
        double(profile.actionCommandActivationThreshold), ...
    "commandLevels", double(profile.actionCommandLevels));
end

