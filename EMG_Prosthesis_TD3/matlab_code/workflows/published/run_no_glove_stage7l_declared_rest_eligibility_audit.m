    error("run_no_glove_stage7l_declared_rest_eligibility_audit:Agent7250Hash", ...
        "The canonical Agent7250 file changed.");
end
manifest = struct("stage", "7L", "schemaVersion", 1, ...
    "result", "PASS", "scientificResult", analysis.classification, ...
    "contractSupported", analysis.contractSupported, ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", gitTrackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", ...
        "run_no_glove_stage7l_declared_rest_eligibility_audit", ...
    "preregistrationCommit", ...
        "2bea46282206dc2406d4aaf38268389a682a5450", ...
    "stage7kRunRoot", options.stage7kRunRoot, ...
    "stage7iRunRoot", string(stage7k.stage7iRunRoot), ...
    "stage7jRunRoot", string(stage7k.stage7jRunRoot), ...
    "stage7kManifestSha256", sourceHashesBefore.sha256(1), ...
    "stage7kResultsSha256", sourceHashesBefore.sha256(2), ...
    "stage7kDecisionCorpusSha256", sourceHashesBefore.sha256(3), ...
    "stage7iManifestSha256", sourceHashesBefore.sha256(5), ...
    "stage7iResultsSha256", sourceHashesBefore.sha256(6), ...
    "stage7iWindowCorpusSha256", sourceHashesBefore.sha256(7), ...
    "stage7jManifestSha256", sourceHashesBefore.sha256(9), ...
    "inputEpisodeCount", height(episodeHashesBefore), ...
    "inputWindowCount", height(frozen.windows), ...
    "inputsPreserved", true, "parentAudit", table2struct(parentAudit), ...
    "thresholds", analysis.thresholds, ...
    "variantSummary", table2struct(analysis.variantSummary), ...
    "gateChecks", table2struct(analysis.gateChecks), ...
    "sourceDecision", table2struct(analysis.sourceDecision), ...
    "prefixCheckCount", analysis.prefixCheckCount, ...
    "prefixMismatchCount", analysis.prefixMismatchCount, ...
    "explicitMemoryRequired", analysis.explicitMemoryRequired, ...
    "proposedObservationVariant", analysis.proposedObservationVariant, ...
    "proposedObservationDimension", ...
        analysis.proposedObservationDimension, ...
    "observationVariantImplemented", false, ...
    "behavioralInterventionExecuted", false, ...
    "behavioralAblationAuthorized", false, ...
    "stage7jScientificResultPreserved", ...
        string(stage7j.scientificResult), ...
    "stage7jContractReauthorized", false, ...
    "rootCauseIdentified", false, ...
    "referenceSource", "emgIntent", ...
    "observationVariant", "intentMarkov60", ...
    "actionInterfaceVariant", "baselineQuantized", ...
    "policyChanged", false, "stateChanged", false, ...
    "rewardChanged", false, "referenceChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "runTraining", false, ...
    "newTraining", false, "agentLoaded", false, ...
    "envCreated", false, "simulatorInvoked", false, ...
    "rewardFunctionInvoked", false, "dtwCalculated", false, ...
    "simMotors", true, "hardwareUsed", false, ...
