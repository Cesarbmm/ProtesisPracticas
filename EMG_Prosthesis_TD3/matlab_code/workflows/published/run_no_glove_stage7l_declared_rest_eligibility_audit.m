function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("resultsRoot", "", "stage7kRunRoot", ...
    "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7k_artifacts\" + ...
    "stage7k_final\2026-08-28_21-25-50-214");
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7kRunRoot = string(options.stage7kRunRoot);
if ~isfile(fullfile(options.stage7kRunRoot, "manifest.json"))
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:MissingStage7k", ...
        "ETAPA 7K manifest not found under %s.", options.stage7kRunRoot);
end
end

function [stage7k, stage7i, stage7j, frozen, hashes, audit] = ...
        loadAndValidateInputs(stage7kRoot)
stage7k = jsondecode(fileread(fullfile(stage7kRoot, "manifest.json")));
valid7k = string(stage7k.stage) == "7K" && ...
    string(stage7k.result) == "PASS" && ...
    string(stage7k.scientificResult) == ...
        "zeroReferenceMixedCausalMechanisms" && ...
    logical(stage7k.replayGatePassed) && ...
    double(stage7k.inputEpisodeCount) == 548 && ...
    double(stage7k.inputWindowCount) == 31220 && ...
    logical(stage7k.inputsPreserved) && ...
    ~logical(stage7k.latchContractReauthorized) && ...
    ~logical(stage7k.behavioralInterventionExecuted) && ...
    ~logical(stage7k.runTraining) && ~logical(stage7k.agentLoaded) && ...
    ~logical(stage7k.scientificReplaySimulatorInvoked) && ...
    ~logical(stage7k.dtwCalculated) && ~logical(stage7k.hardwareUsed) && ...
    ~logical(stage7k.agent7250Loaded);
if ~valid7k
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:Stage7kContract", ...
        "Input manifest is not the frozen ETAPA 7K result.");
end
stage7iRoot = string(stage7k.stage7iRunRoot);
stage7jRoot = string(stage7k.stage7jRunRoot);
stage7i = jsondecode(fileread(fullfile(stage7iRoot, "manifest.json")));
stage7j = jsondecode(fileread(fullfile(stage7jRoot, "manifest.json")));
validParents = string(stage7i.stage) == "7I" && ...
    string(stage7i.result) == "PASS" && ...
    string(stage7i.scientificResult) == ...
        "holdSupportNotSeparableFromFarCorrection" && ...
    logical(stage7i.episodeInputsPreserved) && ...
    ~logical(stage7i.runTraining) && ~logical(stage7i.hardwareUsed) && ...
    string(stage7j.stage) == "7J" && ...
    string(stage7j.result) == "PASS" && ...
    string(stage7j.scientificResult) == ...
        "latchedHoldNotSeparableFromFarCorrection" && ...
    ~logical(stage7j.contractSupported) && ...
    ~logical(stage7j.behavioralInterventionExecuted) && ...
    ~logical(stage7j.runTraining) && ~logical(stage7j.hardwareUsed);
if ~validParents
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:ParentContract", ...
        "Stage 7K does not point to the frozen 7I/7J results.");
end
required = ["stage7k_results.mat", "decision_provenance.csv", ...
    "source_decision.csv"];
for name = required
    if ~isfile(fullfile(stage7kRoot, name))
        error("run_no_glove_stage7l_declared_rest_eligibility_audit:Stage7kArtifact", ...
            "Frozen ETAPA 7K artifact %s is missing.", name);
    end
end
stage7kData = load(fullfile(stage7kRoot, "stage7k_results.mat"), ...
    "analysis");
stage7iData = load(fullfile(stage7iRoot, "stage7i_results.mat"), ...
    "windows", "episodeAudit", "inputHashesBefore");
if height(stage7kData.analysis.decisionAudit) ~= 31220 || ...
        string(stage7kData.analysis.classification) ~= ...
        string(stage7k.scientificResult) || ...
        height(stage7iData.windows) ~= 31220 || ...
        height(stage7iData.episodeAudit) ~= 548 || ...
        height(stage7iData.inputHashesBefore) ~= 548
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:ParentResults", ...
        "Frozen parent MAT files have unexpected contents.");
end
frozen = struct("decisions", stage7kData.analysis.decisionAudit, ...
    "windows", stage7iData.windows, ...
    "episodeAudit", stage7iData.episodeAudit, ...
    "inputHashesBefore", stage7iData.inputHashesBefore);
hashes = hashFrozenSources(stage7kRoot, stage7iRoot, stage7jRoot);
audit = table(string(stage7k.scientificResult), ...
    logical(stage7k.replayGatePassed), ...
    string(stage7i.scientificResult), ...
    string(stage7j.scientificResult), ...
    logical(stage7j.contractSupported), ...
    double(stage7k.inputEpisodeCount), ...
    double(stage7k.inputWindowCount), logical(stage7k.inputsPreserved), ...
    logical(stage7i.episodeInputsPreserved), ...
    'VariableNames', ["stage7kScientificResult", ...
    "stage7kReplayGatePassed", "stage7iScientificResult", ...
    "stage7jScientificResult", "stage7jContractSupported", ...
    "episodeCount", "windowCount", "stage7kInputsPreserved", ...
    "stage7iInputsPreserved"]);
end

function hashes = hashFrozenSources(stage7kRoot, stage7iRoot, stage7jRoot)
paths = [fullfile(stage7kRoot, "manifest.json"); ...
    fullfile(stage7kRoot, "stage7k_results.mat"); ...
    fullfile(stage7kRoot, "decision_provenance.csv"); ...
    fullfile(stage7kRoot, "source_decision.csv"); ...
    fullfile(stage7iRoot, "manifest.json"); ...
    fullfile(stage7iRoot, "stage7i_results.mat"); ...
    fullfile(stage7iRoot, "window_corpus.csv"); ...
    fullfile(stage7iRoot, "episode_input_hashes.csv"); ...
    fullfile(stage7jRoot, "manifest.json"); ...
    fullfile(stage7jRoot, "source_decision.csv")];
labels = ["stage7kManifest"; "stage7kResults"; ...
    "stage7kDecisionCorpus"; "stage7kSourceDecision"; ...
    "stage7iManifest"; "stage7iResults"; "stage7iWindowCorpus"; ...
    "stage7iEpisodeInventory"; "stage7jManifest"; ...
    "stage7jSourceDecision"];
sha256 = strings(numel(paths), 1);
bytes = zeros(numel(paths), 1);
for idx = 1:numel(paths)
    info = dir(paths(idx));
    if isempty(info)
        error("run_no_glove_stage7l_declared_rest_eligibility_audit:SourceMissing", ...
            "Frozen source %s is missing.", paths(idx));
    end
    sha256(idx) = fileSha256(paths(idx));
    bytes(idx) = info.bytes;
end
hashes = table(labels, paths, sha256, bytes);
end

function observed = rehashEpisodeInputs(expected)
observed = expected;
for idx = 1:height(expected)
    path = string(expected.path(idx));
    if ~isfile(path)
        error("run_no_glove_stage7l_declared_rest_eligibility_audit:EpisodeMissing", ...
            "Frozen episode %s is missing.", path);
    end
    info = dir(path);
    observed.bytes(idx) = info.bytes;
    observed.sha256(idx) = fileSha256(path);
end
end

