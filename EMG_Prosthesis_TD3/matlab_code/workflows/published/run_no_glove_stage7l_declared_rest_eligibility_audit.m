if ~all([testResults.Passed])
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:TestsFailed", ...
        "ETAPA 7L tests failed. See %s.", runRoot);
end

[stage7k, stage7i, stage7j, frozen, sourceHashesBefore, ...
    parentAudit] = loadAndValidateInputs(options.stage7kRunRoot);
episodeHashesBefore = rehashEpisodeInputs(frozen.inputHashesBefore);
