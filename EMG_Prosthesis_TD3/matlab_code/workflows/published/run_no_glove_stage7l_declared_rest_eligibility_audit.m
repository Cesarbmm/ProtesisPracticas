    frozen.decisions, frozen.windows);
episodeHashesAfter = rehashEpisodeInputs(frozen.inputHashesBefore);
if ~isequal(episodeHashesBefore, episodeHashesAfter)
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:InputModified", ...
        "A frozen episode changed during the offline audit.");
end
sourceHashesAfter = hashFrozenSources(options.stage7kRunRoot, ...
    string(stage7k.stage7iRunRoot), string(stage7k.stage7jRunRoot));
if ~isequal(sourceHashesBefore, sourceHashesAfter)
    error("run_no_glove_stage7l_declared_rest_eligibility_audit:SourceModified", ...
        "A frozen parent artifact changed during the offline audit.");
