    "actor_replay_audit.csv", "interface_components.csv", ...
    "canonical_sweep.csv", "interface_summary.csv", ...
    "level_sign_summary.csv", "gate_motor_summary.csv", ...
    "gate_window_summary.csv", "safety_summary.csv", ...
    "safety_context_summary.csv", ...
    "decision_audit.csv", "operational_checks.csv", ...
    "stage7p_results.mat", "offline_report.md", ...
