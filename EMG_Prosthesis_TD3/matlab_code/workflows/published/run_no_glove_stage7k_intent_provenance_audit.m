function report = run_no_glove_stage7k_intent_provenance_audit(options)
%run_no_glove_stage7k_intent_provenance_audit replays intent provenance.
%
% Scientific results are reconstructed offline from raw EMG logs. Runtime
% tests exercise only additive diagnostic logging with SimController.

arguments
    options struct = struct()
end

options = normalizeOptions(options);
paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = string(paths.matlabRoot);
repoRoot = string(paths.workspaceRoot);
originalDir = string(pwd);
cleanup = onCleanup(@() cleanupRuntime(originalDir));
cd(matlabRoot);
addpath(genpath(fullfile(matlabRoot, "src")));
addpath(genpath(fullfile(matlabRoot, "config")));
addpath(genpath(fullfile(matlabRoot, "lib")));
addpath(genpath(fullfile(matlabRoot, "tests")));
addpath(genpath(fullfile(matlabRoot, "workflows", "published")));

if strlength(options.resultsRoot) == 0
    options.resultsRoot = fullfile(repoRoot, "Agentes", ...
        "no_glove_intent_control", "stage7k_intent_provenance");
end
runRoot = fullfile(options.resultsRoot, ...
    string(datetime("now", "Format", "yyyy-MM-dd_HH-mm-ss-SSS")));
if isfolder(runRoot)
    error("run_no_glove_stage7k_intent_provenance_audit:OutputExists", ...
        "Refusing to reuse %s.", runRoot);
end
mkdir(runRoot);

testFiles = [ ...
    fullfile(matlabRoot, "tests", "no_glove", ...
        "testNoGloveStage7kIntentProvenance.m"), ...
    fullfile(matlabRoot, "tests", "no_glove", ...
        "testIntentMarkov60.m"), ...
    fullfile(matlabRoot, "tests", "no_glove", ...
        "testReferenceSources.m")];
testResults = runtests(testFiles);
save(fullfile(runRoot, "test_results.mat"), "testResults");
if ~all([testResults.Passed])
    error("run_no_glove_stage7k_intent_provenance_audit:TestsFailed", ...
        "ETAPA 7K tests failed. See %s.", runRoot);
end

[stage7j, stage7i, frozen, profiles, sourceHashesBefore, ...
    parentAudit] = loadAndValidateInputs(options.stage7jRunRoot);
episodeHashesBefore = rehashEpisodeInputs(frozen.inputHashesBefore);
if ~isequal(frozen.inputHashesBefore, episodeHashesBefore)
    error("run_no_glove_stage7k_intent_provenance_audit:EpisodeHash", ...
        "A frozen episode differs from the 7I inventory.");
end
analysis = replayNoGloveStage7kIntentProvenance( ...
    frozen.episodeAudit, frozen.windows, frozen.latchAudit, profiles);
episodeHashesAfter = rehashEpisodeInputs(frozen.inputHashesBefore);
if ~isequal(episodeHashesBefore, episodeHashesAfter)
    error("run_no_glove_stage7k_intent_provenance_audit:InputModified", ...
        "A frozen episode changed during the offline replay.");
end
sourceHashesAfter = hashFrozenSources(options.stage7jRunRoot, ...
    string(stage7j.stage7iRunRoot), stage7i);
if ~isequal(sourceHashesBefore, sourceHashesAfter)
    error("run_no_glove_stage7k_intent_provenance_audit:SourceModified", ...
        "A frozen parent artifact changed during the replay.");
end

loggingContractAudit = table("intentProvenanceLog", 1, true, true, ...
    false, false, false, false, true, ...
    'VariableNames', ["logVariable", "schemaVersion", ...
    "resetPerEpisode", "savedPerTransition", ...
    "includedInObservation", "includedInRewardContext", ...
    "changesReference", "changesAction", "glovePathRemainsEmpty"]);
writetable(episodeHashesBefore, ...
    fullfile(runRoot, "episode_input_hashes.csv"));
writetable(sourceHashesBefore, fullfile(runRoot, "source_hashes.csv"));
writetable(parentAudit, fullfile(runRoot, "parent_audit.csv"));
writetable(loggingContractAudit, ...
    fullfile(runRoot, "logging_contract_audit.csv"));
writetable(analysis.decisionAudit, ...
    fullfile(runRoot, "decision_provenance.csv"));
writetable(analysis.transitionAudit, ...
    fullfile(runRoot, "transition_replay.csv"));
writetable(analysis.episodeReplayAudit, ...
    fullfile(runRoot, "episode_replay_audit.csv"));
writetable(analysis.provenanceSummary, ...
    fullfile(runRoot, "provenance_summary.csv"));
writetable(analysis.segmentProvenanceAudit, ...
    fullfile(runRoot, "segment_provenance.csv"));
writetable(analysis.gateChecks, fullfile(runRoot, "gate_checks.csv"));
writetable(analysis.sourceDecision, ...
    fullfile(runRoot, "source_decision.csv"));

[gitCommit, gitDirty, gitTrackedDirty, gitStatus] = getGitState(repoRoot);
agent7250Path = string(stage7j.agent7250CheckpointPath);
agent7250Hash = fileSha256(agent7250Path);
if agent7250Hash ~= string(stage7j.agent7250CheckpointSha256)
    error("run_no_glove_stage7k_intent_provenance_audit:Agent7250Hash", ...
        "The canonical Agent7250 file changed.");
end
manifest = struct("stage", "7K", "schemaVersion", 1, ...
    "result", "PASS", "scientificResult", analysis.classification, ...
    "replayGatePassed", analysis.replayGatePassed, ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", gitTrackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", "run_no_glove_stage7k_intent_provenance_audit", ...
    "preregistrationCommit", ...
        "0467d7e2093a253f10d33b051da0c1bb6cb1e278", ...
    "stage7jRunRoot", options.stage7jRunRoot, ...
    "stage7iRunRoot", string(stage7j.stage7iRunRoot), ...
    "stage7jManifestSha256", sourceHashesBefore.sha256(1), ...
    "stage7jResultsSha256", sourceHashesBefore.sha256(2), ...
    "stage7iManifestSha256", sourceHashesBefore.sha256(4), ...
    "stage7iResultsSha256", sourceHashesBefore.sha256(5), ...
    "inputEpisodeCount", height(episodeHashesBefore), ...
    "inputWindowCount", height(frozen.windows), ...
    "inputsPreserved", true, "parentAudit", table2struct(parentAudit), ...
    "thresholds", analysis.thresholds, ...
    "gateChecks", table2struct(analysis.gateChecks), ...
    "sourceDecision", table2struct(analysis.sourceDecision), ...
    "directPerStepLabelAbsentInFrozenInputs", ...
        analysis.directPerStepLabelAbsentInFrozenInputs, ...
    "offlineReconstructionAvailable", true, ...
    "loggingInstrumentationImplemented", true, ...
    "loggingContractAudit", table2struct(loggingContractAudit), ...
    "loggingChanged", true, "loggingAffectsObservation", false, ...
    "loggingAffectsReward", false, "loggingAffectsReference", false, ...
    "loggingAffectsAction", false, "loggingAffectsSafety", false, ...
    "latchContractReauthorized", false, ...
    "intentHoldMarkov61Implemented", false, ...
    "behavioralInterventionExecuted", false, ...
    "rootCauseIdentified", false, ...
    "referenceSource", "emgIntent", ...
    "observationVariant", "intentMarkov60", ...
    "actionInterfaceVariant", "baselineQuantized", ...
    "policyChanged", false, "stateChanged", false, ...
    "rewardChanged", false, "referenceChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "runTraining", false, ...
    "newTraining", false, "agentLoaded", false, ...
    "scientificReplaySimulatorInvoked", false, ...
    "simulationUsedByLoggingTests", true, ...
    "simMotors", true, "rewardFunctionInvokedForAnalysis", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false, ...
    "agent7250Loaded", false, ...
    "agent7250CheckpointPath", agent7250Path, ...
    "agent7250CheckpointSha256", agent7250Hash, ...
    "testsTotal", numel(testResults), ...
    "testsPassed", sum([testResults.Passed]), ...
    "testsFailed", sum([testResults.Failed]), ...
    "outputPath", runRoot);
save(fullfile(runRoot, "stage7k_results.mat"), "manifest", ...
    "analysis", "episodeHashesBefore", "sourceHashesBefore", ...
    "parentAudit", "loggingContractAudit", "stage7j", "stage7i", ...
    "-v7.3");
writeText(fullfile(runRoot, "offline_report.md"), ...
    buildOfflineReport(manifest));
writeText(fullfile(runRoot, "reproducible_command.txt"), ...
    buildReproducibleCommand(matlabRoot, options, runRoot));
manifest.artifactHashes = inventoryArtifacts(runRoot);
writeText(fullfile(runRoot, "manifest.json"), ...
    jsonencode(manifest, "PrettyPrint", true));

report = struct("result", "PASS", ...
    "scientificResult", analysis.classification, ...
    "replayGatePassed", analysis.replayGatePassed, ...
    "outputPath", runRoot, "manifest", manifest, ...
    "analysis", analysis);
