disp(analysis.sourceDecision);
end

function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7k_intent_provenance_audit:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("resultsRoot", "", "stage7jRunRoot", ...
    "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7j_artifacts\" + ...
    "stage7j_final\2026-08-28_21-02-19-544");
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7k_intent_provenance_audit:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7jRunRoot = string(options.stage7jRunRoot);
if ~isfile(fullfile(options.stage7jRunRoot, "manifest.json"))
    error("run_no_glove_stage7k_intent_provenance_audit:MissingStage7j", ...
        "ETAPA 7J manifest not found under %s.", options.stage7jRunRoot);
end
end

function [stage7j, stage7i, frozen, profiles, hashes, audit] = ...
        loadAndValidateInputs(stage7jRoot)
stage7j = jsondecode(fileread(fullfile(stage7jRoot, "manifest.json")));
if string(stage7j.stage) ~= "7J" || string(stage7j.result) ~= "PASS" || ...
        string(stage7j.scientificResult) ~= ...
        "latchedHoldNotSeparableFromFarCorrection" || ...
        logical(stage7j.contractSupported) || ...
        logical(stage7j.behavioralInterventionExecuted) || ...
        logical(stage7j.runTraining) || logical(stage7j.hardwareUsed) || ...
        logical(stage7j.agentLoaded) || logical(stage7j.dtwCalculated)
    error("run_no_glove_stage7k_intent_provenance_audit:Stage7jContract", ...
        "Input manifest is not the frozen ETAPA 7J result.");
end
stage7iRoot = string(stage7j.stage7iRunRoot);
stage7i = jsondecode(fileread(fullfile(stage7iRoot, "manifest.json")));
if string(stage7i.stage) ~= "7I" || string(stage7i.result) ~= "PASS" || ...
        double(stage7i.episodeInputCount) ~= 548 || ...
        double(stage7i.windowCount) ~= 31220 || ...
        ~logical(stage7i.episodeInputsPreserved) || ...
        logical(stage7i.hardwareUsed) || logical(stage7i.runTraining)
    error("run_no_glove_stage7k_intent_provenance_audit:Stage7iContract", ...
        "7J does not point to the frozen ETAPA 7I corpus.");
end
stage7jData = load(fullfile(stage7jRoot, "stage7j_results.mat"), ...
    "analysis");
stage7iData = load(fullfile(stage7iRoot, "stage7i_results.mat"), ...
    "windows", "episodeAudit", "inputHashesBefore");
if height(stage7jData.analysis.windowAudit) ~= 31220 || ...
        height(stage7iData.windows) ~= 31220 || ...
        height(stage7iData.episodeAudit) ~= 548 || ...
        height(stage7iData.inputHashesBefore) ~= 548
    error("run_no_glove_stage7k_intent_provenance_audit:ParentResults", ...
        "Frozen parent MAT files have unexpected dimensions.");
end
controlData = load(fullfile(string(stage7i.controlRunRoot), ...
    "seed_11", "effective_training_profile.mat"), "profile");
candidateData = load(fullfile(string(stage7i.candidateRunRoot), ...
    "seed_11", "effective_training_profile.mat"), "profile");
profiles = struct("control", controlData.profile, ...
    "candidate", candidateData.profile);
if string(profiles.control.intentCalibration.contentSha256) ~= ...
        string(profiles.candidate.intentCalibration.contentSha256) || ...
        ~profiles.control.simMotors || ~profiles.candidate.simMotors || ...
        string(profiles.control.observationVariant) ~= "intentMarkov60" || ...
        string(profiles.candidate.observationVariant) ~= "intentMarkov60"
    error("run_no_glove_stage7k_intent_provenance_audit:ProfileContract", ...
        "Frozen profiles do not share the causal intent calibration.");
end
frozen = struct("windows", stage7iData.windows, ...
    "episodeAudit", stage7iData.episodeAudit, ...
    "inputHashesBefore", stage7iData.inputHashesBefore, ...
    "latchAudit", stage7jData.analysis.windowAudit);
hashes = hashFrozenSources(stage7jRoot, stage7iRoot, stage7i);
audit = table(string(stage7j.scientificResult), ...
    logical(stage7j.contractSupported), string(stage7i.scientificResult), ...
    double(stage7i.episodeInputCount), double(stage7i.windowCount), ...
    string(profiles.control.intentCalibration.contentSha256), ...
    logical(stage7j.inputsPreserved), logical(stage7i.episodeInputsPreserved), ...
    'VariableNames', ["stage7jScientificResult", ...
    "stage7jContractSupported", "stage7iScientificResult", ...
    "episodeCount", "windowCount", "calibrationSha256", ...
    "stage7jInputsPreserved", "stage7iInputsPreserved"]);
end

function hashes = hashFrozenSources(stage7jRoot, stage7iRoot, stage7i)
paths = [fullfile(stage7jRoot, "manifest.json"); ...
    fullfile(stage7jRoot, "stage7j_results.mat"); ...
    fullfile(stage7jRoot, "window_latch_audit.csv"); ...
    fullfile(stage7iRoot, "manifest.json"); ...
    fullfile(stage7iRoot, "stage7i_results.mat"); ...
    fullfile(stage7iRoot, "episode_input_hashes.csv"); ...
    fullfile(string(stage7i.controlRunRoot), "seed_11", ...
        "effective_training_profile.mat"); ...
    fullfile(string(stage7i.candidateRunRoot), "seed_11", ...
        "effective_training_profile.mat")];
labels = ["stage7jManifest"; "stage7jResults"; ...
    "stage7jWindowLatchAudit"; "stage7iManifest"; ...
    "stage7iResults"; "stage7iEpisodeInventory"; ...
    "controlProfile"; "candidateProfile"];
sha256 = strings(numel(paths), 1);
bytes = zeros(numel(paths), 1);
for idx = 1:numel(paths)
    info = dir(paths(idx));
    if isempty(info)
        error("run_no_glove_stage7k_intent_provenance_audit:SourceMissing", ...
            "Frozen source %s is missing.", paths(idx));
    end
    sha256(idx) = fileSha256(paths(idx));
    bytes(idx) = info.bytes;
end
hashes = table(labels, paths, sha256, bytes);
end

function observed = rehashEpisodeInputs(expected)
observed = expected;
for idx = 1:height(expected)
    path = string(expected.path(idx));
    if ~isfile(path)
        error("run_no_glove_stage7k_intent_provenance_audit:EpisodeMissing", ...
            "Frozen episode %s is missing.", path);
    end
    info = dir(path);
    observed.bytes(idx) = info.bytes;
    observed.sha256(idx) = fileSha256(path);
end
end

