function writeOfflineReport(reportPath, manifest)
lines = strings(0, 1);
lines(end+1) = "# ETAPA 6 " + upper(manifest.phase);
lines(end+1) = "";
lines(end+1) = "- Resultado del gate: " + manifest.result + ".";
lines(end+1) = sprintf("- Episodios por seed: %d.", ...
    manifest.protocol.episodes);
lines(end+1) = "- Seeds: [" + strjoin(string(manifest.seeds), ",") + "].";
lines(end+1) = "- Calibración sintética: `" + ...
    manifest.calibrationContentSha256 + "`.";
lines(end+1) = "- Agent7250 cargado/usado: no/no.";
lines(end+1) = "- Ablación de límites de posición: " + ...
    string(manifest.positionSafetyAblation) + ".";
lines(end+1) = "- Hardware: no; simulador: sí.";
lines(end+1) = "- Métricas por seed: `seed_summary.csv`.";
writeText(reportPath, strjoin(lines, newline));
end

function writeText(filePath, value)
fid = fopen(filePath, "w");
if fid < 0
    error("run_no_glove_stage6_training:WriteFailed", ...
        "Could not open %s.", filePath);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s", value);
end

