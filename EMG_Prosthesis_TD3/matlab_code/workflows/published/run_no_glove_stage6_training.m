row.otherMotorFunctionalFlagCount = ...
    acceptance.otherMotorFunctionalFlagCount;
row.restDirectory = restDir;
row.restSaturationFraction = rest.saturationFraction;
row.restFalseActivationFraction = gate.restFalseActivationFraction;
row.gatePassed = gate.passed;
end

