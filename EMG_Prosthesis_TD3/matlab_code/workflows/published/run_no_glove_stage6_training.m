    "actionL2Std", std(seedTable.actionL2), ...
    "deltaActionL2Mean", mean(seedTable.deltaActionL2), ...
    "deltaActionL2Std", std(seedTable.deltaActionL2), ...
    "saturationFractionMean", mean(seedTable.saturationFraction), ...
    "saturationFractionStd", std(seedTable.saturationFraction), ...
    "restSaturationFractionMean", ...
        mean(seedTable.restSaturationFraction), ...
    "trainingPositionSafetyInterventionCount", ...
        sum(seedTable.trainingPositionSafetyInterventionCount), ...
    "acceptancePositionSafetyInterventionCount", ...
        sum(seedTable.acceptancePositionSafetyInterventionCount), ...
    "gatePassCount", sum(seedTable.gatePassed));
end

function newestDir = findNewestSubdir(parentDir)
info = dir(parentDir);
info = info([info.isdir]);
info = info(~ismember({info.name}, {'.', '..'}));
if isempty(info)
    error("run_no_glove_stage6_training:MissingOutputDirectory", ...
        "No output directory found under %s.", parentDir);
end
[~, idx] = max([info.datenum]);
newestDir = string(fullfile(info(idx).folder, info(idx).name));
end

function [commit, dirty] = getGitState(repoRoot)
[status, output] = system(sprintf('git -C "%s" rev-parse HEAD', repoRoot));
if status == 0
    commit = string(strtrim(output));
else
    commit = "unknown";
end
[status, output] = system(sprintf('git -C "%s" status --porcelain', repoRoot));
dirty = status ~= 0 || strlength(strtrim(string(output))) > 0;
end

function hash = fileSha256(filePath)
escaped = strrep(char(string(filePath)), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("run_no_glove_stage6_training:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = string(strtrim(output));
end

function value = conditionalString(condition, trueValue, falseValue)
if condition
    value = string(trueValue);
else
    value = string(falseValue);
end
end

function command = buildReproducibleCommand(matlabRoot, options, runRoot)
reproRoot = string(fileparts(runRoot));
authorizationOption = "";
if options.phase == "pilot"
    authorizationOption = sprintf(",'smokeManifestPath','%s'", ...
        strrep(char(options.smokeManifestPath), "'", "''"));
elseif options.phase == "campaign"
    authorizationOption = sprintf(",'pilotManifestPath','%s'", ...
        strrep(char(options.pilotManifestPath), "'", "''"));
end
command = sprintf( ...
    "cd('%s'); addpath(genpath(pwd)); " + ...
    "run_no_glove_stage6_training(struct('phase','%s'," + ...
    "'resultsRoot','%s','calibrationSeed',%d," + ...
    "'evaluationSeed',%d,'evaluationSimulations',%d," + ...
    "'restSimulations',%d,'positionSafetyAblation',%s," + ...
    "'intentRewardActionWeight',%.17g," + ...
    "'intentHoldRewardEnabled',%s,'intentHoldActionWeight',%.17g," + ...
    "'intentHoldVelocityTolerance',%.17g," + ...
    "'intentHoldPositionMseTolerance',%.17g%s))", ...
    strrep(char(matlabRoot), "'", "''"), options.phase, ...
    strrep(char(reproRoot), "'", "''"), options.calibrationSeed, ...
    options.evaluationSeed, options.evaluationSimulations, ...
    options.restSimulations, mat2str(options.positionSafetyAblation), ...
    options.intentRewardActionWeight, ...
    mat2str(options.intentHoldRewardEnabled), ...
    options.intentHoldActionWeight, ...
    options.intentHoldVelocityTolerance, ...
    options.intentHoldPositionMseTolerance, ...
    authorizationOption);
end

