trainingPath = fullfile(fixtureDir, "stage6_training_emg_only.mat");
evaluationPath = fullfile(fixtureDir, "stage6_evaluation_emg_only.mat");
restPath = fullfile(fixtureDir, "stage6_steady_rest_emg_only.mat");
emgs = corpus.trainingEmgs;
