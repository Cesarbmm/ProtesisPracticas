end

function assertSafeTrainingProfile( ...
        profile, protocol, expectedSafetyEnabled, options)
expectedRewardType = conditionalString(options.intentHoldRewardEnabled, ...
    "trackingIntentHoldActionReward", ...
    "trackingIntentActionRateReward");
holdSettingsMatch = ~options.intentHoldRewardEnabled || ( ...
    isfield(profile, "intentHoldActionWeight") && ...
    isfield(profile, "intentHoldVelocityTolerance") && ...
    isfield(profile, "intentHoldPositionMseTolerance") && ...
    profile.intentHoldActionWeight == options.intentHoldActionWeight && ...
    profile.intentHoldVelocityTolerance == ...
        options.intentHoldVelocityTolerance && ...
    profile.intentHoldPositionMseTolerance == ...
        options.intentHoldPositionMseTolerance);
safe = profile.run_training && profile.newTraining && ...
    strlength(string(profile.agentFile)) == 0 && ...
    string(profile.agent_id) == "td3_no_glove_intent" && ...
    profile.referenceSource == "emgIntent" && ...
    profile.observationVariant == "intentMarkov60" && ...
    profile.rewardType == expectedRewardType && ...
    profile.actionInterfaceVariant == "baselineQuantized" && ...
    profile.usePrerecorded && profile.simMotors && ...
    ~profile.connect_glove && ~profile.td3.useRecurrent && ...
    ~profile.td3Residual.enabled && ...
    profile.simulationPositionSafety.enabled == expectedSafetyEnabled && ...
    string(profile.simulationPositionSafety.mode) == ...
        "clipTrajectoryOutput" && ...
    profile.intentRewardPositionWeight == 1.00 && ...
    profile.intentRewardVelocityWeight == 0.00 && ...
    profile.intentRewardActionWeight == options.intentRewardActionWeight && ...
    profile.intentRewardDeltaActionWeight == 0.05 && ...
    profile.intentRewardSaturationWeight == 0.02 && ...
    profile.intentRewardSoftActionLimit == 0.90 && ...
    holdSettingsMatch && ...
    profile.trainingMaxEpisodes == protocol.episodes;
if ~safe
    error("run_no_glove_stage6_training:UnsafeTrainingProfile", ...
        "ETAPA 6 training profile violates an invariant.");
end
end

function evaluationDir = runEvaluation( ...
        trainingProfile, checkpointPath, datasetPath, evaluationBase, ...
        evaluationSeed, simulationCount)
mkdir(evaluationBase);
[datasetFolder, datasetStem] = fileparts(datasetPath);
profile = trainingProfile;
profile.run_training = false;
profile.newTraining = false;
profile.agentFile = checkpointPath;
profile.agent_id = "td3_no_glove_intent";
profile.randomSeed = evaluationSeed;
profile.dataset = {char(string(datasetStem))};
profile.dataset_folder = string(datasetFolder);
profile.flagSaveTraining = true;
profile.episode_save_freq = 1;
profile.plotEpisodeOnTest = false;
profile.simOpts = rlSimulationOptions( ...
    "MaxSteps", profile.maxNumberStepsInEpisodes, ...
    "NumSimulations", simulationCount, ...
    "StopOnError", "on", ...
    "UseParallel", false);
profile.agents_directory = @(agent_id, variant) fullfile( ...
    evaluationBase, string(datetime("now", "Format", "yy-MM-dd HH m s")));
setConfigurablesOverride(profile);
trainInterface("td3_no_glove_intent", "", "");
clearConfigurablesOverride();
evaluationDir = findNewestSubdir(evaluationBase);
end

function checkpointTable = inventoryCheckpoints(trainingDir, seed, finalEpisode)
files = dir(fullfile(trainingDir, "Agent*.mat"));
if isempty(files)
    error("run_no_glove_stage6_training:NoCheckpoints", ...
        "Training produced no checkpoints in %s.", trainingDir);
end
episode = zeros(numel(files), 1);
path = strings(numel(files), 1);
sha256 = strings(numel(files), 1);
bytes = zeros(numel(files), 1);
for fileIdx = 1:numel(files)
    token = regexp(files(fileIdx).name, '^Agent(\d+)\.mat$', ...
        'tokens', 'once');
    if isempty(token)
        error("run_no_glove_stage6_training:UnexpectedCheckpointName", ...
            "Unexpected checkpoint %s.", files(fileIdx).name);
    end
    episode(fileIdx) = str2double(token{1});
    path(fileIdx) = string(fullfile(files(fileIdx).folder, files(fileIdx).name));
    sha256(fileIdx) = fileSha256(path(fileIdx));
    bytes(fileIdx) = files(fileIdx).bytes;
end
[episode, order] = sort(episode);
path = path(order);
sha256 = sha256(order);
bytes = bytes(order);
checkpointTable = table( ...
    repmat(seed, numel(files), 1), episode, path, sha256, bytes, ...
    episode == finalEpisode, ...
    'VariableNames', {'seed', 'episode', 'checkpointPath', ...
    'checkpointSha256', 'bytes', 'isFinal'});
end

