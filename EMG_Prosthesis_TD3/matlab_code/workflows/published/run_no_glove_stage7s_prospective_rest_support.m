function value = validateAcceptanceInvariant(corpus, parent)
newMask = corpus.metadata.source == "acceptance";
oldMask = parent.metadata.source == "acceptance";
value = sum(newMask) == 3050 && sum(oldMask) == 3050 && ...
    isequal(corpus.states(newMask, :), parent.states(oldMask, :)) && ...
    isequal(corpus.rawAction(newMask, :), ...
        parent.rawAction(oldMask, :)) && ...
    isequal(corpus.effectiveAction(newMask, :), ...
        parent.effectiveAction(oldMask, :)) && ...
    isequal(corpus.pwm(newMask, :), parent.pwm(oldMask, :)) && ...
    isequal(corpus.qAfter(newMask, :), parent.qAfter(oldMask, :));
if ~value
    error("run_no_glove_stage7s_prospective_rest_support:AcceptanceChanged", ...
        "The frozen Agent200 acceptance corpus changed.");
end
end

function inventory = addEpisodeHashes(inventory)
sha256 = strings(height(inventory), 1);
bytes = zeros(height(inventory), 1);
for idx = 1:height(inventory)
    path = string(inventory.filePath(idx));
    info = dir(path);
    bytes(idx) = info.bytes;
    sha256(idx) = fileSha256(path);
end
inventory.bytes = bytes;
inventory.sha256 = sha256;
end

function [evaluations, audit] = evaluateCheckpointSet(data, corpus)
rows = sortrows(data.checkpointTable, "episode");
evaluations = repmat(struct("episode", 0, "raw", [], ...
    "effective", [], "pwm", []), height(rows), 1);
auditParts = cell(height(rows), 1);
newAcceptance = corpus.metadata.source == "acceptance";
parentAcceptance = data.primaryCorpus.metadata.source == "acceptance";
for idx = 1:height(rows)
    episode = double(rows.episode(idx));
    checkpointPath = string(rows.checkpointPath(idx));
    agent = loadSavedAgent(checkpointPath);
    actor = getActor(agent);
    model = getModel(actor);
    raw = evaluateFrozenActorModelStates(model, corpus.states);
    [effective, pwm] = quantizeRows(raw, data.actuator);
    evaluations(idx) = struct("episode", episode, "raw", raw, ...
        "effective", effective, "pwm", pwm);
    parentIdx = find([data.sharedEvaluations.episode] == episode, 1);
    acceptanceRawError = max(abs(raw(newAcceptance, :) - ...
        data.sharedEvaluations(parentIdx).raw(parentAcceptance, :)), ...
        [], "all");
    acceptancePwmMismatch = sum(pwm(newAcceptance, :) ~= ...
        data.sharedEvaluations(parentIdx).pwm(parentAcceptance, :), "all");
    savedRawError = NaN;
    savedPwmMismatch = NaN;
    if episode == 200
        savedRawError = max(abs(raw-corpus.rawAction), [], "all");
        savedPwmMismatch = sum(pwm ~= corpus.pwm, "all");
    end
    replayPassed = acceptanceRawError <= 1e-5 && ...
        acceptancePwmMismatch == 0 && ...
        (episode ~= 200 || (savedRawError <= 1e-5 && ...
        savedPwmMismatch == 0));
    auditParts{idx} = table(episode, checkpointPath, ...
        string(rows.checkpointSha256(idx)), size(raw, 1), ...
        acceptanceRawError, acceptancePwmMismatch, ...
        savedRawError, savedPwmMismatch, replayPassed, ...
        'VariableNames', ["checkpointEpisode", "checkpointPath", ...
        "checkpointSha256", "evaluatedStateCount", ...
        "acceptanceRawMaximumError", "acceptancePwmMismatchCount", ...
        "agent200SavedRawMaximumError", ...
        "agent200SavedPwmMismatchCount", "replayPassed"]);
    clear agent actor model raw effective pwm
end
audit = vertcat(auditParts{:});
end

function [effective, pwm] = quantizeRows(raw, actuator)
effective = zeros(size(raw));
pwm = zeros(size(raw));
for row = 1:size(raw, 1)
    [e, p] = quantizeBaselineAction(raw(row, :), ...
        actuator.maxPwm, actuator.activationThreshold, ...
        actuator.commandLevels);
    effective(row, :) = double(e(:)');
    pwm(row, :) = double(p(:)');
end
end

