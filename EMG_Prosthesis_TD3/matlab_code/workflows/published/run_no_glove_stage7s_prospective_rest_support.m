function hashes = inventoryArtifacts(runRoot)
files = dir(fullfile(runRoot, "**", "*"));
files = files(~[files.isdir]);
fullPaths = string(fullfile({files.folder}, {files.name}))';
manifestPath = string(fullfile(runRoot, "manifest.json"));
fullPaths = fullPaths(fullPaths ~= manifestPath);
relativePath = erase(fullPaths, string(runRoot)+filesep);
sha256 = strings(numel(fullPaths), 1);
for idx = 1:numel(fullPaths)
    sha256(idx) = fileSha256(fullPaths(idx));
end
hashes = table2struct(table(relativePath, sha256));
end

