        "No evaluation directory was created under %s.", parentDir);
end
[~, idx] = max([entries.datenum]);
newestDir = string(fullfile(entries(idx).folder, entries(idx).name));
end

function [commit, dirty, trackedDirty, statusText] = getGitState(repoRoot)
[status, output] = system(sprintf('git -C "%s" rev-parse HEAD', repoRoot));
if status ~= 0
    commit = "unknown";
else
    commit = string(strtrim(output));
end
[status, output] = system(sprintf( ...
    'git -C "%s" status --porcelain --untracked-files=all', repoRoot));
if status ~= 0
    dirty = true;
    trackedDirty = true;
    statusText = "git status failed";
else
    statusText = string(strtrim(output));
    dirty = strlength(statusText) > 0;
    lines = splitlines(statusText);
    lines = lines(strlength(lines) > 0);
    trackedDirty = any(~startsWith(lines, "??"));
end
end

function hash = fileSha256(filePath)
escaped = strrep(char(filePath), "'", "''");
command = sprintf([ ...
    'powershell -NoProfile -Command "(Get-FileHash -Algorithm SHA256 ' ...
    '-LiteralPath ''%s'').Hash"'], escaped);
[status, output] = system(command);
if status ~= 0
    error("run_no_glove_stage7s_prospective_rest_support:HashFailed", ...
        "Could not hash %s.", filePath);
end
hash = string(strtrim(output));
end

function writeText(path, value)
fid = fopen(path, "w");
if fid < 0
    error("run_no_glove_stage7s_prospective_rest_support:WriteFailed", ...
        "Could not write %s.", path);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s", value);
end

function value = escape(value)
value = strrep(string(value), "'", "''");
end

