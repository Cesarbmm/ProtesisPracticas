function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7m_observable_hold_state:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("resultsRoot", "", "stage7lRunRoot", ...
    "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7l_artifacts\" + ...
    "stage7l_final\2026-08-28_21-44-35-302", ...
    "randomSeed", 11, "smokeStepCount", 20);
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7m_observable_hold_state:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7lRunRoot = string(options.stage7lRunRoot);
if ~isnumeric(options.randomSeed) || ~isscalar(options.randomSeed) || ...
        ~isfinite(options.randomSeed) || options.randomSeed < 0 || ...
        fix(options.randomSeed) ~= options.randomSeed
    error("run_no_glove_stage7m_observable_hold_state:InvalidSeed", ...
        "randomSeed must be a nonnegative integer.");
