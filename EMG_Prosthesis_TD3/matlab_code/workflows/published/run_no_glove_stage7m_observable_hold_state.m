    logical(manifest.inputsPreserved) && ...
    ~logical(manifest.observationVariantImplemented) && ...
    ~logical(manifest.behavioralAblationAuthorized) && ...
    ~logical(manifest.stage7jContractReauthorized) && ...
    ~logical(manifest.runTraining) && ~logical(manifest.agentLoaded) && ...
    ~logical(manifest.simulatorInvoked) && ...
    ~logical(manifest.dtwCalculated) && ~logical(manifest.hardwareUsed) && ...
