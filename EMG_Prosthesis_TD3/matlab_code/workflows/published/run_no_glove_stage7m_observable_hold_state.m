function audit = buildEquivalenceAudit(control, candidate)
count = size(control.observations, 1);
decisionIndex = (0:count-1)';
statePrefixMaxAbsDifference = max(abs( ...
    control.observations-candidate.observations(:, 1:60)), [], 2);
referencePositionMaxAbsDifference = max(abs( ...
    control.observations(:, 53:56)- ...
    candidate.observations(:, 53:56)), [], 2);
referenceVelocityMaxAbsDifference = max(abs( ...
    control.observations(:, 57:60)- ...
    candidate.observations(:, 57:60)), [], 2);
rewardAbsDifference = [NaN; abs(control.rewards-candidate.rewards)];
rawActionMaxAbsDifference = [NaN; max(abs( ...
    control.rawAction-candidate.rawAction), [], 2)];
effectiveActionMaxAbsDifference = [NaN; max(abs( ...
    control.effectiveAction-candidate.effectiveAction), [], 2)];
pwmMaxAbsDifference = [NaN; max(abs(control.pwm-candidate.pwm), [], 2)];
safetyMaxAbsDifference = [NaN; max(abs( ...
    control.safety-candidate.safety), [], 2)];
controlFinite = all(isfinite(control.observations), 2);
candidateFinite = all(isfinite(candidate.observations), 2);
candidateWithinBounds = all(candidate.observations >= ...
    candidate.lowerLimit & candidate.observations <= ...
    candidate.upperLimit, 2);
audit = table(decisionIndex, statePrefixMaxAbsDifference, ...
    referencePositionMaxAbsDifference, ...
    referenceVelocityMaxAbsDifference, rewardAbsDifference, ...
    rawActionMaxAbsDifference, effectiveActionMaxAbsDifference, ...
    pwmMaxAbsDifference, safetyMaxAbsDifference, controlFinite, ...
    candidateFinite, candidateWithinBounds);
end

function audit = buildRuntimeAlignmentAudit(trace, profile)
layout = trace.layout;
count = size(trace.observations, 1);
decisionIndex = (0:count-1)';
provenance = strings(count, 1);
observedDeclaredRest = logical( ...
    trace.observations(:, layout.declaredRest));
observedHoldLatch = logical(trace.observations(:, layout.holdLatch));
expectedDeclaredRest = false(count, 1);
expectedHoldLatch = false(count, 1);
positionMse = zeros(count, 1);
nearTarget = false(count, 1);
schemaVersion = nan(count, 1);
expectedDeclaredRest(1) = true;
expectedHoldLatch(1) = true;
provenance(1) = "episodeInitialization";
positionMse(1) = mean((trace.observations(1, layout.encoder)- ...
    trace.observations(1, layout.referencePosition)).^2);
nearTarget(1) = positionMse(1) <= ...
    profile.intentDeclaredRestHoldPositionMseTolerance;
for idx = 2:count
    item = trace.provenance{idx-1};
    provenance(idx) = string(item.zeroReferenceReason);
    expectedDeclaredRest(idx) = logical(item.isRest);
    positionMse(idx) = mean((trace.observations(idx, layout.encoder)- ...
        trace.observations(idx, layout.referencePosition)).^2);
    nearTarget(idx) = positionMse(idx) <= ...
        profile.intentDeclaredRestHoldPositionMseTolerance;
    if ~expectedDeclaredRest(idx)
        expectedHoldLatch(idx) = false;
    elseif nearTarget(idx)
        expectedHoldLatch(idx) = true;
    else
        expectedHoldLatch(idx) = expectedHoldLatch(idx-1);
    end
    schemaVersion(idx) = item.schemaVersion;
end
declaredRestMismatch = observedDeclaredRest ~= expectedDeclaredRest;
holdLatchMismatch = observedHoldLatch ~= expectedHoldLatch;
audit = table(decisionIndex, provenance, positionMse, nearTarget, ...
    observedDeclaredRest, expectedDeclaredRest, declaredRestMismatch, ...
    observedHoldLatch, expectedHoldLatch, holdLatchMismatch, schemaVersion);
end

function audit = buildSemanticTransitionAudit(tolerance)
caseName = ["initializeNear"; "retainFarRest"; ...
    "releaseCountdownNear"; "remainInactiveFarRest"];
previousLatch = logical([0; 1; 1; 0]);
declaredRest = logical([1; 1; 0; 1]);
encoder = repmat([0.2, 0.3, 0.4, 0.5], 4, 1);
reference = encoder;
reference(2, :) = reference(2, :)+0.02;
reference(4, :) = reference(4, :)+0.02;
expectedLatch = logical([1; 1; 0; 0]);
observedLatch = false(4, 1);
nearTarget = false(4, 1);
positionMse = zeros(4, 1);
for idx = 1:4
    [observedLatch(idx), details] = ...
        updateIntentDeclaredRestHoldState(previousLatch(idx), ...
        declaredRest(idx), encoder(idx, :), reference(idx, :), tolerance);
    nearTarget(idx) = details.nearTarget;
    positionMse(idx) = details.positionMse;
end
geometricNearWouldActivate = nearTarget;
semanticGeometricDivergence = observedLatch ~= ...
    geometricNearWouldActivate;
passed = observedLatch == expectedLatch;
audit = table(caseName, previousLatch, declaredRest, positionMse, ...
    nearTarget, expectedLatch, observedLatch, ...
    geometricNearWouldActivate, semanticGeometricDivergence, passed);
end

function [checks, classification] = buildGateChecks(layout, config, ...
        equivalence, runtime, semantic, tests)
candidateLayout = layout(layout.variants == ...
    "intentDeclaredRestHoldMarkov62", :);
candidateConfig = config(config.names == "candidate", :);
defaultConfig = config(config.names == "default", :);
tolerance = 1e-12;
values = [candidateLayout.totalLength; ...
    double(candidateLayout.declaredRestIndex == 61 && ...
        candidateLayout.holdLatchIndex == 62); ...
    double(defaultConfig.observationVariant == "markov52" && ...
        defaultConfig.stateLength == 52); ...
    double(candidateConfig.simMotors && ~candidateConfig.runTraining); ...
    max(equivalence.statePrefixMaxAbsDifference); ...
    max(equivalence.rewardAbsDifference(2:end)); ...
    max([equivalence.referencePositionMaxAbsDifference; ...
        equivalence.referenceVelocityMaxAbsDifference]); ...
    max([equivalence.rawActionMaxAbsDifference(2:end); ...
        equivalence.effectiveActionMaxAbsDifference(2:end); ...
        equivalence.pwmMaxAbsDifference(2:end); ...
        equivalence.safetyMaxAbsDifference(2:end)]); ...
    sum(runtime.declaredRestMismatch); sum(runtime.holdLatchMismatch); ...
    double(runtime.observedDeclaredRest(1) && ...
        runtime.observedHoldLatch(1)); ...
    double(all(semantic.passed)); ...
    double(any(semantic.semanticGeometricDivergence & ...
        ~semantic.declaredRest & semantic.nearTarget)); ...
    double(all(equivalence.controlFinite & ...
        equivalence.candidateFinite & equivalence.candidateWithinBounds)); ...
    double(all([tests.Passed]))];
threshold = [62; 1; 1; 1; tolerance; tolerance; tolerance; ...
    tolerance; 0; 0; 1; 1; 1; 1; 1];
comparison = ["equal"; "equal"; "equal"; "equal"; ...
    "lessOrEqual"; "lessOrEqual"; "lessOrEqual"; "lessOrEqual"; ...
    "equal"; "equal"; "equal"; "equal"; "equal"; "equal"; "equal"];
passed = false(numel(values), 1);
for idx = 1:numel(values)
    if comparison(idx) == "lessOrEqual"
        passed(idx) = values(idx) <= threshold(idx);
    else
        passed(idx) = values(idx) == threshold(idx);
    end
end
check = ["candidateStateLength"; "semanticBitIndices"; ...
    "historicalDefaultPreserved"; "simulationOnlyProfile"; ...
    "statePrefixDifference"; "rewardDifference"; ...
    "referenceDifference"; "actuatorAndSafetyDifference"; ...
    "declaredRestReplayMismatchCount"; "holdLatchReplayMismatchCount"; ...
    "initialSemanticBits"; "semanticTransitions"; ...
    "countdownGeometricDivergence"; "finiteBoundedObservations"; ...
    "specificTests"];
checks = table(check, values, threshold, comparison, passed, ...
    'VariableNames', ["check", "observed", "threshold", ...
    "comparison", "passed"]);
if ~all(passed(1:4))
    classification = "intentDeclaredRestHoldLayoutInvalid";
elseif ~all(passed(9:13))
    classification = "intentDeclaredRestHoldCausalityInvalid";
elseif ~all(passed([5:8, 14]))
