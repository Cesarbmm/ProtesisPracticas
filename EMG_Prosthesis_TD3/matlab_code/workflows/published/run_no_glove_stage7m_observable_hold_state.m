        ~isscalar(options.smokeStepCount) || ...
        ~isfinite(options.smokeStepCount) || ...
        options.smokeStepCount < 4 || ...
        fix(options.smokeStepCount) ~= options.smokeStepCount
    error("run_no_glove_stage7m_observable_hold_state:InvalidStepCount", ...
        "smokeStepCount must be an integer of at least four.");
end
if ~isfile(fullfile(options.stage7lRunRoot, "manifest.json"))
    error("run_no_glove_stage7m_observable_hold_state:MissingStage7l", ...
        "ETAPA 7L manifest not found under %s.", options.stage7lRunRoot);
end
end

