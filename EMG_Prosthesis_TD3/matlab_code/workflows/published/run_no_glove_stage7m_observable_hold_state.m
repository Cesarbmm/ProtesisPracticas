function hashes = hashParentSources(root)
names = ["manifest.json"; "stage7l_results.mat"; ...
    "source_decision.csv"];
labels = ["stage7lManifest"; "stage7lResults"; ...
    "stage7lSourceDecision"];
paths = fullfile(root, names);
sha256 = strings(numel(paths), 1);
bytes = zeros(numel(paths), 1);
for idx = 1:numel(paths)
    info = dir(paths(idx));
    if isempty(info)
        error("run_no_glove_stage7m_observable_hold_state:SourceMissing", ...
            "Frozen source %s is missing.", paths(idx));
    end
    sha256(idx) = fileSha256(paths(idx));
    bytes(idx) = info.bytes;
end
hashes = table(labels, paths, sha256, bytes);
end

function trace = runTrace(profile, raw, actions, seed)
rng(seed, "twister");
setConfigurablesOverride(profile);
root = string(tempname);
mkdir(root);
cleanup = onCleanup(@() removeTempDir(root));
env = Env(root, true, {raw, raw}, {});
layout = buildObservationLayout(string(profile.observationVariant), 40, 3, 4);
obsInfo = env.getObservationInfo();
count = size(actions, 1);
trace.variant = string(profile.observationVariant);
trace.layout = layout;
trace.observations = nan(count+1, layout.totalLength);
trace.rewards = nan(count, 1);
trace.provenance = cell(count, 1);
trace.observations(1, :) = reset(env)';
for idx = 1:count
    [observation, trace.rewards(idx)] = step(env, actions(idx, :)');
    trace.observations(idx+1, :) = observation';
    trace.provenance{idx} = env.intentProvenanceLog{idx};
end
trace.rawAction = env.actionLog(1:count, :);
trace.effectiveAction = env.actionSatLog(1:count, :);
trace.pwm = env.actionPwmLog(1:count, :);
trace.referenceHistory = env.referenceHistory(1:count, :);
trace.safety = env.positionSafetyInterventionLog(1:count, :);
trace.lowerLimit = obsInfo.LowerLimit(:)';
trace.upperLimit = obsInfo.UpperLimit(:)';
end

