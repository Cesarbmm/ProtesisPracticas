function hashes = inventoryArtifacts(runRoot)
names = ["test_results.mat", "variant_summary.csv", "comparison.csv", ...
    "gate_checks.csv", "rest_motor_summary.csv", ...
    "checkpoint_inventory.csv", "profile_audit.csv", ...
