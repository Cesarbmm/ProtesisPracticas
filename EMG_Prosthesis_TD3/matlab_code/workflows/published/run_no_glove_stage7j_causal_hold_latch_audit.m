function report = run_no_glove_stage7j_causal_hold_latch_audit(options)
%run_no_glove_stage7j_causal_hold_latch_audit replays a latch offline.
%
% The frozen 7I corpus is read as numeric tables. No agent, Env, simulator,
% reward function, training, DTW or hardware route is invoked.

arguments
    options struct = struct()
end

options = normalizeOptions(options);
paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = string(paths.matlabRoot);
repoRoot = string(paths.workspaceRoot);
originalDir = string(pwd);
cleanup = onCleanup(@() cleanupRuntime(originalDir));
cd(matlabRoot);
addpath(genpath(fullfile(matlabRoot, "src")));
addpath(genpath(fullfile(matlabRoot, "config")));
addpath(genpath(fullfile(matlabRoot, "lib")));
addpath(genpath(fullfile(matlabRoot, "tests")));
addpath(genpath(fullfile(matlabRoot, "workflows", "published")));

if strlength(options.resultsRoot) == 0
    options.resultsRoot = fullfile(repoRoot, "Agentes", ...
        "no_glove_intent_control", "stage7j_causal_hold_latch");
end
runRoot = fullfile(options.resultsRoot, ...
    string(datetime("now", "Format", "yyyy-MM-dd_HH-mm-ss-SSS")));
if isfolder(runRoot)
    error("run_no_glove_stage7j_causal_hold_latch_audit:OutputExists", ...
        "Refusing to reuse %s.", runRoot);
end
mkdir(runRoot);

testResults = runtests(fullfile(matlabRoot, "tests", "no_glove", ...
    "testNoGloveStage7jCausalLatch.m"));
save(fullfile(runRoot, "test_results.mat"), "testResults");
if ~all([testResults.Passed])
    error("run_no_glove_stage7j_causal_hold_latch_audit:TestsFailed", ...
        "ETAPA 7J tests failed. See %s.", runRoot);
end

[stage7i, frozen, sourceHashesBefore, parentAudit] = ...
    loadAndValidateInput(options.stage7iRunRoot);
episodeHashesBefore = rehashEpisodeInputs(frozen.inputHashesBefore);
if ~isequal(frozen.inputHashesBefore, episodeHashesBefore)
    error("run_no_glove_stage7j_causal_hold_latch_audit:EpisodeHash", ...
        "A frozen 7H episode differs from the 7I inventory.");
end
analysis = analyzeNoGloveStage7jCausalLatch(frozen.windows);
episodeHashesAfter = rehashEpisodeInputs(frozen.inputHashesBefore);
if ~isequal(episodeHashesBefore, episodeHashesAfter)
    error("run_no_glove_stage7j_causal_hold_latch_audit:InputModified", ...
        "A frozen episode changed during the offline replay.");
end
sourceHashesAfter = hashStage7iSources(options.stage7iRunRoot);
if ~isequal(sourceHashesBefore, sourceHashesAfter)
    error("run_no_glove_stage7j_causal_hold_latch_audit:SourceModified", ...
        "A frozen 7I artifact changed during the offline replay.");
end

writetable(episodeHashesBefore, ...
    fullfile(runRoot, "episode_input_hashes.csv"));
writetable(sourceHashesBefore, fullfile(runRoot, "source_hashes.csv"));
writetable(parentAudit, fullfile(runRoot, "parent_audit.csv"));
writetable(analysis.windowAudit, ...
    fullfile(runRoot, "window_latch_audit.csv"));
writetable(analysis.segmentAudit, ...
    fullfile(runRoot, "stopped_segment_audit.csv"));
writetable(analysis.restEpisodeAudit, ...
    fullfile(runRoot, "rest_episode_audit.csv"));
writetable(analysis.sourceSummary, ...
    fullfile(runRoot, "source_summary.csv"));
writetable(analysis.variantSummary, ...
    fullfile(runRoot, "variant_summary.csv"));
writetable(analysis.gateChecks, fullfile(runRoot, "gate_checks.csv"));
writetable(analysis.sourceDecision, ...
    fullfile(runRoot, "source_decision.csv"));

[gitCommit, gitDirty, gitTrackedDirty, gitStatus] = getGitState(repoRoot);
agent7250Path = string(stage7i.agent7250CheckpointPath);
agent7250Hash = fileSha256(agent7250Path);
if agent7250Hash ~= string(stage7i.agent7250CheckpointSha256)
    error("run_no_glove_stage7j_causal_hold_latch_audit:Agent7250Hash", ...
        "The canonical Agent7250 file changed.");
end
manifest = struct("stage", "7J", "schemaVersion", 1, ...
    "result", "PASS", "scientificResult", analysis.classification, ...
    "contractSupported", analysis.contractSupported, ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", gitTrackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", "run_no_glove_stage7j_causal_hold_latch_audit", ...
    "preregistrationCommit", ...
        "2de6cb380a97d7a34653a3774216816cc1ea7aa7", ...
    "stage7iRunRoot", options.stage7iRunRoot, ...
    "stage7iManifestSha256", sourceHashesBefore.sha256(1), ...
    "stage7iResultsSha256", sourceHashesBefore.sha256(2), ...
    "stage7iWindowCorpusSha256", sourceHashesBefore.sha256(3), ...
    "stage7iEpisodeInventorySha256", sourceHashesBefore.sha256(4), ...
    "stage7hRunRoot", string(stage7i.stage7hRunRoot), ...
    "stage7jInputEpisodeCount", height(episodeHashesBefore), ...
    "stage7jInputWindowCount", height(frozen.windows), ...
    "inputsPreserved", true, "parentAudit", table2struct(parentAudit), ...
    "thresholds", analysis.thresholds, ...
    "variantSummary", table2struct(analysis.variantSummary), ...
    "gateChecks", table2struct(analysis.gateChecks), ...
    "sourceDecision", table2struct(analysis.sourceDecision), ...
    "prefixCheckCount", analysis.prefixCheckCount, ...
    "prefixMismatchCount", analysis.prefixMismatchCount, ...
    "explicitMemoryRequired", analysis.explicitMemoryRequired, ...
    "proposedObservationVariant", analysis.proposedObservationVariant, ...
    "proposedObservationDimension", ...
        analysis.proposedObservationDimension, ...
    "observationVariantImplemented", false, ...
    "behavioralInterventionExecuted", false, ...
    "behavioralAblationAuthorized", false, ...
    "rootCauseIdentified", false, ...
    "referenceSource", "emgIntent", ...
    "observationVariant", "intentMarkov60", ...
    "actionInterfaceVariant", "baselineQuantized", ...
    "policyChanged", false, "stateChanged", false, ...
    "rewardChanged", false, "referenceChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "runTraining", false, ...
    "newTraining", false, "agentLoaded", false, ...
    "envCreated", false, "simulatorInvoked", false, ...
    "rewardFunctionInvoked", false, "dtwCalculated", false, ...
    "simMotors", true, "hardwareUsed", false, ...
    "pilotAuthorized", false, "longCampaignAuthorized", false, ...
    "agent7250Loaded", false, ...
    "agent7250CheckpointPath", agent7250Path, ...
    "agent7250CheckpointSha256", agent7250Hash, ...
    "testsTotal", numel(testResults), ...
    "testsPassed", sum([testResults.Passed]), ...
    "testsFailed", sum([testResults.Failed]), ...
    "outputPath", runRoot);
save(fullfile(runRoot, "stage7j_results.mat"), "manifest", ...
    "analysis", "episodeHashesBefore", "sourceHashesBefore", ...
    "parentAudit", "stage7i", "-v7.3");
writeText(fullfile(runRoot, "offline_report.md"), ...
    buildOfflineReport(manifest));
