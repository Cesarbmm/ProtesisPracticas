function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7j_causal_hold_latch_audit:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("resultsRoot", "", "stage7iRunRoot", ...
    "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7i_artifacts\" + ...
    "stage7i_final\2026-08-28_17-54-13-526");
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7j_causal_hold_latch_audit:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7iRunRoot = string(options.stage7iRunRoot);
if ~isfile(fullfile(options.stage7iRunRoot, "manifest.json"))
    error("run_no_glove_stage7j_causal_hold_latch_audit:MissingStage7i", ...
        "ETAPA 7I manifest not found under %s.", options.stage7iRunRoot);
end
end

function [manifest, frozen, sourceHashes, parentAudit] = ...
        loadAndValidateInput(root)
manifest = jsondecode(fileread(fullfile(root, "manifest.json")));
valid = string(manifest.stage) == "7I" && ...
    string(manifest.result) == "PASS" && ...
    string(manifest.scientificResult) == ...
        "holdSupportNotSeparableFromFarCorrection" && ...
    double(manifest.episodeInputCount) == 548 && ...
    double(manifest.windowCount) == 31220 && ...
    logical(manifest.episodeInputsPreserved) && ...
    ~logical(manifest.runTraining) && ...
    ~logical(manifest.simulatorInvoked) && ...
    ~logical(manifest.agentLoaded) && ~logical(manifest.envCreated) && ...
    ~logical(manifest.rewardFunctionInvoked) && ...
    ~logical(manifest.dtwCalculated) && ~logical(manifest.hardwareUsed) && ...
    ~logical(manifest.agent7250Loaded) && ...
    string(manifest.referenceSource) == "emgIntent" && ...
    string(manifest.observationVariant) == "intentMarkov60" && ...
    string(manifest.actionInterfaceVariant) == "baselineQuantized";
if ~valid
    error("run_no_glove_stage7j_causal_hold_latch_audit:Stage7iContract", ...
        "Input manifest is not the frozen ETAPA 7I result.");
end
required = ["stage7i_results.mat", "window_corpus.csv", ...
    "episode_input_hashes.csv", "source_decision.csv"];
for name = required
    if ~isfile(fullfile(root, name))
        error("run_no_glove_stage7j_causal_hold_latch_audit:Stage7iArtifact", ...
            "Frozen ETAPA 7I artifact %s is missing.", name);
    end
end
data = load(fullfile(root, "stage7i_results.mat"), ...
    "windows", "episodeAudit", "inputHashesBefore", "analysis");
if height(data.windows) ~= 31220 || ...
        height(data.episodeAudit) ~= 548 || ...
        height(data.inputHashesBefore) ~= 548 || ...
        string(data.analysis.classification) ~= ...
        string(manifest.scientificResult) || ...
        data.analysis.behavioralInterventionExecuted || ...
        data.analysis.hardwareUsed
    error("run_no_glove_stage7j_causal_hold_latch_audit:Stage7iResults", ...
        "Frozen ETAPA 7I MAT contents violate the published contract.");
end
frozen = struct("windows", data.windows, ...
    "episodeAudit", data.episodeAudit, ...
    "inputHashesBefore", data.inputHashesBefore, ...
    "analysis", data.analysis);
sourceHashes = hashStage7iSources(root);
parentAudit = table(string(manifest.scientificResult), ...
    double(manifest.episodeInputCount), double(manifest.windowCount), ...
    double(manifest.maximumDiagnosticReplayError), ...
    logical(manifest.episodeInputsPreserved), ...
    logical(manifest.gitTrackedDirty), ...
    string(manifest.gitCommit), ...
    'VariableNames', ["scientificResult", "episodeCount", ...
    "windowCount", "maximumDiagnosticReplayError", ...
    "episodeInputsPreserved", "gitTrackedDirty", "gitCommit"]);
end

function hashes = hashStage7iSources(root)
names = ["manifest.json"; "stage7i_results.mat"; ...
    "window_corpus.csv"; "episode_input_hashes.csv"; ...
    "source_decision.csv"];
labels = ["stage7iManifest"; "stage7iResults"; ...
    "stage7iWindowCorpus"; "stage7iEpisodeInventory"; ...
    "stage7iSourceDecision"];
paths = fullfile(root, names);
sha256 = strings(numel(paths), 1);
bytes = zeros(numel(paths), 1);
for idx = 1:numel(paths)
    info = dir(paths(idx));
    sha256(idx) = fileSha256(paths(idx));
    bytes(idx) = info.bytes;
end
hashes = table(labels, paths, sha256, bytes);
end

function observed = rehashEpisodeInputs(expected)
required = ["variant", "source", "episode", "path", "sha256", "bytes"];
if height(expected) ~= 548 || ~all(ismember(required, ...
        string(expected.Properties.VariableNames)))
    error("run_no_glove_stage7j_causal_hold_latch_audit:EpisodeInventory", ...
        "The frozen episode inventory is incomplete.");
end
observed = expected;
for idx = 1:height(expected)
    path = string(expected.path(idx));
    if ~isfile(path)
        error("run_no_glove_stage7j_causal_hold_latch_audit:EpisodeMissing", ...
            "Frozen episode %s is missing.", path);
    end
    info = dir(path);
    observed.bytes(idx) = info.bytes;
    observed.sha256(idx) = fileSha256(path);
end
end

