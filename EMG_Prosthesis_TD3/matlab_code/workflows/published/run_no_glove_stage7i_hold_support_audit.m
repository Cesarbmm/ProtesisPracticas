function hashes = hashSourceFiles(stage7hRoot, child)
paths = [fullfile(stage7hRoot, "manifest.json"); ...
    fullfile(child.control.runRoot, "manifest.json"); ...
    fullfile(child.candidate.runRoot, "manifest.json"); ...
    fullfile(child.control.runRoot, "seed_11", ...
        "effective_training_profile.mat"); ...
    fullfile(child.candidate.runRoot, "seed_11", ...
        "effective_training_profile.mat"); ...
    child.control.finalCheckpoint; child.candidate.finalCheckpoint];
labels = ["stage7hManifest"; "controlManifest"; ...
    "candidateManifest"; "controlProfile"; "candidateProfile"; ...
    "controlAgent200"; "candidateAgent200"];
sha256 = strings(numel(paths), 1);
for idx = 1:numel(paths)
    sha256(idx) = fileSha256(paths(idx));
end
hashes = table(labels, paths, sha256);
end

function tableValue = inventoryEpisodeInputs(child)
parts = cell(6, 1);
variants = ["control", "candidate"];
sources = ["training", "acceptance", "steadyRest"];
cursor = 0;
for variant = variants
    for source = sources
        cursor = cursor+1;
        directory = episodeDirectories(child.(variant));
        parts{cursor} = hashEpisodeDirectory(variant, source, ...
            directory.(source));
    end
end
tableValue = vertcat(parts{:});
end

function tableValue = hashEpisodeDirectory(variant, source, directory)
files = dir(fullfile(directory, "episode*.mat"));
[~, order] = sort({files.name});
files = files(order);
episode = zeros(numel(files), 1);
path = strings(numel(files), 1);
sha256 = strings(numel(files), 1);
bytes = zeros(numel(files), 1);
for idx = 1:numel(files)
    token = regexp(files(idx).name, '^episode(\d+)\.mat$', ...
        'tokens', 'once');
    episode(idx) = str2double(token{1});
    path(idx) = string(fullfile(files(idx).folder, files(idx).name));
    sha256(idx) = fileSha256(path(idx));
    bytes(idx) = files(idx).bytes;
end
tableValue = table(repmat(variant, numel(files), 1), ...
    repmat(source, numel(files), 1), episode, path, sha256, bytes, ...
    'VariableNames', ["variant", "source", "episode", "path", ...
    "sha256", "bytes"]);
end

function validateEpisodeInventory(audit)
expected = table( ...
    ["control"; "control"; "control"; ...
        "candidate"; "candidate"; "candidate"], ...
    ["training"; "acceptance"; "steadyRest"; ...
        "training"; "acceptance"; "steadyRest"], ...
    [200; 50; 24; 200; 50; 24], ...
    'VariableNames', ["variant", "source", "episodeCount"]);
for idx = 1:height(expected)
    rows = audit.variant == expected.variant(idx) & ...
        audit.source == expected.source(idx);
    if sum(rows) ~= expected.episodeCount(idx)
        error("run_no_glove_stage7i_hold_support_audit:EpisodeInventory", ...
            "Unexpected %s/%s episode inventory.", ...
            expected.variant(idx), expected.source(idx));
    end
end
if height(audit) ~= 548
    error("run_no_glove_stage7i_hold_support_audit:EpisodeInventory", ...
        "Expected exactly 548 frozen episode files.");
end
end

