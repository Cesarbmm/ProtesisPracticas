function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7i_hold_support_audit:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("resultsRoot", "", "stage7hRunRoot", ...
    "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7h_artifacts\" + ...
    "stage7h_final\2026-08-28_16-00-33-357");
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7i_hold_support_audit:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7hRunRoot = string(options.stage7hRunRoot);
if ~isfile(fullfile(options.stage7hRunRoot, "manifest.json"))
    error("run_no_glove_stage7i_hold_support_audit:MissingStage7h", ...
        "ETAPA 7H manifest not found under %s.", options.stage7hRunRoot);
end
end

function [stage7h, child, profiles, audit] = loadAndValidateInputs(root)
manifestPath = fullfile(root, "manifest.json");
stage7h = jsondecode(fileread(manifestPath));
if string(stage7h.stage) ~= "7H" || string(stage7h.result) ~= "PASS" || ...
        string(stage7h.scientificResult) ~= "holdExposureInsufficient" || ...
        logical(stage7h.hardwareUsed) || logical(stage7h.pilotAuthorized) || ...
        string(stage7h.referenceSource) ~= "emgIntent" || ...
        string(stage7h.observationVariant) ~= "intentMarkov60" || ...
        string(stage7h.rewardType) ~= "trackingIntentHoldActionReward" || ...
        string(stage7h.actionInterfaceVariant) ~= "baselineQuantized"
    error("run_no_glove_stage7i_hold_support_audit:Stage7hContract", ...
        "Input manifest is not the frozen ETAPA 7H result.");
end
control = loadChild(string(stage7h.controlRunRoot), 0.00);
candidate = loadChild(string(stage7h.candidateRunRoot), 0.20);
child = struct("control", control, "candidate", candidate);
controlData = load(fullfile(control.runRoot, "seed_11", ...
    "effective_training_profile.mat"), "profile");
candidateData = load(fullfile(candidate.runRoot, "seed_11", ...
    "effective_training_profile.mat"), "profile");
profiles = struct("control", controlData.profile, ...
    "candidate", candidateData.profile);
validateProfiles(profiles);
sourceHashes = hashSourceFiles(root, child);
audit = struct("stage7hManifestSha256", sourceHashes.sha256(1), ...
    "controlManifestSha256", sourceHashes.sha256(2), ...
    "candidateManifestSha256", sourceHashes.sha256(3), ...
    "controlCheckpointSha256", sourceHashes.sha256(6), ...
    "candidateCheckpointSha256", sourceHashes.sha256(7), ...
    "sourceHashesBefore", sourceHashes);
end

function child = loadChild(root, expectedHoldWeight)
manifestPath = fullfile(root, "manifest.json");
if ~isfile(manifestPath)
    error("run_no_glove_stage7i_hold_support_audit:ChildManifest", ...
        "Missing child manifest under %s.", root);
end
m = jsondecode(fileread(manifestPath));
if string(m.stage) ~= "6" || string(m.phase) ~= "smoke" || ...
        double(m.episodeBudget) ~= 200 || ~isequal(double(m.seeds), 11) || ...
        ~logical(m.newTraining) || logical(m.agent7250Loaded) || ...
        logical(m.hardwareUsed) || ~logical(m.simMotors) || ...
        string(m.referenceSource) ~= "emgIntent" || ...
        string(m.observationVariant) ~= "intentMarkov60" || ...
        string(m.rewardType) ~= "trackingIntentHoldActionReward" || ...
        string(m.actionInterfaceVariant) ~= "baselineQuantized" || ...
        double(m.intentHoldActionWeight) ~= expectedHoldWeight
    error("run_no_glove_stage7i_hold_support_audit:ChildContract", ...
        "A 7H child run violates the frozen smoke contract.");
end
seed = m.seedSummary;
child = struct("runRoot", root, "manifest", m, ...
    "trainingDirectory", string(seed.trainingDirectory), ...
    "acceptanceDirectory", string(seed.acceptanceDirectory), ...
    "restDirectory", string(seed.restDirectory), ...
    "finalCheckpoint", string(seed.finalCheckpoint));
required = [child.trainingDirectory; child.acceptanceDirectory; ...
    child.restDirectory; child.finalCheckpoint];
if ~all([isfolder(required(1:3)); isfile(required(4))])
    error("run_no_glove_stage7i_hold_support_audit:ChildArtifacts", ...
        "A frozen child artifact is missing.");
end
end

function validateProfiles(profiles)
c = profiles.control;
k = profiles.candidate;
valid = c.intentHoldActionWeight == 0 && ...
    k.intentHoldActionWeight == 0.20 && ...
    c.intentHoldRewardEnabled && k.intentHoldRewardEnabled && ...
    c.intentHoldVelocityTolerance == 1e-12 && ...
    k.intentHoldVelocityTolerance == 1e-12 && ...
    c.intentHoldPositionMseTolerance == 1e-4 && ...
    k.intentHoldPositionMseTolerance == 1e-4 && ...
    c.intentRewardActionWeight == 0.05 && ...
    k.intentRewardActionWeight == 0.05 && ...
    string(c.observationVariant) == "intentMarkov60" && ...
    string(k.observationVariant) == "intentMarkov60" && ...
    logical(c.simMotors) && logical(k.simMotors);
if ~valid
    error("run_no_glove_stage7i_hold_support_audit:ProfileContract", ...
        "Effective profiles violate the pre-registered 7I contract.");
end
end

