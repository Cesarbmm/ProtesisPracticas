function report = run_no_glove_stage7i_hold_support_audit(options)
%run_no_glove_stage7i_hold_support_audit audits frozen 7H logs offline.
%
% The launcher reconstructs the causal hold condition from state_t, maps
% steady-rest coverage against far-correction exposure and audits temporal
% exits from the hold region. It never loads an agent, creates Env, invokes
% the simulator/reward, trains, calculates DTW or accesses hardware.

arguments
    options struct = struct()
end

options = normalizeOptions(options);
paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = string(paths.matlabRoot);
repoRoot = string(paths.workspaceRoot);
originalDir = string(pwd);
cleanup = onCleanup(@() cleanupRuntime(originalDir));
cd(matlabRoot);
addpath(genpath(fullfile(matlabRoot, "src")));
addpath(genpath(fullfile(matlabRoot, "config")));
addpath(genpath(fullfile(matlabRoot, "lib")));
addpath(genpath(fullfile(matlabRoot, "tests")));
addpath(genpath(fullfile(matlabRoot, "workflows", "published")));

if strlength(options.resultsRoot) == 0
    options.resultsRoot = fullfile(repoRoot, "Agentes", ...
        "no_glove_intent_control", "stage7i_hold_support_audit");
end
runRoot = fullfile(options.resultsRoot, ...
    string(datetime("now", "Format", "yyyy-MM-dd_HH-mm-ss-SSS")));
if isfolder(runRoot)
    error("run_no_glove_stage7i_hold_support_audit:OutputExists", ...
        "Refusing to reuse %s.", runRoot);
end
mkdir(runRoot);

testResults = runtests(fullfile(matlabRoot, "tests", "no_glove", ...
    "testNoGloveStage7iHoldSupport.m"));
save(fullfile(runRoot, "test_results.mat"), "testResults");
if ~all([testResults.Passed])
    error("run_no_glove_stage7i_hold_support_audit:TestsFailed", ...
        "ETAPA 7I tests failed. See %s.", runRoot);
end

[stage7h, child, profiles, sourceAudit] = loadAndValidateInputs( ...
    options.stage7hRunRoot);
inputHashesBefore = inventoryEpisodeInputs(child);
validateEpisodeInventory(inputHashesBefore);
controlSettings = holdSettings(profiles.control);
candidateSettings = holdSettings(profiles.candidate);
[controlWindows, controlEpisodes] = ...
    loadNoGloveStage7iHoldSupportCorpus("control", ...
        episodeDirectories(child.control), controlSettings);
[candidateWindows, candidateEpisodes] = ...
    loadNoGloveStage7iHoldSupportCorpus("candidate", ...
        episodeDirectories(child.candidate), candidateSettings);
windows = [controlWindows; candidateWindows];
episodeAudit = [controlEpisodes; candidateEpisodes];
analysis = analyzeNoGloveStage7iHoldSupport(windows);

inputHashesAfter = inventoryEpisodeInputs(child);
if ~isequal(inputHashesBefore, inputHashesAfter)
    error("run_no_glove_stage7i_hold_support_audit:InputModified", ...
        "A source episode changed during the offline audit.");
end
sourceHashesAfter = hashSourceFiles(options.stage7hRunRoot, child);
if ~isequal(sourceAudit.sourceHashesBefore, sourceHashesAfter)
    error("run_no_glove_stage7i_hold_support_audit:SourceModified", ...
        "A source manifest, profile or checkpoint changed.");
end

profileAudit = buildProfileAudit(profiles);
writetable(inputHashesBefore, ...
    fullfile(runRoot, "episode_input_hashes.csv"));
writetable(episodeAudit, fullfile(runRoot, "episode_audit.csv"));
writetable(profileAudit, fullfile(runRoot, "profile_audit.csv"));
writetable(windows, fullfile(runRoot, "window_corpus.csv"));
writetable(analysis.episodeTimeline, ...
    fullfile(runRoot, "rest_episode_timeline.csv"));
writetable(analysis.exitAudit, ...
    fullfile(runRoot, "rest_exit_audit.csv"));
writetable(analysis.timelineSummary, ...
    fullfile(runRoot, "timeline_summary.csv"));
writetable(analysis.stratumSummary, ...
    fullfile(runRoot, "stratum_summary.csv"));
writetable(analysis.epsilonCurve, ...
    fullfile(runRoot, "epsilon_curve.csv"));
writetable(analysis.supportDecision, ...
    fullfile(runRoot, "support_decision.csv"));
writetable(analysis.softGateSummary, ...
    fullfile(runRoot, "soft_gate_summary.csv"));
writetable(analysis.sourceDecision, ...
    fullfile(runRoot, "source_decision.csv"));

[gitCommit, gitDirty, gitTrackedDirty, gitStatus] = getGitState(repoRoot);
agent7250Path = getAgent7250CheckpointPath();
manifest = struct("stage", "7I", "schemaVersion", 1, ...
    "result", "PASS", "scientificResult", analysis.classification, ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", gitTrackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", "run_no_glove_stage7i_hold_support_audit", ...
    "preregistrationCommit", ...
        "52c454758a9a3c942fcf7148e65d5ed9c16a5bd3", ...
    "stage7hRunRoot", options.stage7hRunRoot, ...
    "stage7hManifestSha256", sourceAudit.stage7hManifestSha256, ...
    "controlRunRoot", child.control.runRoot, ...
    "candidateRunRoot", child.candidate.runRoot, ...
    "controlManifestSha256", sourceAudit.controlManifestSha256, ...
    "candidateManifestSha256", sourceAudit.candidateManifestSha256, ...
    "controlCheckpointSha256", sourceAudit.controlCheckpointSha256, ...
    "candidateCheckpointSha256", ...
        sourceAudit.candidateCheckpointSha256, ...
    "episodeInputCount", height(inputHashesBefore), ...
    "episodeInputsPreserved", true, ...
    "episodeCount", height(episodeAudit), ...
    "windowCount", height(windows), ...
    "maximumDiagnosticReplayError", ...
        max(episodeAudit.maximumDiagnosticReplayError), ...
    "profileAudit", table2struct(profileAudit), ...
    "thresholds", analysis.thresholds, ...
    "supportDecision", table2struct(analysis.supportDecision), ...
    "sourceDecision", table2struct(analysis.sourceDecision), ...
    "rootCauseIdentified", false, ...
    "behavioralInterventionExecuted", false, ...
    "referenceSource", "emgIntent", ...
    "observationVariant", "intentMarkov60", ...
    "actionInterfaceVariant", "baselineQuantized", ...
    "policyChanged", false, "quantizationChanged", false, ...
    "rewardChanged", false, "referenceChanged", false, ...
    "simulatorChanged", false, "safetyLayerChanged", false, ...
    "runTraining", false, "newTraining", false, ...
    "agentLoaded", false, "envCreated", false, ...
    "simulatorInvoked", false, "rewardFunctionInvoked", false, ...
    "dtwCalculated", false, "hardwareUsed", false, ...
    "simMotors", true, "pilotAuthorized", false, ...
    "longCampaignAuthorized", false, ...
    "agent7250Loaded", false, ...
    "agent7250CheckpointPath", agent7250Path, ...
    "agent7250CheckpointSha256", fileSha256(agent7250Path), ...
    "testsTotal", numel(testResults), ...
    "testsPassed", sum([testResults.Passed]), ...
    "testsFailed", sum([testResults.Failed]), ...
    "outputPath", runRoot);
save(fullfile(runRoot, "stage7i_results.mat"), "manifest", ...
    "analysis", "windows", "episodeAudit", "inputHashesBefore", ...
    "profileAudit", "stage7h", "sourceAudit", "-v7.3");
writeText(fullfile(runRoot, "offline_report.md"), ...
    buildOfflineReport(manifest, analysis));
writeText(fullfile(runRoot, "reproducible_command.txt"), ...
    buildReproducibleCommand(matlabRoot, options, runRoot));
manifest.artifactHashes = inventoryArtifacts(runRoot);
writeText(fullfile(runRoot, "manifest.json"), ...
    jsonencode(manifest, "PrettyPrint", true));

report = struct("result", "PASS", ...
    "scientificResult", analysis.classification, ...
    "outputPath", runRoot, "manifest", manifest, ...
    "analysis", analysis);
fprintf("ETAPA 7I HOLD SUPPORT AUDIT PASS\n");
