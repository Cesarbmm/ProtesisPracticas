function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7o_bit_counterfactual_audit:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct( ...
    "resultsRoot", "", ...
    "stage7nRunRoot", ...
        "C:\Users\Cesarbmm\ProtesisPracticas_no_glove_stage7n_artifacts\stage7n_corrected_final\2026-08-29_07-34-46-814", ...
    "maxPerContext", 512);
unknown = setdiff(string(fieldnames(options)), string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7o_bit_counterfactual_audit:UnknownOption", ...
        "Unknown option(s): %s", strjoin(unknown, ", "));
end
names = fieldnames(defaults);
for idx = 1:numel(names)
    name = names{idx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.resultsRoot = string(options.resultsRoot);
options.stage7nRunRoot = string(options.stage7nRunRoot);
if options.maxPerContext ~= 512
    error("run_no_glove_stage7o_bit_counterfactual_audit:ProtocolChanged", ...
        "ETAPA 7O requires maxPerContext=512.");
end
end

function parent = validateStage7n(runRoot)
manifestPath = fullfile(runRoot, "manifest.json");
summaryPath = fullfile(runRoot, "checkpoint_summary.csv");
if ~isfile(manifestPath) || ~isfile(summaryPath)
    error("run_no_glove_stage7o_bit_counterfactual_audit:MissingStage7n", ...
        "Canonical ETAPA 7N artifacts are missing.");
end
expectedHash = ...
    "082DADB41DAA1DAB6AE2B5E02AE15191479410F10B5DF0398837814BFC53D480";
actualHash = fileSha256(manifestPath);
m = jsondecode(fileread(manifestPath));
valid = actualHash == expectedHash && string(m.stage) == "7N" && ...
    string(m.result) == "PASS" && ...
    string(m.scientificResult) == "actionRegularityGateFailed" && ...
    ~logical(m.hardwareUsed) && ~logical(m.dtwCalculated);
if ~valid
    error("run_no_glove_stage7o_bit_counterfactual_audit:Stage7nChanged", ...
        "ETAPA 7N does not match the pre-registered parent.");
end
summary = readtable(summaryPath, "TextType", "string");
primary = summary(summary.variant == "candidate62" & ...
    summary.episode == 200, :);
if height(primary) ~= 1
    error("run_no_glove_stage7o_bit_counterfactual_audit:PrimaryRow", ...
        "ETAPA 7N must contain exactly one candidate62 Agent200 row.");
end
parent = struct("runRoot", runRoot, "manifestPath", manifestPath, ...
    "manifestSha256", actualHash, "gitCommit", string(m.gitCommit), ...
    "scientificResult", string(m.scientificResult), ...
    "validated", true, "checkpointSummary", summary, ...
    "primaryCandidate", table2struct(primary));
end

