function actuator = loadActuatorContract(checkpointPath)
configPath = fullfile(fileparts(checkpointPath), "00_configs.mat");
data = load(configPath, "configs");
c = data.configs;
valid = string(c.actionInterfaceVariant) == "baselineQuantized" && ...
    logical(c.quantizeCommandsForSimulation) && ~logical(c.unifyActions) && ...
    c.actionCommandActivationThreshold == 0.05 && ...
    isequal(double(c.actionCommandLevels), ...
        [0, 64, 96, 128, 160, 192, 224, 255]) && ...
    all(double(c.speeds) == 255);
% The saved config belongs to training and therefore run_training=true.
valid = valid && logical(c.run_training) && logical(c.simMotors) && ...
    ~logical(c.connect_glove) && ...
    string(c.rewardType) == "trackingIntentActionRateReward";
if ~valid
    error("run_no_glove_stage7o_bit_counterfactual_audit:ActuatorContract", ...
        "Frozen Agent200 configuration changed.");
end
actuator = struct("interface", "baselineQuantized", ...
    "maxPwm", 255, "activationThreshold", 0.05, ...
    "commandLevels", double(c.actionCommandLevels), ...
    "saturationThreshold", 0.95);
end

function [summary, audit] = evaluateControlReference( ...
        checkpointPath, corpus, actuator)
agent = loadSavedAgent(checkpointPath);
actor = getActor(agent);
model = getModel(actor);
raw = evaluateFrozenActorModelStates(model, corpus.prefix60);
[effective, pwm] = quantizeRows(raw, actuator);
contexts = unique(corpus.metadata.context, "stable");
parts = cell(numel(contexts)*4, 1);
cursor = 0;
for context = contexts'
    for motor = 1:4
        mask = corpus.metadata.context == context;
        cursor = cursor+1;
        parts{cursor} = table(context, motor, sum(mask), ...
            mean(raw(mask, motor)), mean(abs(raw(mask, motor))), ...
            mean(abs(pwm(mask, motor))), mean(pwm(mask, motor) ~= 0), ...
            mean(abs(effective(mask, motor)) >= 0.95), ...
            'VariableNames', ["context", "motor", "sampleCount", ...
            "meanRawAction", "meanAbsRawAction", "meanAbsPwm", ...
            "commandActiveFraction", "saturationFraction"]);
    end
end
summary = vertcat(parts{1:cursor});
audit = struct("allFinite", all(isfinite([raw(:); effective(:); pwm(:)])), ...
    "stateCount", size(raw, 1), "checkpointPath", checkpointPath, ...
    "checkpointSha256", fileSha256(checkpointPath));
end

function [effective, pwm] = quantizeRows(raw, actuator)
effective = nan(size(raw));
pwm = nan(size(raw));
for rowIdx = 1:size(raw, 1)
    [e, p] = quantizeBaselineAction(raw(rowIdx, :), ...
        actuator.maxPwm, actuator.activationThreshold, ...
        actuator.commandLevels);
    effective(rowIdx, :) = double(e(:))';
    pwm(rowIdx, :) = double(p(:))';
end
end

function row = emptyReplayRow()
row = struct("checkpointEpisode", 0, "evaluatedRowCount", 0, ...
    "serialSavedMaximumError", NaN, ...
    "batchSerialMaximumError", NaN, ...
    "batchSerialPwmMismatchCount", NaN);
end

function row = emptyGradientAuditRow()
row = struct("checkpointEpisode", 0, "sampleCount", 0, ...
    "step", NaN, "absoluteTolerance", NaN, ...
    "relativeTolerance", NaN, "maximumAbsoluteError", NaN, ...
    "maximumTolerance", NaN, "withinTolerance", false);
end

function output = addEpisode(input, episode)
if isfield(input, "withinTolerance")
    output = input;
    output.checkpointEpisode = episode;
    output = orderfields(output, fieldnames(emptyGradientAuditRow()));
else
    output = input;
    output.checkpointEpisode = episode;
    output = orderfields(output, fieldnames(emptyReplayRow()));
end
end

