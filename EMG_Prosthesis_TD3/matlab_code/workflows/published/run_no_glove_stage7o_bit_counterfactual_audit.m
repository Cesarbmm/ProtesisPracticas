    rows{idx} = table("candidate62", episode, path, expected, actual, ...
        actual == expected, episode == 200, ...
        'VariableNames', ["label", "checkpointEpisode", ...
        "checkpointPath", "expectedSha256", "actualSha256", ...
        "hashMatched", "primary"]);
    candidatePaths(string(episode)) = path;
end
control = summary(summary.variant == "control60" & ...
    summary.episode == 200, :);
if height(control) ~= 1
    error("run_no_glove_stage7o_bit_counterfactual_audit:ControlRow", ...
        "Missing control60 Agent200.");
end
controlPath = string(control.checkpointPath);
expected = ...
    "440F003450A368A13A0E5DACB04FD7755BB929033EB879B217E47F32B5AA185E";
actual = fileSha256(controlPath);
