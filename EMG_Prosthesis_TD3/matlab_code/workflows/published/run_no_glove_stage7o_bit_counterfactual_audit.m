    "B4E9D705EB713DC1507B0FD55785A24186C239C0BF263F38E06E3E0FE792BA55", ...
    "3F82182EE3F99FBEF23D327A76900B13A9B481FF9EBB707F66AD4D74D2F7F17F", ...
    "301231C840DF2E6704149AF380D496B84575D66C50AB422737C753A9287850FC", ...
    "2A51F0F1F8800C2F44F6C632109EBB0A3E146907496A47EA0DED85450AB92E69"];
candidatePaths = dictionary(string.empty, string.empty);
rows = cell(5, 1);
for idx = 1:numel(expectedEpisodes)
    episode = expectedEpisodes(idx);
    match = summary(summary.variant == "candidate62" & ...
        summary.episode == episode, :);
    if height(match) ~= 1
        error("run_no_glove_stage7o_bit_counterfactual_audit:CheckpointRow", ...
            "Missing candidate62 Agent%d.", episode);
    end
    path = string(match.checkpointPath);
    actual = fileSha256(path);
