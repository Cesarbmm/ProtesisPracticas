function variant = buildVariant(label, holdWeight, childReport)
seed = unwrapSingleSeedResult(childReport.seedResults);
settings = struct("actionWeight", holdWeight, ...
    "velocityTolerance", 1e-12, ...
    "positionMseTolerance", 1e-4);
restCommands = summarizeNoGloveStage7fRestCommands(seed.restDirectory);
restHold = summarizeNoGloveStage7hHoldReward( ...
    seed.restDirectory, settings, "requireSteadyRest", true);
restCommands = mergeHoldSummary(restCommands, restHold);
restCommands.positionViolationEpisodeCount = ...
    seed.rest.positionViolationEpisodeCount;
restCommands.positionSafetyInterventionCount = ...
    seed.rest.positionSafetyInterventionCount;
acceptanceHold = summarizeNoGloveStage7hHoldReward( ...
    seed.acceptanceDirectory, settings);
training = selectSafetyMetrics(seed.trainingSafety);
acceptance = selectAcceptanceMetrics(seed.acceptance);
finalRow = childReport.checkpointTable( ...
    childReport.checkpointTable.isFinal, :);
variant = struct("label", label, "holdWeight", holdWeight, ...
    "actionWeight", 0.05, "training", training, ...
    "acceptance", acceptance, "rest", restCommands, ...
    "acceptanceHold", acceptanceHold, ...
    "decodedRestFalseActivationFraction", ...
        childReport.manifest.restFalseActivationFraction, ...
    "checkpointSha256", string(finalRow.checkpointSha256));
end

function seed = unwrapSingleSeedResult(seedResults)
if iscell(seedResults) && isscalar(seedResults)
    seed = seedResults{1};
elseif isstruct(seedResults) && isscalar(seedResults)
    seed = seedResults;
else
    error("run_no_glove_stage7h_hold_reward_ablation:SeedResultContract", ...
        "A 7H child smoke must contain exactly one seed result.");
end
if ~isstruct(seed) || ~isscalar(seed)
    error("run_no_glove_stage7h_hold_reward_ablation:SeedResultContract", ...
        "The single seed result must be a scalar struct.");
end
end

