function tableValue = buildHoldContextSummary(control, candidate)
variants = [control, candidate];
rows = cell(4, 1);
cursor = 0;
for variantIdx = 1:2
    value = variants(variantIdx);
    sources = ["acceptance", "steadyRest"];
    summaries = {value.acceptanceHold, value.rest};
    for sourceIdx = 1:2
        cursor = cursor+1;
        summary = summaries{sourceIdx};
        rows{cursor} = table(string(value.label), sources(sourceIdx), ...
            summary.episodeCount, summary.windowCount, ...
            summary.holdActiveFraction, summary.holdPositionMseMean, ...
            summary.holdPositionMseMax, summary.holdVelocityMaxAbs, ...
            summary.holdActionL2Mean, summary.holdActionPenaltyMean, ...
            summary.activeHoldWindowAnyCommandFraction, ...
            summary.maximumDiagnosticReplayError, ...
            'VariableNames', ["variant", "source", "episodeCount", ...
            "windowCount", "holdActiveFraction", ...
            "holdPositionMseMean", "holdPositionMseMax", ...
            "holdVelocityMaxAbs", "holdActionL2Mean", ...
            "holdActionPenaltyMean", ...
            "activeHoldWindowAnyCommandFraction", ...
            "maximumDiagnosticReplayError"]);
    end
end
tableValue = vertcat(rows{:});
end

