function report = run_no_glove_stage7b_designed_excitation(options)
%run_no_glove_stage7b_designed_excitation executes ETAPA 7B only.
%
% A frozen Agent200 and the validated P controller receive matched designed
% EMG-intent reference profiles in simulation. No training, Agent7250, DTW,
% hardware or behavioral configuration change is permitted.

arguments
    options struct = struct()
end

options = normalizeOptions(options);
paths = resolveMatlabCodePaths(string(mfilename("fullpath")));
matlabRoot = string(paths.matlabRoot);
repoRoot = string(paths.workspaceRoot);
originalDir = string(pwd);
cleanup = onCleanup(@() cleanupRuntime(originalDir));
cd(matlabRoot);
addpath(genpath(fullfile(matlabRoot, "src")));
addpath(genpath(fullfile(matlabRoot, "config")));
addpath(genpath(fullfile(matlabRoot, "lib")));
addpath(genpath(fullfile(matlabRoot, "agents")));
addpath(genpath(fullfile(matlabRoot, "tests")));
clearConfigurablesOverride();

[stage7aManifest, stage7aManifestPath, stage7aResultsPath] = ...
    loadAndValidateStage7a(options.stage7aRunRoot);
[stage6Manifest, stage6ManifestPath, agentPath, agentExpectedHash, ...
    trainingProfile] = loadAndValidateStage6(options.stage6RunRoot);
stage7aHashBefore = fileSha256(stage7aResultsPath);
stage6ManifestHashBefore = fileSha256(stage6ManifestPath);
agentHashBefore = fileSha256(agentPath);
if agentHashBefore ~= agentExpectedHash
    error("run_no_glove_stage7b_designed_excitation:AgentHashMismatch", ...
        "Agent200 does not match the ETAPA 6 inventory.");
end

if strlength(options.resultsRoot) == 0
    options.resultsRoot = fullfile(repoRoot, "Agentes", ...
        "no_glove_intent_control", "stage7b_designed_excitation");
end
runDir = fullfile(options.resultsRoot, ...
    string(datetime("now", "Format", "yyyy-MM-dd_HH-mm-ss-SSS")));
if isfolder(runDir)
    error("run_no_glove_stage7b_designed_excitation:OutputExists", ...
        "Refusing to reuse output directory %s.", runDir);
end
mkdir(runDir);

testPath = fullfile(matlabRoot, "tests", "no_glove", ...
    "testNoGloveStage7bDesignedExcitation.m");
testResults = runtests(testPath);
save(fullfile(runDir, "test_results.mat"), "testResults");
if ~all([testResults.Passed])
    error("run_no_glove_stage7b_designed_excitation:TestsFailed", ...
        "ETAPA 7B tests failed; simulation is forbidden. See %s.", runDir);
end

corpus = buildNoGloveStage7bTemporalCorpus( ...
    trainingProfile.intentCalibration, ...
    trainingProfile.intentExpectedContext, ...
    "calibrationSeed", options.calibrationSeed, ...
    "profileSeed", options.profileSeed, ...
    "repetitionsPerAxis", options.repetitionsPerAxis);
fixtureDir = fullfile(runDir, "fixture");
mkdir(fixtureDir);
fullDatasetPath = fullfile(fixtureDir, ...
    "stage7b_designed_temporal_emg_only.mat");
smokeDatasetPath = fullfile(fixtureDir, ...
    "stage7b_smoke_temporal_emg_only.mat");
writeDataset(fullDatasetPath, corpus.emgs, corpus.metadata);
smokeMetadata = corpus.metadata;
smokeMetadata.role = "designed_temporal_smoke";
smokeMetadata.profileCount = 2;
writeDataset(smokeDatasetPath, corpus.emgs(1, :), smokeMetadata);
writetable(corpus.protocolTable, fullfile(runDir, "profile_protocol.csv"));
writetable(corpus.validationTable, ...
    fullfile(runDir, "profile_validation.csv"));
writetable(corpus.windowProtocol, ...
    fullfile(runDir, "window_protocol.csv"));

matchedProfile = buildMatchedProfile(trainingProfile);
smokeProfile = buildEvaluationProfile(trainingProfile, agentPath, ...
    smokeDatasetPath, options.smokeSeed, 2, ...
    fullfile(runDir, "smoke", "agent200"));
assertSafeEvaluationProfile(smokeProfile, agentPath, 2);
save(fullfile(runDir, "effective_smoke_profile.mat"), "smokeProfile");
smokeAgentDir = runAgentEvaluation(smokeProfile);
smokeMatched = evaluateNoGloveStage6cMatchedController( ...
    smokeAgentDir, matchedProfile, "designed_temporal_smoke", ...
    "activeVelocityThreshold", options.activeVelocityThreshold, ...
    "motionTolerance", options.motionTolerance, ...
    "positionTolerance", options.positionTolerance, ...
    "saturationThreshold", options.saturationThreshold, ...
    "simulatorSamplingPeriod", options.simulatorSamplingPeriod);
if ~smokeMatched.pairing.allExact || ...
        any(smokeMatched.componentTable.positionViolation) || ...
        height(smokeMatched.pairingTable) ~= 2
    error("run_no_glove_stage7b_designed_excitation:SmokeFailed", ...
        "The two-episode designed smoke failed pairing or safety.");
end
smokeEpisodeHashes = inventoryEpisodes(smokeAgentDir);
writetable(smokeEpisodeHashes, ...
    fullfile(runDir, "smoke_episode_hashes.csv"));

evaluationProfile = buildEvaluationProfile(trainingProfile, agentPath, ...
    fullDatasetPath, options.evaluationSeed, ...
    corpus.expectedSimulationCount, ...
    fullfile(runDir, "evaluation", "agent200"));
assertSafeEvaluationProfile(evaluationProfile, agentPath, ...
    corpus.expectedSimulationCount);
save(fullfile(runDir, "effective_evaluation_profile.mat"), ...
    "evaluationProfile", "matchedProfile", "options");
evaluationTic = tic;
agentEvaluationDir = runAgentEvaluation(evaluationProfile);
agentEvaluationElapsedSec = toc(evaluationTic);
agentEpisodeHashes = inventoryEpisodes(agentEvaluationDir);
if height(agentEpisodeHashes) ~= corpus.expectedSimulationCount
    error("run_no_glove_stage7b_designed_excitation:EpisodeCountMismatch", ...
        "Expected %d frozen-agent episodes, found %d.", ...
        corpus.expectedSimulationCount, height(agentEpisodeHashes));
end
writetable(agentEpisodeHashes, ...
    fullfile(runDir, "agent_episode_hashes.csv"));

matchedTic = tic;
matched = evaluateNoGloveStage6cMatchedController( ...
    agentEvaluationDir, matchedProfile, "designed_temporal", ...
    "activeVelocityThreshold", options.activeVelocityThreshold, ...
    "motionTolerance", options.motionTolerance, ...
    "positionTolerance", options.positionTolerance, ...
    "saturationThreshold", options.saturationThreshold, ...
    "simulatorSamplingPeriod", options.simulatorSamplingPeriod);
matchedElapsedSec = toc(matchedTic);
if ~matched.pairing.allExact || any(matched.componentTable.positionViolation)
    error("run_no_glove_stage7b_designed_excitation:PairingFailed", ...
        "Full Agent200/P matching or position safety failed.");
end

analysisOptions = struct( ...
    "targetMotors", options.targetMotors, ...
    "maxLagSteps", options.maxLagSteps, ...
    "activeVelocityThreshold", options.activeVelocityThreshold, ...
    "motionVelocityThreshold", options.motionVelocityThreshold, ...
    "offsetHoldSteps", options.offsetHoldSteps, ...
    "minimumSamplesPerFold", options.minimumSamplesPerFold, ...
    "minimumBenefitFraction", options.minimumBenefitFraction, ...
    "minimumMaterialFoldFraction", ...
        options.minimumMaterialFoldFraction, ...
    "minimumSignConsistency", options.minimumSignConsistency, ...
    "maximumBoundaryFraction", options.maximumBoundaryFraction, ...
    "minimumFiniteOnsetFraction", ...
        options.minimumFiniteOnsetFraction, ...
    "periodSec", options.periodSec);
analysisArguments = namedargs2cell(analysisOptions);
analysisTic = tic;
analysis = analyzeNoGloveStage7bDesignedResponse( ...
    matched.componentTable, matched.pairingTable, ...
    corpus.protocolTable, "designed_temporal", analysisArguments{:});
analysisElapsedSec = toc(analysisTic);

writeAnalysisTables(runDir, matched, analysis);
causalCompensationGatePassed = ...
    logical(analysis.primaryDecision.causalCompensationCandidate);
compensationInterventionExecuted = false;
filteredReferenceInterventionExecuted = false;
dtwCalculated = false;
stage8Authorized = false;
save(fullfile(runDir, "stage7b_results.mat"), ...
    "corpus", "matched", "analysis", "analysisOptions", ...
    "causalCompensationGatePassed", ...
    "compensationInterventionExecuted", ...
    "filteredReferenceInterventionExecuted", "dtwCalculated", ...
    "stage8Authorized", "stage7aManifest", "stage6Manifest", ...
    "agentEvaluationElapsedSec", "matchedElapsedSec", ...
    "analysisElapsedSec", "-v7.3");

stage7aHashAfter = fileSha256(stage7aResultsPath);
stage6ManifestHashAfter = fileSha256(stage6ManifestPath);
agentHashAfter = fileSha256(agentPath);
if stage7aHashAfter ~= stage7aHashBefore || ...
        stage6ManifestHashAfter ~= stage6ManifestHashBefore || ...
        agentHashAfter ~= agentHashBefore
    error("run_no_glove_stage7b_designed_excitation:InputModified", ...
        "An immutable input or Agent200 changed during ETAPA 7B.");
end

reproducibleCommand = buildReproducibleCommand( ...
    matlabRoot, options, fileparts(runDir));
writeText(fullfile(runDir, "reproducible_command.txt"), ...
    reproducibleCommand);
writeOfflineReport(fullfile(runDir, "offline_report.md"), ...
    analysis, matched, corpus, options, ...
    agentEvaluationElapsedSec, matchedElapsedSec, ...
    analysisElapsedSec, runDir);

primaryArtifacts = ["profile_protocol.csv", "profile_validation.csv", ...
    "window_protocol.csv", "smoke_episode_hashes.csv", ...
    "agent_episode_hashes.csv", "pairing.csv", ...
    "episode_summary.csv", "motor_summary.csv", ...
    "aggregate_summary.csv", "lag_confirmation_summary.csv", ...
    "held_out_fold_evaluation.csv", "event_latency.csv", ...
    "event_latency_summary.csv", "designed_gate.csv", ...
    "source_decision.csv", "stage7b_results.mat", ...
    "test_results.mat", "effective_smoke_profile.mat", ...
    "effective_evaluation_profile.mat", ...
    "reproducible_command.txt", "offline_report.md", ...
    "fixture/stage7b_designed_temporal_emg_only.mat", ...
    "fixture/stage7b_smoke_temporal_emg_only.mat"];
artifactHashes = repmat(struct("path", "", "sha256", ""), ...
    numel(primaryArtifacts), 1);
for artifactIdx = 1:numel(primaryArtifacts)
    artifactHashes(artifactIdx).path = primaryArtifacts(artifactIdx);
    artifactHashes(artifactIdx).sha256 = fileSha256( ...
        fullfile(runDir, primaryArtifacts(artifactIdx)));
end
writetable(struct2table(artifactHashes), ...
    fullfile(runDir, "artifact_hashes.csv"));

[gitCommit, gitDirty, trackedDirty, gitStatus] = getGitState(repoRoot);
agent7250Path = getAgent7250CheckpointPath();
manifest = struct( ...
    "stage", "7B", "schemaVersion", 1, "result", "PASS", ...
    "scientificGateResult", ...
        string(analysis.primaryDecision.classification), ...
    "createdAt", string(datetime("now", "TimeZone", "UTC", ...
        "Format", "yyyy-MM-dd'T'HH:mm:ssXXX")), ...
    "gitCommit", gitCommit, "gitDirty", gitDirty, ...
    "gitTrackedDirty", trackedDirty, "gitStatus", gitStatus, ...
    "matlabVersion", string(version), ...
    "launcher", "run_no_glove_stage7b_designed_excitation", ...
    "inputStage7aRunRoot", options.stage7aRunRoot, ...
    "inputStage7aManifestPath", stage7aManifestPath, ...
    "inputStage7aManifestSha256", fileSha256(stage7aManifestPath), ...
    "inputStage7aResultsPath", stage7aResultsPath, ...
    "inputStage7aResultsSha256Before", stage7aHashBefore, ...
    "inputStage7aResultsSha256After", stage7aHashAfter, ...
    "inputStage6RunRoot", options.stage6RunRoot, ...
    "inputStage6ManifestPath", stage6ManifestPath, ...
    "inputStage6ManifestSha256Before", stage6ManifestHashBefore, ...
    "inputStage6ManifestSha256After", stage6ManifestHashAfter, ...
    "inputsPreserved", true, ...
    "agentCheckpointPath", agentPath, ...
    "agentCheckpointLabel", "Agent200", ...
    "agentCheckpointSha256Before", agentHashBefore, ...
    "agentCheckpointSha256After", agentHashAfter, ...
    "agentCheckpointPreserved", agentHashBefore == agentHashAfter, ...
    "agentFrozen", true, "newTraining", false, ...
    "checkpointLoadedForTraining", false, ...
    "calibrationSeed", options.calibrationSeed, ...
    "profileSeed", options.profileSeed, ...
    "smokeSeed", options.smokeSeed, ...
    "evaluationSeed", options.evaluationSeed, ...
    "fixtureVersion", corpus.fixtureVersion, ...
    "calibrationContentSha256", corpus.calibrationContentSha256, ...
    "profileCount", height(corpus.protocolTable), ...
    "repetitionCount", size(corpus.emgs, 1), ...
    "smokeSimulationCount", 2, ...
    "evaluationSimulationCount", corpus.expectedSimulationCount, ...
    "analysisOptions", analysisOptions, ...
    "exactPairing", matched.pairing.allExact, ...
    "positionViolationCount", sum(matched.componentTable.positionViolation), ...
    "primaryCommandSource", "Agent200", ...
    "primaryClassification", analysis.primaryDecision.classification, ...
    "primaryCausalCandidateCount", ...
        analysis.primaryDecision.causalCandidateCount, ...
    "primaryUnresolvedCount", analysis.primaryDecision.unresolvedCount, ...
    "primaryRejectedCount", analysis.primaryDecision.rejectedCount, ...
    "causalCompensationGatePassed", causalCompensationGatePassed, ...
    "compensationInterventionExecuted", ...
        compensationInterventionExecuted, ...
    "filteredReferenceInterventionExecuted", ...
        filteredReferenceInterventionExecuted, ...
    "dtwCalculated", dtwCalculated, "dtwRewardUsed", false, ...
    "stage8Authorized", stage8Authorized, ...
    "designedEvaluationDataset", true, ...
    "evaluationReferenceProfilesChanged", true, ...
    "referenceGeneratorChanged", false, "stateChanged", false, ...
    "rewardChanged", false, "policyChanged", false, ...
    "quantizationChanged", false, "simulatorChanged", false, ...
    "safetyLayerChanged", false, "conventionalControllerChanged", false, ...
