    "testsTotal", numel(testResults), ...
    "testsPassed", sum([testResults.Passed]), ...
    "testsFailed", sum([testResults.Failed]), ...
    "artifactHashes", artifactHashes, "outputPath", runDir);
save(fullfile(runDir, "manifest.mat"), "manifest", "artifactHashes");
writeText(fullfile(runDir, "manifest.json"), ...
    jsonencode(manifest, "PrettyPrint", true));

report = struct("result", "PASS", "outputPath", runDir, ...
    "manifest", manifest, "analysis", analysis, "matched", matched, ...
    "corpus", corpus, "testResults", testResults);
fprintf("ETAPA 7B DESIGNED EXCITATION PASS\n");
fprintf("Output: %s\n", runDir);
disp(analysis.designedGateTable);
disp(analysis.sourceDecision);
end

function options = normalizeOptions(options)
if ~isstruct(options) || ~isscalar(options)
    error("run_no_glove_stage7b_designed_excitation:InvalidOptions", ...
        "options must be a scalar struct.");
end
defaults = struct("stage7aRunRoot", "", "stage6RunRoot", "", ...
    "resultsRoot", "", "calibrationSeed", 11, "profileSeed", 7701, ...
    "smokeSeed", 7702, "evaluationSeed", 7703, ...
    "repetitionsPerAxis", 4, "targetMotors", [2 3], ...
    "maxLagSteps", 5, "activeVelocityThreshold", 0.005, ...
    "motionVelocityThreshold", 0.001, "offsetHoldSteps", 2, ...
    "minimumSamplesPerFold", 10, "minimumBenefitFraction", 0.05, ...
    "minimumMaterialFoldFraction", 0.75, ...
    "minimumSignConsistency", 0.75, ...
    "maximumBoundaryFraction", 0.25, ...
    "minimumFiniteOnsetFraction", 1.0, "periodSec", 0.2, ...
    "motionTolerance", 1e-4, "positionTolerance", 1e-9, ...
    "saturationThreshold", 0.95, "simulatorSamplingPeriod", 0.14);
unknown = setdiff(string(fieldnames(options)), ...
    string(fieldnames(defaults)));
if ~isempty(unknown)
    error("run_no_glove_stage7b_designed_excitation:UnknownOption", ...
        "Unknown option(s): %s.", strjoin(unknown, ", "));
end
fields = fieldnames(defaults);
for fieldIdx = 1:numel(fields)
    name = fields{fieldIdx};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaults.(name);
    end
end
options.stage7aRunRoot = string(options.stage7aRunRoot);
options.stage6RunRoot = string(options.stage6RunRoot);
options.resultsRoot = string(options.resultsRoot);
if strlength(options.stage7aRunRoot) == 0 || ...
        strlength(options.stage6RunRoot) == 0
    error("run_no_glove_stage7b_designed_excitation:MissingInput", ...
        "stage7aRunRoot and stage6RunRoot are required.");
end
integerFields = ["calibrationSeed", "profileSeed", "smokeSeed", ...
    "evaluationSeed", "repetitionsPerAxis", "maxLagSteps", ...
    "offsetHoldSteps", "minimumSamplesPerFold"];
for fieldIdx = 1:numel(integerFields)
    name = integerFields(fieldIdx);
    value = options.(name);
    if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || ...
            value < 0 || fix(value) ~= value
        error("run_no_glove_stage7b_designed_excitation:InvalidOption", ...
            "%s must be a nonnegative integer.", name);
    end
end
if options.repetitionsPerAxis < 3 || options.maxLagSteps < 1 || ...
        options.offsetHoldSteps < 1 || options.minimumSamplesPerFold < 1
    error("run_no_glove_stage7b_designed_excitation:InvalidOption", ...
        "Fold, lag, hold and sample counts are too small.");
end
end

function [manifest, manifestPath, resultsPath] = ...
        loadAndValidateStage7a(runRoot)
manifestPath = fullfile(runRoot, "manifest.json");
resultsPath = fullfile(runRoot, "stage7a_results.mat");
if ~isfile(manifestPath) || ~isfile(resultsPath)
    error("run_no_glove_stage7b_designed_excitation:Stage7aNotFound", ...
        "ETAPA 7A manifest/results are missing.");
end
manifest = jsondecode(fileread(manifestPath));
required = ["stage", "result", "causalCompensationGatePassed", ...
    "compensationInterventionExecuted", ...
    "filteredReferenceInterventionExecuted", "dtwCalculated", ...
    "stage8Authorized", "hardwareUsed", "artifactHashes"];
if ~all(isfield(manifest, cellstr(required)))
    error("run_no_glove_stage7b_designed_excitation:InvalidStage7a", ...
        "ETAPA 7A manifest contract is incomplete.");
end
valid = string(manifest.stage) == "7A" && ...
    string(manifest.result) == "PASS" && ...
    ~logical(manifest.causalCompensationGatePassed) && ...
    ~logical(manifest.compensationInterventionExecuted) && ...
    ~logical(manifest.filteredReferenceInterventionExecuted) && ...
    ~logical(manifest.dtwCalculated) && ~logical(manifest.stage8Authorized) && ...
    ~logical(manifest.hardwareUsed);
if ~valid
    error("run_no_glove_stage7b_designed_excitation:IncompatibleStage7a", ...
        "ETAPA 7B requires the no-intervention ETAPA 7A output.");
end
expectedHash = findArtifactHash(manifest.artifactHashes, ...
    "stage7a_results.mat");
if fileSha256(resultsPath) ~= expectedHash
    error("run_no_glove_stage7b_designed_excitation:Stage7aHashMismatch", ...
        "ETAPA 7A results do not match their manifest.");
end
end

function [manifest, manifestPath, agentPath, agentHash, profile] = ...
        loadAndValidateStage6(runRoot)
manifestPath = fullfile(runRoot, "manifest.json");
inventoryPath = fullfile(runRoot, "checkpoint_inventory.csv");
if ~isfile(manifestPath) || ~isfile(inventoryPath)
    error("run_no_glove_stage7b_designed_excitation:Stage6NotFound", ...
        "ETAPA 6 manifest/inventory are missing.");
end
manifest = jsondecode(fileread(manifestPath));
if double(manifest.stage) ~= 6 || string(manifest.phase) ~= "smoke" || ...
        string(manifest.result) ~= "PARTIAL" || ...
        logical(manifest.hardwareUsed) || ~logical(manifest.simMotors) || ...
        logical(manifest.agent7250Loaded) || ...
        ~logical(manifest.positionSafetyAblation)
    error("run_no_glove_stage7b_designed_excitation:IncompatibleStage6", ...
        "ETAPA 7B requires the bounded position-safety Agent200 smoke.");
end
agentPath = string(manifest.seedSummary.finalCheckpoint);
if ~endsWith(agentPath, "Agent200.mat") || ~isfile(agentPath)
    error("run_no_glove_stage7b_designed_excitation:AgentNotFound", ...
        "Frozen Agent200 checkpoint is missing.");
end
inventory = readtable(inventoryPath, "TextType", "string");
match = inventory.checkpointPath == agentPath & inventory.episode == 200;
if sum(match) ~= 1
    error("run_no_glove_stage7b_designed_excitation:AgentInventoryMismatch", ...
        "Agent200 is not uniquely identified by the ETAPA 6 inventory.");
end
agentHash = upper(string(inventory.checkpointSha256(match)));
configPath = fullfile(fileparts(agentPath), "00_configs.mat");
if ~isfile(configPath)
    error("run_no_glove_stage7b_designed_excitation:ConfigNotFound", ...
        "Agent200 effective configuration is missing.");
end
loaded = load(configPath, "configs");
profile = loaded.configs;
required = ["intentCalibration", "intentExpectedContext", ...
    "referenceSource", "observationVariant", "rewardType", ...
    "actionInterfaceVariant", "simulationPositionSafety", ...
    "quantizeCommandsForSimulation", "td3", "td3Residual"];
if ~all(isfield(profile, cellstr(required)))
    error("run_no_glove_stage7b_designed_excitation:IncompleteProfile", ...
        "Agent200 profile is incomplete.");
end
safe = string(profile.referenceSource) == "emgIntent" && ...
    string(profile.observationVariant) == "intentMarkov60" && ...
    string(profile.rewardType) == "trackingIntentActionRateReward" && ...
    string(profile.actionInterfaceVariant) == "baselineQuantized" && ...
    logical(profile.quantizeCommandsForSimulation) && ...
    logical(profile.simulationPositionSafety.enabled) && ...
    ~logical(profile.td3.useRecurrent) && ...
    ~logical(profile.td3Residual.enabled);
if ~safe
    error("run_no_glove_stage7b_designed_excitation:UnsafeProfile", ...
        "Agent200 profile drifted from the bounded no-glove contract.");
end
end

function expected = findArtifactHash(artifactHashes, artifactName)
paths = string({artifactHashes.path});
match = paths == artifactName;
if sum(match) ~= 1
    error("run_no_glove_stage7b_designed_excitation:HashNotFound", ...
        "Manifest does not contain one hash for %s.", artifactName);
end
expected = upper(string(artifactHashes(match).sha256));
end

function profile = buildEvaluationProfile( ...
        trainingProfile, agentPath, datasetPath, randomSeed, ...
        simulationCount, outputBase)
[datasetFolder, datasetStem] = fileparts(datasetPath);
profile = trainingProfile;
profile.run_training = false;
profile.newTraining = false;
profile.agentFile = agentPath;
profile.agent_id = "td3_no_glove_intent";
profile.randomSeed = randomSeed;
profile.dataset = {char(string(datasetStem))};
profile.dataset_folder = string(datasetFolder);
profile.flagSaveTraining = true;
profile.episode_save_freq = 1;
profile.plotEpisodeOnTest = false;
profile.trainingPlots = "none";
profile.simOpts = rlSimulationOptions( ...
    "MaxSteps", profile.maxNumberStepsInEpisodes, ...
    "NumSimulations", simulationCount, "StopOnError", "on", ...
    "UseParallel", false);
profile.agents_directory = @(agent_id, variant) fullfile( ...
    outputBase, string(datetime("now", "Format", "yy-MM-dd HH m s")));
profile.simMotors = true;
profile.connect_glove = false;
profile.usePrerecorded = true;
profile.referenceSource = "emgIntent";
end

function assertSafeEvaluationProfile(profile, agentPath, simulationCount)
safe = ~logical(profile.run_training) && ~logical(profile.newTraining) && ...
    string(profile.agentFile) == agentPath && ...
    string(profile.agent_id) == "td3_no_glove_intent" && ...
    logical(profile.simMotors) && ~logical(profile.connect_glove) && ...
    logical(profile.usePrerecorded) && ...
    string(profile.referenceSource) == "emgIntent" && ...
    string(profile.observationVariant) == "intentMarkov60" && ...
    string(profile.rewardType) == "trackingIntentActionRateReward" && ...
    string(profile.actionInterfaceVariant) == "baselineQuantized" && ...
    logical(profile.quantizeCommandsForSimulation) && ...
    logical(profile.simulationPositionSafety.enabled) && ...
    profile.simOpts.NumSimulations == simulationCount;
if ~safe
    error("run_no_glove_stage7b_designed_excitation:UnsafeEvaluation", ...
        "Frozen Agent200 evaluation profile violates an invariant.");
end
end

