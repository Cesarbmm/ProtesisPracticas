function testReasonClassifierOrder(testCase)
decoder = decoderDetails(false, true, false);
reference = referenceDetails(false, false, false);
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    [0.1, 0, 0, 0], zeros(1, 4), decoder, reference), ...
    "movingReference");
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), zeros(1, 4), decoder, reference), ...
    "decoderRest");

decoder = decoderDetails(true, false, true);
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), zeros(1, 4), decoder, reference), ...
    "activeCountdownZero");
decoder.lowActivityCountdown = false;
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), zeros(1, 4), decoder, reference), ...
    "activeSynergyZero");

desired = [0.1, 0, 0, 0];
reference.positionLimited(1) = true;
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), desired, decoder, reference), ...
    "mechanicalPositionLimitZero");
reference.positionLimited(:) = false;
reference.accelerationLimited(1) = true;
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), desired, decoder, reference), ...
    "mechanicalRateLimitZero");
reference.accelerationLimited(:) = false;
testCase.verifyEqual(classifyIntentZeroReferenceReason( ...
    zeros(1, 4), desired, decoder, reference), ...
    "unresolvedActiveZero");
end

