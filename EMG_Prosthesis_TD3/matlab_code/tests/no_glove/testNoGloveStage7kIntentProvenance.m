function testOfflineReplayAlignmentAndLabels(testCase)
root = string(tempname);
mkdir(root);
cleanup = onCleanup(@() removeTempDir(root));
[path, stepCount] = writeReplayFixture(root, ...
    testCase.TestData.dataset, testCase.TestData.calibration, ...
    testCase.TestData.expected);
episodeAudit = table("candidate", "training", 1, 1, path, ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "episodePath"]);
step = (1:stepCount)';
windows = table(repmat("candidate", stepCount, 1), ...
    repmat("training", stepCount, 1), ones(stepCount, 1), ...
    ones(stepCount, 1), step, step, zeros(stepCount, 1), ...
    true(stepCount, 1), ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "step", "windowIndex", ...
    "holdPositionMse", "stopped"]);
latch = table(windows.variant, windows.source, windows.episode, ...
    windows.repetitionId, step, step, true(stepCount, 1), ...
    false(stepCount, 1), ones(stepCount, 1), false(stepCount, 1), ...
    'VariableNames', ["variant", "source", "episode", ...
    "repetitionId", "step", "windowIndex", "latchActive", ...
    "recoveredByMemory", "stoppedSegmentId", ...
    "segmentFarStarted"]);
profile = struct("intentCalibration", testCase.TestData.calibration, ...
    "intentExpectedContext", testCase.TestData.expected);
profiles = struct("control", profile, "candidate", profile);
analysis = replayNoGloveStage7kIntentProvenance( ...
    episodeAudit, windows, latch, profiles, ...
    "expectedEpisodeCount", 1, "expectedWindowCount", stepCount);
testCase.verifyTrue(analysis.replayGatePassed);
testCase.verifyEqual(analysis.classification, ...
    "zeroReferenceFullyExplainedByRestGate");
testCase.verifyEqual(analysis.decisionAudit.provenance(1), ...
    "episodeInitialization");
testCase.verifyTrue(all(analysis.decisionAudit.provenance(2:end) == ...
    "decoderRest"));
testCase.verifyEqual( ...
    max(analysis.transitionAudit.shiftedPositionReplayError), 0);
testCase.verifyEqual( ...
    max(analysis.transitionAudit.shiftedVelocityReplayError), 0);
testCase.verifyFalse( ...
    analysis.episodeReplayAudit.directProvenanceLogPresent);
end

