function [path, stepCount] = writeReplayFixture( ...
        root, dataset, calibration, expected)
stepCount = 3;
windowLength = calibration.windowLengthSamples;
raw = double(dataset.restCapture.rawEmg);
emgLog = cell(stepCount, 1);
for idx = 1:stepCount
    rows = (idx-1)*windowLength+(1:windowLength);
    emgLog{idx} = raw(rows, :);
end
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
stateLog = zeros(stepCount, 60);
qCurrent = (calibration.limits.positionMin+ ...
    calibration.limits.positionMax)./2;
vCurrent = zeros(1, 4);
stateLog(1, layout.referencePosition) = qCurrent;
stateLog(1, layout.referenceVelocity) = vCurrent;
gateState = struct("isActive", false, "onCount", 0, "offCount", 0);
for idx = 1:stepCount
    [desired, ~, gateState, details] = mapEmgToIntentVelocity( ...
        emgLog{idx}, calibration, expected, gateState);
    [qNext, vNext] = updateIntentReference(qCurrent, desired, ...
        calibration, details.isRest, vCurrent);
    if idx < stepCount
        stateLog(idx+1, layout.referencePosition) = qNext(end, :);
        stateLog(idx+1, layout.referenceVelocity) = vNext(end, :);
    end
    qCurrent = qNext(end, :);
    vCurrent = vNext(end, :);
end
referenceHistory = stateLog(:, layout.referencePosition);
referenceHistoryCount = stepCount;
intentTarget = qCurrent(:);
intentVelocity = vCurrent(:);
intentGateState = gateState;
intentCalibrationContentSha256 = calibration.contentSha256;
referenceSource = "emgIntent";
observationVariant = "intentMarkov60";
stateLength = 60;
repetitionId = 1;
path = fullfile(root, "episode00001.mat");
save(path, "stateLog", "emgLog", "referenceHistory", ...
    "referenceHistoryCount", "intentTarget", "intentVelocity", ...
    "intentGateState", "intentCalibrationContentSha256", ...
    "referenceSource", "observationVariant", "stateLength", ...
    "repetitionId");
end

function value = decoderDetails(gateActive, isRest, countdown)
value = struct("gateActive", logical(gateActive), ...
    "isRest", logical(isRest), ...
    "lowActivityCountdown", logical(countdown));
end

function value = referenceDetails(position, braking, acceleration)
value = struct("positionLimited", repmat(logical(position), 1, 4), ...
    "brakingLimited", repmat(logical(braking), 1, 4), ...
    "accelerationLimited", repmat(logical(acceleration), 1, 4));
end

function [dataset, calibration, expected] = buildFixture(seed)
config = buildNoGloveStage2OfflineConfig(seed);
dataset = buildSyntheticEmgIntentDataset(config);
calibration = calibrateEmgIntent(dataset.restCapture, ...
    dataset.instructionTrials, config.calibrationOptions);
options = config.calibrationOptions;
expected = struct( ...
    "userId", dataset.restCapture.userId, ...
    "sessionId", dataset.restCapture.sessionId, ...
    "channelOrder", dataset.restCapture.channelOrder, ...
    "sampleRateHz", dataset.restCapture.sampleRateHz, ...
    "windowLengthSamples", dataset.windowLengthSamples, ...
    "hopLengthSamples", dataset.hopLengthSamples, ...
    "dataProvenance", dataset.restCapture.dataProvenance, ...
    "motorOrder", options.motorOrder, ...
    "units", struct("rawEmg", dataset.restCapture.rawEmgUnits, ...
        "envelope", options.envelopeUnits, ...
        "position", options.positionUnits, ...
        "velocity", options.velocityUnits, ...
        "acceleration", options.accelerationUnits), ...
    "synergyMatrixVersion", options.synergyMatrixVersion, ...
    "instructionProtocolVersion", options.instructionProtocolVersion, ...
    "sourceDomain", "rawEmgSameSession", ...
    "calibrationContentSha256", calibration.contentSha256);
end

function removeTempDir(path)
if isfolder(path) && startsWith(path, string(tempdir))
    rmdir(path, "s");
end
end
