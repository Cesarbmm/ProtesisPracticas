function tests = testNoGloveStage6cMatchedController
% Deterministic tests for the simulation-only ETAPA 6C comparison.
tests = functiontests(localfunctions);
end

function testExactReferenceAndInitialPositionPairing(testCase)
[episodeDir, cleanup] = createFixture(); %#ok<ASGLU>
configs = fixtureConfig();
result = evaluateNoGloveStage6cMatchedController( ...
    episodeDir, configs, "acceptance");

testCase.verifyTrue(result.pairing.allExact);
testCase.verifyEqual(result.pairing.episodeCount, 1);
testCase.verifyEqual(result.pairing.referenceMaxAbs, 0);
testCase.verifyEqual(result.pairing.referenceVelocityMaxAbs, 0);
testCase.verifyEqual(result.pairing.initialPositionMaxAbs, 0);
testCase.verifyEqual(unique(result.componentTable.commandSource), ...
    ["Agent200"; "conventionalP"]);
testCase.verifyLessThanOrEqual(max(abs( ...
    result.componentTable.appliedPwm( ...
    result.componentTable.commandSource == "conventionalP"))), 64);
testCase.verifyFalse(result.agentLoaded);
testCase.verifyFalse(result.reinforcementLearningInvoked);
testCase.verifyTrue(result.simulatorInvokedForConventionalOnly);
testCase.verifyFalse(result.hardwareUsed);
testCase.verifyFalse(result.dtwCalculated);
end

function testReplayIsDeterministic(testCase)
[episodeDir, cleanup] = createFixture(); %#ok<ASGLU>
configs = fixtureConfig();
first = evaluateNoGloveStage6cMatchedController( ...
    episodeDir, configs, "acceptance");
second = evaluateNoGloveStage6cMatchedController( ...
    episodeDir, configs, "acceptance");
firstRows = first.componentTable( ...
    first.componentTable.commandSource == "conventionalP", :);
secondRows = second.componentTable( ...
    second.componentTable.commandSource == "conventionalP", :);
testCase.verifyEqual(firstRows.qAfter, secondRows.qAfter, ...
    "AbsTol", 0);
testCase.verifyEqual(firstRows.appliedPwm, secondRows.appliedPwm, ...
    "AbsTol", 0);
testCase.verifyEqual(firstRows.safetyInterventionCount, ...
    secondRows.safetyInterventionCount, "AbsTol", 0);
end

