    "stateLog", "trackingPredictionHistory", "referenceHistory", ...
    "actionLog", "actionSatLog", "actionPwmLog", ...
    "positionSafetyInterventionLog", "simulationPositionSafety", ...
    "referenceSource", "observationVariant", "stateLength", ...
    "repetitionId");
end

