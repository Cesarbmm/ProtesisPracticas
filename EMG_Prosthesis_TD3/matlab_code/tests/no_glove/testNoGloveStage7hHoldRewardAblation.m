function testHoldSummaryReplaysStateDecisionExactly(testCase)
tempDir = string(tempname);
mkdir(tempDir);
cleanup = onCleanup(@() removeTempDir(tempDir));
layout = buildObservationLayout("intentMarkov60", 40, 3, 4);
stateLog = zeros(3, 60);
stateLog(:, layout.encoder) = [zeros(1, 4); ...
    0.02.*ones(1, 4); zeros(1, 4)];
stateLog(:, layout.referencePosition) = zeros(3, 4);
stateLog(:, layout.referenceVelocity) = zeros(3, 4);
actionSatLog = [0.5, 0, 0, 0; 0.5, 0, 0, 0; 0, 0, 0, 0];
actionPwmLog = [128, 0, 0, 0; 128, 0, 0, 0; 0, 0, 0, 0];
positionMse = [0; 4e-4; 0];
active = [1; 0; 1];
rewardInfoLog = cell(3, 1);
for idx = 1:3
    holdAction = active(idx)*mean(actionSatLog(idx, :).^2);
    rewardInfoLog{idx} = struct( ...
        "holdActive", active(idx), ...
        "holdPositionMse", positionMse(idx), ...
        "holdVelocityMaxAbs", 0, ...
        "holdActionL2", holdAction, ...
        "holdActionPenalty", 0.2*holdAction);
end
referenceSource = "emgIntent";
observationVariant = "intentMarkov60";
save(fullfile(tempDir, "episode00001.mat"), "stateLog", ...
    "actionSatLog", "actionPwmLog", "rewardInfoLog", ...
    "referenceSource", "observationVariant");
settings = struct("actionWeight", 0.2, ...
    "velocityTolerance", 1e-12, ...
    "positionMseTolerance", 1e-4);
summary = summarizeNoGloveStage7hHoldReward(tempDir, settings, ...
    "requireSteadyRest", true);
testCase.verifyEqual(summary.holdActiveFraction, 2/3, ...
    "AbsTol", 1e-15);
testCase.verifyEqual(summary.holdActionPenaltyMean, ...
    mean([0.2*0.5^2/4, 0, 0]), "AbsTol", 1e-15);
testCase.verifyEqual(summary.maximumDiagnosticReplayError, 0);

rewardInfoLog{1}.holdActive = 0;
save(fullfile(tempDir, "episode00001.mat"), "stateLog", ...
    "actionSatLog", "actionPwmLog", "rewardInfoLog", ...
    "referenceSource", "observationVariant");
testCase.verifyError(@() summarizeNoGloveStage7hHoldReward( ...
    tempDir, settings), ...
    "summarizeNoGloveStage7hHoldReward:DiagnosticMismatch");
end

