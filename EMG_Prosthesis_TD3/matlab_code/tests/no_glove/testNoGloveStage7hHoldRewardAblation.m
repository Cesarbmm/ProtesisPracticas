function [control, candidate] = nominalPair()
training = struct("allFinite", true, ...
    "positionViolationEpisodeCount", 0, ...
    "positionSafetyInterventionCount", 2);
acceptance = struct("allFinite", true, ...
    "positionViolationEpisodeCount", 0, ...
    "positionSafetyInterventionCount", 1, ...
    "trackingMse", 0.10, "trackingMae", 0.20, ...
    "actionL2", 0.20, "deltaActionL2", 0.20, ...
    "saturationFraction", 0.10, ...
    "motor2FunctionalFlagCount", 0, ...
    "otherMotorFunctionalFlagCount", 0);
rest = struct("allFinite", true, ...
    "positionViolationEpisodeCount", 0, ...
    "positionSafetyInterventionCount", 0, ...
    "commandActiveFraction", 0.005, ...
    "windowAnyCommandFraction", 0.005, "meanAbsPwm", 1, ...
    "saturationFraction", 0, ...
    "commandActiveFractionByMotor", 0.005.*ones(1, 4), ...
    "meanAbsPwmByMotor", ones(1, 4), ...
    "saturationFractionByMotor", zeros(1, 4), ...
    "holdActiveFraction", 0.95, "holdActionL2Mean", 0.01, ...
    "holdActionPenaltyMean", 0, ...
    "maximumDiagnosticReplayError", 0);
control = struct("label", "control", "holdWeight", 0, ...
    "actionWeight", 0.05, "training", training, ...
    "acceptance", acceptance, "rest", rest, ...
    "decodedRestFalseActivationFraction", 0, ...
    "checkpointSha256", "control-sha");
candidate = control;
candidate.label = "candidate";
candidate.holdWeight = 0.20;
candidate.checkpointSha256 = "candidate-sha";
candidate.training.positionSafetyInterventionCount = 1;
candidate.acceptance.trackingMse = 0.09;
candidate.acceptance.actionL2 = 0.18;
candidate.acceptance.deltaActionL2 = 0.18;
candidate.acceptance.saturationFraction = 0.08;
candidate.rest.holdActionPenaltyMean = 0.002;
end

function removeTempDir(path)
if isfolder(path) && startsWith(path, string(tempdir))
    rmdir(path, "s");
end
end
