function testSupportedClassification(testCase)
[control, candidate] = nominalPair();
analysis = analyzeNoGloveStage7hHoldRewardAblation( ...
    control, candidate);
testCase.verifyTrue(analysis.gatePassed);
testCase.verifyEqual(analysis.classification, ...
    "holdConditionedRegularizationSupported");
testCase.verifyTrue(all(analysis.gateChecks.passed));
testCase.verifyEqual(analysis.ablationFactor, ...
    "intentHoldActionWeight");
testCase.verifyFalse(analysis.pilotAuthorized);
testCase.verifyFalse(analysis.rootCauseIdentified);
end

function testExposureFailurePrecedesOtherScientificFailures(testCase)
[control, candidate] = nominalPair();
candidate.rest.holdActiveFraction = 0.5;
candidate.rest.windowAnyCommandFraction = 1;
candidate.acceptance.trackingMse = 1;
analysis = analyzeNoGloveStage7hHoldRewardAblation( ...
    control, candidate);
testCase.verifyFalse(analysis.gatePassed);
testCase.verifyEqual(analysis.classification, ...
    "holdExposureInsufficient");
end

